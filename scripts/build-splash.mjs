// Заставка экрана загрузки: `campfire` — вождь у костра, племя вокруг, горы и луна.
// Вертикальная, во весь экран, лежит в `public/assets/splash/boot.webp` и качается
// сразу: её тянет экран загрузки (после первого кадра — см. docs/loading.md).
//
// Второй арт — «дружина за воротами» на занавесе первого входа на карту — ушёл
// вместе с занавесом: при пороге показа в 240 мс и первом входе в десятки
// миллисекунд занавес не показывался практически никогда.
//
// Руками `public/assets/splash/` не править — скрипт его перезапишет. Большие
// исходники в клиент не едут вовсе: они лежат в assets-src, как и музыкальные паки.
//
// Запуск: node scripts/build-splash.mjs
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath, URL } from 'node:url';

const SRC = fileURLToPath(new URL('../assets-src/splash', import.meta.url));
const BOOT_OUT = fileURLToPath(new URL('../public/assets/splash', import.meta.url));

// ---------- заставка экрана загрузки ----------
//
// Кадр вертикальный и лежит фоном `object-fit: cover`, то есть его подрежет
// **и телефон, и широкое окно** — по разным осям. Одним кадром обе ориентации
// красиво не закрываются: композиция высокая (луна вверху, вождь посередине,
// костёр ниже, племя внизу), и широкое окно неминуемо срежет её сверху и снизу.
// Поэтому кадр подрезан осмысленно, а не растянут, и правило одно:
//
//   **вождь и костёр остаются в кадре при обеих ориентациях.**
//
// Из него выведено ВСЁ, что ниже, и врозь эти числа не правятся.
//
// Пропорция кадра ASPECT = 0.888 — не «на глаз», а верхний предел. Телефон
// (390×844, 0.462) режет по горизонтали и оставляет ASPECT⁻¹×0.462 = 52% ширины;
// вождь с протянутой рукой и костёр занимают ровно 52% ширины исходника
// (x 0.15…0.67). Возьми пропорцию выше — и на телефоне отрежет либо плащ, либо
// огонь. Отсюда высота кадра: вся ширина исходника, делённая на 0.888.
//
// 15% высоты исходника в кадр всё равно не влезают, и `top` = 0.125 говорит, что
// именно из них уходит: верх с луной, а не низ с племенем. Проверено кадром, а не
// рассуждением. Кадр от верхнего края луну сохранял, но сдвигал костёр в самый низ,
// под подпись: огонь оказывался и обрезан, и ровно под строками, то есть худшим
// местом сразу по двум причинам. Низ же нужен тёмным — на нём лежит подпись, — и
// тёмный он именно там, где сидит племя. Луна возвращается разве что на очень
// высоком окне; вождь и костёр не уезжают никогда, и выбор между ними и луной
// сделан в пользу вождя и костра.
//
// Куда смотреть при подрезке, говорит `object-position` в index.html, и его числа
// выведены из тех же границ — они записаны там, рядом с CSS, потому что подрезает
// браузер, а не этот скрипт.
//
// Ширина — родная ширина исходника: ни одного пикселя вверх. При dpr 3 на 390pt
// видимая доля кадра растягивается до ~2250 px, то есть арт всё равно
// увеличивается, и отдавать ему меньше пикселей ради качества смысла нет —
// замерено: 640 px при quality 70 весит те же 36 КБ и заметно мягче, чем родные
// 969 px при quality 34.
//
// Качество 34 подобрано замером на самом рискованном месте — искры и поленья
// костра в масштабе показа: при 30 искры смазываются в кашу, при 38 разницы с 34
// не видно, а файл тяжелее на 2.8 КБ.
const BOOT = { name: 'campfire', aspect: 0.888, top: 0.125, quality: 34 };
const BOOT_CAP_KB = 40;

{
  const src = `${SRC}/${BOOT.name}-full.jpg`;
  const meta = await sharp(src).metadata();
  const height = Math.round(meta.width / BOOT.aspect);
  if (height > meta.height) {
    throw new Error(`${BOOT.name}-full.jpg ниже, чем нужно кадру: ${meta.height} < ${height}`);
  }
  const top = Math.min(Math.round(BOOT.top * meta.height), meta.height - height);
  const boot = await sharp(src)
    .extract({ left: 0, top, width: meta.width, height })
    .webp({ quality: BOOT.quality, effort: 6 })
    .toBuffer();
  await writeFile(`${BOOT_OUT}/boot.webp`, boot);
  const bootKb = boot.length / 1024;
  console.log(`boot.webp  ${meta.width}×${height}  ${bootKb.toFixed(1)} КБ`);
  if (bootKb > BOOT_CAP_KB) {
    console.error(`заставка не влезла в потолок ${BOOT_CAP_KB} КБ`);
    process.exit(1);
  }
}
