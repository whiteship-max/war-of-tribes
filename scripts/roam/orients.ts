/** Разделы ГДД (0–9) с пометкой `[… ориентир …]`: в каком разделе строка, по последнему заголовку с номером. */
export function orientSections(gdd: string): Set<string> {
  const out = new Set<string>();
  let head = '';
  for (const line of gdd.split('\n')) {
    const h = /^#+ (\d+(?:\.\d+)*)\.?\s/.exec(line);
    if (h) head = h[1];
    // Передачи и журналы пачек (10 и дальше) говорят об ориентирах, а не задают их.
    if (head === '' || Number(head.split('.')[0]) >= 10) continue;
    if (/\[[^\]]*ориентир/.test(line)) out.add(head);
  }
  return out;
}
