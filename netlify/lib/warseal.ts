/**
 * Сид живой войны (БЕЗ-1, docs/trust-boundary.md, 6в): номер войны, осады и дела лазутчика клиент видит (по нему он шлёт приказы), а
 * общий код боя, фаз осады и падения города у него есть — сид, выведенный из одного номера, клиент досчитал бы раньше сервера и знал
 * бы исход до приказа. Поэтому в живой игре сид — HMAC(секрет сервера, номер и назначение): без секрета не досчитать, а назначение
 * в ключе не даёт по одному сиду, показанному после боя, вывести другие.
 *
 * Секрет — только переменная окружения сервера (`TRIBE_WAR_SECRET`, образец имени — `.env.example`); значения нет ни в коде, ни в
 * тестах, ни в журнале. **Нет переменной — номер как есть**: сиды прежние (выкладка не падает, сервер пишет предупреждение при запуске —
 * `vps/config.launchNotes`), и так же идут тесты, отчёты и прибор — у них секрета нет, и их числа не сдвигаются ни на бит.
 *
 * Репетиции окна вольного замка (`world/freeodds`) идут без секрета нарочно (`unsealed`): это не живая война, а «что было бы» на сидах
 * окна, и сервер считает их той же дверью и теми же числами, что прибор.
 */
import { createHmac } from 'node:crypto';

/** Имя переменной секрета сидов войны. */
export const WAR_SECRET = 'TRIBE_WAR_SECRET';

/** Секрет сидов из окружения; пусто — секрета нет. */
export const warSecret = (env: Record<string, string | undefined> = process.env): string => (env[WAR_SECRET] ?? '').trim();

let bare = 0;

/**
 * Номер дела `id`, закрытый секретом, — для назначения `tag` (бой `battle#n`, падение, осада, лазутчик). Секрета нет или идёт
 * репетиция (`unsealed`) — `id` как есть: сиды без секрета те же, что до БЕЗ-1.
 */
export function sealed(id: string, tag: string, secret: string = bare > 0 ? '' : warSecret()): string {
  if (!secret) return id;
  return createHmac('sha256', secret).update(`${tag}|${id}`).digest('base64url').slice(0, 24);
}

/** Посчитать `fn` без секрета — репетиция, а не живая война. Синхронно: в промежутке ни одной живой войны не идёт. */
export function unsealed<T>(fn: () => T): T {
  bare += 1;
  try {
    return fn();
  } finally {
    bare -= 1;
  }
}
