/** Как идёт дух жалованьем: строка под полосами. `left` — срок словами, пусто — уже там. */
export function wageLine(mode: WageMode, share: number, left: string | null): string {
  if (mode === 'min') return share > 0 && left ? `Жалованье минимальное: дух падает, до дна ~${left}.` : 'Жалованье минимальное: дух на дне.';
  return share < 1 && left ? `Жалованье полное: дух возвращается, до потолка ~${left}.` : 'Жалованье полное: дух держится у потолка.';
}

