import { Suspense, lazy } from 'react';

/** Сетка построек и лист постройки — в куске нового вида (`ui/next/HallBuild.tsx`), рядом с окном постройки, внутри которого
 * ратуша и рисуется: первая загрузка за них не платит, а к открытию ратуши кусок уже приехал. */
const HallBuild = lazy(() => import('@/ui/next').then((m) => ({ default: m.HallBuild })));

/**
 * Вкладка «Стройка» — главная в ратуше и единственное место, откуда ведут улучшения всего города. Отдельного раздела
 * «Здания» нет: одно и то же дело не делается в двух местах (docs/handbook/ui.md, «Диегетический интерфейс»).
 *
 * С UI-2 (docs/ui_v2.md, раздел 5) это одна сетка, а не лента карточек: все постройки плитками в квадрат экрана —
 * уровень, руки, выход в день, «можно улучшить» и срок стройки; группы и порядок; касание плитки — лист постройки с
 * рабочими, выходом с разбором, улучшением и ценой. Метки обучения — `data-tut="list-<тип>"` у плитки (`HallBuild.tsx`).
 */
export function TownBuild() {
  return (
    <Suspense fallback={null}>
      <HallBuild />
    </Suspense>
  );
}
