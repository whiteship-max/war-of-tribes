/**
 * Русское склонение числительных: «1 шаг», «2 шага», «5 шагов».
 *
 * Живёт отдельным файлом, потому что писалось уже дважды — в летописи своё, в
 * лабиринте своё, — и второй раз вышло неправильным: `n === 1 ? 'шаг' : 'шагов'`
 * даёт «оставалось 2 шагов». Тройка форм — не украшение: игрок читает это в тот
 * момент, когда проиграл по таймеру, и кривая строка добавляет к проигрышу
 * ощущение, что игру делали наспех.
 *
 * Правило одно на все слова: 11–14 — всегда третья форма (одиннадцать шагов),
 * дальше решает последняя цифра.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.trunc(n));
  const tens = abs % 100;
  if (tens >= 11 && tens <= 14) return many;
  const last = abs % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

/** Число со склонённым словом: `count(3, 'шаг', 'шага', 'шагов')` → «3 шага». */
export const count = (n: number, one: string, few: string, many: string): string =>
  `${n} ${plural(n, one, few, many)}`;
