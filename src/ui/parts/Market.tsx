import { Suspense, lazy } from 'react';

/**
 * Рынок: за золото сюда привозят чужое добро. Закупка у проезжих торговцев; вкладки под торг между игроками нет:
 * невыпущенное не показывается (docs/ui_audit.md, 14.1, 3), место ему заведут вместе с сервером.
 *
 * С UI-7 (docs/ui_v2.md, 5.6) прилавок — таблица выбора, а не лента карточек с рядом шага в каждой: окно — в куске нового
 * вида (`ui/next/MarketNew.tsx`), рядом с окном постройки, внутри которого рынок рисуется; первая загрузка за него не платит.
 * Тупика без объяснения нет и там: у товара видно, почём, сколько осталось на сегодня и почему «Купить» погасла.
 */
const MarketNew = lazy(() => import('@/ui/next').then((m) => ({ default: m.MarketNew })));

export function Market() {
  return (
    <Suspense fallback={null}>
      <MarketNew />
    </Suspense>
  );
}
