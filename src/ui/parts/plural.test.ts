import { describe, expect, it } from 'vitest';
import { count, plural } from './plural';

describe('склонение числительных', () => {
  it('единица, двойка-четвёрка и всё остальное берут свою форму', () => {
    const форма = (n: number): string => plural(n, 'шаг', 'шага', 'шагов');
    expect(форма(1)).toBe('шаг');
    expect(форма(2)).toBe('шага');
    expect(форма(3)).toBe('шага');
    expect(форма(4)).toBe('шага');
    expect(форма(5)).toBe('шагов');
    expect(форма(0)).toBe('шагов');
    expect(форма(21)).toBe('шаг');
    expect(форма(22)).toBe('шага');
    expect(форма(25)).toBe('шагов');
    expect(форма(101)).toBe('шаг');
  });

  it('одиннадцать–четырнадцать — исключение, а не «последняя цифра»', () => {
    for (const n of [11, 12, 13, 14, 111, 112, 113, 114]) {
      expect(plural(n, 'шаг', 'шага', 'шагов')).toBe('шагов');
    }
  });

  /**
   * Ровно та строка, ради которой правило вынесено в отдельный файл: лабиринт
   * писал «оставалось 2 шагов» — по `n === 1 ? 'шаг' : 'шагов'`. Читает это
   * игрок в момент проигрыша по таймеру, то есть чаще всего при остатке в
   * два-четыре хода — как раз там, где старое правило и врало.
   */
  it('строка проигрыша в лабиринте склоняется на всех остатках', () => {
    expect(count(1, 'шаг', 'шага', 'шагов')).toBe('1 шаг');
    expect(count(2, 'шаг', 'шага', 'шагов')).toBe('2 шага');
    expect(count(7, 'шаг', 'шага', 'шагов')).toBe('7 шагов');
  });

  it('схема боя склоняет и существительное, и глагол', () => {
    const line = (n: number): string =>
      `${count(n, 'боец', 'бойца', 'бойцов')} ${plural(n, 'не расставлен', 'не расставлены', 'не расставлено')}`;
    expect(line(1)).toBe('1 боец не расставлен');
    expect(line(2)).toBe('2 бойца не расставлены');
    expect(line(5)).toBe('5 бойцов не расставлено');
    expect(line(11)).toBe('11 бойцов не расставлено');
  });

  it('летопись считает записи и дни тем же правилом', () => {
    expect(count(1, 'запись', 'записи', 'записей')).toBe('1 запись');
    expect(count(3, 'запись', 'записи', 'записей')).toBe('3 записи');
    expect(count(12, 'запись', 'записи', 'записей')).toBe('12 записей');
    expect(count(2, 'день', 'дня', 'дней')).toBe('2 дня');
    expect(count(11, 'день', 'дня', 'дней')).toBe('11 дней');
  });
});
