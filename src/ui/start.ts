/**
 * Что написано на кнопке стартового экрана.
 *
 * Кнопка **одна**, и это решение, а не упрощение. Просили пару «Регистрация» и
 * «Вход», но заводить их нечестно: игрок опознаётся подписью Telegram сам,
 * учётная запись появляется при первом же заходе, и обе кнопки делали бы одно и
 * то же — нажавший «Вход» получил бы регистрацию. Пара кнопок, ведущих в одно
 * место, — это не выбор, а вид выбора.
 *
 * Поэтому на экране стоит та кнопка, которая правдива:
 *
 *   - партии на устройстве нет — «Начать игру»;
 *   - партия есть — «Продолжить».
 *
 * Настоящий выбор здесь появится вместе с настоящим входом по почте и паролю:
 * тогда на этом же месте встанут два разных пути, и переделывать разметку не
 * придётся — поменяется только эта функция.
 *
 * Модуль чистый нарочно: правило «одна кнопка, та, которая правдива» проверяется
 * тестом, а не чтением разметки.
 */

/** Что делает единственная кнопка стартового экрана. */
export type StartAction = 'new' | 'continue';

/**
 * Есть ли что продолжать.
 *
 * `hasSave` — было ли на устройстве сохранение в момент запуска (`fresh` из
 * `loadGame`, наоборот). Серверную партию сюда не подмешиваем: она приезжает
 * позже запуска и своим ходом, а кнопка обязана быть правдой в ту секунду, в
 * которую её показали.
 */
export function startAction(hasSave: boolean): StartAction {
  return hasSave ? 'continue' : 'new';
}

/** Слово на кнопке. Второго набора слов для того же действия быть не должно. */
export const START_LABEL: Record<StartAction, string> = {
  new: 'Начать игру',
  continue: 'Продолжить',
};
