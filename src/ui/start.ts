/**
 * Что написано на кнопке стартового экрана.
 *
 * Кнопка **одна**, и это решение, а не упрощение. Просили пару «Регистрация» и
 * «Вход», но заводить их нечестно: игрок опознаётся подписью Telegram сам,
 * учётная запись появляется при первом же заходе, и обе кнопки делали бы одно и
 * то же — нажавший «Вход» получил бы регистрацию. Пара кнопок, ведущих в одно
 * место, — это не выбор, а вид выбора.
 *
 * Поэтому на экране стоит та кнопка, которая правдива:
 *
 *   - партии на устройстве нет — «Начать игру»;
 *   - партия есть — «Продолжить».
 *
 * Настоящий выбор здесь появится вместе с настоящим входом по почте и паролю:
 * тогда на этом же месте встанут два разных пути, и переделывать разметку не
 * придётся — поменяется только эта функция.
 *
 * Модуль чистый нарочно: правило «одна кнопка, та, которая правдива» проверяется
 * тестом, а не чтением разметки.
 */

/** Что делает единственная кнопка стартового экрана. */
export type StartAction = 'new' | 'continue';

/**
 * Есть ли что продолжать.
 *
 * `hasSave` — было ли на устройстве сохранение в момент запуска (`fresh` из
 * `loadGame`, наоборот). Серверную партию сюда не подмешиваем: она приезжает
 * позже запуска и своим ходом, а кнопка обязана быть правдой в ту секунду, в
 * которую её показали.
 */
export function startAction(hasSave: boolean): StartAction {
  return hasSave ? 'continue' : 'new';
}

/**
 * Что делает главная кнопка: входит в партию или сперва спрашивает имя города (docs/ui_audit.md, 13). Имя
 * спрашивается, пока его нет, — у новой партии и у старой, где город не называли, — и только там, где шаг имени
 * есть (новый интерфейс: `next/CityNaming`). Назвал — больше не спрашивает: имя лежит в сохранении
 * (`ProfileState.city`), своего флага у шага нет.
 */
export function startStep(hasNaming: boolean, named: boolean): 'enter' | 'name' {
  return hasNaming && !named ? 'name' : 'enter';
}

/** Слово на кнопке. Второго набора слов для того же действия быть не должно. */
export const START_LABEL: Record<StartAction, string> = {
  new: 'Начать игру',
  continue: 'Продолжить',
};

/**
 * ВРЕМЕННАЯ КНОПКА: «Предыстория».
 *
 * Правило «кнопка одна, и та, которая правдива» она не нарушает — оно про пару
 * «Регистрация»/«Вход», то есть про два пути в одно и то же место. Здесь путь
 * другой: предыстория (`src/prologue/`) — отдельный режим, и открывается он
 * отсюда только потому, что открывать его пока больше неоткуда.
 *
 * ПОЧЕМУ ОНА ВРЕМЕННАЯ И ЧТО С НЕЙ БУДЕТ. По замыслу предысторией будут
 * **начинать все**, прежде чем получить деревню: человек у костра в лесу, а
 * племя — потом. Тогда это перестанет быть выбором и станет первым экраном
 * новой партии, а кнопка исчезнет вместе с самим вопросом «во что играть».
 * Держать её отдельным именем нужно ровно затем, чтобы в тот день её убрали
 * целиком, а не оставили третьей строкой, которую никто не решается тронуть.
 *
 * Пока она стоит, она обязана быть честной: предыстория ни с чем не связана,
 * прогресс деревни не трогает и на сервер не едет — об этом сказано игроку
 * подписью под кнопкой (`PROLOGUE_NOTE`), а не умолчанием.
 */
export const PROLOGUE_LABEL = 'Предыстория';

/** Подпись под временной кнопкой. Врать про связь с партией нельзя. */
export const PROLOGUE_NOTE = 'С твоим племенем не связана.';

/**
 * Признак того, что вход в предысторию — временный.
 *
 * Не украшение и не флаг настройки: его читает тест, и он же — то место, за
 * которое эту кнопку выдернут. Ставить его в `false`, чтобы «оставить пока»,
 * нельзя: тогда пометка перестанет значить что-либо.
 */
export const PROLOGUE_IS_TEMPORARY = true;
