import { useGame } from '@/game/store';
import { storageCap } from '@/game/derived';
import { RESOURCE_IDS, RESOURCE_META } from '@/game/constants';
import { Icon } from '@/ui/icons/Icon';

/**
 * Сколько добра поместится в ячейку полоски. На 360 px их семь, и каждая
 * получает около сорока пикселей — четырёх цифр туда не встанет, а склад
 * десятого уровня держит десятки тысяч. Поэтому тысячи сокращаются: до тысячи
 * число стоит целиком, дальше — «1.2к» и «32к».
 *
 * Точность здесь не нужна и вредна: полоска отвечает на вопрос «хватит ли»,
 * а не «сколько ровно». Ровно — на складе, и туда ведёт та же иконка.
 */
export function shortNum(n: number): string {
  const v = Math.floor(Math.max(0, n));
  if (v < 1000) return String(v);
  // С 9 950 дробь округлилась бы до «10,0к» — самой широкой записи строки; там уже «10к».
  if (v < 9950) return `${(v / 1000).toFixed(1).replace('.', ',')}к`;
  return `${Math.round(v / 1000)}к`;
}

/**
 * Полоска ресурсов — самая верхняя строка экрана.
 *
 * Зачем она есть. Данные в игре живут внутри зданий, и полный список запасов
 * стоит на складе — это правило остаётся. Но решений, которые просят отдать
 * добро, в игре хватает, и часть из них приходит окном поверх всего: событие с
 * обменом, письмо с данью, выкуп за пленных. Из-под такого окна на склад не
 * зайти, отложить его нельзя, и «отдать припасы» нажималось вслепую.
 *
 * Поэтому два правила, и оба обязательные:
 *
 * 1. **Полоску не закрывает ни одно окно.** Она стоит выше всех модалок, а
 *    затемнение начинается под ней (`--hud-res-h` в стилях). Полоска, которую
 *    прячет то самое окно, ради которого её завели, не нужна вовсе.
 * 2. **Полоска ничего не нажимает.** Она только показывает
 *    (`pointer-events: none`): будь она кнопкой, тап поверх открытого события
 *    открыл бы шторку под ним. За подробностями — на склад, обычным путём.
 *
 * Здесь только ресурсы: снаряжения, войск и золота нет. Снаряжение и оружие
 * склад не ограничивает и набег не уносит — им место на складе, а не в строке
 * состояния; золото не ресурс и живёт там, где им платят.
 *
 * Полный склад покрашен: производство в этот ресурс с этой минуты пропадает,
 * и узнать об этом игрок должен раньше, чем пересчитает запасы вручную. Полным
 * считается склад, в котором осталось меньше единицы места, а не ровно
 * упёршийся в потолок: расход идёт каждый тик, и «ровно потолок» не выпадает
 * почти никогда — запас стоит на волосок ниже и выглядел бы обычным.
 */
export function ResourceBar() {
  const s = useGame((g) => g.s);
  const cap = storageCap(s);
  return (
    <div className="res-bar">
      {RESOURCE_IDS.map((r) => {
        const have = Math.floor(s.resources[r]);
        const full = s.resources[r] >= cap - 1;
        return (
          <span key={r} className={`res${full ? ' full' : ''}`} title={RESOURCE_META[r].name}>
            <Icon name={`res-${r}`} glyph={RESOURCE_META[r].icon} />
            <b>{shortNum(have)}</b>
          </span>
        );
      })}
    </div>
  );
}
