/** Список имён для веры земли; вера не известна — описательные имена. */
export const cityList = (faith: FaithId | null): readonly string[] => (faith ? CITY_NAMES[faith] : CITY_SUGGESTIONS);

/** Своя перестановка списка для партии: у соседей с другим сидом первые имена разные. */
function order(seed: number, list: readonly string[]): number[] {
  const out = list.map((_, i) => i);
  const rnd = seeded(mixSeed(seed, 0x63697479));
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** n-е имя на выбор: нулевое стоит в поле сразу, следующие — по кубику; список идёт по кругу. */
export function suggestCity(seed: number, n: number, faith: FaithId | null = null): string {
  const list = cityList(faith);
  const len = list.length;
  return list[order(seed, list)[((n % len) + len) % len]];
}
