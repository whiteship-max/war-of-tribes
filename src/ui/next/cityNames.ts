/** Своя перестановка списка для партии: у соседей с другим сидом первые имена разные. */
function order(seed: number): number[] {
  const out = CITY_SUGGESTIONS.map((_, i) => i);
  const rnd = seeded(mixSeed(seed, 0x63697479));
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** n-е имя на выбор: нулевое стоит в поле сразу, следующие — по кубику; список идёт по кругу. */
export function suggestCity(seed: number, n: number): string {
  const len = CITY_SUGGESTIONS.length;
  return CITY_SUGGESTIONS[order(seed)[((n % len) + len) % len]];
}
