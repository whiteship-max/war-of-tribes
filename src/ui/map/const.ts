// Числа детальной карты в одном месте: масштабы, геометрия тайла, палитра.
// Правится здесь, а не по коду, — как `world/data/tuning.ts` для самого мира.

// ---------- Масштабы ----------

/**
 * Пикселей на клетку. Рабочих масштабов два, и они далеко друг от друга:
 * обзор показывает расстановку сил, ближний — нарисованный мир.
 */
export const SCALE_MIN = 3.5;
export const SCALE_MAX = 80;
/** Дальний вид: пиксельный растр, ~55 клеток по ширине телефона. */
export const SCALE_OVERVIEW = 7;
/**
 * Ближний вид: ~7 клеток по ширине 390 px. Меньше делать нельзя — по поселению
 * перестанет попадать палец, а оно тут главная цель тапа.
 */
export const SCALE_DETAIL = 56;
/**
 * С какого масштаба карта открывается. Не `SCALE_DETAIL`: ближайший сосед стоит
 * в 5–9 клетках, и на семи клетках экрана игрок увидел бы пустую траву вокруг
 * своей деревни. Здесь мир уже нарисованный, но соседи ещё в кадре.
 */
export const SCALE_START = 30;

/**
 * Полоса перехода между видами. Внутри неё оба слоя рисуются с встречной
 * прозрачностью: подмена «вдруг» читается как сбой отрисовки, а не как зум.
 */
export const FADE_LO = 15;
export const FADE_HI = 26;

/** Имена поселений: на обзоре они сливаются в кашу. */
export const LABEL_FROM = 17;

// ---------- Тайлы земли ----------

/**
 * Сторона тайла в клетках. Тайл — единица выпечки: он печётся один раз и дальше
 * только копируется. Шесть клеток — это 336 CSS px на ближнем масштабе, то есть
 * экран накрывают 6–12 тайлов, и столько же `drawImage` стоит вся земля за кадр.
 */
export const TILE_CELLS = 6;

/**
 * Device-пикселей на клетку при выпечке. Показывается земля крупнее (48–64 CSS px
 * при dpr 2 — это 96–128 device px), то есть тайл растягивается в полтора-два
 * раза. Для травы, воды и холмов растяжение выглядит мазком кисти и даже на руку;
 * поднимать до 128 нельзя — память на тайл вырастет вчетверо.
 */
export const TILE_BAKE = 64;

/**
 * Вылет за край тайла, в клетках. Штампы соседнего тайла заходят внутрь, и без
 * запаса билинейное растяжение вытянуло бы на границу пустоту вместо соседа.
 */
export const TILE_BLEED = 0.5;

/**
 * Запас вокруг тайла, откуда берутся штампы, в клетках. Должен быть не меньше
 * самого большого радиуса штампа, иначе клякса, рождённая за краем, не дотянется
 * внутрь тайла — и на стыке появится шов.
 */
export const TILE_MARGIN = 3;

/** Сторона холста тайла в device-пикселях. */
export const TILE_PX = Math.round((TILE_CELLS + TILE_BLEED * 2) * TILE_BAKE);

/** Сколько тайлов держим в памяти. Видимые плюс кольцо запаса. */
export const TILE_CACHE = 20;

/** Сколько тайлов печётся за кадр. Больше одного — и бросок карты дёргается. */
export const TILE_BAKES_PER_FRAME = 1;

// ---------- Ландшафт ----------

/**
 * Уровень поля метаболов, на котором проходит берег. Сумма мягких дисков
 * соседних клеток даёт гладкую кляксу поперёк сетки — вода и холмы не клеточные.
 */
export const FIELD_LEVEL = 1;

/** Штампов на клетку и разброс их радиуса, в клетках. */
export const STAMPS_PER_CELL = 3;
export const STAMP_R_MIN = 0.85;
export const STAMP_R_MAX = 1.35;
/** Насколько штамп может уехать от центра клетки. */
export const STAMP_JITTER = 0.4;

/** Максимум ёлок на клетку сплошного леса. */
export const TREES_PER_CELL = 5;
/** Виды ёлок в атласе: одинаковые деревья читаются как узор, а не как лес. */
export const TREE_KINDS = 6;

