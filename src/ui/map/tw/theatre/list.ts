// (`theatre.test.ts`) — поправил список или цену, не пересобрал данные — красный тест, а не другой мир.
//
// Порядок списка — номер региона в данных (1..N; 0 — ничья земля). Новый регион дописывается в конец:
// перестановка сменит номера всех следующих.

export interface TheatreDef {
  /** Имя в коде и в данных. */
  id: string;
  /** Имя игроку. */
  name: string;
  /**
   * Центры: долгота и широта — столица, долина или ядро земли. Их несколько, когда у земли было несколько
   * сердец (Кастилия, Португалия и Арагон у Иберии): разлив из одной точки увёл бы дальний край к соседу.
   * Центр в воде (город в устье или на фьорде) встаёт на ближнюю сушу.
   */
  at: readonly (readonly [number, number])[];
}

