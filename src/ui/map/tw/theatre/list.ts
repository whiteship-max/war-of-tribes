// «театр» (`theatre`): слово «регион» в этой папке уже занято именами морей и гор (`tw/regions.ts`).
//
// Здесь только то, из чего регионы **выводятся**: центры исторических земель 1200 года и цена местности.
// Сама разметка клеток — разлив от центров по атласу (`derive.ts`): горы, хребты и реки держат границу,
