// Очередь выпечки нового вида (docs/map_tw.md, раздел 8): кусок обзора, тайл среднего масштаба и лист
// старой карты печётся не больше одного за кадр **на всех троих**. Порознь каждый держал бы свой предел, и в
// неудачный кадр сошлись бы три выпечки разом — рывок втрое длиннее. Тайлы ближнего масштаба держат свой
// предел (`TILE_BAKES_PER_FRAME`, `ground.ts`): они печётся только вблизи, где этих троих почти нет.
//
// Кто первым спросил в кадре, тот и печёт: кадр спрашивает в порядке нужды — сначала лист над незнанием
// (без него под листом видна земля), потом обзор (без него — пустота), потом средний слой (без него — мыло).

/** Кадр карты — 60 в секунду: ближе этого две выпечки считаются одним кадром. */
export const GATE_MS = 14;

let last = -Infinity;

/** Можно ли печь сейчас. Испёк — `baked()`. */
export const mayBake = (now: number): boolean => now - last >= GATE_MS;

export function baked(now: number): void {
  last = now;
}
