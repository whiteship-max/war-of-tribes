// Очередь выпечки нового вида (docs/map_tw.md, раздел 8): лист старой карты, кусок обзора, тайл среднего
// масштаба и тайл ближнего масштаба печётся не больше одного за кадр **на всех**. Порознь каждый держал бы свой
// предел, и в неудачный кадр сошлись бы несколько выпечек разом — рывок в разы длиннее.
//
// Счёт — по номеру кадра, а не по часам. По часам предел держался только для быстрых выпечек: метка ставилась
// временем до выпечки, и после куска обзора в 23 мс следующий в том же кадре видел «прошло больше кадра» и
// пёк тоже — бросок карты пёк весь экран кусков за один кадр (проверка этапа 2, находка 1).
//
// Кто первым спросил в кадре, тот и печёт: кадр спрашивает в порядке нужды — сначала лист над незнанием
// (без него под листом видна земля), потом обзор (без него — пустота), потом средний слой, потом тайлы.
// Вблизи обзор и средний слой не печётся вовсе (`NEAR_ONLY`): их там закрывают тайлы.

let frame = 0;
let bakedIn = -1;
let near = 0;

/**
 * Начало кадра: номер растёт с каждым кадром карты (`WorldMap`, `++frameNo`), `nearAlpha` — доля ближнего
 * слоя на масштабе кадра (`grid.detailAlpha`).
 */
export function startFrame(n: number, nearAlpha: number): void {
  frame = n;
  near = nearAlpha;
}

/** Можно ли печь в этом кадре. Испёк — `baked()`. */
export const mayBake = (): boolean => bakedIn !== frame;

export function baked(): void {
  bakedIn = frame;
}

/**
 * С какой доли ближнего слоя (`grid.detailAlpha`) кусок обзора и средний слой не печётся: их почти целиком
 * закрывают тайлы, и очередь отдаётся тайлам. Испечённое по-прежнему рисуется.
 */
export const NEAR_ONLY = 0.5;

/** Печь ли в этом кадре кусок обзора и средний слой: вблизи — нет, очередь у тайлов. */
export const farBakes = (): boolean => near < NEAR_ONLY;
