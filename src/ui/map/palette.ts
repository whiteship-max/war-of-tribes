/**
 * Отряд на карте. Здесь цвет **и есть** сторона, и это не противоречит правилу
 * поселений, а вытекает из него: у домов цвет занят материалом, по которому
 * читается стадия, а у колонны читать нечего — она либо наша, либо чужая, и
 * ответить на это надо с одного взгляда. Поэтому сторону несут и плащ, и вымпел
 * разом; различает отряды силуэт — число фигур, знамя, шатры, — а не оттенок.
 *
 * Плащ обоих наборов — цвет стороны (`side.ts`: золото и красный, те же, что у
 * `RELATION_META` `self` и `enemy`, в бою и в отчёте), тень плаща выведена из него
 * же (`sideShade`); остальное приглушено до землистой карты.
 */
export interface PartyPalette {
  /** Плащ и вымпел: самая большая плоскость бойца — она и говорит, чей он. */
  cloth: string;
  /** Теневая половина плаща: объём без градиента. */
  clothDark: string;
  /**
   * Шлемы. Приглушённый нарочно: ряд ярких точек над плащами читается не
   * головами, а бусами, и перебивает силуэт колонны — проверено глазами.
   */
  steel: string;
  /** Наконечники копий: тон между древком и шлемом, чтобы острие не пропало. */
  tip: string;
  /** Древки и шесты. */
  shaft: string;
  /** Контур: он держит силуэт, когда боец мельче двадцати пикселей. */
  line: string;
  /** Пятно под ногами. */
  shade: string;
  /** Пыль за колонной, два тона. */
  dust: string;
  dustThin: string;
  /** Тёмная масса задних рядов и неразличимые тени донесения. */
  mass: string;
  /** Шатры лагеря. */
  tent: string;
  tentDark: string;
  /** Костёр посреди лагеря — единственное тёплое пятно в нём. */
  fire: string;
}

