import { useEffect, useRef, useState } from 'react';
import { useGame, type Curtain } from '@/game/store';
import march from './art/curtain-march.webp';

/**
 * Раньше этого срока занавес не показывается вовсе — тот же порог, что у экрана
 * загрузки (`SHOW_AFTER_MS` в index.html), и по той же причине: отклик короче
 * четверти секунды человек читает как мгновенный, а картинка, мелькнувшая внутри
 * неё, выглядит сбоем, а не переходом.
 *
 * На всякой быстрой машине первый вход укладывается в этот порог (замер —
 * `npm run scene:report`), и занавеса игрок не видит никогда. Это правильный
 * исход, а не недоработка: занавес заведён для медленного телефона.
 */
const SHOW_AFTER_MS = 240;

/**
 * Занавес первого входа на карту.
 *
 * Висит ровно в одном месте за сессию: первый раз, когда открывают карту и
 * печётся земля. Остальные переходы мгновенные — диорама на время карты не
 * выгружается, а только перестаёт рисоваться, — и занавес на них был бы не
 * объяснением, а морганием.
 *
 * Арт здесь — «дружина за воротами», а не «племя у костра». Артов всего два, и
 * второй занят заставкой запуска: один и тот же кадр, увиденный дважды за минуту,
 * читается поломкой, а не стилем. Войско на этом месте не натяжка — занавес висит
 * ровно тогда, когда игрок впервые открывает карту, то есть в минуту, когда
 * дружина ждёт, куда её поведут.
 *
 * Раньше здесь стоял костёр, а походом была заставка. Поменялись они местами
 * вместе с приходом нарисованного костра: «племя собирается у костра» — это минута
 * запуска игры, а не минута выхода на карту.
 *
 * Второй арт («вождь у костра») лежит рядом собранным и в игре стоит заставкой
 * (`public/assets/splash/boot.webp`, собирается тем же скриптом).
 *
 * **В первую загрузку игры арт не входит ни байтом.** В чанке лежит только адрес
 * файла; сам файл браузер качает, когда `<img>` впервые встанет в разметку, то
 * есть при первом входе на карту, — и дальше берёт из кэша.
 */

const ART: Record<Curtain, { src: string; line: string }> = {
  map: { src: march, line: 'Дружина ждёт, куда её поведут' },
};

export function SceneCurtain() {
  const curtain = useGame((g) => g.curtain);
  // Занавес переживает своё снятие: без этого он исчезал бы рывком, вместе с
  // тем самым кадром, ради которого его и вешали.
  const [shown, setShown] = useState<Curtain | null>(curtain);
  // Видимость отдельно от разметки: пока занавес в разметке, но невидим,
  // браузер уже тянет арт — к порогу тот успевает приехать.
  const [visible, setVisible] = useState(false);
  const seen = useRef(false);

  useEffect(() => {
    if (curtain) {
      setShown(curtain);
      const t = setTimeout(() => {
        seen.current = true;
        setVisible(true);
      }, SHOW_AFTER_MS);
      return () => clearTimeout(t);
    }
    setVisible(false);
    // Не показался — снимаем сразу; показался — даём ему угаснуть переливом.
    const t = setTimeout(() => setShown(null), seen.current ? 260 : 0);
    return () => clearTimeout(t);
  }, [curtain]);

  if (!shown) return null;
  const art = ART[shown];
  return (
    <div className={`curtain${visible && curtain ? ' on' : ''}`}>
      {/* Арт стоит во всю ширину и своей высотой. Растягивать его на весь
          вертикальный экран нельзя: 640 px исходника на 844 pt — почти
          четырёхкратное увеличение, то есть каша вместо костра. Пустоту вокруг
          закрывает не размытая копия (она читалась грязным пятном), а тёплое
          свечение из палитры — тем же приёмом, что на экране загрузки. */}
      <div className="curtain-frame">
        <img className="curtain-art" src={art.src} alt="" />
        <div className="curtain-line">{art.line}</div>
      </div>
    </div>
  );
}
