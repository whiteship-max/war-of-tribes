/**
 * Журнал касаний — прибор того же рода, что `scenelog.ts`, и заведён по той же
 * причине.
 *
 * Жалоба звучала так: «тап по зданию срабатывает иногда, непредсказуемо».
 * Проверить её нечем: отладчик к телефону в Телеграме не подключить, а на
 * стенде всё зелено — стенд подаёт синтетические события, и живой палец от них
 * отличается ровно тем, из-за чего тап и терялся. Значит, спрашивать надо само
 * устройство: пусть запишет, что было под пальцем, и отдаст текстом.
 *
 * ГЛАВНОЕ ПРАВИЛО ТО ЖЕ — ЧЕСТНОСТЬ. Журнал пишет только то, что видел:
 * сколько пальцев, сколько миллисекунд, на сколько уехало, чем кончилось. Он не
 * называет причину и не подставляет ближайшую похожую: не понял, что было, —
 * так и пишет. Сломанный прибор хуже отсутствующего.
 *
 * Модуль чистый: ни DOM, ни three, ни React. Пишут в него те, кто видит палец
 * (`render/Scene`, `ui/map/WorldMap`), читает — служебный экран в «Заданиях».
 * Лежит в корне `src/` по той же причине, что `gestures.ts`: холста два, а
 * палец один, и журнал у него обязан быть общим — иначе «на карте работает, в
 * деревне нет» так и останется ощущением.
 */

/**
 * Где касались. Слово то же, что игрок видит на экране.
 *
 * Холстов стало три: к деревне и карте добавилась предыстория — режим от
 * первого лица, где палец ходит и смотрит одновременно. Она пишет сюда же и
 * нарочно: сравнивать «там работает, а здесь нет» можно только в одном списке,
 * и заводить второй журнал под третий холст значило бы потерять ровно ту
 * возможность, ради которой этот и написан.
 */
export type Surface = 'деревня' | 'карта' | 'предыстория';

/**
 * Чем кончилось касание. Порядок слов — от самого понятного к самому глухому,
 * и последнее из них и есть честное «не знаю».
 */
export type End =
  /** Тап: холст открыл то, во что целились. */
  | 'тап'
  /** Тап пришёлся мимо всего — в чистое поле. Это тоже ответ, а не пропажа. */
  | 'мимо'
  /** Ведение: палец ушёл дальше порога, камера поехала. */
  | 'ведение'
  /** Два пальца: щипок. Тапа в таком жесте не бывает. */
  | 'два пальца'
  /** Палец пролежал дольше `TAP_MS`. */
  | 'долгое'
  /** Жест отобрал браузер (`pointercancel`) — это не наше решение. */
  | 'отменено браузером';

export interface Touch {
  /**
   * Стенные часы: в отчёте с телефона нужны именно они. Ставит их сам журнал —
   * холстам про часы знать незачем, а `src/ui` их и не читает (см. `net/clock`).
   */
  at: number;
  where: Surface;
  /** Сколько пальцев побывало на холсте за этот жест. */
  fingers: number;
  /** Сколько длилось касание, мс. */
  ms: number;
  /** Самый дальний сход от точки нажатия, px. */
  far: number;
  /** Длина пути пальца, px. Ведение от дрожи отличается именно ею. */
  path: number;
  end: End;
  /** Что открылось. null — ничего; для `мимо` так и есть. */
  hit: string | null;
  /**
   * На сколько пикселей уехала картинка за время касания. null — «не знаю»:
   * холст не смог измерить, и подставлять сюда ноль нельзя.
   */
  drift: number | null;
}

/** Сколько касаний помним. Полсотни — это пара минут игры пальцем. */
export const TOUCH_MAX = 50;

/**
 * Журнал. Один на игру и один на оба холста: вопрос «почему на карте работает,
 * а в деревне нет» без общего журнала не разобрать.
 */
class GestLog {
  private touches: Touch[] = [];
  private readers = new Set<() => void>();

  add(t: Omit<Touch, 'at'>): void {
    this.touches.push({ ...t, at: Date.now() });
    if (this.touches.length > TOUCH_MAX) this.touches.splice(0, this.touches.length - TOUCH_MAX);
    for (const fn of this.readers) fn();
  }

  list(): readonly Touch[] {
    return this.touches;
  }

  clear(): void {
    this.touches = [];
    for (const fn of this.readers) fn();
  }

  subscribe(fn: () => void): () => void {
    this.readers.add(fn);
    return () => this.readers.delete(fn);
  }

  /**
   * Итог словами. Считает и называет факты, причину не выводит: она бывает
   * снаружи — в разметке поверх холста, в вебвью, в самом устройстве.
   */
  summary(): string[] {
    if (!this.touches.length) return ['Касаний не записано.'];
    const n = this.touches.length;
    const taps = this.touches.filter((t) => t.end === 'тап').length;
    const drags = this.touches.filter((t) => t.end === 'ведение').length;
    const cancelled = this.touches.filter((t) => t.end === 'отменено браузером').length;
    const lines = [`Касаний ${n}: тапов ${taps}, ведений ${drags}, отменённых браузером ${cancelled}.`];
    // Форма самой жалобы: палец почти не двигался, а не открылось ничего.
    const still = this.touches.filter((t) => t.end !== 'тап' && t.end !== 'мимо' && t.far < 12 && t.fingers === 1);
    if (still.length) {
      lines.push(`Из них ${still.length} почти не двигались и всё равно не открыли ничего — это и есть жалоба.`);
    }
    const shaken = this.touches.filter((t) => t.drift !== null && t.drift > 6 && t.far <= 12);
    if (shaken.length) {
      lines.push(`У ${shaken.length} картинка уехала больше чем на 6 px, хотя палец стоял, — камеру двигает не палец.`);
    }
    return lines;
  }

  /** Отчёт одной строкой на всё — его игрок и скопирует в переписку. */
  report(extra: Record<string, string> = {}): string {
    const lines = ['TRIBE, касания:'];
    for (const s of this.summary()) lines.push(`  ${s}`);
    for (const [k, v] of Object.entries(extra)) lines.push(`${k}: ${v}`);
    lines.push('журнал (последнее внизу):');
    const t0 = this.touches[0]?.at ?? Date.now();
    for (const t of this.touches) {
      lines.push(
        `  +${((t.at - t0) / 1000).toFixed(1)}s ${t.where} · ${t.fingers} пал. · ${Math.round(t.ms)} мс · сход ${Math.round(t.far)} px · путь ${Math.round(t.path)} px · ${t.end}${t.hit ? ` → ${t.hit}` : ''} · картинка ${t.drift === null ? 'не знаю' : `${Math.round(t.drift)} px`}`,
      );
    }
    if (!this.touches.length) lines.push('  пусто');
    return lines.join('\n');
  }
}

export const gestLog = new GestLog();
