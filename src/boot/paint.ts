/**
 * Уступить браузеру кадр.
 *
 * Нужно всюду, где следом идёт долгая работа в главном потоке: подсчёт офлайна
 * на запуске, выгрузка диорамы и сборка карты при переходе. Всё, что не
 * нарисовано ДО такой работы, не нарисуется до самого её конца, и подпись
 * «считаем, что было без тебя» появилась бы ровно тогда, когда счёт уже
 * кончился.
 *
 * Функция одна на всех нарочно: два «подождать кадр» с разными правилами
 * разошлись бы при первой же правке.
 */

/**
 * Сколько ждём кадра, прежде чем идти дальше без него.
 *
 * В свёрнутой вкладке и в скрытом вебвью `requestAnimationFrame` не вызывается
 * **вовсе** — не «редко», а никогда, пока страницу не покажут. Без этого срока
 * экран загрузки висел бы у свернувшего игру до самого возвращения, а сторожевой
 * таймер успел бы объявить исправную игру сломанной. Это не теория: ровно так и
 * вышло при первой проверке в скрытой панели браузера.
 */
export const PAINT_WAIT_MS = 250;

/**
 * Ждёт двух кадров наперегонки с таймером.
 *
 * Два, а не один: первый только вычисляет стиль после правки DOM, рисует
 * второй. Кадр при этом — вежливость, а не условие: не дождались — идём дальше.
 */
export function afterPaint(then?: () => void): Promise<void> {
  const wait =
    typeof requestAnimationFrame !== 'function'
      ? Promise.resolve()
      : new Promise<void>((resolve) => {
          let settled = false;
          const finish = (): void => {
            if (settled) return;
            settled = true;
            resolve();
          };
          setTimeout(finish, PAINT_WAIT_MS);
          requestAnimationFrame(() => requestAnimationFrame(finish));
        });
  return then ? wait.then(then) : wait;
}
