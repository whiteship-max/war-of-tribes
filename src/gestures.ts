/**
 * Жесты пальцем — одни на всю игру.
 *
 * Лежит вне `ui/` и вне `render/` нарочно, как и `debug.ts`: холста в игре два —
 * диорама деревни и карта мира, — а палец один, и переучиваться при переходе
 * между ними игрок не должен. Числа поэтому записаны здесь и только здесь.
 *
 * Правило деревни и карты одно: **ведение одним пальцем, приближение щипком**.
 * Расходятся они ровно в одном месте, и это записано в CLAUDE.md: у диорамы есть
 * третий жест — поворот двумя пальцами, — которого у плоской карты нет и быть не
 * может. Конфликта нет: карта этот жест не занимает ничем.
 */

/**
 * Сколько палец может проехать, оставаясь тапом.
 *
 * Десять пикселей — примерно четверть отпечатка: меньше человек не удержит,
 * больше — это уже осознанное ведение. Порог **защёлкивается**: уехал дальше —
 * жест стал ведением навсегда, и возвращение пальца на место тапа не вернёт.
 * Без защёлки петля «вниз и обратно» засчитывалась тапом, потому что сравнивались
 * только точка нажатия и точка отпускания.
 */
export const TAP_MOVE = 10;

/**
 * Сколько тап может длиться. Треть секунды — обычный предел для «нажал и отпустил»;
 * пятьдесят миллисекунд сверху отданы телефону: при 20 кадрах в секунду события
 * ждут своей очереди за кадром сцены, и эта задержка ложится на длительность.
 */
export const TAP_MS = 350;

/**
 * Минимальная цель под палец в пикселях экрана — та же величина, что `--tap` в
 * стилях. Здание на 390 px занимает 18–39 px, то есть меньше отпечатка: область
 * попадания раздувается до этого числа, даже если модель мельче.
 */
export const TAP_TARGET = 44;

/**
 * Насколько прощается промах мимо области попадания, в пикселях экрана.
 * Полпальца: игрок целится в дом, а не в пиксель, и тап рядом с домом открывает
 * дом. Дальше этого — пустое поле, и тогда не открывается ничего.
 */
export const TAP_FORGIVE = 26;

/**
 * Одно нажатие: где началось, когда началось и успело ли стать ведением.
 *
 * **Точка отпускания в счёт не идёт, и это важно именно на телефоне.** Когда
 * палец сходит с экрана, пятно контакта схлопывается несимметрично, и центр,
 * который сообщает система, прыгает на десяток-другой пикселей — мышь так не
 * умеет. Поэтому жест судится по пути (`move`), а не по концу, а цель берётся
 * там, где палец лёг: игрок целился в момент нажатия.
 */
export class Press {
  private dragged = false;

  constructor(
    readonly id: number,
    readonly x: number,
    readonly y: number,
    readonly t: number,
  ) {}

  /** Палец поехал. Возвращает, остался ли жест тапом. */
  move(x: number, y: number): boolean {
    if (Math.hypot(x - this.x, y - this.y) > TAP_MOVE) this.dragged = true;
    return !this.dragged;
  }

  /** Жест уже стал ведением. */
  get moved(): boolean {
    return this.dragged;
  }

  /** Тап ли это на момент отпускания. */
  isTap(now: number): boolean {
    return !this.dragged && now - this.t <= TAP_MS;
  }
}
