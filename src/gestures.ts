/**
 * Жесты пальцем — одни на всю игру.
 *
 * Лежит вне `ui/` и вне `render/` нарочно, как и `debug.ts`: холста в игре два —
 * диорама деревни и карта мира, — а палец один, и переучиваться при переходе
 * между ними игрок не должен. Числа поэтому записаны здесь и только здесь.
 *
 * Правило деревни и карты одно: **ведение одним пальцем, приближение щипком**.
 * Расходятся они ровно в одном месте, и это записано в CLAUDE.md: у диорамы есть
 * третий жест — поворот двумя пальцами, — которого у плоской карты нет и быть не
 * может. Конфликта нет: карта этот жест не занимает ничем.
 *
 * **Общий здесь не только порог, но и разбор жеста целиком** (`Gesture`). Так
 * сделано после того, как две копии одного разбора успели разойтись: карта
 * убивала тап на втором пальце, деревня — перебивала им первый, и щипок в
 * деревне открывал здание. Что именно значит тап, каждый холст по-прежнему
 * решает сам (деревня — здание под нажатием, карта — клетку под отпусканием),
 * а вот **тап это или ведение** судит один код.
 *
 * ДВА ПОРОГА, ДВА РАЗНЫХ СМЫСЛА — и часов между ними больше нет.
 *
 *   `TAP_MOVE` (10 px)  камера пошла за пальцем;
 *   `TAP_SLIP` (32 px)  тапа в этом жесте больше нет.
 *
 * Между ними камера уже едет, а тап ещё жив, и это не противоречие: ведёт она
 * один к одному, то есть на тридцать два пикселя сдвига картинка уезжает ровно
 * на столько же, сколько прошёл палец, — а палец при этом остаётся на той же
 * постройке (`TAP_SLIP` меньше `TAP_TARGET`). Хуже из двух ошибок — потерянный
 * тап, и вот почему: панель, открывшаяся после сдвига в двадцать пикселей,
 * закрывается одним касанием, а тап, не открывший ничего, игрок повторяет
 * вслепую и решает, что игра сломана. Именно на это и пришла жалоба.
 */

/**
 * Сколько палец может проехать, прежде чем камера пойдёт за ним.
 *
 * Десять пикселей — примерно четверть отпечатка и та же мерка, что у системного
 * порога прокрутки: меньше человек не удержит, и сдвигать картинку от дрожи
 * лежащего пальца незачем. Это порог **камеры**, а не тапа: тап живёт дальше,
 * до `TAP_SLIP`.
 */
export const TAP_MOVE = 10;

/**
 * Дальше этого тапа в жесте больше нет — сколько бы он ни длился и куда бы
 * палец потом ни вернулся.
 *
 * Порог один, и часов при нём нет. Прежде рядом стояла **выдержка**: сход
 * между `TAP_MOVE` и `TAP_SLIP` считался тапом только первые 90 мс, а дальше
 * жест защёлкивался ведением. Замер настоящим касанием (не синтетическим
 * событием — `npm run tap:report`) показал, что этим и терялся тап на телефоне:
 * палец, ложась на экран, проезжает 14–20 px в первые 60–80 мс — пятно контакта
 * растекается, пока подушечка садится, — а потом лежит неподвижно ещё двести-
 * четыреста миллисекунд, пока игрок целится. Выдержка к моменту снятия давно
 * истекала, и обычный человеческий тап отбрасывался молча. Стенд этого не видел:
 * он моделировал сход только **перед** снятием.
 *
 * Тридцать два — меньше `TAP_TARGET`: палец, ушедший на столько, всё ещё стоит
 * в области того здания, в которое целился. Это и есть смысл числа, а не запас
 * на глаз, и на этом стоит тест.
 */
export const TAP_SLIP = 32;

/**
 * Сколько тап может длиться.
 *
 * Раньше стояло 350 мс, и это было одной из причин, по которой тап по зданию не
 * открывал панель: замер на живой сцене давал 21 из 21 при 340 мс и **ноль из
 * 21** при 420 мс. Между тем прицелиться в постройку размером с палец на
 * кольцевой планировке дольше трети секунды — обычное дело, а у самого браузера
 * предела на длительность `click` нет вовсе, и долгое нажатие в системе
 * начинается только с 500 мс.
 *
 * Семьсот — заведомо дальше и того, и другого. Держать предел вообще стоит:
 * палец, забытый на экране на секунды, тапом не был. Отдельного жеста «долгое
 * нажатие» в игре нет, и заводить его нельзя — иначе это число придётся делить
 * с ним, и тап снова начнёт теряться.
 */
export const TAP_MS = 700;

/**
 * Минимальная цель под палец в пикселях экрана — та же величина, что `--tap` в
 * стилях. Здание на 390 px занимает 18–39 px, то есть меньше отпечатка: область
 * попадания раздувается до этого числа, даже если модель мельче.
 */
export const TAP_TARGET = 44;

/**
 * Насколько прощается промах мимо области попадания, в пикселях экрана.
 * Полпальца: игрок целится в дом, а не в пиксель, и тап рядом с домом открывает
 * дом. Дальше этого — пустое поле, и тогда не открывается ничего.
 */
export const TAP_FORGIVE = 26;

/**
 * Сколько ждём «призрачный» щелчок после тапа.
 *
 * Браузер после касания синтезирует совместимый `click` — тем и живут обычные
 * кнопки на телефоне. Приходит он через считанные миллисекунды после
 * `pointerup`, так что четырёхсот хватает с большим запасом; больше и не надо —
 * сторож снимается первым же щелчком и почти никогда не досиживает до срока.
 */
export const GHOST_CLICK_MS = 400;

/**
 * Проглотить призрачный щелчок, который придёт следом за этим тапом.
 *
 * ЭТО НЕ ПРЕДОСТОРОЖНОСТЬ, А ПОЧИНКА, И ВОТ ПОЧЕМУ. Тап по зданию открывает
 * панель, панель поднимает над сценой затемнение (`.sheet-backdrop`), а
 * затемнение закрывается щелчком. Между `pointerup` и синтезированным `click`
 * React успевает нарисовать и то, и другое — и щелчок, порождённый **тем же
 * касанием**, что открыло панель, тут же её и закрывает. Снаружи это выглядит
 * ровно как жалоба: «тап срабатывает иногда, непредсказуемо».
 *
 * Почему «иногда»: браузер не шлёт совместимый щелчок, если палец за время
 * касания успел уехать. Замер настоящим касанием: неподвижный тап — щелчок по
 * затемнению и панель закрылась; тот же тап со сходом в 20 px — щелчка нет и
 * панель осталась. То есть чем аккуратнее игрок целился, тем вернее терял тап.
 *
 * Гасить щелчок в источнике нельзя: `preventDefault` ни на `pointerdown`, ни на
 * `touchstart` его не убирает — проверено на живой канве, щелчок приходит в
 * обоих случаях. Значит, ловить его надо на подходе, и ровно один: сторож
 * снимается первым же щелчком, а если тот не пришёл — по сроку.
 *
 * Живёт здесь, а не в сцене, по той же причине, что и весь этот модуль: холста
 * два, а палец один, и панель поверх сцены открывают оба.
 */
export function swallowGhostClick(): void {
  if (typeof window === 'undefined') return;
  let timer = 0;
  const off = (): void => {
    window.removeEventListener('click', eat, true);
    window.clearTimeout(timer);
  };
  // Перехват на погружении и до всех: щелчок обязан не дойти ни до затемнения,
  // ни до кнопки на только что открывшейся панели — она стоит там же, где палец.
  function eat(e: Event): void {
    e.stopPropagation();
    e.preventDefault();
    off();
  }
  timer = window.setTimeout(off, GHOST_CLICK_MS);
  window.addEventListener('click', eat, true);
}

/**
 * Одно нажатие: где началось, когда началось, докуда доехало.
 *
 * **Точка отпускания в счёт не идёт, и это важно именно на телефоне.** Когда
 * палец сходит с экрана, пятно контакта схлопывается несимметрично, и центр,
 * который сообщает система, прыгает на десяток-другой пикселей — мышь так не
 * умеет. Поэтому жест судится по пути (`move`), а не по концу, а цель берётся
 * там, где палец лёг: игрок целился в момент нажатия.
 */
export class Press {
  /** Ушёл дальше `TAP_SLIP` — обратной дороги нет. */
  private dragged = false;
  /** Прошёл `TAP_MOVE` — камера с этого места едет за пальцем. */
  private led = false;
  /** Самый дальний сход от точки нажатия. Нужен журналу касаний. */
  far = 0;
  /** Длина пройденного пути. Тоже журналу: ведение от дрожи по ней и видно. */
  path = 0;
  /** Где палец был на прошлом шаге — из этого и складывается путь. */
  private px: number;
  private py: number;

  constructor(
    readonly id: number,
    readonly x: number,
    readonly y: number,
    readonly t: number,
  ) {
    this.px = x;
    this.py = y;
  }

  /** Палец поехал. Возвращает, остался ли жест тапом. */
  move(x: number, y: number, now: number): boolean {
    this.path += Math.hypot(x - this.px, y - this.py);
    this.px = x;
    this.py = y;
    const d = Math.hypot(x - this.x, y - this.y);
    if (d > this.far) this.far = d;
    if (d > TAP_MOVE) this.led = true;
    if (d > TAP_SLIP) this.dragged = true;
    return this.isTap(now);
  }

  /** Жест уже точно ведение: вернуть его в тап ничем нельзя. */
  get moved(): boolean {
    return this.dragged;
  }

  /** Камера ведёт за пальцем. Однажды пошла — обратно уже не встаёт. */
  get leading(): boolean {
    return this.led;
  }

  /**
   * Тап ли это сейчас. Считается на момент вопроса, а не запоминается: палец,
   * забытый на экране, перестаёт быть тапом сам, даже если новых `pointermove`
   * больше не пришло.
   */
  isTap(now: number): boolean {
    if (this.dragged) return false;
    return now - this.t <= TAP_MS;
  }
}

/**
 * Разбор жеста на холсте: сколько пальцев лежит, был ли тап и едет ли камера.
 *
 * Один на деревню и на карту. **Камерой оба холста правят сами, но команду
 * «поехали» берут здесь** (`panning`): у диорамы перспективная камера и
 * панорама по земле, у карты плоское аффинное преобразование, свести их в один
 * модуль значило бы переписать одно через другое. А вот решение «это ведение
 * или ещё тап» обязано быть одно — иначе получаются два судьи, и второй (у
 * деревни им был `OrbitControls`, начинавший панораму с первого же пикселя)
 * успевает сдвинуть картинку раньше, чем первый вынес приговор.
 *
 * Правило одно и без исключений: **тап бывает только одним пальцем**. Второй
 * палец на экране — это щипок или поворот, и тапа в этом жесте больше не будет
 * ни у одного из пальцев, даже если второй тут же сняли. Иначе мигнувшее
 * касание посреди ведения открывало бы то, что оказалось под первым пальцем, —
 * так и было в деревне до этого класса.
 */
export class Gesture {
  private press: Press | null = null;
  private live = new Set<number>();

  /** Сколько пальцев лежит на холсте. */
  get fingers(): number {
    return this.live.size;
  }

  /** Жест многопальцевый: щипок или поворот, но не тап. */
  get multi(): boolean {
    return this.live.size > 1;
  }

  /** Где палец лёг — туда и целились. null, если тапа в этом жесте уже нет. */
  get origin(): { x: number; y: number } | null {
    return this.press ? { x: this.press.x, y: this.press.y } : null;
  }

  /** Нажатие целиком — журналу касаний, больше никому. */
  get current(): Press | null {
    return this.press;
  }

  /**
   * Должна ли камера ехать за пальцем прямо сейчас.
   *
   * Три случая, и все три означают одно: тапа в этом жесте уже не выйдет либо
   * палец прошёл порог, за которым стоять на месте странно. Пока ответ `false`,
   * картинка не двигается ни на пиксель — именно этого не хватало деревне.
   */
  panning(now: number): boolean {
    const p = this.press;
    return p === null || p.leading || !p.isTap(now);
  }

  down(id: number, x: number, y: number, now: number): void {
    this.live.add(id);
    this.press = this.live.size === 1 ? new Press(id, x, y, now) : null;
  }

  move(id: number, x: number, y: number, now: number): void {
    if (this.press?.id === id) this.press.move(x, y, now);
  }

  /** Палец снят. `true` — это был тап. */
  up(id: number, now: number): boolean {
    this.live.delete(id);
    const p = this.press;
    if (!p || p.id !== id) return false;
    this.press = null;
    return p.isTap(now);
  }

  /** Жест отменил браузер: тапом он уже не станет. */
  cancel(id: number): void {
    this.live.delete(id);
    if (this.press?.id === id) this.press = null;
  }
}
