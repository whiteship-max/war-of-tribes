// Вой волка — единственный звук в игре, которого нет файлом.
//
// **Он синтезируется, и это решение, а не заглушка.** Музыка приезжает
// дорожками, потому что музыку не синтезируют; вой же — одна нота с глиссандо
// под фильтром, то есть ровно то, что Web Audio делает даром: горстка узлов
// (`HowlVoice` ниже) против сорока килобайт mp3, которые пришлось бы качать посреди ночи,
// когда волки уже вышли. Дорожка тут стоила бы дороже самого воя.
//
// МАШИНКА И ГРАФ ЛЕЖАТ ЗДЕСЬ, А НЕ В `web.ts`, И ЭТО ПРО ВЕС. Всё, что
// импортирует `web.ts`, едет в первую загрузку: его зовёт деревня. Вой нужен
// только предыстории — значит, и его код обязан ехать её чанком. Первой версией
// граф стоял в `web.ts`, и первая загрузка выросла на полкилобайта; заметила это
// опись сборки, а не глаз. Контекст при этом по-прежнему один на всю игру и
// создаётся по-прежнему в `web.ts`: сюда оттуда приходит только выход с
// громкостью (`openBus`), а узлы на нём вешаются здесь. Импортирует этот файл
// только предыстория — это тест (`howl.test.ts`).
//
// ЛЕНИВАЯ ЗАГРУЗКА ЗДЕСЬ НЕ НАРУШАЕТ ПРАВИЛА «машинки нельзя грузить через
// `import()`», и сказать это надо, чтобы правило не «починили». Правило стоит на
// том, что `await` в обработчике жеста теряет активацию. Здесь `await` нет нигде:
// код приезжает вместе с экраном поляны, **до** первого касания, а касание зовёт
// `wolfHowl.arm()` синхронно. Нельзя другое — тянуть этот модуль `import()` из
// самого обработчика нажатия.
//
// ЧЕСТНОЕ МЕСТО ПОД ФАЙЛ — ИНТЕРФЕЙС `HowlHost`, И ДРУГОГО НЕ НУЖНО. Он знает
// одно слово, `howl(seed)`. Окажется синтез непохожим на ухо — меняется **только
// хозяин** (`HowlVoice` ниже): вместо графа узлов он качает и проигрывает файл, а
// машинка, правило «через общий переключатель» и все места вызова остаются как
// есть. Заготовки под загрузку здесь нет нарочно: заготовка, которой никто не
// пользуется, — это обещание, которое некому проверить.
//
// ПЕРЕКЛЮЧАТЕЛЬ ОБЩИЙ, И ВТОРОГО НЕТ. Тот же `soundOn`, что у деревни и боя, тот
// же «по умолчанию выключено», та же дверь в настройках. Выключили звук — вой
// замолкает на следующем же вызове: машинка спрашивает настройку каждый раз, и
// отдельной команды «замолчи» ей не нужно.
import { soundOn } from './settings';
import { openBus } from './web';

/** Что вою нужно от среды. Ровно два слова, и оба про жест и про звук. */
export interface HowlHost {
  /** Открыть звук. Зовётся ТОЛЬКО из жеста игрока. `false` — звука тут нет. */
  open(): boolean;
  /** Провыть один раз. `seed` разводит два воя подряд, чтобы они не были копией. */
  howl(seed: number): void;
}

/**
 * Вой.
 *
 * Машинка ничего не помнит, кроме того, был ли жест: у воя нет ни очереди, ни
 * слоёв, ни петли — он случается и кончается. Поэтому и правил всего два, зато
 * оба обязательные: без жеста молчит, при выключенном звуке молчит и **ничего
 * не открывает**.
 */
export class WolfHowl {
  private armed = false;

  constructor(
    private host: HowlHost,
    private enabled: () => boolean = soundOn,
  ) {}

  /**
   * Жест был — можно открывать звук.
   *
   * Идемпотентно: контекст один на все жесты. При выключенном звуке не делает
   * ничего и не открывает контекста — это то же правило, что у деревни, и
   * проверяется оно счётчиком, а не обещанием.
   */
  arm(): void {
    if (this.armed || !this.enabled()) return;
    if (!this.host.open()) return;
    this.armed = true;
  }

  /** Провыть. Молча, если звук выключен или жеста ещё не было. */
  howl(seed: number): void {
    if (!this.armed || !this.enabled()) return;
    this.host.howl(seed);
  }

  /** Открыт ли звук — тесту. */
  get ready(): boolean {
    return this.armed;
  }
}

/**
 * Громкость воя.
 *
 * Громче деревни и тише боя: вой — не фон и не зрелище, а предупреждение, и
 * услышать его надо с первого раза. Полная громкость при этом ни к чему: волки
 * далеко, и близкий вой читался бы волком за спиной.
 */
const HOWL_VOLUME = 0.5;

/**
 * Вой волка: синтез, а не дорожка.
 *
 * ЧТО ИМЕННО ЗДЕСЬ СИНТЕЗИРУЕТСЯ, СКАЗАНО ЧИСЛАМИ, ЧТОБЫ ЭТО МОЖНО БЫЛО
 * ПОПРАВИТЬ НА СЛУХ, А НЕ ПЕРЕПИСЫВАТЬ.
 *
 *   две «пилы»    расстроенные на восемь тысячных: одна пила — это гудок, две
 *                 бьются друг о друга и дают живой, дышащий тон;
 *   глиссандо     от 320–370 Гц (разброс по сиду) вверх на треть за четыре
 *                 десятых секунды, стойка, и спуск на пятую часть ниже начала.
 *                 Вой — это подъём и долгий спуск; ровная нота читается
 *                 сиреной, а не зверем;
 *   вибрато       5.5 Гц на полтора процента высоты — дрожь голоса. Без него
 *                 подъём звучит электроорганом;
 *   фильтр        полосовой, ползёт 620 → 1500 → 800 Гц: это подобие
 *                 голосового тракта, и именно он делает из пилы голос;
 *   конверт       набор чуть больше четверти секунды, стойка до середины, спад
 *                 — всего две с половиной секунды. Резкий набор дал бы лай.
 *
 * ЧЕГО Я НЕ МОГУ ОБЕЩАТЬ: что это похоже. Синтез слышен только ухом, а ухом
 * никто из нас его пока не проверял. Числа выше — это рецепт, а не приговор:
 * если на слух выйдет гудок, крутить надо их, а не архитектуру; а если гудок
 * останется гудком, этот класс меняется на загрузку файла целиком.
 */
class HowlVoice implements HowlHost {
  private out: GainNode | null = null;

  open(): boolean {
    if (!this.out) this.out = openBus(HOWL_VOLUME);
    return this.out !== null;
  }

  howl(seed: number): void {
    const out = this.out;
    if (!out) return;
    // Узлы вешаются на контекст выхода: создан он в `web.ts`, и второго нет.
    const ctx = out.context;
    const t = ctx.currentTime;
    // Разброс от сида, а не от случайности: два воя подряд не должны быть
    // копией друг друга, но и «каждый раз новый зверь» ни к чему.
    const k = (((seed % 100) + 100) % 100) / 100;
    const base = 320 + k * 50;
    const top = base * 1.36;
    const life = 2.3 + k * 0.5;

    const amp = ctx.createGain();
    amp.gain.setValueAtTime(0.0001, t);
    amp.gain.exponentialRampToValueAtTime(1, t + 0.28);
    amp.gain.setValueAtTime(1, t + life * 0.55);
    amp.gain.exponentialRampToValueAtTime(0.0001, t + life);
    amp.connect(out);

    // Полосовой фильтр — тот самый «голос»: он ползёт вверх на подъёме и
    // опускается вместе с тоном.
    const throat = ctx.createBiquadFilter();
    throat.type = 'bandpass';
    throat.Q.value = 3.2;
    throat.frequency.setValueAtTime(620, t);
    throat.frequency.linearRampToValueAtTime(1500, t + 0.5);
    throat.frequency.linearRampToValueAtTime(800, t + life);
    throat.connect(amp);

    // Вибрато одно на оба голоса: дрожит зверь, а не половина его гортани.
    const shake = ctx.createOscillator();
    shake.frequency.value = 5.5;
    const shakeDepth = ctx.createGain();
    shakeDepth.gain.value = base * 0.015;
    shake.connect(shakeDepth);

    const voices: OscillatorNode[] = [];
    for (const detune of [1, 1.008]) {
      const osc = ctx.createOscillator();
      osc.type = 'sawtooth';
      osc.frequency.setValueAtTime(base * detune, t);
      osc.frequency.linearRampToValueAtTime(top * detune, t + 0.4);
      osc.frequency.setValueAtTime(top * detune, t + life * 0.5);
      osc.frequency.linearRampToValueAtTime(base * 0.78 * detune, t + life);
      shakeDepth.connect(osc.frequency);
      const level = ctx.createGain();
      level.gain.value = 0.5;
      osc.connect(level);
      level.connect(throat);
      voices.push(osc);
    }

    shake.start(t);
    for (const osc of voices) osc.start(t);
    shake.stop(t + life + 0.1);
    for (const osc of voices) osc.stop(t + life + 0.1);
  }
}

/**
 * Вой на всю игру. Заводится жестом игрока на поляне предыстории, как деревня —
 * первым нажатием в интерфейсе. Выключенный звук не открывает контекста вовсе.
 */
export const wolfHowl = new WolfHowl(new HowlVoice(), soundOn);
