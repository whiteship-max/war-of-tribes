/**
 * Коды: инструмент проверки, а не секрет.
 *
 * ЧТО ЭТО ТАКОЕ И ЧЕМ НЕ ЯВЛЯЕТСЯ. Игра длинная: до полного склада, до дружины,
 * до достроенного дома в предыстории и до её финала идти часами. Проверять
 * дальний кусок, каждый раз доигрывая до него руками, нельзя — значит, до него
 * нужна дверь. Эта дверь открыта **любому**, у кого есть адрес игры: код лежит в
 * бандле обычной строкой, и найти его — дело одного поиска по исходнику
 * страницы. Поэтому здесь не написано «защита», «пароль» и «секретный»:
 * притворяться, что строка в бандле что-то запирает, значило бы врать себе.
 * Запирает его ровно одно — `CHEATS_ON` ниже, и запирает по-настоящему, потому
 * что выключенного кода в сборке нет вовсе.
 *
 * ЛЕЖИТ ОН ВНЕ `game/`, `world/` И `prologue/` НАРОЧНО — по той же причине, по
 * какой вне них живут `gestures.ts`, `debug.ts` и `gestlog.ts`: режимов два,
 * деревня и поляна, а правило одно, и второй его копии быть не должно. Модуль
 * чистый: ни DOM, ни React, ни состояния, ни часов. Что именно код делает с
 * состоянием, знают две отдельные двери — `game/sim/cheat.ts` для деревни и
 * `prologue/cheat.ts` для поляны: состояния у них разные, и общего кода там нет
 * ни строки.
 *
 * АЛМАЗОВ КОД НЕ ДАЁТ И ДАТЬ НЕ МОЖЕТ. Правило «клиент не умеет начислять себе
 * алмазы» держится не обещанием, а замком по всему `src` (`game/sim/gems.test.ts`),
 * и коды под него попали сами, без единой строки исключения. Проверено: замок
 * ловит и вызов начисления, и правку поля, и ключ в литерале, и запись мимо
 * сохранения. Десятым обходом код не стал — он стал десятым файлом под замком.
 *
 * ПАРТИЯ, ГДЕ КОД ПРИМЕНЯЛИ, ПОМЕЧАЕТСЯ НАВСЕГДА. Поле в сохранении и видимая
 * строка — в летописи деревни и в служебном разделе, в родословной поляны.
 * Причина не в честности перед игроком (он сам это и нажал), а в том, что через
 * месяц накрученную партию примут за настоящую и сделают из неё вывод о балансе:
 * «посёлок дошёл до потолка за сорок минут». Метка снимает этот вопрос до того,
 * как он возникнет, и снять её нечем, кроме новой партии.
 */

/**
 * Включены ли коды. **Это и есть то одно действие, которым их снимают.**
 *
 * Поставить `false` — и кнопки нет ни в деревне, ни на поляне, а введённый код
 * не значит ничего: `cheatOf` возвращает `null` раньше всех проверок. Больше
 * трогать нечего и нигде — ни разметки, ни стилей, ни сохранения. Метка на уже
 * помеченной партии при этом остаётся: она о том, что было, а не о том, что
 * можно.
 */
export const CHEATS_ON = false;

/** Где код работает. Деревня и поляна — разные игры с разным состоянием. */
export type CheatWhere = 'village' | 'prologue';

/** Какой это код. Имя, по которому его узнают обе двери. */
export type CheatId = 'tribe' | 'glade' | 'home' | 'energy';

export interface Cheat {
  id: CheatId;
  /** Что набирают в поле. Строчными латиницей: она есть на любой клавиатуре. */
  code: string;
  where: CheatWhere;
  /** Что он даёт — теми же словами, какими об этом скажут игроку. */
  what: string;
  /**
   * Только вне Telegram: там, где прогресс не уходит на сервер (стенд, браузер без входа через Telegram). В Telegram
   * кода нет, даже с поднятым выключателем, — бесконечные игры дали бы бесконечные запасы настоящей партии.
   */
  offTelegram?: true;
}

/**
 * Все коды игры.
 *
 * ЧЕТЫРЕ, И КАЖДЫЙ ОТКРЫВАЕТ СВОЙ КУСОК ИГРЫ ОДНИМ НАЖАТИЕМ — это и есть мерка, по
 * которой их отбирали. Четвёртый, `energy`, завёлся ровно тогда, когда появился
 * кусок, до которого тремя не дойти: энергия промыслов идёт настоящими сутками,
 * скорость проверки её не ускоряет, и пятая игра за сутки без кода невозможна
 * (решение владельца 04.10.2026: код — только вне Telegram, `offTelegram`).
 *
 * Почему в поляне их два. Запас в руках и достроенный дом — разные вещи: первый
 * нужен, чтобы проверять огонь, охоту и зиму, второй — чтобы проверять род и
 * финал. Один код на оба давал бы проверяющему то, чего он не просил, и после
 * него нельзя было бы посмотреть, как выглядит поляна без дома.
 */
