/**
 * Через сколько после последнего бревна к огню выходит первая.
 *
 * Двадцать секунд: достроивший успевает оглядеть дом, и выходит она при нём, а
 * не где-то между заходами. От опушки (`glade.GUEST_FROM`) до очага она ещё
 * идёт своим шагом (`scene.MATE_WALK`).
 */
export const GUEST_FIRST_MS = 20_000;

/**
 * Через сколько после отказа приходит следующая.
 *
 * Сутки поляны (`SKY_MS`). Меньше — и отказ становится перебором имён;
 * больше — и отказавший заходит несколько раз подряд к пустому огню, то есть
 * отказ превращается в наказание, а его здесь быть не должно. Сутки поляны —
 * «на другой день к огню вышла другая», и дождаться её можно, не выходя из игры.
 */
export const GUEST_GAP_MS = SKY_MS;

/**
 * Что знает о роде правило прихода.
 *
 * Маленький тип, а не всё сохранение: приходу незачем знать про очаг и колчан.
 * Сохранение подходит под него целиком — поля названы так же.
 */
export interface Hearthside {
  house: number;
  builtAt: number;
  refused: number;
  refusedAt: number;
  wife: Person | null;
}

/**
 * В какую минуту к огню выходит гостья. `Infinity` — не выйдет.
 *
 * Не выходит, пока дом не достроен: звать некуда. Не выходит, если в доме жена:
 * рода второй женой не множат. Отказ сдвигает следующую на `GUEST_GAP_MS` от
 * своей минуты — и больше ничего не меняет, сколько бы их ни было.
 */
export const guestAt = (k: Hearthside): number => {
  if (k.wife || k.house < HOUSE_LOGS) return Infinity;
  return k.refused > 0 ? k.refusedAt + GUEST_GAP_MS : k.builtAt + GUEST_FIRST_MS;
};

/** Ждёт ли у огня гостья прямо сейчас. */
export const guestHere = (k: Hearthside, now: number): boolean => now >= guestAt(k);

/** Кто она — по числу отказов до неё. */
export const guestOf = (refused: number): Guest => {
  const n = GUESTS.length;
  return GUESTS[((Math.floor(refused) % n) + n) % n];
};

