// ---------- Любовь ----------

/** Одно дело общей жизни: сколько дней засчитано и в какие сутки поляны последний раз. */
export interface Tally {
  n: number;
  /** Номер суток поляны (`dayOf`), когда дело засчитано последний раз. −1 — ни разу. */
  day: number;
}

/**
 * Из чего растёт любовь — четыре дела, и ни одно не заменяет остальные.
 *
 *   meal   разделённая еда: отдал ей кусок мяса;
 *   hug    объятие;
 *   night  ночь, пережитая вместе: ночь застала человека дома — у огня или под
 *          крышей, — пока она там;
 *   wood   достроенное вместе. Дом стоит, строить больше нечего, а очаг держат
 *          вдвоём: он носит дрова, она их бережёт. Засчитывается полено,
 *          положенное в общий очаг.
 */
export interface Bond {
  meal: Tally;
  hug: Tally;
  night: Tally;
  wood: Tally;
}

export type BondKind = keyof Bond;

export const BOND_KINDS: readonly BondKind[] = ['meal', 'hug', 'night', 'wood'];

export const newTally = (): Tally => ({ n: 0, day: -1 });

export const newBond = (): Bond => ({ meal: newTally(), hug: newTally(), night: newTally(), wood: newTally() });

/** Номер суток поляны. Сутки поляны — тот же круг, что у неба (`sky.SKY_MS`). */
export const dayOf = (now: number): number => Math.floor(now / SKY_MS);

/**
 * Засчитается ли дело сейчас: в эти сутки поляны его ещё не было.
 *
 * Часы, переведённые назад, не засчитывают заново: сутки меньше записанных — это
 * «уже было», а не «новый день».
 */
export const counts = (t: Tally, now: number): boolean => dayOf(now) > t.day;

/** Засчитать дело. В те же сутки второй раз не засчитывается — возвращается то же. */
export const tally = (t: Tally, now: number): Tally => (counts(t, now) ? { n: t.n + 1, day: dayOf(now) } : t);

/**
 * Сколько любви даёт один засчитанный день одного дела.
 *
 * РАСЧЁТ, А НЕ ВКУС. До ста — двадцать засчитанных дней (100 / 5). Каждое дело
 * засчитывается раз в сутки поляны (`SKY_MS`), и за одни сутки
 * их не больше четырёх. Заход длится три-пять минут и почти всегда задевает двое
 * суток поляны — начинается в одних, кончается в следующих, — поэтому самый
 * старательный заход даёт до восьми дней (сорок), а обычный, где каждое дело
 * сделано по разу и ночь застала дома, — четыре (двадцать). Отсюда путь до ста:
 * **не меньше трёх заходов, обычно пять.**
 */
export const LOVE_STEP = 5;

/**
 * Сколько дней одного дела идёт в счёт.
 *
 * Семь — одно дело даёт не больше `LOVE_DAYS × LOVE_STEP`, и из-за этого любовь
 * растёт «не от одного мяса»: два дела вместе до `LOVE_FULL` не дотягивают, нужны
 * хотя бы три. Это тест, а не пожелание.
 */
export const LOVE_DAYS = 7;

export const LOVE_FULL = 100;

/**
 * Сколько любви.
 *
 * ЧИСТАЯ ФУНКЦИЯ ОТ НАКОПЛЕННОГО, А НЕ ОТ КАДРОВ И НЕ ОТ ЧАСОВ. Времени у неё в
 * аргументах нет вовсе: одни и те же засчитанные дни дают одну и ту же любовь,
 * когда бы их ни засчитали и сколько бы раз ни спросили. Копится не любовь, а
 * дни общей жизни (`tally`), и двигают их только события — дело сделано, ночь
 * застала дома. Шкала не тает от отлучки: жена ждёт, а не забывает.
 */
export const love = (b: Bond): number =>
  Math.min(
    LOVE_FULL,
    BOND_KINDS.reduce((sum, k) => sum + Math.min(Math.max(0, Math.floor(b[k].n)), LOVE_DAYS) * LOVE_STEP, 0),
  );

/** Дошла ли любовь до `LOVE_FULL`. */
export const loveFull = (b: Bond): boolean => love(b) >= LOVE_FULL;

// ---------- Имя сына ----------

/** Короче двух букв имени не бывает. */
export const HEIR_MIN = 2;

/**
 * Длиннее — не имя, а строка.
 *
 * Шестнадцать: самые длинные имена эпохи — Святополк, Всеволод, Ярополк — в
 * девять букв, «Жан-Поль» с дефисом в восемь. И шестнадцать заведомо влезает
 * туда, куда это имя поедет потом: имя вождя в профиле деревни держит больше
 * (`profile/identity.NAME_MAX`).
 */
export const HEIR_MAX = 16;

/** Ответ на введённое: имя, приведённое к виду, или причина отказа. */
export interface Named {
  /** Пусто, если имя не принято. */
  name: string;
  /** Почему не принято. Пусто, если принято. */
  why: string;
}

const CYRILLIC = /^[а-яё]+$/i;
const LATIN = /^[a-z]+$/i;
const VOWELS = /[аеёиоуыэюяaeiouy]/i;
/** Пять согласных подряд — не имя, а пальцы по клавиатуре. */
const CONSONANTS = /[бвгджзйклмнпрстфхцчшщъьbcdfghjklmnpqrstvwxz]{5}/i;

const refuse = (why: string): Named => ({ name: '', why });

/** Каждая часть имени — с большой буквы, остальное строчными. */
const capital = (text: string): string =>
  text.toLowerCase().replace(/(^|[ -])(\p{L})/gu, (_, sep: string, ch: string) => sep + ch.toUpperCase());

/**
 * Принять имя сына — или сказать, почему нет.
 *
 * ПРАВИЛО «ПУСТОЕ И МУСОР НЕ ПРИНИМАЮТСЯ» ЗДЕСЬ И ТОЛЬКО ЗДЕСЬ. Кнопка гаснет по
 * нему же и говорит причину, сцена записывает только то, что оно пропустило.
 *
 *   пусто и пробелы         «Впиши имя»;
 *   цифры, знаки, эмодзи    «Только буквы»;
 *   три части и больше,     «Одно имя, можно через дефис» — «Жан-Поль» и
 *   висящий дефис           «Олег Вещий» проходят;
 *   короче `HEIR_MIN`,      по длине;
 *   длиннее `HEIR_MAX`
 *   смесь алфавитов,        «Кириллицей или латиницей» — «Ivaн» не имя, а
 *   иные письменности       ошибка раскладки;
 *   без гласных, три одних  «Так имя не звучит» — ловит «ффф», «ааа» и «кпрст».
 *   буквы подряд, пять
 *   согласных подряд
 *
 * Мусор ловится разумно, а не наверняка: «фывапр» пройдёт. Угадывать настоящие
 * имена игра не берётся — назвать сына так игрок волен.
 *
 * Принятое приводится к виду: пробелы схлопнуты, каждая часть с большой буквы.
 */
export function heirName(raw: string): Named {
  const text = String(raw ?? '')
    .normalize('NFC')
    .replace(/\s+/g, ' ')
    .trim();
  if (text === '') return refuse('Впиши имя');
  if (/[^\p{L} -]/u.test(text)) return refuse('Только буквы');
  const parts = text.split(/[ -]/);
  if (parts.length > 2 || parts.some((p) => p === '')) return refuse('Одно имя, можно через дефис');
  const letters = parts.join('');
  if ([...text].length > HEIR_MAX) return refuse(`Не длиннее ${HEIR_MAX} букв`);
  if ([...letters].length < HEIR_MIN) return refuse(`Не короче ${count(HEIR_MIN, 'буквы', 'букв', 'букв')}`);
  if (!CYRILLIC.test(letters) && !LATIN.test(letters)) return refuse('Кириллицей или латиницей');
  if (!VOWELS.test(letters) || /(.)\1\1/i.test(letters) || CONSONANTS.test(letters)) return refuse('Так имя не звучит');
  return { name: capital(text), why: '' };
}

// ---------- Родословная ----------

/** Строка родословной. */
export interface KinLine {
  who: 'you' | 'wife' | 'son';
  name: string;
  note: string;
}

/**
 * Родословная — ровно то, что есть, и ни строкой больше.
 *
 * Три ступени, и между ними нет заготовок: до жены — один человек на пустой
 * странице; жена — две строки; сын — три. Пустых мест «под жену» и «под сына»
 * страница не держит: пустая строка обещала бы то, чего игрок ещё не сделал, и
 * читалась бы подсказкой, а не родом. Древа на поколения нет и не будет.
 */
export function lineage(wife: Person | null, heir: Person | null): KinLine[] {
  const out: KinLine[] = [{ who: 'you', name: 'Ты', note: 'хозяин дома у огня' }];
  if (wife) {
    const from = GUESTS.find((g) => g.name === wife.name)?.kin;
    out.push({ who: 'wife', name: wife.name, note: from ? `жена · ${from}` : 'жена' });
  }
  if (heir) out.push({ who: 'son', name: heir.name, note: 'сын' });
  return out;
}

