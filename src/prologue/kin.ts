/** Что знает о роде жена, когда говорит. */
export interface Household {
  wife: Person | null;
  heir: Person | null;
  bond: Bond;
}

/**
 * Что жена говорит, когда к ней подходят.
 *
 * Слова — из того же, что считает игра, а не заготовка на все случаи: погас
 * огонь — так и говорит, дошла любовь — говорит о сыне.
 */
export function wifeSays(k: Household, h: Hearth, now: number): string {
  if (k.heir) return `${k.heir.name} спит. Огонь я берегу.`;
  if (loveFull(k.bond)) return 'Скоро у нас будет сын. Как назовём?';
  if (!burning(h, now)) return 'Огонь погас, дров не осталось. Принеси, я сберегу.';
  return 'Огонь берегу. Принесёшь дров, хватит надолго.';
}

/**
 * С какой отлучки жена встречает словами.
 *
 * Двадцать минут: вернувшийся через минуту никуда не уходил, и встречать его
 * было бы странно, а тот, кого не было полчаса, должен узнать, что стало с огнём.
 */
export const GREET_AWAY_MS = 20 * 60_000;

/**
 * Первая строка при входе на поляну.
 *
 * Это и есть «встречает»: жена говорит, что стало с огнём, пока человека не было,
 * — тем же сроком, что называет полоса. Пуста строка, когда сказать нечего: вход
 * без отлучки или у огня никого.
 */
export function welcome(k: Household & Hearthside, h: Hearth, now: number, awayMs: number): string {
  if (!k.wife) return guestHere(k, now) ? 'У огня ждёт женщина.' : '';
  if (awayMs < GREET_AWAY_MS) return '';
  const who = k.wife.name;
  if (!k.heir && loveFull(k.bond)) return `${who} ждала тебя. Ей надо что-то сказать.`;
  if (!burning(h, now)) return `${who}: «Дрова кончились, огонь погас. Принеси, разожжём».`;
  return `${who}: «Огонь я сберегла. Дров ещё на ${burnWords(h, now)}».`;
}
