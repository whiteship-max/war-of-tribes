/**
 * Вид поляны числами: ступени качества, их выбор, сторож плавности, экспозиция,
 * дымка по часу и цвет солнца по толще воздуха.
 *
 * ЗДЕСЬ НЕТ НИ THREE, НИ ЧАСОВ, И ЭТО НАРОЧНО. Всё, что решает, как выглядит и во
 * что обходится кадр, — чистые функции от чисел, которые им подают: сцена
 * (`scene.ts`) приносит час, погоду и длительность кадра, конвейер (`post.ts`)
 * берёт ответ. Поэтому правила вида держит тест, а не снимок: снимок покажет, что
 * красиво, но не скажет, почему ступень опустилась.
 *
 * ГЛАВНОЕ ОГРАНИЧЕНИЕ — ПЛАВНОСТЬ НА ТЕЛЕФОНЕ, А НЕ ВЕС (решение владельца). Цель —
 * тридцать кадров в секунду на среднем телефоне; красивый кадр, который дёргается,
 * считается провалом. Отсюда две вещи. Ступень выбирается по тому, что умеет
 * устройство, а не по угадыванию его имени (`startTier`). И выбор этот проверяется
 * кадрами на самом устройстве: не держит тридцати — ступень опускается сама
 * (`Steady`), и ниже нижней, `base`, опускаться некуда: это прежний кадр поляны
 * без постобработки, ровно тот, что был до этой пачки.
 */

/**
 * Ступени качества, от дорогой к дешёвой.
 *
 *   full  настольный браузер: сцена в цель половинной точности со сглаживанием,
 *         затенение складок, объёмная дымка, лучи сквозь кроны, свечение, глубина
 *         резкости, виньетка, зерно, мягкие тени по всей поляне и от стены леса;
 *   lite  телефон: та же дымка, лучи, свечение и тень стены леса, но дешевле — без
 *         затенения складок, глубины резкости и мягких теней, лучи и свечение на
 *         четверти экрана, сглаживание проходом (FXAA), а не выборками;
 *   base  пол: прежний кадр поляны без постобработки — сцена прямо в канву, туман
 *         материалов. Тонирование и свет у неё те же, что у двух других.
 */
export type Tier = 'full' | 'lite' | 'base';

/** Порядок ступеней: сторож опускает по нему, и только вниз. */
export const TIERS: readonly Tier[] = ['full', 'lite', 'base'];

/** Что умеет устройство — то, по чему выбирается первая ступень. */
export interface Caps {
  /**
   * Рисует ли видеокарта в цель половинной точности (`EXT_color_buffer_float` или
   * `EXT_color_buffer_half_float`). Без этого не на чем держать свет ярче белого —
   * а на нём стоит и свечение, и тонирование, — и ступень одна: `base`.
   */
  hdr: boolean;
  /**
   * Главный указатель — палец (`(pointer: coarse)`). Это и есть граница «телефон или
   * настольный», которую провёл владелец, и спрашивается она у браузера, а не
   * угадывается по строке устройства: строка врёт, указатель — нет.
   */
  coarse: boolean;
}

/**
 * С какой ступени начать.
 *
 * `stored` — на чём сторож остановился в прошлый раз на этом устройстве: телефон,
 * однажды не удержавший `lite`, не должен дёргаться две секунды на каждом входе,
 * пока сторож опускает его снова. `asked` — ступень из адреса (`?look=`), для
 * проверки глазами; она сильнее всего, кроме того, чего устройство не умеет вовсе.
 */
export function startTier(caps: Caps, stored: Tier | null = null, asked: Tier | null = null): Tier {
  if (!caps.hdr) return 'base';
  if (asked) return asked;
  const can: Tier = caps.coarse ? 'lite' : 'full';
  if (stored && TIERS.indexOf(stored) > TIERS.indexOf(can)) return stored;
  return can;
}

/** Ступень из строки — адреса или записи; чужое слово — не ступень. */
export const tierOf = (s: string | null | undefined): Tier | null =>
  s === 'full' || s === 'lite' || s === 'base' ? s : null;

/** Ступень ниже этой; у пола ниже нет. */
export const lower = (t: Tier): Tier | null => TIERS[TIERS.indexOf(t) + 1] ?? null;

/**
 * Где устройство помнит, на чём остановился сторож, и сколько.
 *
 * Свой ключ, а не запись поляны: запись — про игру и переживает переустановку, а это
 * про видеокарту одного телефона. И не навсегда: телефон, опустившийся однажды из-за
 * жары или фоновой задачи, через неделю проверяется заново — иначе одна плохая минута
 * запирала бы его на нижней ступени до переустановки.
 */
export const LOOK_KEY = 'tribe.prologue.look';
export const LOOK_KEEP_MS = 7 * 24 * 3_600_000;

/** Что помнит устройство — ступень, если запись цела и не старше недели. */
export function storedTier(raw: string | null, now: number): Tier | null {
  try {
    const o = JSON.parse(raw ?? 'null') as { tier?: unknown; at?: unknown } | null;
    if (!o || typeof o.at !== 'number' || now < o.at || now - o.at > LOOK_KEEP_MS) return null;
    return tierOf(typeof o.tier === 'string' ? o.tier : null);
  } catch {
    return null;
  }
}

/** Запись для `LOOK_KEY`. */
export const storeTier = (tier: Tier, now: number): string => JSON.stringify({ tier, at: now });

/**
 * Сторож плавности: сколько кадров он пропускает после смены ступени, какое окно
 * меряет и что считает провалом.
 *
 * ПОРОГИ ВЫВЕДЕНЫ ИЗ ЦЕЛИ «ТРИДЦАТЬ», А НЕ ПОДОБРАНЫ.
 *   `SLOW_MS` — кадр дольше этого ниже тридцати в секунду с запасом на дрожь
 *     часов: 1000 / 30 = 33.3 мс, и экран в шестьдесят герц выдаёт кадры ровно по
 *     16.7 или 33.3 мс. Телефон в режиме экономии держит ровно тридцать — медиана
 *     33.3, — и это не провал, поэтому порог выше: 36 мс.
 *   `SLOW_SHARE` — доля медленных кадров в окне, при которой картинка уже дёргается:
 *     каждый пятый кадр под тридцатью виден глазом как рывок.
 *   `WINDOW_MS` — окно в две секунды: меньше — сторож дёргается от одной сборки
 *     мусора, больше — игрок успевает увидеть дёрганье.
 *   `WARM_FRAMES` — после смены ступени первые кадры — компиляция шейдеров и новые
 *     цели, а не цена ступени.
 *   `GAP_MS` — промежуток длиннее этого — не кадр, а пауза: вкладка в фоне, сборка
 *     мусора, открытая клавиатура. Судить по нему ступень нельзя.
 */
export const SLOW_MS = 36;
export const SLOW_SHARE = 0.2;
export const WINDOW_MS = 2000;
export const WARM_FRAMES = 45;
export const GAP_MS = 250;

/**
 * Сторож плавности.
 *
 * Кормится длительностью каждого кадра и отвечает, не пора ли опустить ступень. Кадров
 * он не считает сам и часов не читает: время приносит сцена (`performance.now()` живёт
 * только там — тест). Опускает только вниз и только по одному шагу за окно: вверх он не
 * ходит нарочно — ступень, прыгающая туда и обратно, дёргает картинку сильнее, чем
 * любая из двух.
 */
export class Steady {
  private warm = WARM_FRAMES;
  private spent = 0;
  private slow = 0;
  private count = 0;

  constructor(public tier: Tier) {}

  /** Длительность очередного кадра, мс. Вернёт новую ступень, если эту пора опустить. */
  feed(ms: number): Tier | null {
    if (ms > GAP_MS || ms <= 0) return null;
    if (this.warm > 0) {
      this.warm--;
      return null;
    }
    this.spent += ms;
    this.count++;
    if (ms > SLOW_MS) this.slow++;
    if (this.spent < WINDOW_MS) return null;
    const failing = this.slow / this.count >= SLOW_SHARE;
    this.spent = 0;
    this.slow = 0;
    this.count = 0;
    if (!failing) return null;
    const next = lower(this.tier);
    if (!next) return null;
    this.set(next);
    return next;
  }

  /** Сменить ступень руками (стенд, адрес): окно начинается заново, прогрев тоже. */
  set(tier: Tier): void {
    this.tier = tier;
    this.warm = WARM_FRAMES;
    this.spent = 0;
    this.slow = 0;
    this.count = 0;
  }
}

// ---------- Свет ----------

const DEG = Math.PI / 180;

/**
 * Толща воздуха до солнца на этой высоте, в толщах над зенитом (Kasten–Young, 1989).
 *
 * Отсюда и «низкое солнце тусклее и теплее»: свет идёт к земле сквозь воздух, и на
 * двадцати градусах воздуха втрое больше, чем в зените. Прежде это было правило по
 * месту — «×0.7 у горизонта»; теперь это одна формула на силу и на цвет.
 */
export function airMass(elev: number): number {
  const e = Math.max(elev, -2 * DEG);
  const deg = e / DEG;
  return 1 / (Math.sin(e) + 0.50572 * Math.pow(deg + 6.07995, -1.6364));
}

/**
 * Оптическая толща зимнего ясного воздуха по трём каналам.
 *
 * Синее рассеивается сильнее красного (Рэлей, ∝ λ⁻⁴), дымка — почти поровну; сумма
 * подобрана под чистый зимний воздух, где полуденное солнце почти белое, а на десяти
 * градусах — оранжевое. Каналы — те же линейные R, G, B, в которых считает three.
 */
export const OPTICAL_DEPTH: readonly [number, number, number] = [0.1, 0.16, 0.3];

/**
 * Пропускание воздуха по трём каналам на этой высоте солнца — доля полуденного.
 *
 * Делится на полуденное (`noonElev`) затем, чтобы полдень остался тем светом, под
 * который подобрана палитра, а утро и вечер — отличались от него ровно на воздух.
 */
export function sunTransmit(elev: number, noonElev: number, out: [number, number, number]): [number, number, number] {
  const m = airMass(elev);
  const m0 = airMass(noonElev);
  for (let i = 0; i < 3; i++) out[i] = Math.exp(-OPTICAL_DEPTH[i] * (m - m0));
  return out;
}

/**
 * Экспозиция: во сколько раз камера открывает затвор при этой освещённости против
 * полуденной.
 *
 * Глаз привыкает к темноте, но не до конца — ночь обязана остаться ночью. Отсюда
 * степень `ADAPT` меньше единицы: вдвое темнее — открыть не вдвое, а в 2^0.6. И
 * потолок `EXPOSE_MAX`: в глухую ночь без огня камера не вытягивает лес до сумерек.
 */
export const ADAPT = 0.5;
export const EXPOSE_MAX = 3.2;

export function exposure(light: number, noonLight: number): number {
  const k = Math.pow(noonLight / Math.max(1e-3, light), ADAPT);
  return Math.min(EXPOSE_MAX, Math.max(1, k));
}

/**
 * Освещённость кадра одним числом — то, к чему привыкает глаз.
 *
 * Солнце — по его высоте (на горизонтальную землю), небо — целиком, огонь — у лица
 * женщины у очага (`FIRE_ANCHOR`): ночью глаз привыкает к огню, а не к луне, и
 * поляна у костра не выгорает от того, что кругом темно.
 */
export function sceneLight(sunLux: number, sunUp: number, skyLux: number, fireLux: number): number {
  return sunLux * Math.max(0, sunUp) + skyLux + fireLux / (FIRE_ANCHOR * FIRE_ANCHOR);
}

/**
 * Числа вида, подобранные снимками кадра-мерила (`npm run prologue:stand`, `LOOK=`), а не
 * выведенные: это решение глаза, и держит его снимок, а не тест.
 *
 *   `EXPOSE_BASE` — затвор полудня. ACES в three делит на 0.6 (`toneMapping`), и при
 *     единице полдень выходил бы на две трети светлее того, под который подобрана
 *     палитра;
 *   `SUN_GLARE` — во сколько раз диск солнца ярче белого: из этого запаса растёт
 *     свечение, а тонирование сжимает сам диск обратно в белый;
 *   `SKY_GAIN` — купол в цели половинной точности: небо над кромкой леса обязано быть
 *     светлее снега под солнцем, иначе ACES серит его в картон;
 *   `HAZE_GAIN` — насколько светится дымка сама, без солнца: цвет неба над лесом;
 *   `SNOW_BOUNCE` — какая доля света на снегу возвращается снизу — на стволы, на
 *     исподы крон, на руки. Снег отдаёт четыре пятых; в поляне он вытоптан и в тени
 *     крон, отсюда меньше.
 */
export const EXPOSE_BASE = 0.46;
export const SUN_GLARE = 9;
export const SKY_GAIN = 0.9;
export const HAZE_GAIN = 0.6;
export const SNOW_BOUNCE = 0.15;
/**
 * Во сколько раз пламя ярче белого на ступенях с конвейером: как и у солнца, из этого
 * запаса растёт свечение, а тонирование сводит само пламя к жёлто-белому ядру.
 */
export const FIRE_GLARE = 3.5;
/** Насколько дымка светится в сторону солнца (ореол Ми): доля света солнца. */
export const MIE = 0.35;

/**
 * Дымка у земли по часу и погоде: плотность у самой земли (на метр пути) и высота, за
 * которую она редеет в e раз.
 *
 * УТРО ТУМАННОЕ, И ЭТО НЕ КРАСОТА, А ЗИМА. Ясной ночью земля остывает, воздух у неё
 * садится в дымку, и к полудню солнце её съедает; к вечеру она поднимается снова, но
 * жиже. Поэтому у дымки свой ход по кругу солнца: густая на рассвете, редкая в
 * полдень, в сумерки — средняя. Непогода (`gloom`) добавляет своё: в дождь и снег
 * видно хуже в любой час.
 *
 * Числа — через дальность видимости: плотность ρ даёт видимость около 3 / ρ метров.
 * Утром у самой земли — меньше сотни метров, и дальняя стена леса тонет, а на высоте
 * глаз дымка вдвое реже; в полдень — сотни метров, и лес виден насквозь; в ненастье —
 * полсотни.
 */
export interface Mist {
  /** Плотность у земли, на метр пути. */
  density: number;
  /** За сколько метров высоты плотность падает в e раз. */
  height: number;
}

const MIST_KEYS: readonly { at: number; density: number; height: number }[] = [
  { at: 0, density: 0.03, height: 2.4 },
  { at: 0.08, density: 0.026, height: 2.8 },
  { at: 0.2, density: 0.008, height: 7 },
  { at: 0.38, density: 0.008, height: 7 },
  { at: 0.5, density: 0.016, height: 4 },
  { at: 0.62, density: 0.014, height: 5 },
  { at: 0.9, density: 0.02, height: 4 },
  { at: 1, density: 0.03, height: 2.4 },
];

/** Плотность дымки в ненастье: к ней тянется любой час, насколько хмуро (`sky.gloom`). */
const MIST_WET = 0.06;

const smooth = (t: number): number => {
  const k = t < 0 ? 0 : t > 1 ? 1 : t;
  return k * k * (3 - 2 * k);
};

export function mistAt(solar: number, gloom: number, out: Mist): Mist {
  const s = ((solar % 1) + 1) % 1;
  let i = 0;
  while (i + 2 < MIST_KEYS.length && MIST_KEYS[i + 1].at <= s) i++;
  const a = MIST_KEYS[i];
  const b = MIST_KEYS[i + 1];
  const k = smooth((s - a.at) / (b.at - a.at));
  const d = a.density + (b.density - a.density) * k;
  const h = a.height + (b.height - a.height) * k;
  const g = Math.max(0, Math.min(1, gloom));
  out.density = d + (MIST_WET - d) * g;
  out.height = h + g * 3;
  return out;
}

// ---------- Огонь ----------

/**
 * Во сколько раз огонь днём слабее ночного — доля от ночной силы.
 *
 * Костёр днём светит так же, как ночью, — но рядом с солнцем его не видно: в полдень на
 * снег падает в сотню раз больше света. Прежний отсвет днём был третью ночного, и при
 * спаде 1.25 это терялось; при физическом спаде тот же огонь в полдень красил снег у
 * ног в рыжее — на снимке это читалось закатом посреди дня. Ночная сила не тронута.
 */
export const FIRE_DAY = 0.12;

/**
 * Огонь светит по закону обратных квадратов — спадом 2, как любой точечный свет.
 *
 * Прежний спад 1.25 был выбран затем, чтобы стволы в семи метрах не пропадали в
 * черноте (docs/prologue.md, раздел 14). Физический спад эту задачу решает иначе:
 * у огня светлее, вдали темнее, а видимость вдали держит экспозиция и тонирование,
 * которое не даёт выгореть тому, что у самого огня. Сила пересчитана так, чтобы на
 * `FIRE_ANCHOR` метрах — у лица женщины у очага — свет остался прежним; ближе он
 * ярче, дальше слабее, и так и должно быть у костра.
 */
export const FIRE_DECAY = 2;
export const FIRE_ANCHOR = 3;

/** Во сколько раз поднять силу огня при переходе с прежнего спада на физический. */
export function fireGain(oldDecay: number, oldRange: number): number {
  const d = FIRE_ANCHOR;
  const win = Math.pow(Math.max(0, 1 - Math.pow(d / oldRange, 4)), 2);
  return (Math.pow(d, -oldDecay) * win) / Math.pow(d, -FIRE_DECAY);
}
