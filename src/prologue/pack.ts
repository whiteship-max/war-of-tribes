/**
 * Вещи: что у человека есть — ровно то, что есть.
 *
 * ОКНО, А НЕ ВТОРАЯ ПАНЕЛЬ ДЕЙСТВИЙ. Всё, что делают с поляной, делается там же,
 * где делалось: тапом у того, к чему подошёл, и луком. Из вещей не применяется
 * ничего — кроме еды, и причина одна: у еды своя дверь (`act.meal`), и жила она
 * на счётчике мяса. Счётчики в руках ушли сюда — два места, показывающие одно и
 * то же, у нас всегда расходились, — и дверь еды переехала вместе со своим
 * счётчиком. Одежду не снимают, топор не бросают: таких дел в режиме нет.
 *
 * СПИСОК ВЫВОДИТСЯ ИЗ ЗАПИСИ, А НЕ ВЕДЁТСЯ РЯДОМ. Второго счёта вещей нет и быть
 * не должно: окно показывает поля сохранения, и разойтись им не с чем. Чего нет
 * — того в списке нет, пустых строк «на вырост» тоже: они обещали бы то, чего у
 * человека нет. Порядок постоянный — орудия, стрелы, еда, дрова и шкуры, одежда:
 * вещь не прыгает по окну оттого, что у соседки кончился счёт.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов.
 */
import type { PrologueSave } from './save';

export type ItemId = 'axe' | 'bow' | 'arrows' | 'cooked' | 'raw' | 'logs' | 'hides' | 'coat';

export interface Item {
  id: ItemId;
  /** Как вещь называется в окне. */
  name: string;
  /** Сколько. У вещей в одном числе — единица. */
  count: number;
  /** Пишется ли число: топор, лук и одежда бывают в одном числе, и «×1» у них — шум. */
  counted: boolean;
  /** Надето ли. Надевается одно — одежда. */
  worn: boolean;
  /** Строка к вещи: где остальное. Пусто — сказать нечего. */
  note: string;
}

/** Что у человека есть — в постоянном порядке, без пустых. */
export function pack(s: PrologueSave): Item[] {
  const out: Item[] = [];
  const add = (id: ItemId, name: string, count: number, counted: boolean, worn = false, note = ''): void => {
    if (count > 0) out.push({ id, name, count, counted, worn, note });
  };
  add('axe', 'Топор', s.axe ? 1 : 0, false);
  add('bow', 'Лук', s.kit ? 1 : 0, false);
  // Воткнувшиеся в землю — не в колчане, но и не пропали: сказать, где они, честнее,
  // чем молча показать меньше.
  add('arrows', 'Стрелы', s.quiver, true, false, s.arrows.length > 0 ? `ещё ${s.arrows.length} в траве` : '');
  add('cooked', 'Жареное мясо', s.meat.cooked, true);
  add('raw', 'Сырое мясо', s.meat.raw, true);
  add('logs', 'Дрова', s.logs, true);
  add('hides', 'Шкура', s.hides, true);
  add('coat', 'Одежда из шкуры', s.body.coat ? 1 : 0, false, true);
  return out;
}

/** Список одной строкой — сравнивать его сцене надо по значению, как и всё остальное. */
export const packKey = (items: readonly Item[]): string =>
  items.map((i) => `${i.id}:${i.count}:${i.worn ? 1 : 0}:${i.note}`).join('|');
