/**
 * Сколько всего длится последняя сцена после ответа игрока, миллисекунды.
 *
 * Считается из тех же чисел, что и сами такты: срок, переписанный руками,
 * разошёлся бы с ними при первой же правке.
 */
export const finaleMs = (fightMs: number): number =>
  fightMs + BEAT.aim + BEAT.loose + BEAT.fall + BEAT.take + BEAT.lead + BEAT.blind;

/** Какой такт идёт сейчас — по времени от ответа игрока. */
export type Beat = 'fight' | 'aim' | 'loose' | 'fall' | 'take' | 'lead' | 'blind' | 'over';

/**
 * Что происходит на `ms` от ответа игрока, если драка длилась `fightMs`.
 *
 * Чистая функция от двух чисел: сцена спрашивает её каждый кадр и ничего не
 * помнит. `fightMs` — не константа, потому что драка кончается раньше, когда
 * игрок положил всех троих: ждать ещё десять секунд у тел было бы нелепо.
 */
export function beatOf(ms: number, fightMs: number): Beat {
  let t = fightMs;
  if (ms < t) return 'fight';
  t += BEAT.aim;
  if (ms < t) return 'aim';
  t += BEAT.loose;
  if (ms < t) return 'loose';
  t += BEAT.fall;
  if (ms < t) return 'fall';
  t += BEAT.take;
  if (ms < t) return 'take';
  t += BEAT.lead;
  if (ms < t) return 'lead';
  t += BEAT.blind;
  return ms < t ? 'blind' : 'over';
}

/** Начало такта `b` при драке длиной `fightMs` — сцене, чтобы считать доли внутри такта. */
export function beatFrom(b: Beat, fightMs: number): number {
  const order: Beat[] = ['fight', 'aim', 'loose', 'fall', 'take', 'lead', 'blind'];
  const span: Record<string, number> = {
    fight: fightMs,
    aim: BEAT.aim,
    loose: BEAT.loose,
    fall: BEAT.fall,
    take: BEAT.take,
    lead: BEAT.lead,
    blind: BEAT.blind,
  };
  let t = 0;
  for (const k of order) {
    if (k === b) return t;
    t += span[k];
  }
  return t;
}

