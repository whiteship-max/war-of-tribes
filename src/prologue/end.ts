/**
 * На какой ступени финал.
 *
 *   none    финала нет: идёт обычная поляна;
 *   passed  чёрный экран и «Прошло много дней…» — ждёт касания;
 *   family  у огня жена и сын: подложить дров и накормить обоих;
 *   build   новый дом сыну: пять досок;
 *   raid    пришли пятеро. Отсюда и до конца игрок смотрит;
 *   over    предыстория кончена.
 */
export type EndStage = 'none' | 'passed' | 'family' | 'build' | 'raid' | 'over';

/** Что помнит финал между заходами. Ступень и сделанное — и больше ничего. */
export interface EndState {
  stage: EndStage;
  /** Подложены ли дрова в общий очаг. */
  wood: boolean;
  /** Накормлена ли жена. */
  wife: boolean;
  /** Накормлен ли сын. */
  son: boolean;
  /** Сколько досок легло в новый дом. */
  boards: number;
}

export const newEnd = (): EndState => ({ stage: 'none', wood: false, wife: false, son: false, boards: 0 });

