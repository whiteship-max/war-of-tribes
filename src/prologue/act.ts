/**
 * Что сделает действие и почему оно сейчас нельзя.
 *
 * Чистый модуль, отдельный от сцены нарочно: правило «что произойдёт по тапу»
 * и его объяснение словами — это не три.js, а игра, и проверять его надо
 * тестом, а не пальцем на телефоне.
 *
 * ПРАВИЛО ОДНО, И ОНО ТО ЖЕ, ЧТО У ВСЕЙ ИГРЫ: **кнопка, которая не сработает,
 * гаснет и говорит причину.** В деревне так устроены стройка, ковка, наём и
 * письма (`ui/parts/Cost.tsx`); здесь платить нечем, кроме дров и мяса, но
 * правило от этого не меняется — проваливающихся нажатий не бывает, и «ничего
 * не произошло» игрок читать не должен.
 *
 * ДВЕРЕЙ ЧЕТЫРЕ, И ОНИ РАЗВЕДЕНЫ НАРОЧНО.
 *
 *   `offer`  — тап и большая кнопка внизу: **не целится**, а бьёт по
 *              ближайшему в досягаемости. Так взяли топор, свалили дерево,
 *              положили дрова, срезали мясо, подобрали стрелу и отбились
 *              топором от волка — тот единственный зверь, который подошёл сам.
 *              Ремесло — той же дверью: бревно в дом, шкура с туши, одежда у
 *              палатки, стрелы у колоды;
 *   `bow`    — своя кнопка: натянуть и пустить. **Целится**, и летит стрела
 *              туда, куда смотрят;
 *   `meal`   — своя кнопка у мяса в вещах: поесть можно где угодно и когда
 *              угодно, подходить не к чему;
 *   `talk`   — карточка разговора с женщиной у огня: принять или отказать,
 *              дать мясо, обнять, назвать сына. Открывает её первая дверь —
 *              подошёл и тапнул, — а дела в ней свои, и цены у них свои
 *              (`share`). Своя дверь нужна потому, что это не «сделай с тем, к
 *              чему подошёл», а выбор между несколькими делами сразу.
 *
 * Смешивать первую со второй нельзя ни в какую сторону. Тап по зверю не
 * работает, потому что зверь не подпускает; выстрел «по ближайшему» не работает,
 * потому что тогда лук перестанет быть луком и станет второй кнопкой действия.
 * Это записано и здесь, и в `glade.SpotKind`, и проверено тестом.
 */
import { HEARTH_CAP, fuelAt } from './fire';
import { HEAL_MS, STARVE_MS, WOLF_BITES, causeOfDeath, type Death } from './body';
import { TREE_LOGS, type GladeState, type Spot } from './glade';
import { carcassLeft, hideLeft, liveCarcass, type Pt } from './hunt';
import { ARROWS_PER_LOG, COAT_HIDES, HOUSE_LOGS, carveRoom } from './craft';
import { LOVE_DAYS, counts, loveFull } from './kin';
import { BOARDS, TASK_BUILD, TASK_SON, TASK_WIFE, TASK_WOOD, endOn, frameDone, type EndState } from './end';
import type { PrologueSave } from './save';

/**
 * Что именно делает действие. `null` — делать нечего.
 *
 * Один список на все четыре двери, а не четыре коротких: сцена выполняет их
 * одним разбором, и разведи их по типам — появился бы ещё один способ что-то
 * сделать, о котором забыли бы при первой правке.
 */
export type Deed =
  | 'take-axe'
  | 'take-kit'
  | 'chop'
  | 'feed'
  | 'roast'
  | 'butcher'
  | 'take-arrow'
  | 'fight'
  | 'build'
  | 'skin'
  | 'sew'
  | 'carve'
  | 'draw'
  | 'shoot'
  | 'eat'
  | 'talk'
  | 'kin'
  | 'accept'
  | 'refuse'
  | 'share'
  | 'hug'
  | 'name'
  | 'board'
  | 'fight-foe'
  | 'feed-son'
  | null;

export interface Offer {
  deed: Deed;
  /** Слово на кнопке и в подсказке. */
  label: string;
  /** Сработает ли. */
  can: boolean;
  /** Почему нельзя — пусто, если можно. */
  why: string;
}

const NOTHING: Offer = { deed: null, label: 'Осмотрись', can: false, why: 'Подойди ближе' };

const ok = (deed: Deed, label: string): Offer => ({ deed, label, can: true, why: '' });
const no = (deed: Deed, label: string, why: string): Offer => ({ deed, label, can: false, why });

/**
 * Сколько полена сгорает на один кусок мяса.
 *
 * Полполена — половина `fire.LOG_HOURS` горения; полный олень (`hunt.DEER_MEAT`
 * кусков) стоит столько полен, сколько даёт дерево (`glade.TREE_LOGS`), то есть
 * **ровно одного дерева**. Это и есть цена огня как кухни, и
 * она названа числом нарочно: без неё жарка была бы бесплатной, а «есть сырым»
 * — решением без второй стороны.
 */
export const ROAST_COST = 0.5;

/** Ниже какого голода еда живот не наполняет: час на полосе сытости (`STARVE_MS`). */
const FULL_ENOUGH = 3_600_000 / STARVE_MS;

/**
 * Ниже какого урона еда здоровья не прибавляет: час заживания в покое, в укусах.
 * Та же мерка, что у сытости: меньше — ноль на полосе.
 */
const HURT_ENOUGH = (WOLF_BITES * 3_600_000) / HEAL_MS;

/**
 * Что предлагает игроку то, рядом с чем он стоит.
 *
 * `spot` выбирает поляна по досягаемости (`glade.nearest`), а не палец: тап
 * здесь не целится (почему — в `controls.ts`).
 */
export function offer(s: PrologueSave, spot: Spot | null, now: number): Offer {
  if (!spot) return NOTHING;
  if (spot.kind === 'axe') {
    if (!s.axe) return ok('take-axe', 'Взять топор');
    // Колода с взятым топором — место, где строгают стрелы. Дело у неё одно, и
    // погашенная надпись говорит, чего для него не хватает.
    if (!s.kit) return no(null, 'Строгать стрелы', 'Лука нет');
    if (!carveRoom(s.quiver)) return no('carve', 'Строгать стрелы', 'Колчан полон');
    if (s.logs <= 0) return no('carve', 'Строгать стрелы', 'Нужно полено');
    return ok('carve', `Строгать стрелы +${ARROWS_PER_LOG}`);
  }
  if (spot.kind === 'tent') {
    if (!s.kit) return ok('take-kit', 'Взять лук');
    // Палатка — место, где шьют. Целью тапа она становится, только когда шить
    // есть из чего (`reach`), но правило здесь полное: `offer` не знает, откуда
    // его позвали.
    if (s.body.coat) return no(null, 'Сшить одежду', 'Одежда уже сшита');
    if (s.hides < COAT_HIDES) return no('sew', 'Сшить одежду', 'Нужна шкура оленя');
    return ok('sew', 'Сшить одежду');
  }
  /*
   * Дом. Стройка идёт той же дверью, что дрова в очаг: тап кладёт в стену все
   * поленья, какие влезают, — шесть тапов по одному и тому же были бы работой,
   * а не решением. Без топора сруб не рубят; без дров класть нечего — и кнопка
   * говорит, сколько уже стоит, чтобы цель была видна с первого подхода.
   */
  if (spot.kind === 'house') {
    // Достроенный дом — то место, где записан род: тап по нему открывает
    // родословную. Делать с ним больше нечего, и погашенная «Дом стоит» была бы
    // кнопкой, которая ничего не значит.
    if (s.house >= HOUSE_LOGS) return ok('kin', 'Родословная');
    const label = `Ставить дом ${s.house}/${HOUSE_LOGS}`;
    if (!s.axe) return no('build', label, 'Нужен топор');
    if (s.logs <= 0) return no('build', label, 'Нужны дрова');
    return ok('build', label);
  }
  if (spot.kind === 'arrow') {
    return ok('take-arrow', 'Взять стрелу');
  }
  /*
   * Дом сына — последнее дело человека (`end.ts`). Доски лежат у сруба, носить
   * их не надо, и потому гасить кнопку нечем: пока дом не готов, она кладёт
   * доску; готов — цели тапа у него больше нет вовсе (`reach`).
   */
  if (spot.kind === 'frame') {
    return ok('board', `${TASK_BUILD} ${Math.min(BOARDS, s.end.boards)}/${BOARDS}`);
  }
  /*
   * Пришедшие из леса. Та же дверь и то же правило, что у волка: они подошли
   * сами, и «сделай с тем, к чему подошёл» — это удар топором. Без топора
   * кнопка говорит правду, и правда здесь та же неприятная: отбиваться нечем.
   */
  if (spot.kind === 'foe') {
    return s.axe ? ok('fight-foe', 'Отбиться') : no('fight-foe', 'Отбиться', 'Нужен топор');
  }
  // Сын. Дверь разговора, как у матери: что сказать, решается уже в карточке.
  if (spot.kind === 'son') return ok('talk', 'Говорить');
  /*
   * Волк. Единственная цель первой двери, которая подошла сама, — и потому
   * единственный зверь в этом списке (почему так, написано в `wolves.ts`).
   *
   * Без топора кнопка гаснет и говорит правду, а правда неприятная: отбиваться
   * нечем, и ответ один — уйти к огню. Врать тут нельзя ни в какую сторону:
   * «отбиться руками» было бы обещанием, которого игра не держит, а молчащая
   * кнопка — тем «ничего не произошло», которого в режиме не бывает.
   */
  if (spot.kind === 'wolf') {
    return s.axe ? ok('fight', 'Отбиться') : no('fight', 'Отбиться', 'Топора нет. Беги к огню');
  }
  /*
   * Женщина у огня. Подошёл — заговорил; что сказать, решается уже в разговоре
   * (`talk`), и гасить эту кнопку нечем: говорить можно всегда — и с гостьей, и
   * с женой, и мёртвому здесь ничего не предлагают по другой причине (сцена).
   */
  if (spot.kind === 'mate') return ok('talk', 'Говорить');
  if (spot.kind === 'carcass') {
    const left = carcassLeft(s.hunt, now);
    if (left > 0) return ok('butcher', `Срезать мясо ${left}`);
    // Мясо сперва, шкура потом: снимают её с разделанной туши, и так она не
    // заслоняет собой еду у того, кто пришёл за едой.
    if (!hideLeft(s.hunt, now)) return no(null, 'Срезать мясо', 'Туша пуста');
    // Шкура идёт на одну одежду и больше ни на что: лишняя висела бы в руках
    // счётчиком без дела. Туша с ненужной шкурой лежит свой срок и сходит сама —
    // следующий олень от неё не зависит (`hunt.deerLive`).
    if (s.body.coat) return no(null, 'Снять шкуру', 'Одежда уже сшита');
    if (s.hides >= COAT_HIDES) return no(null, 'Снять шкуру', 'Шкура есть. Шей у палатки');
    return ok('skin', 'Снять шкуру');
  }
  if (spot.kind === 'tree') {
    return s.axe ? ok('chop', 'Рубить') : no('chop', 'Рубить', 'Нужен топор');
  }
  /*
   * Костёр. Дел у него два, и порядок между ними не «жарка вперёд», а **что из
   * двух сейчас вообще возможно**.
   *
   * Соблазн написать «с сырым мясом в руках жарим, иначе кладём дрова» велик, и
   * он же заводит ловушку: у человека мясо и полено, а в очаге пусто — и кнопка
   * говорит «в костре нет дров», не давая их положить. Выйти из этого нечем:
   * бросить мясо игра не умеет, а костёр тем временем не разгорится сам.
   *
   * Поэтому сперва спрашивается, можно ли жарить **прямо сейчас**; нельзя —
   * пробуем дрова; и только если и дров нет, объясняем про жарку, за которой и
   * подошли.
   */
  const fuel = fuelAt(s.hearth, now);
  const roomForLogs = fuel < HEARTH_CAP - 0.001;
  /*
   * В финале очаг сперва просит дров, и это не догадка о желании игрока, а
   * задание, которое стоит у него на экране словами. Без этой строки жарка
   * сырого мяса — а оно у человека в руках почти всегда — отнимала бы нажатие у
   * единственного дела ступени, и «подложить дров» нельзя было бы выполнить.
   */
  if (!s.end.wood && s.end.stage === 'family' && s.logs > 0 && roomForLogs) return ok('feed', 'Подложить дров');
  if (s.meat.raw > 0 && fuel >= ROAST_COST) return ok('roast', `Пожарить мясо ${roastCount(s, now)}`);
  if (s.logs > 0 && roomForLogs) return ok('feed', 'Подложить дров');
  if (s.meat.raw > 0) {
    return no('roast', 'Пожарить мясо', fuel <= 0 ? 'Костёр погас' : 'Мало дров в костре');
  }
  if (s.logs <= 0) return no('feed', 'Подложить дров', 'Дров нет');
  return no('feed', 'Подложить дров', 'Костёр полон');
}

/**
 * Сколько кусков костёр вправду прожарит: сколько несут и на сколько хватит дров.
 *
 * Жарит **всё, что может**, а не по куску за нажатие: шесть тапов по одному и
 * тому же костру — это не решение, а работа.
 */
export const roastCount = (s: PrologueSave, now: number): number =>
  Math.max(0, Math.min(s.meat.raw, Math.floor(fuelAt(s.hearth, now) / ROAST_COST)));

/**
 * Что предлагает лук.
 *
 * Два шага, а не удержание: тап натягивает, второй тап пускает. Между ними
 * можно целиться сколько угодно — и целиться при этом **вторым пальцем**, тем
 * самым, которым смотрят. Удержание отняло бы этот палец у взгляда, а других у
 * игрока нет.
 */
export function bow(s: PrologueSave, drawn: boolean): Offer {
  if (!s.kit) return no(null, 'Лук', 'Лука нет');
  if (drawn) return ok('shoot', 'Пустить');
  if (s.quiver <= 0) return no(null, 'Лук', 'Стрелы кончились');
  return ok('draw', 'Натянуть');
}

/**
 * Что предлагает кусок мяса.
 *
 * Мясо даёт две вещи — сытость и здоровье (`body.eat`), — и есть его нельзя
 * только тогда, когда оно не даст ни той, ни другой: на полный живот при полном
 * здоровье. Раненый ест и сытым — кусок уходит на здоровье, а сытость сверх
 * полной пропадает. Погасшая кнопка с причиной честнее, чем съеденный впустую
 * кусок оленя.
 *
 * `harm` — урон в укусах (`body.harmAt`).
 */
export function meal(s: PrologueSave, hunger: number, harm: number, raw: boolean): Offer {
  const have = raw ? s.meat.raw : s.meat.cooked;
  const label = raw ? 'Съесть сырым' : 'Съесть';
  if (have <= 0) return no('eat', label, raw ? 'Сырого мяса нет' : 'Жареного мяса нет');
  // На почти полный живот есть можно: съеденное сверх сытости пропадает, но
  // выбрасывать своё мясо — решение игрока. Запрещено только бессмысленное: меньше
  // часа голода и меньше часа заживания — это ноль на обеих полосах, и «съел, а
  // ничего не двинулось» читается поломкой.
  if (hunger < FULL_ENOUGH && harm < HURT_ENOUGH) return no('eat', label, 'Ты сыт и цел');
  return ok('eat', label);
}

/**
 * Что предлагает «Дать мясо» в разговоре с женой.
 *
 * Разделённая еда — одно из четырёх дел, из которых растёт любовь, и платится
 * она настоящим куском из запаса. Поэтому запрещено ровно бессмысленное — то же
 * правило, по которому нельзя есть на полный живот (`meal`): отдать кусок в
 * сутки, когда еда уже засчитана, или сверх того, что мясо вообще может дать
 * любви. Это был бы выброшенный запас, и кнопка говорит об этом до нажатия.
 *
 * Отдаётся сперва сырое: жареное — запас на отлучку, и отдавать его первым
 * значило бы урезать сутки, за которые игрок и так платит мясом.
 */
export function share(s: PrologueSave, now: number): Offer {
  const label = 'Дать мясо';
  if (!s.wife) return no(null, label, 'Некого угостить');
  if (s.meat.cooked + s.meat.raw <= 0) return no('share', label, 'Мяса нет');
  /*
   * В финале еда — задание ступени, а не дело общей жизни: любовь давно полна, и
   * все обычные запреты сказали бы «незачем» ровно там, где это единственное,
   * что игрока просят сделать. Поэтому ветка стоит **до** них, а не вместо: вне
   * финала правило прежнее до последней строки.
   */
  if (s.end.stage === 'family') {
    return s.end.wife ? no('share', label, 'Она уже поела') : ok('share', label);
  }
  if (loveFull(s.bond)) return no('share', label, 'Любовь полна');
  if (s.bond.meal.n >= LOVE_DAYS) return no('share', label, 'Одним мясом любви не прибавишь');
  if (!counts(s.bond.meal, now)) return no('share', label, 'Сегодня уже ели вместе');
  return ok('share', label);
}

/**
 * Что предлагает «Дать мясо» сыну.
 *
 * Своя функция, а не ветка в `share`: мать и сын — разные люди, и запреты у них
 * разные. У сына их ровно два — есть ли мясо и не ел ли он уже; шкалы общей
 * жизни у него нет и не будет (`docs/prologue.md`, чего нет).
 */
export function feedSon(s: PrologueSave): Offer {
  const label = 'Дать мясо';
  if (!s.heir) return no(null, label, 'Некого угостить');
  if (s.end.son) return no('feed-son', label, 'Он уже поел');
  if (s.meat.cooked + s.meat.raw <= 0) return no('feed-son', label, 'Мяса нет');
  return ok('feed-son', label);
}

/** Сколько полен даёт сваленное дерево — в одном месте с ценой действия. */
export const logsFromTree = (): number => TREE_LOGS;

/**
 * Что на поляне сейчас можно тронуть.
 *
 * Единственное место, где срок жизни туши превращается в «есть она или нет»:
 * геометрия про часы не знает, а помнить о них каждому вызову `nearest` нельзя —
 * забудет первый же.
 */
export const reach = (
  s: PrologueSave,
  now: number,
  wolves: readonly Pt[] = [],
  mate: Pt | null = null,
  son: Pt | null = null,
  foes: readonly Pt[] = [],
): GladeState => ({
  felled: s.felled,
  arrows: s.arrows,
  carcass: liveCarcass(s.hunt, now),
  // У палатки есть дело, только пока пожитки не разобраны или есть из чего шить.
  tent: !s.kit || (!s.body.coat && s.hides >= COAT_HIDES),
  // У дома дело есть всегда: пока строится — стройка, достроен — родословная.
  house: true,
  // Волки приезжают снаружи, из сцены: в записи их нет, и быть не может —
  // где они стоят, знает только кадр.
  wolves,
  // Женщина — тем же путём: есть ли она, решает род, где она — кадр.
  mate,
  // Сын и пришедшие — тоже от сцены, и по той же причине.
  son,
  foes,
  // Дом сына — цель тапа, только пока он строится: у готового дела нет.
  frame: s.end.stage === 'build' && !frameDone(s.end),
});

/**
 * Жив ли человек — и если нет, отчего умер.
 *
 * В ФИНАЛЕ НЕ УМИРАЮТ ОТ ГОЛОДА И ХОЛОДА, И ЭТО ПРАВИЛО, А НЕ ПОБЛАЖКА. Финал —
 * не партия, а последняя сцена: человек в ней делает три дела и кладёт доски
 * (`BOARDS`), и «замёрз, пока клал вторую» отняло бы у него не игру, а конец
 * истории. Умирает он в ней один раз и от стрелы, и смерть эта записана
 * тактами (`end.beatOf`), а не шкалой. Волки по той же причине в финал не
 * приходят вовсе (`scene.syncPack`).
 */
export const death = (s: PrologueSave, now: number): Death =>
  endOn(s.end) ? null : causeOfDeath(s.body, s.hearth, now);

/** Что показывает строка задания финала. Пусто — задания нет. */
export const endTask = (e: EndState): string => {
  if (e.stage === 'family') return !e.wood ? TASK_WOOD : !e.wife ? TASK_WIFE : !e.son ? TASK_SON : '';
  if (e.stage === 'build') return `${TASK_BUILD} ${Math.min(BOARDS, e.boards)}/${BOARDS}`;
  return '';
};
