/**
 * Ремесло: дом, одежда, стрелы. Три вещи — и больше не будет.
 *
 * СМЫСЛ ЛЕСТНИЦЫ — УМЕНЬШАТЬ ДАВЛЕНИЕ, А НЕ ДОБАВЛЯТЬ БЕГОТНЮ. Каждая вещь здесь
 * отвечает на одну из бед режима и снимает её часть:
 *
 *   дом      — непогоду и волков. Под крышей ночь и снег не студят сильнее, а
 *              волк за человеком не войдёт. Между заходами человек ночует в
 *              нём, и без огня живёт восемь холодовых часов погожей меркой, а
 *              не пять с половиной, как под открытым небом;
 *   одежда   — холод целиком: остывание идёт на `body.COAT_CHILL` медленнее
 *              где угодно — у дерева, в дождь, в доме;
 *   стрелы   — промах. Колчан не пустеет после трёх неудачных выстрелов, и
 *              за стрелами не надо ходить после каждого.
 *
 * Сколько это стоит беготни и что даёт взамен, посчитано в
 * `docs/prologue.md` и печатается отчётом. Коротко: одежда и стрелы беготни
 * не прибавляют вовсе, дом прибавляет её на три-четыре захода стройки и
 * отдаёт обратно тем, что ночь без огня перестаёт убивать.
 *
 * ДОМ — ЭТО ЕЩЁ И ЗАМЫСЕЛ, И СКАЗАТЬ ЭТО НАДО ЗДЕСЬ, У ЧИСЕЛ. Позже в дом будут
 * приходить спутники, и с них начнётся деревня: достроенный дом — первое место,
 * куда можно кого-то позвать. Сейчас спутников нет и заготовки под них нет
 * нарочно — заготовка, которой никто не пользуется, это обещание, которое
 * некому проверить. Есть только то, на чём они встанут: дом, который строится
 * постепенно и держит своё число брёвен.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов, ни случайности.
 */

const clamp = (v: number, lo: number, hi: number): number => (v < lo ? lo : v > hi ? hi : v);

/**
 * Сколько брёвен на дом.
 *
 * СОРОК ДВА — НЕ «КРАСИВО», А ТРИ С ПОЛОВИНОЙ ЗАХОДА, И ВОТ РАСЧЁТ. На поляне
 * семь деревьев по три полена — двадцать один за заход, если с прошлого прошло
 * полсуток и лес отрос (`glade.REGROW_MS`). Из них уходит на то, что и так надо
 * делать: около шести полен на очаг, чтобы уйти на сутки (`fire` с поправкой на
 * дождь), и три на жарку оленя. На дом остаётся около двенадцати. Сорок два на
 * двенадцать — три с половиной захода: дом цель, а не покупка.
 *
 * Меньше тридцати — дом ставится за два захода и перестаёт быть целью; больше
 * пятидесяти — пятый заход подряд без видимой награды, и на нём бросают.
 */
export const HOUSE_LOGS = 42;

/** Сколько ступеней видно глазом: от сруба до крыши. */
export const HOUSE_STAGES = 6;

/** Сколько брёвен на ступень. */
export const HOUSE_PER_STAGE = HOUSE_LOGS / HOUSE_STAGES;

/** Достроен ли дом. Укрытие даёт только достроенный: крыша без стен не крыша. */
export const houseDone = (logs: number): boolean => logs >= HOUSE_LOGS;

/** Какая ступень стоит: 0 — разметка, `HOUSE_STAGES` — дом под крышей. */
export const houseStage = (logs: number): number =>
  clamp(Math.floor(Math.max(0, logs) / HOUSE_PER_STAGE), 0, HOUSE_STAGES);

/**
 * Сколько брёвен из тех, что в руках, уйдёт в дом.
 *
 * Всё, что влезает, одним тапом, — по той же причине, по какой очаг принимает
 * все поленья разом и жарится всё мясо: шесть тапов по одному и тому же — это
 * не решение, а работа. Сверх нужного дом не берёт: лишнее остаётся в руках.
 * Дробных брёвен не бывает — полено либо легло в стену, либо нет.
 */
export const buildTake = (house: number, carried: number): number =>
  clamp(Math.floor(Math.min(Math.max(0, carried), HOUSE_LOGS - Math.max(0, house))), 0, HOUSE_LOGS);

/** Сколько шкур на одежду. Один олень — одна одежда: подсчитывать тут нечего. */
export const COAT_HIDES = 1;

/**
 * Сколько стрел выходит из полена.
 *
 * Две — и полено при этом уходит из очага: стрелы стоят огня, как жарка. Треть
 * дерева на пару стрел — это страховка от промаха, а не расход: стрелы и так
 * подбираются.
 */
export const ARROWS_PER_LOG = 2;

/**
 * Больше этого в колчане не держат.
 *
 * Без потолка строгание стало бы способом превратить лес в бесконечные стрелы, а
 * колчан — в счётчик, на который перестают смотреть. Восемь — вдвое больше
 * начального запаса: промахнуться можно семь раз, прежде чем идти подбирать.
 */
export const QUIVER_MAX = 8;

/** Сколько стрел можно выстрогать сейчас: не больше, чем влезет в колчан. */
export const carveRoom = (quiver: number): boolean => quiver + ARROWS_PER_LOG <= QUIVER_MAX;
