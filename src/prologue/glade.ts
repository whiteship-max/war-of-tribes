export const WARM_R = FIRE.r + REACH;

/** Греется ли человек, стоящий здесь. Про огонь это ничего не говорит — только про место. */
export const byFire = (x: number, z: number): boolean => Math.hypot(x - FIRE.x, z - FIRE.z) <= WARM_R;

