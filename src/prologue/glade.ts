export const EYE = 1.62;

/**
 * Угол обзора по вертикали — от формы экрана, градусы.
 *
 * НА ЭТО ЖАЛОВАЛИСЬ ТРИЖДЫ, И ПРИЧИНА В ФОРМЕ ЭКРАНА, А НЕ В ЧИСЛЕ. Угол у камеры
 * вертикальный, и на портрете 375×812 прежние 72° по вертикали оставляли по
 * горизонтали 37° — взгляд сквозь трубу: оглядываться приходилось на каждом
 * шаге. Теперь угол держит **горизонталь не уже `VIEW_H_MIN`**, а вертикаль
 * растёт ровно настолько, насколько для этого нужно. На широком экране прежние
 * 72° и так дают больше девяноста по горизонтали — там не меняется ничего.
 *
 * Прицел и тап угол не трогает, и это не надежда, а устройство. Тап бьёт по
 * ближайшему в досягаемости — метрами, а не пикселями (`nearest`); стрела летит
 * вдоль взгляда, а не в точку экрана (`hunt.arrowLanding`), и попадает по зверю в
 * метрах (`hunt.arrowHits`). Меняется одно — сколько пикселей занимает зверь: на
 * девяти метрах олень в полтора раза мельче. Угловой размер тот же, значит
 * навести на него тот же поворот пальца (`controls.LOOK_PER_PX` — в градусах).
 *
 * Потолок `VIEW_V_MAX` — против рыбьего глаза: выше него верх и низ экрана
 * тянутся так, что стволы у края кадра заваливаются наружу.
 */
export const VIEW_V_MIN = 72;
export const VIEW_H_MIN = 50;
export const VIEW_V_MAX = 96;

export const viewFov = (aspect: number): number => {
  const half = Math.tan((VIEW_H_MIN * Math.PI) / 360) / Math.max(0.1, aspect);
  const need = (Math.atan(half) * 360) / Math.PI;
  return Math.min(VIEW_V_MAX, Math.max(VIEW_V_MIN, need));
};

/** Горизонтальный угол при вертикальном `fov` и форме экрана, градусы. */
export const hFov = (fov: number, aspect: number): number =>
  (Math.atan(Math.tan((fov * Math.PI) / 360) * aspect) * 360) / Math.PI;

