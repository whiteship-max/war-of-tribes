export const CHOP_MS = 620;

/**
 * За сколько зарастает пепелище… то есть пень.
 *
 * Двенадцать часов настоящего времени, и считается это **на чтении**, ровно как
 * горение костра: в сохранении лежит минута, в которую дерево упало, а стоит
 * оно сейчас или нет — выводится формулой. Заведено не ради глубины, а чтобы
 * поляна не кончалась: семь пней и погасший костёр — это тупик, из которого
 * игрок не выйдет ничем, кроме «начать заново».
 */
export const REGROW_MS = 12 * 3_600_000;

/** Стоит ли дерево. `felledAt` — 0, если его не валили. */
export const standing = (felledAt: number, now: number): boolean =>
  felledAt <= 0 || now - felledAt >= REGROW_MS;

/**
 * Все преграды поляны при данном состоянии деревьев.
 *
 * Пень преградой не считается: через него перешагивают, и упираться в
 * невидимую тумбу посреди поляны игрок не должен.
 */
export function blockers(felled: readonly number[], now: number, house = false): Blocker[] {
  const out: Blocker[] = [
    { x: FIRE.x, z: FIRE.z, r: FIRE.r },
    { x: TENT.x, z: TENT.z, r: TENT.r },
    { x: AXE_STUMP.x, z: AXE_STUMP.z, r: AXE_STUMP.r },
  ];
  // Дом становится преградой с первого бревна: разметку переступают, сруб — нет.
  if (house) out.push({ x: HOUSE.x, z: HOUSE.z, r: HOUSE.r });
  TREES.forEach((t, i) => {
    if (standing(felled[i] ?? 0, now)) out.push({ x: t.x, z: t.z, r: TREE_R });
  });
  return out;
}

/**
 * Что лежит на поляне из того, до чего можно дотянуться.
 *
 * Отдельный маленький тип, а не всё сохранение целиком: поляна — про геометрию,
 * и знать ей про очаг, голод и колчан незачем. Туша сюда приходит **уже
 * отсеянной** (растащенная и протухшая — это `null`): срок её жизни — правило
 * охоты, а не геометрии, и живёт оно в `hunt.ts`. Собирает эту тройку `act.ts`,
 * в одном месте, чтобы «уже отсеянной» не приходилось помнить каждому.
 */
export interface GladeState {
  /** Когда свалено каждое дерево; 0 — стоит. */
  felled: readonly number[];
  /** Стрелы, воткнувшиеся в землю. */
  arrows: readonly { x: number; z: number }[];
  /** Туша, с которой ещё есть что взять. */
  carcass: { x: number; z: number } | null;
  /**
   * Есть ли у палатки дело: пожитки не разобраны или есть шкура на одежду.
   *
   * Палатка — цель тапа только тогда, когда тап что-то сделает. Иначе она
   * отнимала бы нажатие у костра рядом (он в двух шагах), а погашенная надпись
   * «пусто» у самого огня читалась бы помехой, а не подсказкой.
   */
  tent: boolean;
  /** Строится ли дом: пока не достроен, место стройки — цель тапа. */
  house: boolean;
  /**
   * Где стоят волки. Приезжает из сцены, а не из записи: их положение живёт во
   * времени кадров (`wolves.ts`). Пустой список — обычное дело.
   */
  wolves: readonly { x: number; z: number }[];
  /**
   * Где стоит женщина — гостья или жена. Тоже от сцены: идёт она кадрами.
   * Пусто — у огня никого (гостья ещё не пришла или ушла с отказом).
   */
  mate?: { x: number; z: number } | null;
}

/**
 * Что рядом с игроком — то и сделает тап.
 *
 * Выбирается **ближайшее в досягаемости**, а не то, что под пальцем: почему
 * именно так, написано в `controls.ts`. Меряется от края преграды, а не от её
 * середины: у дерева и у костра разная толщина, а «вплотную» должно значить
 * одно и то же.
 *
 * Порядок проверок ни на что не влияет — при равном расстоянии побеждает
 * первый, а равных расстояний на поляне не бывает. Стрела при этом — точка без
 * толщины: она лежит в траве, и подходить к ней надо вплотную.
 *
 * ВОЛК ИДЁТ ПЕРВЫМ, И ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ПОРЯДОК ЗНАЧИТ ХОТЬ ЧТО-ТО.
 * Он не «важнее» — он **подвижен**: волк, подошедший к человеку, стоящему у
 * костра, оказывается в досягаемости обоих, и при равном расстоянии тап должен
 * достаться зубам, а не дровам. Расстояния тут вправду сходятся, потому что
 * волк сам выбирает, куда встать.
 */
export function nearest(px: number, pz: number, w: GladeState, now: number): Spot | null {
  let best: Spot | null = null;
  let bestD = Infinity;
  const test = (kind: SpotKind, x: number, z: number, r: number, index: number): void => {
    const d = Math.hypot(px - x, pz - z) - r;
    // «При равном расстоянии побеждает первый» обязано переживать округление:
    // два края, равные на бумаге, в числах с плавающей точкой расходятся на
    // десятую долю нанометра, и порядок проверок перестал бы значить что-либо.
    if (d > REACH || d >= bestD - TIE) return;
    bestD = d;
    best = { kind, x, z, index };
  };
  w.wolves.forEach((v, i) => test('wolf', v.x, v.z, WOLF_R, i));
  // Сразу за волком и по той же причине: она подвижна и сама выбирает, где
  // встать, — при равном расстоянии тап достаётся ей, а не очагу за её спиной.
  if (w.mate) test('mate', w.mate.x, w.mate.z, MATE_R, -1);
  test('fire', FIRE.x, FIRE.z, FIRE.r, -1);
  test('axe', AXE_STUMP.x, AXE_STUMP.z, AXE_STUMP.r, -1);
  if (w.tent) test('tent', TENT.x, TENT.z, TENT.r, -1);
  if (w.house) test('house', HOUSE.x, HOUSE.z, HOUSE.r, -1);
  if (w.carcass) test('carcass', w.carcass.x, w.carcass.z, 0.55, -1);
  w.arrows.forEach((a, i) => test('arrow', a.x, a.z, 0, i));
  TREES.forEach((t, i) => {
    if (standing(w.felled[i] ?? 0, now)) test('tree', t.x, t.z, TREE_R, i);
  });
  return best;
}

/**
 * Подвинуть человека, не пустив его в преграды и за край поляны.
 *
 * Скольжение по кругу, а не остановка: упёршись в дерево под углом, игрок
 * должен его обойти, ведя палец в ту же сторону. Остановка насухо читается как
 * «застрял», и на телефоне это худшее, что может случиться с ходьбой.
 */
export function slide(x: number, z: number, blocks: readonly Blocker[]): { x: number; z: number } {
  let nx = x;
  let nz = z;
  for (const b of blocks) {
    const dx = nx - b.x;
    const dz = nz - b.z;
    const d = Math.hypot(dx, dz);
    const need = b.r + BODY_R;
    if (d >= need) continue;
    // Ровно в середине преграды направления нет — выталкиваем в любую сторону.
    if (d < 1e-4) {
      nx = b.x + need;
      continue;
    }
    nx = b.x + (dx / d) * need;
    nz = b.z + (dz / d) * need;
  }
  const r = Math.hypot(nx, nz);
  if (r > GLADE_R) {
    nx = (nx / r) * GLADE_R;
    nz = (nz / r) * GLADE_R;
  }
  return { x: nx, z: nz };
}

/** Толщина самого игрока: он не точка, иначе носом влезает в ствол. */
export const BODY_R = 0.35;

/** Насколько ближе должен быть следующий предмет, чтобы отнять тап у первого: на глаз — ничего. */
const TIE = 1e-9;

/**
 * Куда повернуть голову, чтобы смотреть из (x, z) на (tx, tz).
 *
 * Камера без поворота смотрит вдоль −Z, поэтому её направление при рыскании
 * `yaw` — это (−sin yaw, −cos yaw). Отсюда и знаки: перепутать их легко, а
 * ошибка видна только тем, что игрок при входе стоит спиной к делу.
 */
export const yawTo = (x: number, z: number, tx: number, tz: number): number =>
  Math.atan2(-(tx - x), -(tz - z));

/** Где игрок стоит, войдя в режим: у костра, лицом к пню с топором. */
export const START = {
  x: -0.4,
  z: 2.6,
  yaw: yawTo(-0.4, 2.6, AXE_STUMP.x, AXE_STUMP.z),
};
