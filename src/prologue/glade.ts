/**
 * Поляна: где что стоит и докуда можно дойти.
 *
 * Чистые числа, без three.js, — по той же причине, по какой отдельно живёт план
 * посёлка (`render/plan.ts`): место предмета на поляне это факт, который должно
 * быть видно в таблице и проверить тестом, а не разглядывать в сцене. Модели
 * ставит `scene.ts`, читая отсюда.
 *
 * Поляна маленькая нарочно. Весь первый кусок предыстории — три шага и один
 * вопрос: доходит ли палец туда, куда целился. Большой лес с тропинками
 * отвечал бы на другой вопрос и стоил бы кадров.
 */

/** Докуда можно уйти от костра. Дальше стена леса. */
export const GLADE_R = 13;

/** С какого расстояния предмет берётся тапом. Шаг с небольшим — «подойти вплотную». */
export const REACH = 2.1;

/**
 * Детерминированный разброс поляны: одно число из двух.
 *
 * Живёт здесь, а не в моделях, потому что по нему считают трое: расстановка
 * деревьев в лесу (`models.ts`), место оленя и смещение стрелы у туши
 * (`hunt.ts`). Второй такой же функции в папке быть не должно — две «случайности»
 * с разными хвостами дают два разных мира из одного числа.
 *
 * `Math.random` в предыстории нет нигде, и это тест: всё, что выглядит
 * случайным, выведено отсюда.
 */
export const hash = (a: number, b: number): number => {
  const s = Math.sin(a * 127.1 + b * 311.7) * 43758.5453;
  return s - Math.floor(s);
};

/** Рост игрока: откуда смотрит камера. */
export const EYE = 1.62;

/** Сколько метров в секунду проходит человек. Быстрый шаг, не бег. */
export const WALK_SPEED = 2.6;

/** Круг, в который нельзя войти: костёр, палатка, дерево. */
export interface Blocker {
  x: number;
  z: number;
  r: number;
}

/**
 * Что на поляне можно тронуть.
 *
 * ОЛЕНЯ В ЭТОМ СПИСКЕ НЕТ И БЫТЬ НЕ МОЖЕТ, и это не пропуск, а вся разница
 * между двумя способами дотянуться. Тап **не целится**: он бьёт по ближайшему в
 * досягаемости (`nearest`), то есть по тому, к чему подошли. Выстрел —
 * наоборот, целится и не требует подходить: он летит туда, куда смотрят
 * (`hunt.arrowLanding`). Зверь досягаемости не подпускает вовсе (`DEER_FLEE`
 * больше `REACH` вчетверо), поэтому достать его можно ровно одним способом — и
 * поэтому лук нужен.
 *
 * А ВОТ ВОЛК В СПИСКЕ ЕСТЬ, И ЭТО ТО ЖЕ ПРАВИЛО, А НЕ ИСКЛЮЧЕНИЕ ИЗ НЕГО. Он
 * **приходит сам**, и когда он в шаге, «сделай с тем, к чему подошёл» — это и
 * есть удар топором. Ничего не целится и здесь: если рядом два волка, топор
 * достаётся ближайшему, как достался бы ближайшему дереву.
 *
 * Он же — единственная цель тапа, которой нет в сохранении: где он стоит,
 * знает только кадр (`wolves.ts`, шапка), поэтому его положение приезжает в
 * `GladeState` снаружи, от сцены, а не выводится из записи.
 */
export type SpotKind = 'tree' | 'fire' | 'axe' | 'tent' | 'carcass' | 'arrow' | 'wolf';

export interface Spot {
  kind: SpotKind;
  x: number;
  z: number;
  /** Номер дерева в `felled` или стрелы в `arrows`; у остальных — −1. */
  index: number;
}

/** Костёр — в середине поляны, и всё остальное отсчитывается от него. */
export const FIRE = { x: 0, z: 0, r: 1.15 };

/**
 * Круг, в котором человек греется у огня.
 *
 * Не своё число, а сумма двух уже записанных: край очага плюс досягаемость.
 * Значит, **греются ровно там, где можно подложить дров**, — и объяснять это
 * игроку не нужно, он выучит это первым же действием. Заведи здесь отдельную
 * величину — и появится полоса шириной в полметра, где дрова кладутся, а тепла
 * нет, или наоборот; ни то, ни другое ничем не объяснимо.
 */
export const WARM_R = FIRE.r + REACH;

/** Греется ли человек, стоящий здесь. Про огонь это ничего не говорит — только про место. */
export const byFire = (x: number, z: number): boolean => Math.hypot(x - FIRE.x, z - FIRE.z) <= WARM_R;

/** Палатка: у костра, вход к огню. */
export const TENT = { x: -3.3, z: -2.5, r: 1.5, rot: Math.atan2(3.3, 2.5) };

/** Пень с топором: с другой стороны костра, чтобы первый шаг был шагом. */
export const AXE_STUMP = { x: 2.5, z: 2.2, r: 0.5 };

/**
 * Деревья, которые можно свалить.
 *
 * Семь, по кругу и на разном удалении: рубить надо доходя, а не поворачиваясь.
 * Числа записаны, а не считаются в цикле, — место дерева это факт, и в диффе
 * должно быть видно, какое именно переехало.
 */
export const TREES: readonly { x: number; z: number }[] = [
  { x: 6.6, z: -3.4 },
  { x: 3.1, z: -7.2 },
  { x: -2.6, z: -8.1 },
  { x: -7.4, z: -4.2 },
  { x: -8.2, z: 2.6 },
  { x: -4.1, z: 7.3 },
  { x: 4.6, z: 6.4 },
];

/**
 * Круг вокруг дерева, в который не войти, — и от его края же считается
 * досягаемость.
 *
 * Метр, а не толщина ствола (полметра): подойдя вплотную к бревну в обхват,
 * игрок утыкается носом в кору и видит одну коричневую стену. Это не
 * придирка к виду — рубить, не видя дерева, нельзя. Лишние полметра ставят его
 * там, откуда виден и ствол, и крона.
 */
export const TREE_R = 1.0;

/**
 * Толщина волка: от неё считается и досягаемость топора, и попадание стрелы.
 *
 * Живёт здесь, а не в `wolves.ts`, вместе с прочими радиусами поляны — и не для
 * порядка: `nearest` мерит волка так же, как дерево, а `wolves.ts` читает
 * геометрию отсюда. Заведи это число там — и `glade` пришлось бы импортировать
 * `wolves`, который импортирует `glade`.
 */
export const WOLF_R = 0.42;

/** Сколько полен даёт одно дерево. */
export const TREE_LOGS = 3;

/** Сколько ударов топором до падения. Живёт во времени сцены и никуда не пишется. */
export const CHOPS_TO_FELL = 3;

/** Сколько длится один замах, миллисекунды. */
export const CHOP_MS = 620;

/**
 * За сколько зарастает пепелище… то есть пень.
 *
 * Двенадцать часов настоящего времени, и считается это **на чтении**, ровно как
 * горение костра: в сохранении лежит минута, в которую дерево упало, а стоит
 * оно сейчас или нет — выводится формулой. Заведено не ради глубины, а чтобы
 * поляна не кончалась: семь пней и погасший костёр — это тупик, из которого
 * игрок не выйдет ничем, кроме «начать заново».
 */
export const REGROW_MS = 12 * 3_600_000;

/** Стоит ли дерево. `felledAt` — 0, если его не валили. */
export const standing = (felledAt: number, now: number): boolean =>
  felledAt <= 0 || now - felledAt >= REGROW_MS;

/**
 * Все преграды поляны при данном состоянии деревьев.
 *
 * Пень преградой не считается: через него перешагивают, и упираться в
 * невидимую тумбу посреди поляны игрок не должен.
 */
export function blockers(felled: readonly number[], now: number): Blocker[] {
  const out: Blocker[] = [
    { x: FIRE.x, z: FIRE.z, r: FIRE.r },
    { x: TENT.x, z: TENT.z, r: TENT.r },
    { x: AXE_STUMP.x, z: AXE_STUMP.z, r: AXE_STUMP.r },
  ];
  TREES.forEach((t, i) => {
    if (standing(felled[i] ?? 0, now)) out.push({ x: t.x, z: t.z, r: TREE_R });
  });
  return out;
}

/**
 * Что лежит на поляне из того, до чего можно дотянуться.
 *
 * Отдельный маленький тип, а не всё сохранение целиком: поляна — про геометрию,
 * и знать ей про очаг, голод и колчан незачем. Туша сюда приходит **уже
 * отсеянной** (растащенная и протухшая — это `null`): срок её жизни — правило
 * охоты, а не геометрии, и живёт оно в `hunt.ts`. Собирает эту тройку `act.ts`,
 * в одном месте, чтобы «уже отсеянной» не приходилось помнить каждому.
 */
export interface GladeState {
  /** Когда свалено каждое дерево; 0 — стоит. */
  felled: readonly number[];
  /** Стрелы, воткнувшиеся в землю. */
  arrows: readonly { x: number; z: number }[];
  /** Туша, с которой ещё есть что взять. */
  carcass: { x: number; z: number } | null;
  /** Разобраны ли пожитки у палатки. */
  kit: boolean;
  /**
   * Где стоят волки. Приезжает из сцены, а не из записи: их положение живёт во
   * времени кадров (`wolves.ts`). Пустой список — обычное дело.
   */
  wolves: readonly { x: number; z: number }[];
}

/**
 * Что рядом с игроком — то и сделает тап.
 *
 * Выбирается **ближайшее в досягаемости**, а не то, что под пальцем: почему
 * именно так, написано в `controls.ts`. Меряется от края преграды, а не от её
 * середины: у дерева и у костра разная толщина, а «вплотную» должно значить
 * одно и то же.
 *
 * Порядок проверок ни на что не влияет — при равном расстоянии побеждает
 * первый, а равных расстояний на поляне не бывает. Стрела при этом — точка без
 * толщины: она лежит в траве, и подходить к ней надо вплотную.
 *
 * ВОЛК ИДЁТ ПЕРВЫМ, И ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ПОРЯДОК ЗНАЧИТ ХОТЬ ЧТО-ТО.
 * Он не «важнее» — он **подвижен**: волк, подошедший к человеку, стоящему у
 * костра, оказывается в досягаемости обоих, и при равном расстоянии тап должен
 * достаться зубам, а не дровам. Расстояния тут вправду сходятся, потому что
 * волк сам выбирает, куда встать.
 */
export function nearest(px: number, pz: number, w: GladeState, now: number): Spot | null {
  let best: Spot | null = null;
  let bestD = Infinity;
  const test = (kind: SpotKind, x: number, z: number, r: number, index: number): void => {
    const d = Math.hypot(px - x, pz - z) - r;
    if (d > REACH || d >= bestD) return;
    bestD = d;
    best = { kind, x, z, index };
  };
  w.wolves.forEach((v, i) => test('wolf', v.x, v.z, WOLF_R, i));
  test('fire', FIRE.x, FIRE.z, FIRE.r, -1);
  test('axe', AXE_STUMP.x, AXE_STUMP.z, AXE_STUMP.r, -1);
  if (!w.kit) test('tent', TENT.x, TENT.z, TENT.r, -1);
  if (w.carcass) test('carcass', w.carcass.x, w.carcass.z, 0.55, -1);
  w.arrows.forEach((a, i) => test('arrow', a.x, a.z, 0, i));
  TREES.forEach((t, i) => {
    if (standing(w.felled[i] ?? 0, now)) test('tree', t.x, t.z, TREE_R, i);
  });
  return best;
}

/**
 * Подвинуть человека, не пустив его в преграды и за край поляны.
 *
 * Скольжение по кругу, а не остановка: упёршись в дерево под углом, игрок
 * должен его обойти, ведя палец в ту же сторону. Остановка насухо читается как
 * «застрял», и на телефоне это худшее, что может случиться с ходьбой.
 */
export function slide(x: number, z: number, blocks: readonly Blocker[]): { x: number; z: number } {
  let nx = x;
  let nz = z;
  for (const b of blocks) {
    const dx = nx - b.x;
    const dz = nz - b.z;
    const d = Math.hypot(dx, dz);
    const need = b.r + BODY_R;
    if (d >= need) continue;
    // Ровно в середине преграды направления нет — выталкиваем в любую сторону.
    if (d < 1e-4) {
      nx = b.x + need;
      continue;
    }
    nx = b.x + (dx / d) * need;
    nz = b.z + (dz / d) * need;
  }
  const r = Math.hypot(nx, nz);
  if (r > GLADE_R) {
    nx = (nx / r) * GLADE_R;
    nz = (nz / r) * GLADE_R;
  }
  return { x: nx, z: nz };
}

/** Толщина самого игрока: он не точка, иначе носом влезает в ствол. */
export const BODY_R = 0.35;

/**
 * Куда повернуть голову, чтобы смотреть из (x, z) на (tx, tz).
 *
 * Камера без поворота смотрит вдоль −Z, поэтому её направление при рыскании
 * `yaw` — это (−sin yaw, −cos yaw). Отсюда и знаки: перепутать их легко, а
 * ошибка видна только тем, что игрок при входе стоит спиной к делу.
 */
export const yawTo = (x: number, z: number, tx: number, tz: number): number =>
  Math.atan2(-(tx - x), -(tz - z));

/** Где игрок стоит, войдя в режим: у костра, лицом к пню с топором. */
export const START = {
  x: -0.4,
  z: 2.6,
  yaw: yawTo(-0.4, 2.6, AXE_STUMP.x, AXE_STUMP.z),
};
