/**
 * Что на поляне можно тронуть.
 *
 * ОЛЕНЯ В ЭТОМ СПИСКЕ НЕТ И БЫТЬ НЕ МОЖЕТ, и это не пропуск, а вся разница
 * между двумя способами дотянуться. Тап **не целится**: он бьёт по ближайшему в
 * досягаемости (`nearest`), то есть по тому, к чему подошли. Выстрел —
 * наоборот, целится и не требует подходить: он летит туда, куда смотрят
 * (`hunt.arrowLanding`). Зверь досягаемости не подпускает вовсе (`DEER_FLEE`
 * больше `REACH` вчетверо), поэтому достать его можно ровно одним способом — и
 * поэтому лук нужен.
 *
 * А ВОТ ВОЛК В СПИСКЕ ЕСТЬ, И ЭТО ТО ЖЕ ПРАВИЛО, А НЕ ИСКЛЮЧЕНИЕ ИЗ НЕГО. Он
 * **приходит сам**, и когда он в шаге, «сделай с тем, к чему подошёл» — это и
 * есть удар топором. Ничего не целится и здесь: если рядом два волка, топор
 * достаётся ближайшему, как достался бы ближайшему дереву.
 *
 * Он же — единственная цель тапа, которой нет в сохранении: где он стоит,
 * знает только кадр (`wolves.ts`, шапка), поэтому его положение приезжает в
 * `GladeState` снаружи, от сцены, а не выводится из записи.
 *
 * ЖЕНЩИНА У ОГНЯ — ТА ЖЕ ДВЕРЬ И ТОТ ЖЕ ПОРЯДОК, ЧТО У ВОЛКА. Подошёл — тап
 * заговаривает; где она стоит, знает кадр (она идёт от опушки, наклоняется к
 * огню), поэтому её место приезжает от сцены. Есть ли она вообще — правило рода
 * (`kin.guestHere`, жена в записи), и сцена просто не отдаёт места, если её нет.
 */
export type SpotKind = 'tree' | 'fire' | 'axe' | 'tent' | 'carcass' | 'arrow' | 'wolf' | 'house' | 'mate' | 'son' | 'frame' | 'foe';

export interface Spot {
  kind: SpotKind;
  x: number;
  z: number;
  /** Номер дерева в `felled` или стрелы в `arrows`; у остальных — −1. */
  index: number;
}

