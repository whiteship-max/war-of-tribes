/**
 * Охота: олень, туша и стрелы.
 *
 * ГДЕ ЗДЕСЬ ПРОХОДИТ ГРАНИЦА ДЕТЕРМИНИЗМА — ГЛАВНЫЙ ВОПРОС ЭТОГО ФАЙЛА, И ОТВЕТ
 * НА НЕГО РАЗНЫЙ ДЛЯ ДВУХ ПОЛОВИН ЗВЕРЯ.
 *
 * **Есть ли олень на поляне, где он вышел и когда придёт следующий — считается
 * на чтении, здесь, чистой функцией.** В сохранении лежит одно число: минута,
 * в которую свалили прошлого. Из неё выводится всё остальное: пока не прошло
 * `DEER_GAP_MS`, поляна пуста; прошло — на ней стоит олень, и вышел он на то
 * место, которое назвал хеш от той же минуты. `Math.random` здесь нет и быть не
 * может — ни одного вызова во всём модуле, это тест.
 *
 * **Как он ходит прямо сейчас — считает сцена, кадровым временем.** Шаг,
 * поворот головы, рывок в сторону от человека: ни одно из этих чисел не
 * переживает выход и никуда не пишется. Игрок, вернувшийся в режим, застаёт
 * оленя не там, где оставил, — и это правильно: зверь не стоит на паузе, пока
 * на него не смотрят, а вести его положение через сохранение значило бы завести
 * вторую правду о том, где он.
 *
 * Граница ровно та же, что у костра, и проведена по тому же признаку: **что
 * переживает выход — формула, что живёт в кадре — кадр.** Разница лишь в том,
 * что у костра переживает выход величина, а у оленя — факт: «он есть».
 *
 * ПОЛНОСТЬЮ ПРЕДСКАЗУЕМЫЙ ОЛЕНЬ — НЕ ОХОТА, и решает это не случайность, а
 * человек: зверь замечает того, кто подошёл, и уходит от него. Куда он уйдёт,
 * зависит от того, откуда шли, — то есть от игрока, а не от броска кости.
 * Случайность в такой игре и не нужна: неопределённость даёт живой противник,
 * пусть и травоядный.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов, ни случайности.
 */
import { GLADE_R, hash } from './glade';

const H = 3_600_000;

/** Сколько кусков мяса даёт один олень. Ровно полный живот (`STARVE_H` / `MEAT_FED_H`). */
export const DEER_MEAT = 6;

/** Через сколько часов после убитого на поляну выходит следующий. */
export const DEER_GAP_H = 3;
export const DEER_GAP_MS = DEER_GAP_H * H;

/** Сколько часов лежит туша, прежде чем от неё ничего не останется. */
export const CARCASS_H = 2;
export const CARCASS_MS = CARCASS_H * H;

/** С какого расстояния олень поднимает голову и перестаёт пастись. */
export const DEER_ALERT = 11;

/** С какого расстояния срывается с места. Ближе не подпустит никогда. */
export const DEER_FLEE = 7.5;

/** Шаг пасущегося зверя, м/с. */
export const DEER_WALK = 0.9;

/**
 * Бег, м/с. Вдвое с лишним быстрее человека (`WALK_SPEED` = 2.6): догнать
 * оленя нельзя, и в этом весь смысл лука.
 */
export const DEER_RUN = 6.4;

/** Сколько миллисекунд он бежит, прежде чем успокоится. Время сцены. */
export const DEER_CALM_MS = 4500;

/** Радиус тела: по нему считается попадание стрелы. */
export const DEER_BODY_R = 0.52;

/** На какой высоте у него корпус — по нему и целятся. */
export const DEER_BODY_Y = 1.02;

/**
 * Где олень выходит на поляну.
 *
 * Четыре места по кругу, все дальше `DEER_FLEE` от костра: зверь, вышедший
 * человеку под руку, — не зверь. Числа записаны, а не считаются: место оленя,
 * как и место дерева, — факт, и в диффе должно быть видно, какое переехало.
 */
export const DEER_SPOTS: readonly { x: number; z: number }[] = [
  { x: 8.4, z: 1.6 },
  { x: -1.8, z: -9.2 },
  { x: -8.6, z: 3.8 },
  { x: 2.2, z: 9.0 },
];

/** Стрел в колчане у новой поляны. Конечны, но не теряются: их подбирают. */
export const ARROWS_START = 4;

/**
 * Как далеко летит стрела.
 *
 * Больше поляны (`GLADE_R` = 13) нарочно: до любого её угла стрела достаёт, и
 * промах — это не «не долетел», а «мимо». Дальше предела стрела втыкается в
 * землю там, где кончился полёт.
 */
export const ARROW_RANGE = 26;

/** Сколько метров в секунду летит стрела. Время сцены. */
export const ARROW_SPEED = 34;

/** Сколько длится снятие одного куска с туши, миллисекунды. Время сцены. */
export const BUTCHER_MS = 900;

/** Точка на земле: стрела, туша, место оленя. */
export interface Pt {
  x: number;
  z: number;
}

/** Туша: где лежит и сколько с неё уже сняли. Когда упала — знает `Hunt.killedAt`. */
export interface Carcass extends Pt {
  /** Сколько кусков уже забрали. */
  taken: number;
}

/**
 * Что охота помнит между заходами.
 *
 * Одно число времени на всё: и «когда придёт следующий», и «сколько лежит
 * туша» отсчитываются от минуты, в которую свалили зверя. Второй отметки тут
 * не нужно — она была бы копией первой и разошлась бы с ней при первой правке.
 */
export interface Hunt {
  /** Когда свалили прошлого оленя. 0 — ещё ни разу. */
  killedAt: number;
  /** Туша на поляне, если ещё не растащена и не пропала. */
  carcass: Carcass | null;
}

/** Новая охота: олень на поляне, туши нет. */
export const newHunt = (): Hunt => ({ killedAt: 0, carcass: null });

/** Ходит ли сейчас по поляне олень. */
export const deerLive = (hunt: Hunt, now: number): boolean =>
  hunt.killedAt <= 0 || now - hunt.killedAt >= DEER_GAP_MS;

/** Через сколько выйдет следующий, миллисекунды. 0 — уже ходит. */
export const deerInMs = (hunt: Hunt, now: number): number =>
  deerLive(hunt, now) ? 0 : hunt.killedAt + DEER_GAP_MS - now;

/**
 * Откуда олень начинает пастись.
 *
 * Хеш от минуты убийства, а не бросок: у двух игроков с одинаковой историей
 * поляна одинаковая, а у одного игрока следующий олень выходит не туда, где
 * стоял прошлый. Из пяти минут выйдет то же место — и это не беда: угадать
 * заранее всё равно нечего, зверь всё равно уйдёт от того, кто подойдёт.
 */
export const deerHome = (hunt: Hunt): Pt =>
  DEER_SPOTS[Math.floor(hash(hunt.killedAt * 0.001, 17) * DEER_SPOTS.length) % DEER_SPOTS.length];

/** Пропала ли туша: растащили до конца или пролежала своё. */
export const carcassGone = (hunt: Hunt, now: number): boolean =>
  !hunt.carcass || hunt.carcass.taken >= DEER_MEAT || now - hunt.killedAt >= CARCASS_MS;

/** Туша, с которой ещё есть что взять. `null` — брать нечего. */
export const liveCarcass = (hunt: Hunt, now: number): Carcass | null =>
  carcassGone(hunt, now) ? null : hunt.carcass;

/** Сколько кусков ещё на туше. */
export const carcassLeft = (hunt: Hunt, now: number): number => {
  const c = liveCarcass(hunt, now);
  return c ? DEER_MEAT - c.taken : 0;
};

/** Сколько туше осталось лежать, миллисекунды. */
export const carcassLeftMs = (hunt: Hunt, now: number): number =>
  liveCarcass(hunt, now) ? Math.max(0, hunt.killedAt + CARCASS_MS - now) : 0;

/**
 * Куда воткнётся стрела, вылетевшая из точки в направлении.
 *
 * Прямая, без падения, — и это решение, а не упрощение. Падающая стрела честнее,
 * но она обещает поправку на дальность, которой игроку негде научиться за три
 * минуты, и первое же «целился в бок, попал в ноги» он прочтёт как поломку.
 * Прямая линия делает правило «летит туда, куда смотришь» правдой без оговорок —
 * а правило это в игре объявлено, и врать ему нельзя.
 *
 * За край поляны стрела не улетает: там стена леса, а стрела, потерянная
 * навсегда, — это тупик, в котором игроку нечем охотиться.
 */
export function arrowLanding(x: number, z: number, dir: Dir, eye: number): Pt {
  const flat = Math.hypot(dir.x, dir.z);
  // Выстрел строго вниз (или вверх) земли перед собой не касается — считаем,
  // что стрела упала под ноги. Иначе она улетала бы в бесконечность по нулю.
  if (flat < 1e-4) return clampToGlade(x, z);
  // Летит она до предела дальности или до земли — что случится раньше.
  const toGround = dir.y < -1e-4 ? eye / -dir.y : Infinity;
  const travel = Math.min(ARROW_RANGE, toGround);
  return clampToGlade(x + dir.x * travel, z + dir.z * travel);
}

/** Куда смотрят: единичный вектор взгляда. Больше сцене от лука ничего не нужно. */
export interface Dir {
  x: number;
  y: number;
  z: number;
}

/** Прижать точку к поляне: за её край ничего не кладём. */
export function clampToGlade(x: number, z: number): Pt {
  const r = Math.hypot(x, z);
  const max = GLADE_R - 0.4;
  return r <= max ? { x, z } : { x: (x / r) * max, z: (z / r) * max };
}

/**
 * Куда ляжет стрела, попавшая в зверя.
 *
 * Рядом с тушей, а не в ней: торчащую стрелу видно, но брать её и мясо надо
 * порознь, иначе `nearest` выбирал бы между ними за игрока. Смещение считается
 * хешем от номера стрелы — две подряд не лягут в одну точку.
 */
export const arrowByCarcass = (c: Pt, n: number): Pt => {
  const a = hash(n, 61) * Math.PI * 2;
  return clampToGlade(c.x + Math.cos(a) * 0.95, c.z + Math.sin(a) * 0.95);
};

/**
 * Попала ли стрела, летящая из точки в точку, по зверю.
 *
 * Считается на отрезке одного кадра, а не по прямой целиком: зверь движется, и
 * «пролетела мимо, потому что он успел шагнуть» — законный промах.
 */
export function arrowHits(
  ax: number,
  ay: number,
  az: number,
  deer: Pt,
): boolean {
  const dy = ay - DEER_BODY_Y;
  if (Math.abs(dy) > DEER_BODY_R * 1.6) return false;
  return Math.hypot(ax - deer.x, az - deer.z) <= DEER_BODY_R;
}

/**
 * Стрелы: сколько в колчане и сколько лежит на поляне.
 *
 * Всё, что с ними делают, — три действия, и живут они здесь, а не в сцене,
 * ровно ради одного обещания: **стрела не размножается и не пропадает.** Сумма
 * «в колчане плюс на земле плюс одна в полёте» не меняется никогда, и проверить
 * это можно только там, где эти три действия и написаны.
 */
export interface Arrows {
  quiver: number;
  arrows: readonly Pt[];
}

/** Взять стрелу из колчана: она уходит в полёт и потому ни там, ни тут. */
export const nockArrow = (a: Arrows): Arrows =>
  a.quiver <= 0 ? a : { quiver: a.quiver - 1, arrows: a.arrows };

/** Стрела воткнулась в землю: теперь она лежит на поляне. */
export const landArrow = (a: Arrows, at: Pt): Arrows => ({ quiver: a.quiver, arrows: [...a.arrows, at] });

/** Подобрать лежащую: с земли она уходит, в колчан приходит. Ровно одна. */
export const pickArrow = (a: Arrows, i: number): Arrows =>
  i < 0 || i >= a.arrows.length
    ? a
    : { quiver: a.quiver + 1, arrows: a.arrows.filter((_, k) => k !== i) };

/** Сколько стрел у человека, не считая летящей. */
export const arrowsAll = (a: Arrows): number => a.quiver + a.arrows.length;
