/**
 * Волки.
 *
 * ГРАНИЦА ДЕТЕРМИНИЗМА ЗДЕСЬ ТА ЖЕ, ЧТО У ОЛЕНЯ, И ПРОВЕДЕНА ПО ТОМУ ЖЕ
 * ПРИЗНАКУ: **что переживает выход — формула, что живёт в кадре — кадр.**
 *
 *   на чтении   есть ли стая этой ночью и сколько в ней волков (`packAt`), где
 *               они вышли из леса (`wolfSpot`), когда придут снова после того,
 *               как их отбили. Одно число в сохранении — минута, в которую
 *               отбили последнюю стаю;
 *   в кадре     как они кружат, когда бросаются, куда отскакивают. Ни одно из
 *               этих чисел никуда не пишется, и вернувшийся игрок застаёт стаю
 *               не там, где оставил.
 *
 * ВОЛК — ЕДИНСТВЕННЫЙ ЗВЕРЬ В СПИСКЕ ДОСЯГАЕМОГО, И ЭТО НЕ ПРОТИВОРЕЧИТ
 * ПРАВИЛУ, А ОБЪЯСНЯЕТ ЕГО. Оленя в списке нет потому, что он не подпускает:
 * срывается с `hunt.DEER_FLEE`, много дальше руки (`glade.REACH`), — и достать его
 * можно только луком.
 * Волк наоборот: он **приходит сам**, и когда он в двух шагах, тап по нему —
 * это не прицел, а то же «сделай с тем, к чему подошёл», что с деревом и
 * костром. Поэтому топор работает первой дверью (`act.offer`), а лук — второй,
 * и смешивать их по-прежнему нельзя.
 *
 * ТРИ ПРАВИЛА, БЕЗ КОТОРЫХ ВОЛКИ БЫЛИ БЫ НЕ ОПАСНОСТЬЮ, А ПОДЛОСТЬЮ.
 *
 *   1. **У горящего костра их нет.** Не «меньше» и не «редко» — нет вовсе
 *      (`WOLF_FIRE_R`). Огонь и так единственное, что человек здесь делает
 *      руками; пусть он же и защищает.
 *   2. **Их видно раньше, чем они дотянутся.** Стая выходит на опушку
 *      (`WOLF_SPOTS`, все дальше `WOLF_STALK_R` от середины), кружит
 *      `WOLF_STALK_MS`, и только потом бросается. Плюс вой ночью. От появления
 *      до смерти не может пройти меньше `EARLIEST_DEATH_MS` — это выведено, а не
 *      обещано, и это тест.
 *   3. **Отбиться можно.** Топором — одним ударом; луком — одной стрелой. Без
 *      топора отбиваться нечем, и единственный ответ — уйти к огню; волк
 *      быстрее человека (`WOLF_RUSH` против `WALK_SPEED`), поэтому уйти можно
 *      только вовремя, а не когда укусили.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов, ни случайности.
 */
import { WOLF_BITES } from './body';
import { GLADE_R, WOLF_R, byHouse, hash } from './glade';
import { SKY_MS, isNight } from './sky';

const H = 3_600_000;

/** Сколько волков приходит днём. Один — это «видел, что они есть». */
export const WOLF_DAY_PACK = 1;

/** Сколько ночью. Двое — это «пара», как и сказано в замысле. */
export const WOLF_NIGHT_PACK = 2;

/** В какой доле ночей приходит стая. */
export const WOLF_NIGHTS = 0.62;

/** В какой доле дней приходит одиночка. Днём они редки — на этом и стоит ночь. */
export const WOLF_DAYS = 0.22;

/** Через сколько часов приходят снова после того, как стаю отбили. */
export const WOLF_GAP_H = 3;
export const WOLF_GAP_MS = WOLF_GAP_H * H;

/**
 * Круг у костра, в который волк не войдёт, пока костёр горит.
 *
 * Шесть с половиной метров — ровно столько, чтобы **все деревья поляны остались
 * снаружи** (ближайшее из `glade.TREES` — дальше круга). Это не совпадение, а сам
 * замысел: ходить за дровами ночью должно быть страшно, иначе волки не значат ничего.
 * Круг тепла при этом меньше (`glade.WARM_R`) — у огня безопасно
 * заметно дальше, чем тепло, и это честно: волка отгоняет свет, а не жар.
 */
export const WOLF_FIRE_R = 6.5;

/** На каком радиусе от человека они кружат, прежде чем броситься. */
export const WOLF_STALK_R = 9;

/** Сколько кружат. Столько у игрока есть, чтобы увидеть и решить. */
export const WOLF_STALK_MS = 7000;

/** Шаг кружащего волка, м/с. */
export const WOLF_TROT = 1.7;

/** Бросок, м/с. Быстрее человека: уйти можно вовремя, а не в последний миг. */
export const WOLF_RUSH = 5.2;

/** С какого расстояния кусает. */
export const WOLF_BITE_R = 1.25;

/**
 * Где бросившийся волк останавливается: в метре от человека, а не в нём.
 *
 * Бросок шёл прямо в точку, где стоит человек, и волк въезжал в камеру: зверь
 * в пяти сантиметрах от глаза — это не опасность, а коричневый экран. Метр
 * меньше `WOLF_BITE_R`, поэтому остановившийся волк по-прежнему достаёт
 * зубами, а топор достаёт его (тест).
 */
export const WOLF_STOP = 0.9;

/** Сколько отскакивает между укусами. */
export const WOLF_BITE_GAP = 3000;

/**
 * Откуда волки выходят из леса.
 *
 * Шесть мест по кромке, все дальше `WOLF_STALK_R` от середины поляны: волк,
 * вышедший человеку под руку, — это не опасность, а подножка. Числа записаны, а
 * не считаются в цикле, — по той же причине, по какой записаны деревья и места
 * оленя: в диффе должно быть видно, какое переехало.
 */
export const WOLF_SPOTS: readonly { x: number; z: number }[] = [
  { x: 10.6, z: 4.2 },
  { x: 4.8, z: 10.4 },
  { x: -5.6, z: 9.8 },
  { x: -10.8, z: -2.4 },
  { x: -3.2, z: -11.0 },
  { x: 7.4, z: -8.6 },
];

/**
 * Раньше этого срока от появления стаи смерть невозможна.
 *
 * Считается, а не обещается: кружат `WOLF_STALK_MS`, между укусами
 * `WOLF_BITE_GAP`, а здоровья у целого человека — на `body.WOLF_BITES` укусов.
 * Значит первый укус не раньше `WOLF_STALK_MS` после того, как человек вышел из
 * круга у огня, а последний — не раньше `EARLIEST_DEATH_MS`. И всё это время стая
 * на виду и на `WOLF_STALK_R`.
 */
export const EARLIEST_BITE_MS = WOLF_STALK_MS;

/**
 * И раньше этого — смерть целого человека. `WOLF_BITES` укусов, между ними отскок.
 * Раненому меньше: здоровье одно на зубы, холод и голод.
 *
 * **Для любой стаи, а не для одного волка**, и держится это правилом «стая
 * бросается по одному» (`wolfRushes` — один отсчёт на стаю). Пока отсчёт был у
 * каждого волка свой, ночная пара кусала разом на седьмой секунде и добивала на
 * десятой — тринадцать секунд оставались правдой ровно для одиночки. Поймано
 * тестом, который переигрывает это правило, а не пересказывает его.
 */
export const EARLIEST_DEATH_MS = WOLF_STALK_MS + (WOLF_BITES - 1) * WOLF_BITE_GAP;

/**
 * Через сколько после выхода стаи слышен первый вой.
 *
 * Меньше секунды, и это не украшение: предупреждение обязано прийти **раньше**
 * зубов. Вой в конце кружения сообщал бы то, что игрок уже видит. Живёт здесь, а
 * не в сцене, потому что это правило волков, а не картинки, — и тест сверяет его
 * с `EARLIEST_BITE_MS`.
 */
export const HOWL_LEAD_MS = 900;

/**
 * Бросается ли стая: кружит она уже столько, сколько положено.
 *
 * ОТСЧЁТ ОДИН НА ВСЮ СТАЮ, И ЭТО ПРАВИЛО, А НЕ УПРОЩЕНИЕ. Бросается и кусает
 * один; укусил — отскакивает вся стая (`stalkAfterBite`), и кружит снова. Так и
 * у зверя, и так только и держится обещание `EARLIEST_DEATH_MS`: будь отсчёт у
 * каждого свой, пара волков кусала бы вдвое чаще одиночки, и срок, за который
 * игрок успевает понять, зависел бы от того, какая выпала ночь.
 *
 * ВРЕМЯ ЗДЕСЬ КАДРОВОЕ, И ЭТО НЕ ПРОТИВОРЕЧИТ ГРАНИЦЕ: модуль его не читает, а
 * получает числом — так же, как `controls.ts` получает время касания. Вынесено
 * сюда из сцены ради одного: обещание проверяется тестом **по тому самому
 * правилу**, которым ходит стая. Второй правды об этом между сценой и тестом
 * быть не должно.
 *
 * `stalkFrom` — минута, с которой стая кружит вокруг вышедшего из круга
 * человека; ноль — не кружит, человек у огня.
 */
export const wolfRushes = (stalkFrom: number, t: number): boolean =>
  stalkFrom > 0 && t - stalkFrom >= WOLF_STALK_MS;

/**
 * С какой минуты считать кружение после укуса.
 *
 * Отсчёт сдвигается так, чтобы до следующего броска прошло ровно
 * `WOLF_BITE_GAP`: стая отскакивает и снова кружит, но не весь `WOLF_STALK_MS`,
 * а только `WOLF_BITE_GAP`. Иначе второй укус был бы так же далёк, как первый, и три укуса перестали
 * бы значить «не стой».
 */
export const stalkAfterBite = (t: number): number => t - WOLF_STALK_MS + WOLF_BITE_GAP;

/**
 * Сколько волков ходит по поляне сейчас.
 *
 * Приходят они не каждую ночь: хеш от номера круга суток решает, эта ночь с
 * волками или тихая. Бросок кости тут не нужен — нужен один и тот же ответ у
 * двух игроков с одинаковой историей, и он же не должен угадываться из
 * предыдущего круга.
 *
 * `beatenAt` — минута, в которую отбили последнюю стаю. Пока не прошло
 * `WOLF_GAP_MS`, на поляне тихо: иначе отбитая стая возвращалась бы тем же
 * вечером, и топор перестал бы быть ответом.
 */
export function packAt(now: number, beatenAt: number): number {
  if (beatenAt > 0 && now - beatenAt < WOLF_GAP_MS && now >= beatenAt) return 0;
  const circle = Math.floor(now / SKY_MS);
  const night = isNight(now);
  const roll = hash(circle, night ? 91 : 93);
  if (night) return roll < WOLF_NIGHTS ? WOLF_NIGHT_PACK : 0;
  return roll < WOLF_DAYS ? WOLF_DAY_PACK : 0;
}

/**
 * Где выходит из леса `n`-й волк стаи.
 *
 * Первого ставит хеш от круга суток: одна и та же ночь даёт одну и ту же
 * опушку. Каждого следующего — **через одно место по кругу**, и это не
 * украшение: прежде у каждого был свой хеш, и два хеша могли совпасть — пара
 * выходила из одной точки и шла одним телом. Через одно место — значит пара
 * подходит с двух сторон, далеко врозь, и увидеть обоих
 * разом нельзя: это и есть стая, а не два волка.
 */
export const wolfSpot = (now: number, n: number): { x: number; z: number } => {
  const circle = Math.floor(now / SKY_MS);
  const first = Math.floor(hash(circle, 97) * WOLF_SPOTS.length) % WOLF_SPOTS.length;
  return WOLF_SPOTS[(first + n * 2) % WOLF_SPOTS.length];
};

/**
 * Держится ли волк в стороне: он в кругу у горящего костра.
 *
 * Одна чистая функция на всю игру, и спрашивают её двое — сцена (куда шагнуть) и
 * тест (не подходит ли к огню). Второй правды об этом между ними быть не должно.
 *
 * Второе место, куда волк не войдёт, — достроенный дом (`house`): укрытие от
 * волков — половина того, зачем дом строят. Круг тот же, что круг под крышей
 * (`glade.byHouse`), и держится при любом огне: дом нужен ровно тогда, когда
 * костёр погас.
 */
export const wolfKeepsOut = (x: number, z: number, lit: boolean, house = false): boolean =>
  (lit && Math.hypot(x, z) < WOLF_FIRE_R) || (house && byHouse(x, z));

/**
 * Может ли волк, стоящий здесь, укусить человека, стоящего там.
 *
 * Огонь считается **по человеку, а не по волку**: у костра не кусают вовсе, и
 * это то же самое правило, что `wolfKeepsOut`, сказанное со стороны укуса.
 * Разводить их нельзя — получилось бы, что волк топчется на границе и достаёт
 * через неё.
 */
export const wolfCanBite = (
  wx: number,
  wz: number,
  px: number,
  pz: number,
  lit: boolean,
  house = false,
): boolean =>
  !wolfKeepsOut(px, pz, lit, house) &&
  !wolfKeepsOut(wx, wz, lit, house) &&
  Math.hypot(px - wx, pz - wz) <= WOLF_BITE_R;

/** На какой высоте у волка корпус — по нему и целятся. Ниже оленя: волк ниже. */
export const WOLF_BODY_Y = 0.62;

/** Попала ли стрела по волку. То же, что у оленя, только тело ниже и уже. */
export const wolfHit = (ax: number, ay: number, az: number, wx: number, wz: number): boolean =>
  Math.abs(ay - WOLF_BODY_Y) <= WOLF_R * 1.6 && Math.hypot(ax - wx, az - wz) <= WOLF_R;

/** Докуда волку можно: за кромку поляны он не выходит, как и зверь. */
export const WOLF_EDGE = GLADE_R - 0.8;
