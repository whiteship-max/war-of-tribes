/**
 * Управление от первого лица: ходить и смотреть одновременно на стекле.
 *
 * ЧТО ВЗЯТО У ОБЩЕГО РАЗБОРА ЖЕСТА И ЧТО ПРИШЛОСЬ ПИСАТЬ — ГЛАВНЫЙ ВОПРОС
 * ЭТОГО ФАЙЛА, И ОТВЕТ НА НЕГО РАЗНЫЙ ДЛЯ ДВУХ ЕГО ПОЛОВИН.
 *
 * **Взято целиком: что такое тап.** `Press` из `@/gestures` и все его пороги —
 * `TAP_MOVE`, `TAP_SLIP`, `TAP_MS` — приезжают сюда как есть, ни одно число не
 * переписано. Это не экономия строк, а то самое правило «один палец — один
 * судья»: игрок, научившийся тапать по зданию в деревне, тапает здесь тем же
 * пальцем и с той же точностью. Три захода на починку тапа по зданию стоили
 * ровно того, чтобы эти числа больше нигде не заводились заново.
 *
 * **Написано своё: чей это палец.** А вот `Gesture` взять было нельзя, и это
 * не недосмотр — у него противоположная грамматика. Он построен на правиле
 * «тап бывает только одним пальцем: второй палец — это щипок, и тапа в жесте
 * больше нет ни у кого». Для деревни и карты это верно: там два пальца всегда
 * означают одно — приближение. Здесь два пальца — норма и основа режима: левый
 * идёт, правый смотрит, и оба осмысленны каждый сам по себе. Подать их в
 * `Gesture` значило бы получить «щипок» на каждом шаге и не получить ни одного
 * тапа. Расширить `Gesture` до обоих смыслов — хуже вдвойне: судья деревни и
 * карты стал бы зависеть от того, какой холст его позвал, и правило, ради
 * которого он писался, перестало бы существовать.
 *
 * Поэтому здесь второй **разбор**, но не второй **свод правил**: пороги и
 * приговор «тап это или ведение» по-прежнему в одном месте, а нового ровно
 * одно — «в какой половине экрана лёг палец». Такого вопроса ни у деревни, ни
 * у карты нет и быть не может.
 *
 * СХЕМА, И ПОЧЕМУ ИМЕННО ТАКАЯ.
 *
 *   левая половина   ходьба. Стик появляется там, где лёг палец, а не стоит в
 *                    углу: на 375 px большой палец ложится куда дотянулся, и
 *                    нарисованный заранее кружок он промахивает;
 *   правая половина  взгляд. Тяга один к одному по градусам на пиксель;
 *   тап              действие — в любой половине.
 *
 * **Действие не целится.** Тап бьёт не туда, куда показывает палец, а по тому,
 * что рядом с игроком (`scene.ts` выбирает ближайшее в досягаемости). Так
 * сделано нарочно, и без этого общие пороги сюда бы не приехали: `TAP_SLIP` —
 * тридцать два пикселя, а на такой сдвиг взгляд успевает повернуться градусов
 * на двадцать. Целься тап прицелом — эти двадцать градусов уводили бы его
 * мимо; целится он досягаемостью — и они не значат ничего. Дальний предмет
 * тапом не берётся вовсе: к нему надо подойти, и в этом весь режим.
 *
 * Модуль чистый: ни DOM, ни three, ни React. На вход — точки и время, на
 * выход — числа. Проверяется тестом, а не пальцем на телефоне.
 */
import { Press, TAP_MOVE } from '@/gestures';

/**
 * Мёртвая зона стика — тот же `TAP_MOVE`, что и порог камеры в деревне.
 *
 * Смысл у числа тот же самый, слово в слово: до него картинка стоит. В деревне
 * это «камера не поехала за пальцем», здесь — «человек не пошёл». Заводить под
 * это второе число значило бы завести вторую правду о том, где кончается дрожь
 * лежащего пальца и начинается движение.
 */
export const STICK_DEAD = TAP_MOVE;

/**
 * На сколько надо увести палец от точки нажатия для полного хода.
 *
 * Пятьдесят шесть: вместе с мёртвой зоной это сорок шесть пикселей полезного
 * хода — дуга, которую большой палец проходит, не отрывая ладони от корпуса.
 * Больше — и до полного хода придётся тянуться, меньше — и промежуточные
 * скорости пропадут, останется «стоит или бежит».
 */
export const STICK_FULL = 56;

/**
 * Сколько градусов поворота даёт один пиксель тяги.
 *
 * Полградуса: удобная тяга большим пальцем поперёк своей половины экрана —
 * полторы сотни пикселей — поворачивает голову на три четверти прямого угла.
 * Осмотреться кругом выходит за три тяги; меньше — и осматриваться придётся
 * гребком, больше — и прицелиться в дерево станет нельзя.
 */
export const LOOK_PER_PX = 0.5;

/** Тот же поворот в радианах на пиксель — им считает сцена. */
export const LOOK_RAD_PER_PX = (LOOK_PER_PX * Math.PI) / 180;

/**
 * Докуда можно задрать и опустить голову, радианы.
 *
 * Не до отвеса: у самого зенита картинка теряет верх и низ, а игроку смотреть
 * там не на что — ни земли, ни костра, ни деревьев.
 */
export const PITCH_LIMIT = (72 * Math.PI) / 180;

/** Куда идём: вперёд-назад и вбок, каждое от −1 до 1. */
export interface Walk {
  forward: number;
  strafe: number;
}

export const STILL: Walk = { forward: 0, strafe: 0 };

/** Половина экрана, в которую лёг палец. */
export type Half = 'walk' | 'look';

/** Один живой палец: общий приговор о тапе плюс то, где он сейчас. */
interface Finger {
  press: Press;
  half: Half;
  /** Где палец сейчас. `Press` этого наружу не отдаёт — он про приговор, не про место. */
  x: number;
  y: number;
}

/**
 * Разбор жеста режима от первого лица.
 *
 * Пальцев может быть два, и каждый живёт своей жизнью: первый в своей половине
 * задаёт смысл и держит его до снятия. Третий палец не делает ничего — он и не
 * нужен: рук у игрока две.
 *
 * Координаты приходят в пикселях холста (не страницы) — кто зовёт, тот и
 * вычитает `getBoundingClientRect`. Ширина нужна затем же, зачем и координаты:
 * половина экрана считается от неё, а не от `window`.
 */
export class Sticks {
  private fingers = new Map<number, Finger>();
  /** Накопленный поворот, ещё не отданный сцене. */
  private dyaw = 0;
  private dpitch = 0;

  /**
   * Палец лёг. `x` — от левого края холста, `width` — его ширина.
   *
   * Половина выбирается один раз и навсегда для этого пальца: уехавший за
   * середину экрана большой палец не должен посреди шага превращаться во
   * взгляд.
   */
  down(id: number, x: number, y: number, now: number, width: number): void {
    const half: Half = x < width / 2 ? 'walk' : 'look';
    // Второй палец в ту же половину не пускаем: два стика ходьбы разом — это не
    // жест, а случайность (ладонь легла краем), и слушать надо тот, что раньше.
    for (const f of this.fingers.values()) if (f.half === half) return;
    this.fingers.set(id, { press: new Press(id, x, y, now), half, x, y });
  }

  /** Палец поехал. Взгляд копится здесь же: поворот — это разница, а не место. */
  move(id: number, x: number, y: number, now: number): void {
    const f = this.fingers.get(id);
    if (!f) return;
    if (f.half === 'look') {
      this.dyaw -= (x - f.x) * LOOK_RAD_PER_PX;
      this.dpitch -= (y - f.y) * LOOK_RAD_PER_PX;
    }
    f.x = x;
    f.y = y;
    f.press.move(x, y, now);
  }

  /**
   * Палец снят. Возвращает приговор и само нажатие — журналу касаний.
   *
   * Приговор целиком чужой: его выносит `Press` теми же порогами, какими он
   * выносит его в деревне. Своего здесь только то, что тап годится из обеих
   * половин — идти и действовать одной рукой игрок должен уметь.
   *
   * Нажатие отдаётся наружу, а не прячется, потому что журнал касаний обязан
   * писать измеренное, а не нули: сколько длилось, докуда сошло, какой длины
   * путь. Прибор, подставляющий ноль вместо «не знаю», хуже отсутствующего.
   */
  up(id: number, now: number): { tap: boolean; press: Press; half: Half } | null {
    const f = this.fingers.get(id);
    if (!f) return null;
    this.fingers.delete(id);
    return { tap: f.press.isTap(now), press: f.press, half: f.half };
  }

  /** Жест отобрал браузер: тапом он уже не станет. */
  cancel(id: number): void {
    this.fingers.delete(id);
  }

  /** Все пальцы сняты (уход со страницы, потеря захвата). */
  clear(): void {
    this.fingers.clear();
    this.dyaw = 0;
    this.dpitch = 0;
  }

  /** Сколько пальцев на холсте — журналу касаний. */
  get fingerCount(): number {
    return this.fingers.size;
  }

  /** Нажатие ходьбы — сцене, чтобы нарисовать стик под пальцем. */
  get stick(): { ox: number; oy: number; x: number; y: number } | null {
    for (const f of this.fingers.values()) {
      if (f.half === 'walk') return { ox: f.press.x, oy: f.press.y, x: f.x, y: f.y };
    }
    return null;
  }

  /**
   * Куда идём прямо сейчас.
   *
   * Экранное «вверх» — это вперёд, «вправо» — вбок вправо. Длина обрезается
   * единицей, а не нормируется: в мёртвой зоне честный ноль, на полпути —
   * половина хода, и по диагонали игрок не должен идти быстрее, чем прямо.
   */
  walk(): Walk {
    const s = this.stick;
    if (!s) return STILL;
    const dx = s.x - s.ox;
    const dy = s.y - s.oy;
    const len = Math.hypot(dx, dy);
    if (len <= STICK_DEAD) return STILL;
    const k = Math.min(1, (len - STICK_DEAD) / (STICK_FULL - STICK_DEAD)) / len;
    return { forward: -dy * k, strafe: dx * k };
  }

  /**
   * Забрать накопленный поворот и обнулить его.
   *
   * Забирают раз в кадр. Копится он в обработчике, а не читается из последней
   * точки, потому что за один кадр `pointermove` приходит по нескольку раз, и
   * потерянные между ними пиксели — это потерянный поворот.
   */
  takeLook(): { yaw: number; pitch: number } {
    const out = { yaw: this.dyaw, pitch: this.dpitch };
    this.dyaw = 0;
    this.dpitch = 0;
    return out;
  }

  /** Добавить поворот со стороны — колесо мыши сюда не ходит, а клавиши да. */
  addLook(yaw: number, pitch: number): void {
    this.dyaw += yaw;
    this.dpitch += pitch;
  }
}

/**
 * Ходьба с клавиатуры — на ПК её ждут, и без неё режим там не проверить.
 *
 * Раскладок две сразу и без выбора в настройках: латинская `wasd` и стрелки.
 * Кириллическая приезжает сама — `KeyW` не зависит от раскладки, в отличие от
 * `key`, который на русской вернул бы «ц».
 */
export class Keys {
  private held = new Set<string>();

  down(code: string): boolean {
    if (!KEY_WALK[code]) return false;
    this.held.add(code);
    return true;
  }

  up(code: string): void {
    this.held.delete(code);
  }

  clear(): void {
    this.held.clear();
  }

  /** Куда ведут зажатые клавиши. Длина, как и у стика, не больше единицы. */
  walk(): Walk {
    let forward = 0;
    let strafe = 0;
    for (const code of this.held) {
      const d = KEY_WALK[code];
      if (!d) continue;
      forward += d.forward;
      strafe += d.strafe;
    }
    const len = Math.hypot(forward, strafe);
    if (len === 0) return STILL;
    const k = Math.min(1, len) / len;
    return { forward: forward * k, strafe: strafe * k };
  }
}

/** Что делает каждая клавиша ходьбы. Таблица, а не условия по коду. */
const KEY_WALK: Record<string, Walk | undefined> = {
  KeyW: { forward: 1, strafe: 0 },
  ArrowUp: { forward: 1, strafe: 0 },
  KeyS: { forward: -1, strafe: 0 },
  ArrowDown: { forward: -1, strafe: 0 },
  KeyA: { forward: 0, strafe: -1 },
  ArrowLeft: { forward: 0, strafe: -1 },
  KeyD: { forward: 0, strafe: 1 },
  ArrowRight: { forward: 0, strafe: 1 },
};

/** Клавиши действия: то же, что тап пальцем. */
export const KEY_ACT = ['Space', 'KeyE', 'Enter'];

/**
 * Клавиша лука — своя, и не рядом с действием.
 *
 * На ПК соблазн повесить выстрел на ту же клавишу велик: «и то, и другое —
 * сделать». Но это ровно та подмена, которой в режиме быть не должно: действие
 * не целится, выстрел целится. Одна клавиша на двоих означала бы, что у пальца
 * и у клавиатуры разные правила, — а тогда и правило одно на всех перестаёт
 * быть правилом.
 */
export const KEY_BOW = 'KeyF';

/** Складывает ходьбу пальцем и клавишами: держать можно и то, и другое. */
export function mergeWalk(a: Walk, b: Walk): Walk {
  const forward = a.forward + b.forward;
  const strafe = a.strafe + b.strafe;
  const len = Math.hypot(forward, strafe);
  if (len <= 1) return { forward, strafe };
  return { forward: forward / len, strafe: strafe / len };
}
