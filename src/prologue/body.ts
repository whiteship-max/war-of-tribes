/**
 * Человек: голод, холод и смерть. Две шкалы — **чистые функции от времени**, по
 * тому же правилу, что костёр.
 *
 * ГРАНИЦА ВРЕМЕНИ ЗДЕСЬ ТА ЖЕ, И ОНА НЕ РАЗМЫТА НИ НА ШАГ. В сохранении лежат
 * два числа на шкалу — сколько было и в какую минуту, — а сколько сейчас,
 * выводит формула в момент вопроса. Тика нет, таймера нет, догона нет. Час игры
 * и час без игры стоят человеку одинаково, и неважно, сколько раз за это время
 * открывали аппку.
 *
 * ГОЛОД РАСТЁТ ВСЕГДА, и это одна прямая: `hunger` от 0 до 1 за `STARVE_MS`.
 *
 * ХОЛОД СЛОЖНЕЕ, ПОТОМУ ЧТО У НЕГО ДВЕ СКОРОСТИ И ОНИ РАЗНЫХ ПОРЯДКОВ.
 *
 *   стынет      восемь часов от тепла до смерти — и вдали от огня, и у
 *               погасшего костра, одной скоростью. Это срок **отсутствия**:
 *               им меряется ночь без огня, а не пробежка до дерева;
 *   отогревается двадцать минут от края до нуля — и только у горящего огня.
 *               Это срок **захода**: игрок видит, как полоса тает, пока он
 *               стоит у костра.
 *
 * Скорости разошлись не для баланса, а потому что иначе не бывает: заход длится
 * три минуты, отсутствие — сутки, и одной линейной скоростью обслужить оба
 * нельзя. Выбрано так, чтобы **видно было то, что игрок делает**, — а делает он
 * ровно одно: возвращается к огню. То, что от огня он стынет медленно, — правда
 * и по жизни: тринадцать метров от костра и погасшая стоянка греют одинаково,
 * то есть никак.
 *
 * УХОДЯ, ЧЕЛОВЕК ВОЗВРАЩАЕТСЯ К КОСТРУ — И ЭТО ПРАВИЛО, А НЕ ОГОВОРКА.
 *
 * Отметка `warm` («грелся ли он в минуту `at`») на диск ложится всегда
 * поднятой: промежуток между заходами человек проводит на стоянке, а не в том
 * месте, где его застало закрытие вкладки. Иначе игра убивала бы за то, что
 * телефон сел у дерева, — а это ровно тот случай, которого быть не должно:
 * «ушёл на сутки — его решение», но «телефон разрядился на полушаге» — не
 * решение вовсе. Делает это `savePrologue`, и делает **структурно**: он
 * закрывает отрезок текущей отметкой и только потом кладёт `warm: true`, —
 * поэтому пройденное вдали от огня не пропадает, а будущее считается по
 * стоянке.
 *
 * НОЧЬ И СНЕГ СТУДЯТ БЫСТРЕЕ, И ЭТО НЕ ТРЕТЬЯ СКОРОСТЬ, А ТА ЖЕ.
 *
 * «Стынет» по-прежнему одно и меряется по-прежнему восьмью часами — только часы
 * эти теперь **холодовые**: ночь идёт за 1.8 обычных, снег за 1.6, вместе за
 * 2.88 (`sky.chilledMs`). Скорость от этого не раздвоилась: она одна, а идёт по
 * ней время неравномерно, и считается это тем же интегралом по кольцу погод,
 * каким прогорает очаг. Добавочность интеграла и есть всё, что нужно: отрезок
 * закрывается в любую минуту, а пересчёт по частям даёт то же число, что
 * целиком.
 *
 * Отогревается человек, наоборот, **одной скоростью в любую погоду**: у огня
 * греет огонь, а не небо. Двух скоростей у отогрева быть не должно — это тест.
 *
 * СМЕРТЬ — ТОЖЕ ЧТЕНИЕ, А НЕ СОБЫТИЕ. Поля «мёртв» в сохранении нет и заводить
 * его нельзя: голод не убывает никогда, холод, дойдя до края, там и остаётся
 * (`coldAt` из единицы не выпускает), и раны, дойдя до смертельного числа,
 * больше не заживают (`hurtAt`). Поэтому «жив ли он» — это вопрос к формуле, и
 * ответ на него один и тот же, сколько раз ни спроси.
 *
 * ПРИЧИН СМЕРТИ ТЕПЕРЬ ТРИ, И ТРЕТЬЯ — ВОЛКИ. Раны — не третья шкала того же
 * рода, что голод и холод: те растут сами и требуют присмотра, а рана случается
 * от чужого зуба и заживает без единого действия игрока. И на экране её нет,
 * пока её нет на человеке, — по тому же правилу, по которому не видно полосы
 * холода, пока с теплом всё хорошо.
 *
 * ОДЕЖДА И КРЫША — ТОЖЕ НЕ НОВЫЕ СКОРОСТИ, А МНОЖИТЕЛИ К ТОЙ ЖЕ. Одежда
 * замедляет остывание ровно на `COAT_CHILL` где угодно; крыша снимает небо —
 * под ней ночь и снег не студят сильнее, и холодовые часы идут как погожие. Ни
 * то, ни другое не греет: у огня греет огонь, и отогрев от них не зависит.
 * Крыша — отметка того же рода, что `warm`: в памяти её ведёт сцена по кругу у
 * дома, на диск она ложится тем, что даёт стоянка, — ночует ли человек в
 * достроенном доме.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов.
 */
import { HEARTH_CAP, LOG_MS, spanWords, type Hearth } from './fire';
import { burnUntil, chillUntil, chilledMs } from './sky';

const H = 3_600_000;

/**
 * Сколько часов человек живёт от полной сытости до смерти.
 *
 * Сорок восемь — ровно столько же, сколько горит полный очаг, и это не
 * совпадение, а то, что игрок должен запомнить с одного раза: **двое суток на
 * полном очаге и полном животе.** Разведи эти два числа — и полоса костра
 * начнёт обещать срок, которого не переживёт человек.
 */
export const STARVE_H = 48;
export const STARVE_MS = STARVE_H * H;

/** Сколько часов человек стынет от тепла до смерти без огня. Одна ночь. */
export const CHILL_H = 8;
export const CHILL_MS = CHILL_H * H;

/** За сколько минут у горящего костра он отогревается с самого края. */
export const WARM_MIN = 20;
export const WARM_MS = WARM_MIN * 60_000;

/**
 * Сколько укусов — смерть.
 *
 * Три, и это не запас прочности, а условие: **волки не должны убивать раньше,
 * чем игрок понял, что они есть.** Один укус смертельный означал бы смерть от
 * зверя, которого игрок в первый раз только увидел; три дают ему увидеть, отойти
 * к огню или отбиться топором. Сколько времени проходит между укусами, решает не
 * этот файл, а `wolves.ts`, — и вместе с этим числом оно и даёт срок, за который
 * стаю нельзя не заметить.
 */
export const WOUNDS_FATAL = 3;

/** За сколько часов заживает один укус. Сам, без единого действия игрока. */
export const WOUND_HEAL_H = 6;
export const WOUND_MS = WOUND_HEAL_H * H;

/**
 * Во сколько раз медленнее стынет одетый.
 *
 * Шесть десятых — и ровно эту цифру обещает одежда, и тест держит её ровно, а не
 * «около»: без огня под открытым небом одетый живёт не пять с половиной часов, а
 * девять с лишним, в доме — тринадцать с третью. Отогрев одежда не ускоряет: у
 * огня греет огонь.
 */
export const COAT_CHILL = 0.6;

/**
 * Что человек помнит о себе между заходами.
 *
 * Четыре числа и три отметки. Больше в нём ничего нет и быть не должно:
 * «сколько осталось», «через сколько умрёт», «мёрзнет ли», «заживёт ли» — всё
 * это считается отсюда при чтении.
 */
export interface Body {
  /** Голод в минуту `at`: 0 — сыт, 1 — умер. */
  hunger: number;
  /** Холод в минуту `at`: 0 — тепло, 1 — умер. */
  cold: number;
  /** Ран в минуту `at`: `WOUNDS_FATAL` — загрызли. Заживают сами. */
  hurt: number;
  /** Одет ли в шкуру. Хранится как есть: одежда — вещь, а не место. */
  coat: boolean;
  /** Когда это было, по `serverNow()`. */
  at: number;
  /**
   * Грелся ли он у огня в минуту `at`.
   *
   * Единственное поле, которое **не хранится**: на диск оно ложится всегда
   * поднятым (см. шапку файла), а в памяти его ведёт сцена — по кругу у костра,
   * а не по кадрам.
   */
  warm: boolean;
  /**
   * Под крышей ли он в минуту `at`.
   *
   * Как и `warm`, **не хранится как есть**: на диск ложится тем, что даёт
   * стоянка, — ночует ли человек в достроенном доме (`camp`), — а в памяти её
   * ведёт сцена, по кругу у дома.
   */
  roof: boolean;
}

const clamp = (v: number, lo: number, hi: number): number => (v < lo ? lo : v > hi ? hi : v);

/** Свежий человек: сыт, в тепле, у огня, цел, раздет и не под крышей. */
export const newBody = (now: number): Body => ({
  hunger: 0,
  cold: 0,
  hurt: 0,
  coat: false,
  at: now,
  warm: true,
  roof: false,
});

/**
 * Когда погаснет костёр.
 *
 * Единственный перелом, который может случиться с холодом сам собой, без
 * единого действия игрока, — и потому его надо уметь назвать числом, а не
 * ловить тиком. Пустой очаг не гаснет «в момент `at`»: он уже погас, и времени
 * до этого у нас не записано (см. `fuelAt` — до `h.at` он отдаёт что записано).
 */
export const fireOutAt = (h: Hearth): number =>
  h.fuel > 0 ? burnUntil(h.at, Math.min(h.fuel, HEARTH_CAP) * LOG_MS) : -Infinity;

/** Сколько голода сейчас. Растёт всегда и не убывает сам никогда. */
export function hungerAt(b: Body, now: number): number {
  return clamp(b.hunger + Math.max(0, now - b.at) / STARVE_MS, 0, 1);
}

/**
 * Сколько ран сейчас.
 *
 * Заживают сами, по часам, и в этом вся разница между раной и шкалой: за
 * голодом и холодом надо следить, а рану надо пережить. Дойдя до смертельного
 * числа, раны больше не заживают — иначе загрызенный оживал бы сам, ровно как
 * оживал бы у костра замёрзший, если бы `coldAt` выпускал из единицы.
 */
export function hurtAt(b: Body, now: number): number {
  const had = clamp(b.hurt, 0, WOUNDS_FATAL);
  if (had >= WOUNDS_FATAL) return WOUNDS_FATAL;
  return clamp(had - Math.max(0, now - b.at) / WOUND_MS, 0, WOUNDS_FATAL);
}

/**
 * Сколько холода набирается за промежуток вдали от огня.
 *
 * Крыша снимает небо — время идёт как погожее; одежда снимает долю. Одна
 * функция на `coldAt` и `coldDeadAt`, и другой быть не должно: разойдись они —
 * полоса называла бы один срок, а умирал бы человек в другой.
 */
const chillGain = (b: Body, from: number, to: number): number =>
  ((b.roof ? Math.max(0, to - from) : chilledMs(from, to)) * (b.coat ? COAT_CHILL : 1)) / CHILL_MS;

/** В какую минуту от `from` наберётся `gain` холода — обратная к `chillGain`. */
const chillReach = (b: Body, from: number, gain: number): number => {
  const need = (gain * CHILL_MS) / (b.coat ? COAT_CHILL : 1);
  return b.roof ? from + need : chillUntil(from, need);
};

/**
 * Сколько холода сейчас.
 *
 * Отрезок от `b.at` до `now` ломается **не больше одного раза** — в минуту, в
 * которую гаснет костёр, — и каждый кусок считается своей скоростью. Разбиение
 * при этом точное: пересчитай тот же промежуток по частям — получишь то же
 * число, что и целиком. На этом стоит право закрывать отрезок в любую минуту
 * (`anchor`), а на нём, в свою очередь, — вся запись на диск.
 *
 * Дойдя до единицы, холод оттуда не выходит: человек умер, и отогревать его
 * незачем. Без этого правила мертвец, оставленный у костра, оживал бы сам.
 */
export function coldAt(b: Body, h: Hearth, now: number): number {
  let c = clamp(b.cold, 0, 1);
  if (c >= 1) return 1;
  const t0 = b.at;
  const t1 = Math.max(t0, now);
  const out = fireOutAt(h);
  const marks = out > t0 && out < t1 ? [t0, out, t1] : [t0, t1];
  for (let i = 0; i + 1 < marks.length; i++) {
    const from = marks[i];
    const to = marks[i + 1];
    // Отрезок целиком до гашения — значит, огонь на нём был.
    const lit = to <= out;
    // Делением, а не умножением на обратное: восемь часов обязаны дать ровно
    // единицу, иначе `coldAt` и `coldDeadAt` разойдутся на границе, и человек,
    // у которого срок вышел, окажется живым на одну наносекунду.
    //
    // Отогрев идёт по настоящим часам, остывание — по холодовым: у огня греет
    // огонь, а стынет человек тем быстрее, чем хуже ночь и погода.
    c = clamp(c + (b.warm && lit ? -(to - from) / WARM_MS : chillGain(b, from, to)), 0, 1);
    if (c >= 1) return 1;
  }
  return c;
}

/** Греется ли человек прямо сейчас: у огня и огонь горит. */
export const warming = (b: Body, h: Hearth, now: number): boolean =>
  b.warm && fireOutAt(h) > Math.max(b.at, now);

/** В какую минуту человек умрёт от голода, если не поест. */
export const hungerDeadAt = (b: Body): number => b.at + (1 - clamp(b.hunger, 0, 1)) * STARVE_MS;

/**
 * В какую минуту человек замёрзнет насмерть, если ничего не изменится.
 *
 * Тот же обход, что у `coldAt`, только наоборот: не «сколько холода к минуте»,
 * а «в какую минуту наберётся единица». Считать это надо, а не прикидывать:
 * полоса тепла обязана называть срок теми же словами, что полоса костра, и
 * ошибка тут — это обещание, которое не сбудется.
 *
 * `Infinity` не бывает: костёр когда-нибудь гаснет, а без огня стынут всегда.
 */
export function coldDeadAt(b: Body, h: Hearth): number {
  let c = clamp(b.cold, 0, 1);
  if (c >= 1) return b.at;
  let t = b.at;
  const out = fireOutAt(h);
  if (out > t) {
    if (b.warm) {
      c = clamp(c - (out - t) / WARM_MS, 0, 1);
    } else {
      // Стынет при живом огне — значит, стоит вдали от него. Успеет ли срок
      // выйти до гашения, спрашиваем у того же кольца: холодовые часы идут
      // неровно, и «сколько осталось» линейкой тут не отмерить.
      const when = chillReach(b, t, 1 - c);
      if (when <= out) return when;
      c = clamp(c + chillGain(b, t, out), 0, 1);
    }
    t = out;
  }
  return chillReach(b, t, 1 - c);
}

/** Сколько осталось до голодной смерти, миллисекунды. */
export const hungerLeftMs = (b: Body, now: number): number => Math.max(0, hungerDeadAt(b) - now);

/** Сколько осталось до смерти от холода, миллисекунды. */
export const coldLeftMs = (b: Body, h: Hearth, now: number): number =>
  Math.max(0, coldDeadAt(b, h) - now);

/** Отчего человек умер. `null` — жив. */
export type Death = 'hunger' | 'cold' | 'wolf' | null;

/**
 * В какую минуту его загрызли. `Infinity` — не загрызли.
 *
 * Рана — единственная причина смерти, у которой нет будущего срока: голод и
 * холод можно предсказать, а зуб — нет. Поэтому и минута тут одна: та, в
 * которую пришёлся последний укус, то есть `b.at`.
 */
export const wolfDeadAt = (b: Body): number => (clamp(b.hurt, 0, WOUNDS_FATAL) >= WOUNDS_FATAL ? b.at : Infinity);

/**
 * Жив ли человек, и если нет — отчего умер.
 *
 * Сравниваются **сроки**, а не шкалы: если сошлись две причины, назвать надо
 * ту, что случилась раньше. Иначе игрок, замёрзший к утру и «доголодавший» бы к
 * вечеру, прочитал бы про голод — и не понял бы, чего ему не хватило.
 */
export function causeOfDeath(b: Body, h: Hearth, now: number): Death {
  const wolf = hurtAt(b, now) >= WOUNDS_FATAL ? wolfDeadAt(b) : Infinity;
  const cold = coldAt(b, h, now) >= 1 ? coldDeadAt(b, h) : Infinity;
  const hunger = hungerAt(b, now) >= 1 ? hungerDeadAt(b) : Infinity;
  const first = Math.min(wolf, cold, hunger);
  if (first === Infinity) return null;
  return first === wolf ? 'wolf' : first === cold ? 'cold' : 'hunger';
}

/** Отчего умер — словами, для экрана. */
export const deathWords = (d: Death): string =>
  d === 'cold' ? 'Замёрз' : d === 'hunger' ? 'Умер от голода' : d === 'wolf' ? 'Загрызли волки' : '';

/**
 * Закрыть отрезок: посчитать голод, холод и раны на минуту `now` и записать её
 * отметкой.
 *
 * Действие само по себе ничего не меняет — числа после него те же, что дала бы
 * формула, — и именно поэтому им можно пользоваться свободно: перед едой, перед
 * записью на диск, при выходе из круга у костра. Это и есть то, чем «на чтении»
 * отличается от «по тику»: у отрезков нет длины, которую нельзя переназначить.
 */
export function anchor(b: Body, h: Hearth, now: number): Body {
  return {
    hunger: hungerAt(b, now),
    cold: coldAt(b, h, now),
    hurt: hurtAt(b, now),
    // Часы, переведённые назад, отметку не двигают: запись из будущего должна
    // остаться записью из будущего, а не подарить человеку прожитое заново.
    at: Math.max(b.at, now),
    warm: b.warm,
    coat: b.coat,
    roof: b.roof,
  };
}

/**
 * Волк дотянулся.
 *
 * ЭТО ТРЕТЬЕ МЕСТО, ГДЕ КАДР КАСАЕТСЯ ЗАПИСИ, И ОНО ТОЖЕ СОБЫТИЕ, А НЕ
 * ВЕЛИЧИНА. Первые два — человек пересёк круг у костра и стрела долетела.
 * Устроено так же: отрезок закрывается формулой, отметка переезжает на текущую
 * минуту, число ран растёт на единицу — и дальше опять считает формула. В
 * кадрах не копится ничего.
 */
export const bite = (b: Body, h: Hearth, now: number): Body => {
  const a = anchor(b, h, now);
  /*
   * УКУСОВ РОВНО СТОЛЬКО, СКОЛЬКО ИХ СЛУЧИЛОСЬ, и недожившая доля идёт в счёт
   * как целая рана. Складывать напрямую нельзя, и это поймал тест: между
   * укусами проходит три секунды, за них заживает одна десятитысячная — и три
   * укуса подряд давали 2.9999, то есть **не смерть**. Волки убивали бы с
   * четвёртого раза, а сказано у нас «с третьего».
   *
   * Заживание при этом осталось непрерывным, и это условие: на нём стоит
   * добавочность (`anchor` можно звать в любую минуту), а на ней — вся запись
   * на диск. Целые укусы в записи и дробное заживание при чтении — то же
   * устройство, что у полена в очаге.
   */
  const open = Math.ceil(a.hurt - 1e-9);
  return { ...a, hurt: clamp(open + 1, 0, WOUNDS_FATAL) };
};

/** Человек вошёл в круг у костра или вышел из него. */
export const setWarm = (b: Body, h: Hearth, now: number, warm: boolean): Body =>
  warm === b.warm ? b : { ...anchor(b, h, now), warm };

/**
 * Человек вошёл под крышу дома или вышел из-под неё.
 *
 * Событие того же рода, что круг у огня: отрезок закрывается прежней скоростью,
 * дальше считает новая. В кадрах не копится ничего.
 */
export const setRoof = (b: Body, h: Hearth, now: number, roof: boolean): Body =>
  roof === b.roof ? b : { ...anchor(b, h, now), roof };

/** Надеть сшитую одежду. До минуты `now` стыл раздетым, дальше — одетым. */
export const wearCoat = (b: Body, h: Hearth, now: number): Body => ({ ...anchor(b, h, now), coat: true });

/**
 * Отметка «человек на стоянке» — та, что уезжает на диск.
 *
 * Пройденное вдали от огня закрывается честно (`anchor`), а всё, что случится
 * дальше, считается по стоянке. Почему так — в шапке файла.
 *
 * Стоянка — это огонь и, если дом достроен, крыша над головой: ночует человек
 * в доме. `roof` передаёт тот, кто знает про дом (`save.ts`), — телу про стройку
 * знать незачем.
 */
export const camp = (b: Body, h: Hearth, now: number, roof = false): Body => ({
  ...anchor(b, h, now),
  warm: true,
  roof,
});

/** Сколько часов сытости даёт кусок жареного мяса. */
export const MEAT_FED_H = 8;

/**
 * Во сколько раз сырое мясо хуже жареного.
 *
 * Есть сырое **можно**, и это решение, а не недоделка: запрет был бы погасшей
 * кнопкой там, где у игрока есть выбор, — а выбор здесь настоящий. Цена сырого
 * не в болезни (болезнь была бы третьей шкалой, а их и так две), а в том, что
 * туша не бесконечна: съеденное сырьём — это две трети оленя, выброшенные в
 * никуда. Отсюда и вся ценность огня: он не только греет, он утраивает добычу.
 */
export const RAW_SHARE = 1 / 3;

/** Сколько часов сытости даёт кусок: жареный или сырой. */
export const mealHours = (raw: boolean): number => (raw ? MEAT_FED_H * RAW_SHARE : MEAT_FED_H);

/**
 * Поесть.
 *
 * Сверх сытости не наедаются: съеденное на полный живот пропадает, и потому
 * есть на полный живот `act.ts` не даёт. Запасают мясо, а не сытость.
 */
export function eat(b: Body, h: Hearth, now: number, raw: boolean): Body {
  const a = anchor(b, h, now);
  return { ...a, hunger: clamp(a.hunger - (mealHours(raw) * H) / STARVE_MS, 0, 1) };
}

/** Сытость полосой: 1 — сыт, 0 — умер. */
export const fedFill = (b: Body, now: number): number => 1 - hungerAt(b, now);

/** Холод полосой: 0 — тепло, 1 — умер. Это полоса тревоги, а не запаса. */
export const coldFill = (b: Body, h: Hearth, now: number): number => coldAt(b, h, now);

/** Сколько ещё протянет без еды — словами. */
export const hungerWords = (b: Body, now: number): string => {
  const ms = hungerLeftMs(b, now);
  return ms <= 0 ? 'голод' : spanWords(ms);
};

/** Что с теплом — словами. */
export const coldWords = (b: Body, h: Hearth, now: number): string => {
  if (coldAt(b, h, now) >= 1) return 'замёрз';
  if (warming(b, h, now)) return coldAt(b, h, now) > 0 ? 'греется' : 'тепло';
  return spanWords(coldLeftMs(b, h, now));
};

/** Раны полосой: 0 — цел, 1 — загрызли. Полоса тревоги, как у холода. */
export const hurtFill = (b: Body, now: number): number => hurtAt(b, now) / WOUNDS_FATAL;

/**
 * Что с ранами — словами.
 *
 * Срок тут не «сколько осталось жить», а «когда заживёт»: рана — единственная
 * беда режима, которая проходит сама, и сказать об этом надо прямо, иначе игрок
 * прочтёт полосу как отсчёт до смерти и уйдёт из игры пережидать.
 */
export const hurtWords = (b: Body, now: number): string => {
  const hurt = hurtAt(b, now);
  if (hurt >= WOUNDS_FATAL) return 'загрызли';
  if (hurt <= 0) return 'цел';
  return `заживёт: ${spanWords(hurt * WOUND_MS)}`;
};
