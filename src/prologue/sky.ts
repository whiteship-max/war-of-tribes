/**
 * Сутки и погода поляны.
 *
 * У ПРЕДЫСТОРИИ ТЕПЕРЬ ТРИ ЧИСЛА ВРЕМЕНИ, И ПУТАТЬ ИХ НЕЛЬЗЯ. Написано это здесь
 * потому, что здесь появилось третье, и следующая сессия обязана прочитать его
 * раньше, чем начнёт правку.
 *
 *   1. **Время сцены** — `performance.now()`, цикл кадров. Шаг, взгляд, замах,
 *      дрожь пламени, бег зверя, полёт стрелы. Живёт только в `scene.ts`, в
 *      сохранение не попадает ни одним числом.
 *   2. **Наши часы** — `serverNow()`. Ими считается всё, что переживает выход:
 *      костёр, голод, холод, пни, зверь. Настоящие часы, настоящие сутки: без
 *      огня человек живёт **восемь настоящих часов**, полено горит **шесть**.
 *   3. **Круг суток** — тоже `serverNow()`, но **свой масштаб**: день и ночь
 *      сменяются за `SKY_MS` (четыре минуты), а не за двадцать четыре часа.
 *
 * ТРЕТЬЕ И ВТОРОЕ — ОДНИ ЧАСЫ, НО РАЗНАЯ МЕРА, И ЭТО РЕШЕНИЕ, А НЕ НЕДОСМОТР.
 * Заход длится три-пять минут, а игрок обязан застать и день, и ночь: ночь —
 * половина того, зачем нужен костёр, и оставить её на «когда-нибудь» значит не
 * показать её никому. Настоящие сутки показали бы одному игроку вечную ночь, а
 * другому вечный день, и оба решили бы, что так и надо.
 *
 * Считать это вместе несложно, потому что **круг тоже чистая функция от
 * времени**: у него нет ни тика, ни таймера, ни догона, и вернувшийся через
 * двое суток застаёт ровно тот час, который назвала формула. Врозь эти две меры
 * живут ровно в одном месте — в словах: срок называется настоящими часами
 * (`spanWords`), а небо — своим кругом.
 *
 * ПОГОДА — ТАКАЯ ЖЕ ФОРМУЛА, И ОНА КОЛЬЦЕВАЯ. Спеллов в кольце `WEATHER_RING`,
 * каждый длиной `SPELL_MS`, и лежат они **данными**, а не броском: место дерева
 * и место оленя в этой папке тоже написаны числами, и по той же причине — в
 * диффе должно быть видно, что именно переехало. `Math.random` здесь нет и быть
 * не может.
 *
 * ЗАЧЕМ КОЛЬЦО, А НЕ ХЕШ ОТ НОМЕРА СПЕЛЛА. Погода двигает две величины, которые
 * обязаны считаться **на чтении и за один шаг**: прогорание очага (дождь жжёт
 * втрое быстрее) и остывание человека (ночь и снег студят сильнее). Обе — это
 * интегралы ставочной функции по промежутку, и промежуток бывает в тридцать
 * суток. Хеш от номера спелла заставил бы обходить пятнадцать тысяч спеллов на
 * каждое чтение — то есть завёл бы догон офлайна, которого в этом режиме нет
 * нигде. Кольцо даёт закрытую форму: целые кольца берутся умножением, неполное
 * — обходом двух десятков отрезков.
 *
 * Плата названа вслух: **погода повторяется раз в двадцать восемь минут**.
 * Заход — три-пять; до второго круга не доживает никто, а кто доживёт, тот и
 * заслужил узнать, что за миром стоит правило.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов, ни случайности. «Сейчас»
 * ему передают числом.
 */

/**
 * Длина круга суток.
 *
 * Четыре минуты — не «красиво», а выведено из захода. Пусть заход `S`, круг `C`,
 * доля дня `d`. Игрок застанет и день, и ночь при любом начале, если `S` не
 * короче самой длинной половины круга, то есть `S ≥ d·C`. При `S` = 3 мин и
 * `d` = 0.62 отсюда `C ≤ 4 мин 50 с`; взято четыре — с запасом, и заодно круг
 * укладывается в заход целиком, так что игрок видит смену дважды, а не однажды.
 *
 * Сравнить не с чем, кроме деревни, и там масштаб того же порядка: игровые
 * сутки посёлка — шестьдесят секунд, сезон — пять минут.
 */
export const SKY_MS = 240_000;

/**
 * Какая доля круга приходится на день.
 *
 * День длиннее ночи (2 мин 29 с против 1 мин 31 с), и это не поблажка: ночь —
 * время, когда спит зверь и ходят волки, то есть время, в которое игрок мало
 * что может. Ночь длиной вполкруга превратила бы половину захода в ожидание.
 */
export const DAY_SHARE = 0.62;

/**
 * Сколько стоит одна погода.
 *
 * Полкруга — то есть либо целиком день, либо конец дня с ночью. Не своё число, а
 * доля круга нарочно: погода, чей шаг не кратен суткам, ползла бы по ним, и
 * кольцо перестало бы замыкаться на целом числе кругов — а на этом стоит вся
 * закрытая форма.
 */
export const SPELL_MS = SKY_MS / 2;

/**
 * Сколько погод в кольце.
 *
 * Четырнадцать — это ровно семь кругов суток, то есть двадцать восемь минут.
 * Чётное нужно затем, чтобы кольцо кончалось на начале круга: тогда общий период
 * «сутки плюс погода» равен кольцу, а не удвоенному кольцу.
 */
export const WEATHER_RING = 14;

/** Полный период мира: двадцать восемь минут, семь кругов суток. */
export const RING_MS = WEATHER_RING * SPELL_MS;

/** Что на небе. Третьего рода непогоды нет и заводить не надо. */
export type Weather = 'clear' | 'rain' | 'snow';

/**
 * Кольцо погод — данными, а не хешем.
 *
 * Чётные спеллы начинаются с началом круга и приходятся на день целиком;
 * нечётные — на хвост дня и всю ночь. Поэтому дождь и снег расставлены и по
 * тем, и по этим: непогода, живущая только ночью, читалась бы частью ночи.
 *
 * Девять погожих, три дождя, два снега: 64% ясно, 21% дождь, 14% снег. За
 * заход в четыре минуты игрок проходит два спелла, и непогоду застаёт примерно
 * каждый второй раз — то есть она событие, а не фон.
 */
export const RING: readonly Weather[] = [
  'clear', // 0  день
  'clear', // 1  вечер и ночь
  'rain', //  2  день
  'clear', // 3
  'clear', // 4  день
  'snow', //  5  вечер и ночь
  'clear', // 6
  'rain', //  7  вечер и ночь
  'clear', // 8
  'clear', // 9
  'snow', //  10 день
  'clear', // 11
  'rain', //  12 день
  'clear', // 13
];

/**
 * Во сколько раз дождь ускоряет прогорание очага.
 *
 * ДОЖДЬ НЕ ГАСИТ КОСТЁР, А ЖЖЁТ ЕГО ВТРОЕ БЫСТРЕЕ, и выбрано это, а не гашение,
 * по трём причинам — все три про обещание, которое даёт полоса.
 *
 *   1. **Задним числом ничего не отбирается.** Полоса костра отвечает на один
 *      вопрос — «успею ли вернуться», — и ответ она считает **через прогноз**
 *      (`fire.burnLeftMs` идёт по этому же кольцу). Уходя, игрок видит честный
 *      срок вместе с дождём, который в него войдёт. Гашение же означало бы, что
 *      обещанные двое суток кончились в минуту, о которой полоса не знала.
 *   2. **Погибнуть из-за погоды нельзя.** Втрое — это «сильно», но конечно:
 *      полный очаг под непрерывным дождём горит шестнадцать часов, и восьми
 *      часов холода сверху не хватит, чтобы уложиться в один дождь. Погашенный
 *      же очаг начинает студить сразу.
 *   3. **Числа режима уцелели.** «Двое суток на полном очаге» — это по-прежнему
 *      правда про погожее время, и `HEARTH_CAP × LOG_HOURS` не тронуты.
 *
 * Видно это сразу и без слов: под дождём полоса ползёт втрое быстрее, а небо
 * хмурится **до** первой капли (`gloom`), так что «успею подложить» — решение, а
 * не неожиданность.
 */
export const RAIN_BURN = 3;

/** Во сколько раз ночью стынут быстрее. */
export const NIGHT_CHILL = 1.8;

/** Во сколько раз быстрее стынут в снег. Множится с ночным. */
export const SNOW_CHILL = 1.6;

/**
 * За сколько до непогоды хмурится небо.
 *
 * Двадцать пять секунд — то, за что человек успевает дойти до дерева и обратно
 * (полный заход за дровами — шесть секунд). Меньше значило бы «узнал, когда
 * полило».
 */
export const OMEN_MS = 25_000;

const clamp = (v: number, lo: number, hi: number): number => (v < lo ? lo : v > hi ? hi : v);

/** Отрезок кольца, внутри которого и небо, и погода постоянны. */
interface Span {
  at: number;
  until: number;
  night: boolean;
  weather: Weather;
}

/**
 * Кольцо, разложенное по отрезкам.
 *
 * Границы двух родов: конец спелла и переход дня в ночь. Внутри отрезка обе
 * ставки постоянны, поэтому интеграл по нему — умножение. Считается это один
 * раз при загрузке модуля: двадцать один отрезок на двадцать восемь минут мира.
 */
const SPANS: Span[] = (() => {
  const marks = new Set<number>([0, RING_MS]);
  for (let i = 0; i <= WEATHER_RING; i++) marks.add(i * SPELL_MS);
  for (let k = 0; k * SKY_MS < RING_MS; k++) marks.add(k * SKY_MS + DAY_SHARE * SKY_MS);
  const sorted = [...marks].sort((a, b) => a - b);
  const out: Span[] = [];
  for (let i = 0; i + 1 < sorted.length; i++) {
    const at = sorted[i];
    const until = sorted[i + 1];
    // Судим по середине отрезка: на самой границе ставка неопределена, а внутри
    // она одна на весь отрезок — на этом и стоит разбиение.
    const mid = (at + until) / 2;
    out.push({
      at,
      until,
      night: (mid % SKY_MS) / SKY_MS >= DAY_SHARE,
      weather: RING[Math.floor(mid / SPELL_MS) % WEATHER_RING],
    });
  }
  return out;
})();

/** Во сколько раз быстрее прогорает очаг на этом отрезке. */
const burnRate = (s: Span): number => (s.weather === 'rain' ? RAIN_BURN : 1);

/** Во сколько раз быстрее стынет человек на этом отрезке. */
const chillRate = (s: Span): number =>
  (s.night ? NIGHT_CHILL : 1) * (s.weather === 'snow' ? SNOW_CHILL : 1);

/** Накопленное к началу каждого отрезка и за кольцо целиком. */
const prefix = (rate: (s: Span) => number): { head: number[]; total: number } => {
  const head: number[] = [];
  let sum = 0;
  for (const s of SPANS) {
    head.push(sum);
    sum += (s.until - s.at) * rate(s);
  }
  return { head, total: sum };
};

const BURN = prefix(burnRate);
const CHILL = prefix(chillRate);

/** Средняя ставка за кольцо: её и печатает отчёт, и по ней считаются сроки «в среднем». */
export const BURN_MEAN = BURN.total / RING_MS;
export const CHILL_MEAN = CHILL.total / RING_MS;

/** Где мы в кольце: номер кольца и остаток. Отрицательное «сейчас» тоже считается. */
const inRing = (t: number): { ring: number; rem: number } => {
  const ring = Math.floor(t / RING_MS);
  return { ring, rem: t - ring * RING_MS };
};

/** Отрезок кольца, в котором лежит остаток. */
const spanAt = (rem: number): number => {
  for (let i = SPANS.length - 1; i >= 0; i--) if (rem >= SPANS[i].at) return i;
  return 0;
};

/** Накопленное от нуля времён до `t`. Строго возрастает: все ставки положительны. */
const upTo = (t: number, p: { head: number[]; total: number }, rate: (s: Span) => number): number => {
  const { ring, rem } = inRing(t);
  const i = spanAt(rem);
  return ring * p.total + p.head[i] + (rem - SPANS[i].at) * rate(SPANS[i]);
};

/**
 * Обратная задача: в какую минуту накопится `need` сверх минуты `from`.
 *
 * Нужна полосам: они обещают срок («хватит на 12 ч»), а срок — это ответ именно
 * на этот вопрос. Считать его приближением нельзя: полоса, ошибшаяся на час,
 * это обещание, которое не сбудется.
 */
const reach = (from: number, need: number, p: { head: number[]; total: number }, rate: (s: Span) => number): number => {
  if (!(need > 0)) return from;
  const target = upTo(from, p, rate) + need;
  const ring = Math.floor(target / p.total);
  const rem = target - ring * p.total;
  let i = SPANS.length - 1;
  for (let k = 0; k < SPANS.length; k++) {
    if (p.head[k] > rem) {
      i = k - 1;
      break;
    }
  }
  if (i < 0) i = 0;
  return ring * RING_MS + SPANS[i].at + (rem - p.head[i]) / rate(SPANS[i]);
};

/** Где мы в круге суток: 0 — рассвет, `DAY_SHARE` — закат. */
export const skyPhase = (now: number): number => {
  const p = (now % SKY_MS) / SKY_MS;
  return p < 0 ? p + 1 : p;
};

/** Ночь ли сейчас. */
export const isNight = (now: number): boolean => skyPhase(now) >= DAY_SHARE;

/**
 * Час поляны для светового рига: 0 — рассвет, 0.25 — полдень, 0.5 — закат,
 * 0.75 — глухая ночь (`render/lighting.applyDayNight`).
 *
 * День круга растягивается на полукруг солнца, ночь — на второй: иначе при
 * `DAY_SHARE` = 0.62 полдень пришёлся бы на четыре минуты и закат случался бы
 * посреди дня.
 */
export const sunAt = (now: number): number => {
  const p = skyPhase(now);
  return p < DAY_SHARE ? (p / DAY_SHARE) * 0.5 : 0.5 + ((p - DAY_SHARE) / (1 - DAY_SHARE)) * 0.5;
};

/**
 * Насколько глубока ночь: 0 днём, 1 в глухую ночь.
 *
 * Своё число, а не то, что считает риг: по нему сцена поднимает отсвет костра,
 * и «ночью костёр — единственный свет» держится именно этим.
 */
export const darkness = (now: number): number => {
  const elev = Math.sin(sunAt(now) * Math.PI * 2);
  const k = clamp(-elev / 0.3, 0, 1);
  return k * k * (3 - 2 * k);
};

/** Какая погода сейчас. */
export const weatherAt = (now: number): Weather => {
  const i = Math.floor(now / SPELL_MS) % WEATHER_RING;
  return RING[i < 0 ? i + WEATHER_RING : i];
};

/** Сколько этой погоде осталось стоять. */
export const spellLeftMs = (now: number): number => {
  const i = Math.floor(now / SPELL_MS);
  return (i + 1) * SPELL_MS - now;
};

/** Какая погода придёт следующей. */
export const nextWeather = (now: number): Weather => weatherAt(now + spellLeftMs(now) + 1);

/**
 * Насколько хмуро: 0 — ясно, 1 — льёт.
 *
 * ИГРОК ОБЯЗАН УВИДЕТЬ, ЧТО ПОРТИТСЯ, А НЕ УЗНАТЬ ПОСТФАКТУМ. Поэтому небо
 * начинает темнеть за `OMEN_MS` **до** первой капли, и это то же самое число, по
 * которому сцена гасит солнце и сгущает туман. Снег хмурее ясного, но светлее
 * дождя: под снегом видно, под дождём — нет.
 */
export const gloom = (now: number): number => {
  const here = weatherAt(now);
  if (here === 'rain') return 1;
  if (here === 'snow') return 0.6;
  const soon = nextWeather(now);
  if (soon === 'clear') return 0;
  const left = spellLeftMs(now);
  if (left > OMEN_MS) return 0;
  return (1 - left / OMEN_MS) * (soon === 'rain' ? 1 : 0.6);
};

/** Погода словами — надстройке. Ясная погода слова не занимает. */
export const weatherWords = (now: number): string => {
  const here = weatherAt(now);
  if (here === 'rain') return 'дождь';
  if (here === 'snow') return 'снег';
  return gloom(now) > 0 ? 'хмурится' : '';
};

/**
 * Сколько «горючего» времени в промежутке: дождь идёт за три обычных минуты.
 *
 * Добавочна по построению: `burnedMs(a, c) === burnedMs(a, b) + burnedMs(b, c)`.
 * На этом стоит право закрывать отрезок очага в любую минуту — то есть вся
 * запись на диск.
 */
export const burnedMs = (from: number, to: number): number =>
  to <= from ? 0 : upTo(to, BURN, burnRate) - upTo(from, BURN, burnRate);

/** В какую минуту сгорит `need` миллисекунд горючего времени. */
export const burnUntil = (from: number, need: number): number => reach(from, need, BURN, burnRate);

/**
 * Сколько «холодового» времени в промежутке: ночь и снег студят быстрее.
 *
 * Тоже добавочна, и по той же причине: холод — величина, которая переживает
 * выход, и её отрезок закрывается когда угодно.
 */
export const chilledMs = (from: number, to: number): number =>
  to <= from ? 0 : upTo(to, CHILL, chillRate) - upTo(from, CHILL, chillRate);

/** В какую минуту наберётся `need` миллисекунд холодового времени. */
export const chillUntil = (from: number, need: number): number => reach(from, need, CHILL, chillRate);

/** Сколько отрезков в кольце — отчёту и тесту: разбиение обязано быть видно. */
export const RING_SPANS = SPANS.length;

/** Кольцо отрезками — только отчёту. Игре хватает интегралов. */
export const ringSpans = (): readonly Span[] => SPANS;
