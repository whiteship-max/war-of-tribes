/**
 * Костёр предыстории: сколько в нём осталось — **чистая функция от времени**.
 *
 * ЗДЕСЬ ПРОХОДИТ ГРАНИЦА, РАДИ КОТОРОЙ ЭТОТ МОДУЛЬ И ЗАВЕДЁН ОТДЕЛЬНО.
 *
 * У режима от первого лица два разных времени, и путать их нельзя:
 *
 *   1. **Время сцены** — `performance.now()`, обычный цикл кадров. Им живут
 *      шаг, поворот головы, замах топора и дрожь пламени. Оно начинается со
 *      входом в режим и умирает вместе с ним; в сохранение не попадает ни одно
 *      его число. Это неизбежно: без кадров нет и картинки.
 *
 *   2. **Наше время** — `serverNow()` из `net/clock.ts`, единственная дверь к
 *      «сейчас». Им живёт всё, что переживает выход: горение костра, голод и
 *      холод человека, зарастание пней, зверь на поляне и срок туши.
 *
 * Второе считается **на чтении**, как логова, осада и вера: в сохранении лежат
 * два числа — сколько было дров и в какую минуту, — а сколько их сейчас,
 * выводится формулой в момент вопроса. Тика у костра нет. Таймера нет.
 * Фоновой работы нет. Догона офлайна нет — догонять нечего, потому что ничего
 * и не накапливалось: `fuelAt` даёт один и тот же ответ и через минуту, и через
 * двое суток, и неважно, сколько раз за это время игру открывали.
 *
 * Отсюда следствие, из-за которого так и сделано: **выход из игры ничем не
 * отличается от любой другой минуты.** Не надо ни ловить закрытие вкладки, ни
 * успевать записать «последний тик», ни бояться, что телефон усыпил страницу.
 * Запись — это замена пары чисел, и она может случиться когда угодно или не
 * случиться вовсе: следующий вход посчитает то же самое.
 *
 * НА ЭТОЙ ГРАНИЦЕ ТЕПЕРЬ СТОЯТ ТРОЕ: костёр, голод и холод (`body.ts`), а с ними
 * жарка и олень (`hunt.ts`). Все они устроены одинаково — пара «сколько было и
 * когда» плюс формула, — и это не совпадение, а условие: величина, заведённая
 * иначе, разойдётся с остальными у первого же игрока, свернувшего аппку.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ЧЕГО НЕЛЬЗЯ ЗАВОДИТЬ: связи с деревней и сервера.
 *
 * Модуль чистый: ни DOM, ни three, ни React, ни часов. «Сейчас» ему передают
 * числом — ровно так же, как ежедневке передают номер дня.
 */

/** Сколько часов горит одно полено. */
export const LOG_HOURS = 6;

/** Сколько миллисекунд горит одно полено. */
export const LOG_MS = LOG_HOURS * 3_600_000;

/**
 * Сколько полен помещается в очаг.
 *
 * Восемь по шесть часов — **сорок восемь**: полный костёр прогорает ровно за
 * двое суток отсутствия. Число не выбрано под красоту, оно и есть обещание
 * режима, и менять его врозь с `LOG_HOURS` нельзя — вместе они и дают двое
 * суток.
 */
export const HEARTH_CAP = 8;

/** Полный костёр в миллисекундах: двое суток. */
export const BURN_FULL_MS = HEARTH_CAP * LOG_MS;

/**
 * Костёр в сохранении: сколько было дров и в какую минуту.
 *
 * Больше в нём ничего нет и быть не должно. Всё остальное — «сколько сейчас»,
 * «на сколько хватит», «горит ли» — считается из этой пары при чтении.
 */
export interface Hearth {
  /** Полен в очаге в момент `at`. От 0 до `HEARTH_CAP`. */
  fuel: number;
  /** Когда это было, по `serverNow()`. */
  at: number;
}

const clamp = (v: number, lo: number, hi: number): number => (v < lo ? lo : v > hi ? hi : v);

/**
 * Свежий очаг. Не полный: полный костёр не оставлял бы игроку дела, а весь
 * первый кусок — про то, чтобы дойти до дерева, срубить и подложить.
 */
export const newHearth = (now: number): Hearth => ({ fuel: 2, at: now });

/**
 * Сколько полен в костре сейчас.
 *
 * Отрицательным не бывает: прогоревший костёр — это ноль, а не долг. Время
 * назад тоже не идёт: часы устройства переводят руками, и запись из будущего
 * не должна выдавать костру дров, которых в нём не было (`now < h.at` даёт
 * ровно то, что записано, — не больше).
 */
export function fuelAt(h: Hearth, now: number): number {
  const passed = Math.max(0, now - h.at);
  return clamp(h.fuel - passed / LOG_MS, 0, HEARTH_CAP);
}

/** Горит ли костёр. Ноль дров — погас. */
export const burning = (h: Hearth, now: number): boolean => fuelAt(h, now) > 0;

/** Насколько полон очаг: 0..1. Это и есть полоса горения. */
export const hearthFill = (h: Hearth, now: number): number => fuelAt(h, now) / HEARTH_CAP;

/** Сколько осталось гореть, миллисекунды. */
export const burnLeftMs = (h: Hearth, now: number): number => fuelAt(h, now) * LOG_MS;

/**
 * Подложить дров.
 *
 * Возвращает **новый** очаг, а не правит старый: запись — это замена пары
 * чисел, и на этом стоит вся граница времени. Сверх вместимости не влезает —
 * лишнее полено остаётся в руках (сколько взяли, говорит `logsTaken`).
 */
export function feed(h: Hearth, now: number, logs: number): Hearth {
  const have = fuelAt(h, now);
  return { fuel: clamp(have + Math.max(0, logs), 0, HEARTH_CAP), at: now };
}

/** Сколько полен из предложенных костёр вправду принял: остальные не влезли. */
export function logsTaken(h: Hearth, now: number, logs: number): number {
  const have = fuelAt(h, now);
  return clamp(Math.max(0, logs), 0, HEARTH_CAP - have);
}

/**
 * Снять с костра — этим платят за жарку мяса.
 *
 * Обратной стороной `feed` быть не может, и не по чистоплюйству: `feed`
 * отрицательных дров не берёт нарочно (тест), иначе опечатка в знаке молча
 * съедала бы очаг. Расход — другое дело и другое слово.
 */
export function spend(h: Hearth, now: number, logs: number): Hearth {
  const have = fuelAt(h, now);
  return { fuel: clamp(have - Math.max(0, logs), 0, HEARTH_CAP), at: now };
}

/**
 * Сколько ещё гореть — словами.
 *
 * Полоса отвечает «насколько полон», а игрок спрашивает другое: «успею ли
 * вернуться». Двое суток — срок, который полосой не выразишь, поэтому рядом с
 * ней стоит строка. Она же и объясняет, почему за один заход полоса стоит на
 * месте: у неё шаг в шесть часов, а заход — три минуты.
 *
 * Слов ровно столько, сколько нужно: раньше строка начиналась с «хватит на»,
 * и это было верно, пока она стояла одна. Полос теперь три, они стоят
 * столбиком, и «хватит на» повторённое трижды — это не пояснение, а шум;
 * заголовком служит значок слева.
 */
export function burnWords(h: Hearth, now: number): string {
  const ms = burnLeftMs(h, now);
  return ms <= 0 ? 'погас' : spanWords(ms);
}

/**
 * Срок словами — общая мерка всех трёх полос: костра, сытости и тепла.
 *
 * Живёт она здесь, потому что здесь и была придумана, и второй такой же в
 * `body.ts` быть не должно: три полосы, называющие один и тот же час по-разному,
 * читаются как три разных времени. Ноль каждая полоса называет своим словом
 * («погас», «голод», «замёрз») — вот это и есть всё, чем они отличаются.
 *
 * Часы округляются, а не отбрасываются: только что подложенные два полена — это
 * ровно двенадцать часов, и `Math.floor` показал бы «11 ч» уже через секунду
 * (поймано стендом `npm run prologue:report` на первой же строке). А вот сутки
 * отбрасываются: на вопрос «успею ли вернуться» ошибаться надо в сторону
 * осторожности, и сорок два часа честнее назвать сутками, чем двумя.
 */
export function spanWords(ms: number): string {
  const raw = ms / 3_600_000;
  if (raw < 1) return `${Math.max(1, Math.round(ms / 60_000))} мин`;
  const hours = Math.round(raw);
  if (hours < 24) return `${hours} ч`;
  const days = Math.floor(hours / 24);
  return days === 1 ? 'сутки' : `${days === 2 ? 'двое' : days} суток`;
}
