/**
 * Журнал происшествий сцены и приговор по нему.
 *
 * Заведён по жалобе, которую иначе не разобрать: игрок свернул мини-аппку в
 * Телеграме, развернул обратно — верхняя панель на месте, счётчики идут, а на
 * месте диорамы чёрный прямоугольник. Воспроизводится не каждый раз.
 *
 * Чёрный экран у трёх разных болезней выглядит одинаково:
 *   1) потерян контекст WebGL — система забрала память у фонового вебвью;
 *   2) канва вернулась нулевого или неверного размера;
 *   3) кадры не возобновились — скрытая страница не зовёт requestAnimationFrame.
 * Лечатся они по-разному, и угадывать здесь нельзя. Поэтому прибор ставится
 * раньше лечения: пусть устройство само скажет, что с ним было.
 *
 * ГЛАВНОЕ ПРАВИЛО — ЧЕСТНОСТЬ. Если по приборам причина не сходится ни с одной
 * из трёх, приговор так и звучит: «не знаю». Сломанный прибор хуже
 * отсутствующего: назвав причину наугад, он увёл бы следующую починку в сторону,
 * и её сочли бы помогшей.
 *
 * Модуль чистый: ни DOM, ни three, ни React. Записи в него кладут те, кто видит
 * события (`render/Scene`, `ui/GameCanvas`, `telegram/webapp`), а читает —
 * служебный экран в «Заданиях». Лежит в корне `src/` по той же причине, что
 * `gestures.ts` и `debug.ts`: пользуются им и сцена, и оболочка, и обёртка
 * Телеграма, и ничьим он быть не должен.
 */

/** Почему луп кадров стоит. Слова те же, что и в приговоре. */
export type Block =
  /** Открыта карта мира — диорама не рисуется нарочно. */
  | 'map'
  /**
   * Канва отдана ролику о бое — диорама не рисуется нарочно. Причина своя, а не
   * `map`: ролик открывают и с карты, и его конец не должен снимать карту.
   */
  | 'lent'
  /** Страница скрыта или аппку свернули в Телеграме: кадров не бывает вовсе. */
  | 'hidden'
  /** Контекст WebGL потерян — рисовать некуда. */
  | 'lost'
  /** Сцена выгружена. */
  | 'gone';

/** Что случилось. Подробности — в `note`, слова там для человека, а не для кода. */
export type Kind =
  /** Сцена собрана. */
  | 'scene'
  /** Сцена выгружена. */
  | 'gone'
  /** Страница скрыта. */
  | 'hide'
  /** Страница снова видима. */
  | 'show'
  /** Событие возврата из кэша страниц (pageshow / resume). */
  | 'wake'
  /** Телеграм сказал о себе: свернули, развернули, поменялся вьюпорт. */
  | 'tg'
  /** Дверь окна пересчитала высоту приложения (`src/viewport.ts`). */
  | 'app'
  /** Потерян контекст WebGL. */
  | 'lost'
  /** Контекст вернулся. */
  | 'restored'
  /** Попросили браузер вернуть контекст. */
  | 'ask'
  /** Сцена пересобрана заново. */
  | 'rebuild'
  /** Пересчитан размер холста. */
  | 'size'
  /** Размер холста нулевой — пересчёт отложен. */
  | 'zero'
  /** Луп кадров пошёл или встал. */
  | 'loop'
  /** Сторож заметил неладное. */
  | 'watch';

export interface Note {
  /** Стенные часы: в отчёте с телефона нужны именно они, а не время от запуска. */
  at: number;
  kind: Kind;
  note?: string;
}

export interface Size {
  w: number;
  h: number;
}

/** Показания приборов на момент вопроса. Всё, из чего выводится приговор. */
export interface Vitals {
  /** performance.now() в момент снятия. */
  now: number;
  /** Сколько кадров сцена нарисовала за свою жизнь. */
  frames: number;
  /** Когда пошёл последний кадр (в шкале `now`). */
  lastFrame: number;
  /** Контекст потерян и ещё не вернулся. */
  lost: boolean;
  /** Почему луп стоит; пусто — значит должен идти. */
  blocks: Block[];
  /** Размер канвы в разметке (CSS-пиксели). */
  css: Size;
  /** Размер буфера рисования (физические пиксели). */
  buffer: Size;
}

/**
 * Приговор. `unknown` — не «прочее», а прямой ответ «не знаю»: приборов нет
 * или они говорят, что всё в порядке, а игрок видит чёрное.
 */
export type Verdict = 'ok' | 'lost' | 'zero' | 'stall' | 'map' | 'hidden' | 'gone' | 'unknown';

/**
 * Сколько кадров может не быть, прежде чем это считается остановкой.
 *
 * Кадр на телефоне — 16 мс, тяжёлая заминка при смене сезона — до трёхсот.
 * Секунда с четвертью заведомо больше любой заминки и заведомо меньше того,
 * что игрок готов считать «подвисло».
 */
export const STALL_MS = 1250;

/** Сколько записей помним: весь путь «свернул — развернул» с запасом. */
export const LOG_MAX = 40;

/**
 * Приговор по показаниям. Порядок правил — это и есть их важность: сначала то,
 * что объясняет чёрный экран целиком, потом то, что объясняет его отчасти.
 *
 * Ни одно правило не догадывается. Нет приборов — `unknown`; приборы говорят,
 * что кадры идут, — `ok`, и если игрок при этом видит чёрное, честный ответ
 * тоже «не знаю», а не подстановка ближайшей похожей причины.
 */
export function diagnose(v: Vitals | null): Verdict {
  if (!v) return 'unknown';
  if (v.blocks.includes('gone')) return 'gone';
  if (v.lost || v.blocks.includes('lost')) return 'lost';
  if (v.css.w < 1 || v.css.h < 1 || v.buffer.w < 1 || v.buffer.h < 1) return 'zero';
  // Скрытую страницу спрашивают только задним числом, из журнала: пока она
  // скрыта, читать приговор некому. Но и врать про остановку кадров нельзя.
  if (v.blocks.includes('hidden')) return 'hidden';
  if (v.blocks.includes('map') || v.blocks.includes('lent')) return 'map';
  if (v.now - v.lastFrame > STALL_MS) return 'stall';
  if (v.frames > 0) return 'ok';
  return 'unknown';
}

/** Приговор словами — ровно то, что игрок прочтёт с телефона. */
export const VERDICT_TEXT: Record<Verdict, string> = {
  ok: 'Сцена рисуется.',
  lost: 'Устройство забрало у игры видеокарту и ещё не вернуло.',
  zero: 'У картинки нулевой размер, рисовать негде.',
  stall: 'Кадры не идут, хотя должны.',
  map: 'Кадры остановлены нарочно: открыта карта или идёт ролик.',
  hidden: 'Игра свёрнута, кадры стоят.',
  gone: 'Город выгружен из памяти и ещё не собран заново.',
  unknown: 'Не знаю. Приборы не говорят ничего определённого.',
};

const SIZE = (s: Size): string => `${Math.round(s.w)}×${Math.round(s.h)}`;

/** Показания и способ пересобрать сцену — их отдаёт тот, кто ею владеет. */
interface Wired {
  vitals: () => Vitals | null;
  revive: () => void;
}

/**
 * Журнал. Один на игру: сцена за партию пересобирается, а история происшествий
 * обязана пережить пересборку — иначе она обрывалась бы ровно на том месте,
 * ради которого заведена.
 */
class SceneLog {
  private notes: Note[] = [];
  private wired: Wired | null = null;
  /** Кому сказать, что журнал пополнился, — служебный экран перерисовывается. */
  private readers = new Set<() => void>();

  /** Сцена подключает себя: без этого приговор честно говорит «не знаю». */
  attach(w: Wired): void {
    this.wired = w;
    this.ping();
  }

  detach(w: Wired): void {
    if (this.wired === w) this.wired = null;
    this.ping();
  }

  /**
   * Записать происшествие. Кольцо на `LOG_MAX`: журнал живёт всю партию, и
   * расти ему нельзя.
   */
  mark(kind: Kind, note?: string): void {
    this.notes.push({ at: Date.now(), kind, note });
    if (this.notes.length > LOG_MAX) this.notes.splice(0, this.notes.length - LOG_MAX);
    this.ping();
  }

  list(): readonly Note[] {
    return this.notes;
  }

  vitals(): Vitals | null {
    return this.wired?.vitals() ?? null;
  }

  verdict(): Verdict {
    return diagnose(this.vitals());
  }

  /** Пересобрать сцену заново. Есть кому — вернёт true. */
  revive(): boolean {
    if (!this.wired) return false;
    this.wired.revive();
    return true;
  }

  subscribe(fn: () => void): () => void {
    this.readers.add(fn);
    return () => this.readers.delete(fn);
  }

  private ping(): void {
    for (const fn of this.readers) fn();
  }

  /**
   * Отчёт одной строкой на всё — его игрок и скопирует в переписку. Числа те
   * же, что на экране: второй правды о состоянии сцены быть не должно.
   */
  report(extra: Record<string, string> = {}): string {
    const v = this.vitals();
    const lines = [`TRIBE, сцена: ${VERDICT_TEXT[diagnose(v)]}`];
    if (v) {
      lines.push(
        `холст ${SIZE(v.css)} css, буфер ${SIZE(v.buffer)}`,
        `кадров ${v.frames}, последний ${Math.round(v.now - v.lastFrame)} мс назад`,
        `луп: ${v.blocks.length ? v.blocks.join(', ') : 'идёт'}, контекст: ${v.lost ? 'потерян' : 'жив'}`,
      );
    }
    for (const [k, val] of Object.entries(extra)) lines.push(`${k}: ${val}`);
    lines.push('журнал:');
    const t0 = this.notes[0]?.at ?? Date.now();
    for (const n of this.notes) {
      const sec = ((n.at - t0) / 1000).toFixed(1);
      lines.push(`  +${sec}s ${n.kind}${n.note ? ` — ${n.note}` : ''}`);
    }
    if (!this.notes.length) lines.push('  пусто');
    return lines.join('\n');
  }
}

export const sceneLog = new SceneLog();

/** Размеры холста и окна одной строкой — их кладут в журнал до и после сна. */
export function sizeNote(css: Size, buffer: Size, win: Size): string {
  return `холст ${SIZE(css)}, буфер ${SIZE(buffer)}, окно ${SIZE(win)}`;
}
