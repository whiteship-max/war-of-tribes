/**
 * Руки промыслов (docs/minigames.md, 18.1): где на экране палец движения и где кнопка действия, и что делает палец.
 *
 * СХЕМА — СЛОВО ВЛАДЕЛЬЦА (этап 6). Во всех промыслах палец движения — с одной стороны, кнопка действия — с другой:
 *
 *   ягоды, скот   слева — палец движения, справа — кнопка действия (и взгляд пальцем по пустому месту);
 *   рыбалка       слева — палец движения (куда бросить, удилище вбок), справа — кнопка действия (заброс,
 *                 подсечка, тянуть);
 *   охота         слева — кнопка «Натянуть» (держать — натяжение, отпустить — выстрел), справа — палец движения:
 *                 плавные повороты и шаг, а с натянутым луком — прицел вверх-вниз.
 *
 * Палец движения — «кнопка-палец»: кружок стоит в своём углу, а ловит палец вся половина экрана — он садится, где лёг
 * большой палец, и ведёт от этой точки (на 375 px нарисованный заранее кружок палец промахивает). Вверх-вниз — шаг,
 * вбок — поворот: одним большим пальцем обходят поле кругом, второй свободен для кнопки. Мёртвая зона и полный ход —
 * те же, что у стика поляны (`prologue/controls.STICK_DEAD`, `STICK_FULL`): дрожь лежащего пальца — одна мерка.
 *
 * Кнопка действия — тоже вся половина: попасть в кнопку большим пальцем вслепую, глядя на оленя, — значит промахнуться.
 * Нажатие судит общий судья тапа (`gestures.Press`, пороги `TAP_SLIP`, `TAP_MS`): касание, уехавшее дальше `TAP_SLIP`,
 * — взгляд, а не кнопка. Кнопки, которые держат (тетива, катушка, замах), судятся не тапом, а «лёг — снят».
 *
 * Модуль чистый: ни DOM, ни three. Проверяется тестом (`pad.test.ts`).
 */

import type { MinigameId } from '@/game/data/minigames';

/** Как разложены руки: обход и сбор (ягоды, скот), лук (охота), удочка (рыбалка). */
export type Layout = 'walk' | 'bow' | 'rod';

/** Раскладка каждой игры — одна таблица на сцену (`Play.layout`) и на оболочку (`Minigame.tsx`): кнопки стоят до сцены. */
export const LAYOUT_OF: Record<MinigameId, Layout> = { berries: 'walk', herd: 'walk', hunt: 'bow', fish: 'rod' };

/** Что ловит половина экрана: палец движения, взгляд пальцем или кнопка действия. */
export type Zone = 'pad' | 'look' | 'press';

/** Половины экрана по раскладке. Взгляд пальцем остаётся там, где кнопку только тапают, — у обхода. */
export const ZONES: Record<Layout, { left: Zone; right: Zone }> = {
  walk: { left: 'pad', right: 'look' },
  bow: { left: 'press', right: 'pad' },
  rod: { left: 'pad', right: 'press' },
};

/** Что ловит палец, лёгший в точку `x` холста шириной `width`. */
export const zoneAt = (layout: Layout, x: number, width: number): Zone => (x < width / 2 ? ZONES[layout].left : ZONES[layout].right);

/**
 * Ширина, которой разбор пальца поляны (`prologue/controls.Sticks.down`) делит экран, для половины `zone`: палец
 * движения ложится «в ходьбу» при любой точке (бесконечная ширина), взгляд — «во взгляд» (нулевая). Так обе половины
 * судит один разбор — со стиком, тапом и порогами общего судьи, а не второй свой.
 */
export const sticksWidth = (zone: Exclude<Zone, 'press'>): number => (zone === 'pad' ? Infinity : 0);

/**
 * Отмена натянутого выстрела (отзыв тестеров 11.10, docs/feedback.md): палец увели с кнопки «Натянуть» — тетива
 * ослабевает без выстрела. «С кнопки» — дальше её размера от места, где палец лёг (кнопка — 88 px, `minigames.css`),
 * или в другую половину экрана. Дрожь держащего пальца (до `TAP_SLIP`) кнопки не покидает.
 */
export const SLIDE_OFF = 88;

/** Увёл ли держащий палец с кнопки: `x0, y0` — где лёг, `x, y` — где сейчас. */
export const slidOff = (layout: Layout, x0: number, y0: number, x: number, y: number, width: number): boolean =>
  zoneAt(layout, x, width) !== 'press' || Math.hypot(x - x0, y - y0) > SLIDE_OFF;

/** С какой стороны кнопка действия — с другой стороны от пальца движения. */
export const buttonSide = (layout: Layout): 'left' | 'right' => (ZONES[layout].left === 'pad' ? 'right' : 'left');

/**
 * Поворот в полный ход пальца, рад/с: сто десять градусов в секунду — осмотреться кругом за три с небольшим. Меньше
 * — оленя, ушедшего вбок, не догнать взглядом; больше — на полпути не прицелиться.
 */
export const TURN_RATE = 1.9;

/**
 * Прицел вверх-вниз с натянутым луком в полный ход пальца, рад/с: тридцать градусов в секунду. Метки дальности лежат
 * в двух-четырёх градусах ниже середины (`hunt.pins`), их ловят малым ходом — для того и кривая (`AIM_CURVE`).
 */
export const AIM_RATE = 0.5;

/**
 * Кривая хода: малый ход пальца — малая скорость, полный — полная, между ними — степенью. Поворот — 1,6: малым
 * ходом доводят прицел на градус; прицел вверх-вниз — 2: метки тоньше.
 */
export const TURN_CURVE = 1.6;
export const AIM_CURVE = 2;

/** Ход пальца (−1..1) в скорость по кривой. */
export const curved = (k: number, power: number): number => Math.sign(k) * Math.min(1, Math.abs(k)) ** power;

/** Скорость поворота при ходе пальца вбок `strafe`, рад/с: вправо — минус (рыскание камеры: плюс — влево). */
export const turnRate = (strafe: number): number => -curved(strafe, TURN_CURVE) * TURN_RATE;

/** Скорость прицела вверх-вниз при ходе пальца `forward`, рад/с: от себя — выше. */
export const aimRate = (forward: number): number => curved(forward, AIM_CURVE) * AIM_RATE;
