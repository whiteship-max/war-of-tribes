// Профиль игрока: кто он, чем силён и что с ним происходило. Живёт в сохранении
// отдельным куском, потому что из него потом соберётся «визитка» для чужих глаз
// на карте мира — там не будет ни зданий, ни армии, ни склада, только эти числа.
import type { Resources } from '@/game/types';

/**
 * Накопительные итоги за всю партию. Журнала событий тут нет и не будет: он
 * растёт без предела, а читать его некому — вопросы, которые игрок себе задаёт,
 * закрываются итогами.
 */
export interface ProfileTotals {
  /** Сколько единиц ресурсов добыто хозяйством. Итог, без разбивки по семи видам. */
  produced: number;
  /** Сколько единиц потрачено: стройка, ковка, наём. */
  spent: number;
  /**
   * Что унесли набеги — по ресурсам. Единственная разбивка в панели, и она нужна:
   * она отвечает на «что у меня утекает», а итог на этот вопрос не отвечает.
   */
  raidLoss: Resources;
  /** Сколько раз чужие уносили добро. */
  raids: number;
  /** Бойцов не вернулось из походов и обороны. */
  troopsLost: number;
  /** Привезённая добыча: ресурсы суммой и золото отдельно — золото не ресурс. */
  lootResources: number;
  lootGold: number;
}

/**
 * Суточная корзина. Они кольцевые: корзина старше `PROFILE_DAYS`
 * игровых дней выпадает. Показателей ровно три — производство, потери от
 * грабежей и мощь; остальное копится итогом и в корзинах не нуждается.
 */
export interface ProfileDay {
  /** Игровой день, к которому относится корзина. */
  day: number;
  produced: number;
  raidLoss: number;
  /** Мощь на конец этого дня. */
  power: number;
}

/**
 * Визитка — готовые значения, а не куски, из которых их собирают. Именно её
 * увидит чужой игрок на карте мира, когда появится сервер: собирать там мощь
 * из зданий и армии будет не из чего, поэтому она лежит посчитанной.
 */
export interface ProfileCard {
  name: string;
  /** Герб державы строкой (`heraldry/arms.armsCode`) — всегда правильный: не выбран — герб по умолчанию. */
  arms: string;
  power: number;
  battlesWon: number;
  battlesLost: number;
  /** Игровое время, на которое собрана визитка. */
  at: number;
}

export interface ProfileState {
  /** Имя, заданное игроком. null — берём из Telegram, нет и там — «Правитель». */
  name: string | null;
  /**
   * Имя города, которое назвал игрок, уже очищенное (`contract.cityName`). Необязательное:
   * сохранение, записанное до имён городов, приезжает без поля, и `SAVE_VERSION` от него не
   * растёт — читается оно только через `identity.profileCity`, которое подставит имя по
   * умолчанию.
   */
  city?: string | null;
  /**
   * Герб державы строкой (`heraldry/arms.armsCode`), выбранный игроком в конструкторе (docs/polish.md, П-2).
   * Необязательное: партия до гербов приезжает без поля и показывает прежний герб-башню (`DEFAULT_ARMS`); `SAVE_VERSION`
   * от него не растёт — читается оно только через `identity.profileArms`, которое проверяет строку по набору (сохранение
   * могло прийти с сервера от другой сборки). Прежнее поле лица `avatarId` в старых сохранениях лежит и не читается.
   */
  arms?: string | null;
  /**
   * Что отдал Telegram при запуске. Кладёт сюда интерфейс: симуляция про Telegram
   * не знает и знать не должна, а визитке нужны готовые значения.
   */
  tgName: string | null;
  tgPhoto: string | null;
  totals: ProfileTotals;
  days: ProfileDay[];
  card: ProfileCard;
}
