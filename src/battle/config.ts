/**
 * Бой — круги всем боем: обстрел → сшибка → сеча, снова и снова (docs/battle_eu4.md, раздел 3.1, решение
 * владельца 6 и раздел 12). Обстрел — стрельба и сближение (рукопашной нет, лучники бьют в полную силу),
 * сшибка — удар с разбега и упор копий, сеча — бой линий, обходы, ввод резерва и падение морали. Так у
 * каждого рода есть слабая фаза из чисел, которые уже стоят: копья — обстрел, пехота — сшибка против
 * латной, лучники — сшибка и сеча, лёгкая и латная конница — сеча.
 *
 * Длины — из прежнего боя в один проход, чтобы средний вклад рода не сдвинулся, а изменился порядок:
 * каждая фаза делится поровну на `BASE_CIRCLES` кругов, остаток — первым (`splitTicks`); сшибка не делится —
 * удар повторяется целиком. Круги сверх трёх идут как третий, пока кто-то не сломается, но не дальше
 * потолка (`roundsCap`). Своих чисел у круга нет ни одного.
 */
export const CIRCLE_PHASES: readonly PhaseId[] = ['ranged', 'approach', 'clash', 'lines', 'flanking', 'reserve', 'morale'];

/** Фазы сечи круга — с первого удара: в обстреле рукопашной нет. */
export const CIRCLE_MELEE: readonly PhaseId[] = ['clash', 'lines', 'flanking', 'reserve', 'morale'];

/** На сколько кругов делится прежний бой в один проход — решение владельца 6 («три круга»). */
export const BASE_CIRCLES = 3;

/** Доля `total` тиков на круг `k` (с единицы): поровну на `BASE_CIRCLES`, остаток — первым; дальше — как последний из них. */
export const splitTicks = (total: number, k: number): number =>
  Math.floor(total / BASE_CIRCLES) + (Math.min(k, BASE_CIRCLES) <= total % BASE_CIRCLES ? 1 : 0);

/** Сколько тиков фаза длится в круге `k`. Сшибка не делится. */
export const circleTicks = (phase: PhaseId, k: number): number =>
  phase === 'clash' ? PHASE_TICKS.clash : splitTicks(PHASE_TICKS[phase], k);

/** Меньше скольких тиков фаза круга `k` не длится после слома — доля `PHASE_MIN` тем же делением; нет своего — вся фаза. */
export const circleMin = (phase: PhaseId, k: number): number => {
  const min = PHASE_MIN[phase];
  return min === undefined ? circleTicks(phase, k) : splitTicks(min, k);
};

/** Весь круг `k` в тиках. */
export const circleLength = (k: number): number => CIRCLE_PHASES.reduce((n, p) => n + circleTicks(p, k), 0);

/** Тики сечи круга `k`: всё с первого удара. */
export const meleeTicksOf = (k: number): number => CIRCLE_MELEE.reduce((n, p) => n + circleTicks(p, k), 0);

/**
 * Потолок кругов (docs/battle_eu4.md, пачка 3) — сколько кругов может прибавиться к первому. Круги идут,
 * пока кто-то не сломается, но не дольше, чем ровный бой может идти, никого не сломав.
 *
 * Число выведено, а не выбрано. Ровный фронт в полную силу выбивает за тик сечи долю `MELEE_RATE` того,
 * что против него стоит в ширину; армия глубиной `depth` — вся армия к трём полосам ширины фронта —
 * теряет `MORALE.autoBreakLoss`, долю, после которой ломается без всякой морали, за
 * `autoBreakLoss · depth / MELEE_RATE` тиков сечи. Тики сечи — всё, где линии в контакте (`meleeTicksOf`:
 * сшибка, линии, обходы, резерв, мораль; в обстреле рукопашной нет). Потолок — наименьшее число кругов
 * сверх первого, при котором сечи хватает на это. Глубина берётся у меньшей по ней стороны: она ломается
 * первой. Без ширины глубина — единица (бьют все).
 *
 * На потолке не сломан никто, хотя ровный бой уже сломал бы одними потерями — это не сеча, а стояние: ни
 * одна сторона другую не берёт. Кончается оно тем же, чем бой без развала морали, — итогом по сохранённым
 * (`WITHDRAW_RATIO`): кто сохранил заметно меньше, отходит в порядке, остальное — ничья. Своего числа у
 * потолка нет ни одного.
 */
export const roundsCap = (depth: number): number => {
  const need = (MORALE.autoBreakLoss * Math.max(1, depth)) / MELEE_RATE;
  let have = meleeTicksOf(1);
  let extra = 0;
  while (have < need) {
    extra += 1;
    have += meleeTicksOf(extra + 1);
  }
  return extra;
};

/** Сила урона от морали сектора: при нуле — половина. */
