/**
 * Формула урона EU4 (вики, «Land warfare»): база потерь фазы — `15 + 5 · (кость + отметки)`, числа EU4 буквально. Из неё —
 * цена отметки (`PIP`); сами 15 и 5 в бою не живут: грань нашей кости — только разброс (`DICE.step`).
 */
export const EU4_DAMAGE = { base: 15, perFace: 5 };

/** Граней у кости фазы: 0…9, как у EU4. Один счёт на кость (`DICE`) и на цену отметки (`PIP`). */
const DICE_FACES = 10;

/**
 * Цена отметки — показателя рода и отметки полководца — долей урона фазы: одна отметка EU4 к средней базе
 * `15 + 5 · 4.5` (средняя кость — середина граней; у EU4 та же кость 0…9): 5 / 37.5 = 0.133 (слово владельца по 14.35,
 * п. 4). Своего числа у цены нет. Урон в фазе множится на `1 + разброс кости + PIP · (отметки полководца + нападение
 * бьющего − защита цели)`, урон морали — на `1 + PIP · (нападение морали − защита морали)`. Штраф места — в гранях кости, а
 * не в отметках: он бьёт по всем фазам стороны разом, и в отметках −1 земли выходил сильнее перевеса в 10 % войска по
 * построению (щуп шага 3, docs/battle_eu4.md, 14.35).
 */
export const PIP = EU4_DAMAGE.perFace / (EU4_DAMAGE.base + (EU4_DAMAGE.perFace * (DICE_FACES - 1)) / 2);

