// Типы боевой симуляции. Модуль `battle/` самодостаточен: ни React, ни three,
// ни состояния игры — только эти типы, конфиг и чистая функция. Это условие
// того, что ровно этот код потом запустит сервер, а клиент прогонит его же
// для показа.

/**
 * Пять родов войск полевого боя. Осадные — только против стен, их здесь нет.
 *
 * Конных родов два, и делит их доспех: `cavalry` — лёгкая, та, что держится на скорости (быстрая цель, погоня);
 * `heavy` — тяжёлая, тот же конь под доспехом, без скорости. Числа обеих — в `UNIT_STATS`, `KIND_PROFILE` и `TEMPER`
 * (docs/stable.md; кольца, делившего их прежний профиль, с пересмотра баланса нет — 14.35).
 */
export type UnitKind = 'spear' | 'infantry' | 'archer' | 'cavalry' | 'heavy';
export const UNIT_KINDS: readonly UnitKind[] = ['spear', 'infantry', 'archer', 'cavalry', 'heavy'];

/** Конные рода: всё, что верхом. Приказ у каждого свой, но оба — конница. */
export const HORSE_KINDS: readonly UnitKind[] = ['cavalry', 'heavy'];

/** Сколько кого. Внутри симуляции числа дробные, наружу — целые. */
export type Stack = Record<UnitKind, number>;

/**
 * Показатели полка, как у EU4 (вики, «Land units»; слово владельца по 14.35, docs/battle_eu4.md): нападение и защита в
 * огне, в натиске и в морали — в отметках, малыми целыми. Урон в фазе зависит от нападения бьющего и защиты цели, урон
 * морали — от показателей морали. Натиск — и сшибка, и сеча: фаз натиска у нас две, показатель у них один.
 */
export type StatId = 'fireAtk' | 'fireDef' | 'shockAtk' | 'shockDef' | 'moraleAtk' | 'moraleDef';
export const STAT_IDS: readonly StatId[] = ['fireAtk', 'fireDef', 'shockAtk', 'shockDef', 'moraleAtk', 'moraleDef'];
export type Profile = Record<StatId, number>;

/**
 * Сектора расстановки, как в документе: фронт A B C (слева направо со стороны
 * самой армии), тыл D E F под ними, резерв R.
 */
export type FrontSector = 'A' | 'B' | 'C';
export type RearSector = 'D' | 'E' | 'F';
export type Sector = FrontSector | RearSector | 'R';
export const FRONT: readonly FrontSector[] = ['A', 'B', 'C'];
export const REAR: readonly RearSector[] = ['D', 'E', 'F'];
export const SECTORS: readonly Sector[] = ['A', 'B', 'C', 'D', 'E', 'F', 'R'];

/** Полоса поля со стороны своей армии: 0 — левый фланг, 1 — центр, 2 — правый. */
export type Lane = 0 | 1 | 2;

/** Фазы боя — фиксированные и в этом порядке (раздел 11). */
export type PhaseId =
  | 'ranged'
  | 'approach'
  | 'clash'
  | 'lines'
  | 'flanking'
  | 'reserve'
  | 'morale'
  | 'retreat'
  | 'pursuit';
export const PHASES: readonly PhaseId[] = [
  'ranged',
  'approach',
  'clash',
  'lines',
  'flanking',
  'reserve',
  'morale',
  'retreat',
  'pursuit',
];

/**
 * Отметки полководца: по одной на обстрел, сшибку и сечу и одна на манёвр (docs/battle_eu4.md,
 * раздел 2.4). Отметка — грань кости своей фазы (`DICE`, `PHASE_PIP` в конфиге): полководец с двумя
 * отметками сшибки бросает в сшибке так, будто у кости на две грани больше.
 */
export type PipId = 'fire' | 'shock' | 'melee' | 'maneuver';
export const PIP_IDS: readonly PipId[] = ['fire', 'shock', 'melee', 'maneuver'];
export type Pips = Partial<Record<PipId, number>>;

/**
 * С чем сторона выходит в бой. Плана, приказов и условия резерва у стороны нет (docs/battle_eu4.md, 14.5):
 * решения игрока в бою — это состав и кто его ведёт, как у EU4, а где кто встанет, решает правило
 * развёртывания (`setup.deploy`). Сектора остались полем входа: их заполняет правило, а до поставки 2 —
 * ещё и раскладка обороны игрока.
 */
export interface ArmySetup {
  sectors: Record<Sector, Stack>;
  /**
   * Прибавка к стартовой морали **каждого своего** сектора: то, с чем эта армия
   * вышла в поле. Ноль по умолчанию, и ядро про источник
   * ничего не знает — обряд ли это перед боем, речь ли полководца.
   *
   * Поля веры, племени или стороны у `BattleInput` нет и быть не может, и это
   * не оговорка, а то, чем держится обещание «никаких боевых бонусов вида «моя
   * вера бьёт твою»»: противнику неоткуда взять то, чего ему не передали.
   * Число одно и то же против кого угодно; что оно даст в бою, зависит от боя — исход и размен с ним не обязаны
   * меняться одинаково (`game/sim/faith.test.ts`).
   */
  resolve?: number;
  /**
   * Отметки того, кто ведёт эту сторону. Ядро про источник не знает — как не знает, откуда
   * `resolve`: у игры это уровень полководца, у логова полководца нет, и поле пустое. Нет поля —
   * ноль по всем четырём.
   */
  pips?: Pips;
  /**
   * Штраф кости этой стороны в гранях — от места боя (docs/battle_eu4.md, 14.5 и 14.14; таблица EU4): земля и
   * переправа. Ядро про землю не знает, как не знает источника `resolve`: у игры штраф выводит мир, и только
   * нападающему (`world/battle.resolveField`). Переправу снимает манёвр своего полководца выше чужого (`groundFaces`).
   */
  ground?: GroundPenalty;
  /**
   * Мораль между боями (docs/battle_eu4.md, 14.30–14.31; EU4): с какой долей полной морали сторона вышла в бой, 0..1.
   * Множит стартовую мораль каждой группы — и строя, и резерва (`startMorale`). Ядро про источник не знает, как про
   * `resolve`: у игры это время с последнего боя (`world/rest`). Нет поля — полная мораль, и бой байт в байт прежний.
   */
  rest?: number;
  /**
   * Какая часть этой армии — гарнизон, вышедший из ворот своего города в совместный удар, по родам; остальное — дружина
   * (docs/battle_tw.md, раздел 13; решение владельца 03.10.2026, вариант А). **Наблюдение для показа, а не вход боя:**
   * ядро поле не читает, только раскладывает по секторам расстановки в итог (`SideResult.sectors[].garrison`,
   * `setup.garrisonShare`) — так ролик выводит гарнизон из ворот, а дружину с поля. Бой с полем и без него — один бой до
   * бита (тест «происхождение бойцов не меняет исход», `world/battle.test.ts`). Настоящие клещи — удар с двух сторон,
   * который ядро считало бы, — не это поле (вариант Б, docs/siege.md).
   */
  garrison?: Partial<Stack>;
}

/** Штраф кости в гранях: земля клетки боя и переправа на неё. Нет поля — ноль. */
export interface GroundPenalty {
  land?: number;
  crossing?: number;
  /**
   * Укрепления лагеря, на который идут (`world/siegecraft`, приказ «Укрепить лагерь»): та же грань кости, что земля, —
   * манёвр её не снимает. Ядро про лагерь не знает, как не знает про землю; нет поля — ноль.
   */
  works?: number;
  /**
   * Стена, на которую лезут (docs/siege_v2.md, 4.1; `world/wall`): грани кости нападающего, средние по его фронту — по
   * лестницам −2, в проломе и воротах ноль. Манёвр её не снимает, как укрепления лагеря. Ядро про стену не знает, как не
   * знает про землю: узкий фронт приходит шириной боя (`BattleInput.width`), грань — сюда. Нет поля — ноль.
   */
  wall?: number;
}

/**
 * Проём, который открывается посреди боя (docs/siege_v2.md, 4.1: таран выбивает ворота после первого круга): с круга
 * `round` (0 — первый, 1 — второй…) ширина боя становится `width`, а штраф стены нападающего — `wall` граней. Ядро не
 * знает, что это ворота: ему дают ширину и грань с такого-то круга, как дают их на весь бой.
 */
export interface Widen {
  round: number;
  width: number;
  wall: number;
}

export type Side = 'attacker' | 'defender';
export const SIDES: readonly Side[] = ['attacker', 'defender'];
export type Winner = Side | 'draw';

export interface BattleInput {
  seed: number;
  attacker: ArmySetup;
  defender: ArmySetup;
  /**
   * Ширина фронта полосы в этом бою, бойцов строя: в ряду полосы с каждой стороны стоит не больше стольких,
   * остальные — в резерве стороны. Нет поля — `FRONT_WIDTH`; `Infinity` — боя без ширины.
   */
  width?: number;
  /**
   * Ширина стрельбы, бойцов строя на полосу: в ряду полосы стреляет не больше стольких. Нет поля — ширина боя. У боя у
   * стены она полная, а ширина боя — проёмы (docs/siege_v2.md, 4.1): сходятся в проломе и на лестницах, а стреляют со
   * всей стены и по всей стене.
   */
  fire?: number;
  /** Проём посреди боя (`Widen`): с круга `round` ширина и штраф стены другие. Нет поля — весь бой как начался. */
  widen?: Widen;
}

