// Статуя Героя (ДР-7, docs/city_v3.md, «Решения ДР-7») — что памятник даёт дружине и державе: мораль строкой духа (ДР-1,
// `spiritrules`, дверь `sim/spirit`) и тихий сдвиг стабильности вверх (СБ-1, `stabrules`, дверь `sim/stability`), с ростом по
// уровню. С полководцем памятник не связан: отметок, найма и окна отряда у него нет. Числа одни на игру и на книги сервера
// (потолок духа — `watch.spiritCeilOf`, подъём стабильности — `watch.stabFlags`). Без `@/`: модуль читает сервер.
//
// **Своих чисел нет — оба выведены из того, что игра уже сказала:**
// - мораль на вершине — польза лучшего Воеводы (`councilrules.giftCeil('marshal')`, третий уровень и усердие) в очках морали той
//   же мерой, что у всей стойкости (`spiritrules.resolvePoints`): памятник в десять уровней стоит лучшего советника войны, —
//   заметно, но не главное: обряд, рыцарство в силе, память боёв и ступени стабильности дают каждое не меньше;
// - первый уровень — ноль, как у казарм и полководца («за каждый уровень сверх первого», `spiritrules`): Статуя стоит в посёлке
//   с первого дня, и стартовая дружина бьётся, как до ДР-7; дальше — ровно по уровню до вершины;
// - стабильность — мораль памятника причиной того же веса: сдвиг ступени в день, с каким недовольство такого веса тянет
//   вниз (`stabrules.battleShock` — та же мерка, что у толчка боя). Выше «Лада» сама стабильность не поднимается, и памятник
//   — тоже: он только раньше доводит до «Лада» и держит против сдвига вниз (правило `sim/stability.push`).
import { MAX_BUILDING_LEVEL } from './constants';
import { giftCeil } from './councilrules';
import { resolvePoints } from './spiritrules';
import { battleShock } from './stabrules';

/** Вершина Статуи — потолок постройки. */
export const STATUE_TOP = MAX_BUILDING_LEVEL;

/** Мораль дружины от Статуи на вершине, очков шкалы 0…100: лучший Воевода той же мерой стойкости. */
export const STATUE_MORALE_TOP = resolvePoints(giftCeil('marshal'));

/** Мораль дружины от Статуи уровня `level`: ноль на первом (и без Статуи), вершина — на последнем, ровно по уровню между ними. */
export const statueMorale = (level: number): number =>
  (STATUE_MORALE_TOP * Math.max(0, Math.min(STATUE_TOP, Math.floor(level || 0)) - 1)) / (STATUE_TOP - 1);

/** Сдвиг стабильности от Статуи уровня `level`, % ступени за игровой день: её мораль причиной того же веса. */
export const statueCalm = (level: number): number => battleShock(statueMorale(level));
