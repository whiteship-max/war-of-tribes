// Единицы настоящего времени в миллисекундах — одни на посёлок, мир и сервер.
//
// Не часы и не игровое время: «сейчас» спрашивают у `net/clock.ts`, игровой день —
// `DAY_LENGTH` в `constants.ts`. Здесь только то, сколько миллисекунд в минуте, часе и
// сутках, чтобы одно и то же число не писали в пяти файлах пятью способами.
//
// Модуль без единого импорта нарочно: его читает `world/data/tuning.ts`, а тот — земля и
// расселение, которые собирает и серверная функция (CLAUDE.md, «Личность игрока»).
export const MINUTE_MS = 60_000;
export const HOUR_MS = 60 * MINUTE_MS;
export const DAY_MS = 24 * HOUR_MS;
