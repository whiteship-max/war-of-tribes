// Дверь времени: единственное место, где настоящие секунды становятся игровыми и обратно.
//
// У игры двое часов. Мир живёт настоящими миллисекундами (`net/clock.partyNow`), племя —
// игровыми секундами (`GameState.time`, в игровом дне их `DAY_LENGTH`). До этой двери игровая
// секунда молча равнялась настоящей, и равенство было размазано по мосту, миру, миграциям и
// показу сроков: `s.time + ms / 1000`, `seconds * 1000`, «~40 с» на кнопке. Замедлить время
// при таком устройстве значило бы найти все эти места заново и не пропустить ни одного
// (docs/time.md, раздел 1).
//
// Теперь перевод один и назван. **Шкала — тридцать: игровой день длится полчаса** (повёрнута
// 20.09.2026, docs/time.md, раздел 17). До поворота она была единицей, и поворот был правкой одной
// строки здесь; формат сохранения от неё не зависит, потому что в партии лежат игровые секунды, а в
// мире — настоящие миллисекунды.
//
// Модуль без единого импорта нарочно, как `game/time.ts`: его читают и племя, и мир, и отчёты.

/** Сколько настоящих секунд длится одна игровая. Тридцать: игровой день (`DAY_LENGTH`) — полчаса. */
const TIME_SCALE = 30;

let scale = TIME_SCALE;

/** Шкала времени: настоящих секунд в игровой. */
export const timeScale = (): number => scale;

/**
 * Подмена шкалы — **только для тестов-свойств**, тем же приёмом, что `sim/random.setRandom`:
 * при шкале 1 перевод неотличим от его отсутствия, и тест на «перевод стоит на месте» при ней
 * зелёный даром. Без довода возвращает шкалу игры. Вне тестов не зовётся — тест по исходникам.
 */
export function setTimeScale(next: number = TIME_SCALE): void {
  if (!Number.isFinite(next) || next <= 0) throw new Error(`шкала времени должна быть положительным числом: ${next}`);
  scale = next;
}

/** Настоящие секунды → игровые: на сколько сдвинуть `s.time` за прошедшее настоящее время. */
export const gameSeconds = (realSeconds: number): number => realSeconds / scale;

/** Настоящие миллисекунды мира → игровые секунды. */
export const gameSecondsOfMs = (realMs: number): number => realMs / 1000 / scale;

/** Игровые секунды → настоящие: сколько игрок прождёт срок, записанный в игровых секундах. */
export const realSeconds = (gameSec: number): number => gameSec * scale;

/** Игровые секунды → настоящие миллисекунды мира. */
export const realMs = (gameSec: number): number => gameSec * scale * 1000;

// ---------- Классы величин времени ----------
//
// У каждой величины времени в игре есть класс, и класс — не ярлык из списка, а ответ на вопрос
// «чему она служит» (docs/time.md, раздел 13):
//
//  · **игровое время** — то, что сравнивается с хозяйством или расходуется им: выработка, еда,
//    жалованье, труд стройки, срок лечения, ритм угрозы, созревание, восстановление. Замедляется
//    вместе с игровым днём: иначе после поворота шкалы война, добыча и сроки съедают хозяйство;
//  · **настоящее время** — то, что игрок ждёт своими глазами внутри одного захода (поход, сбор
//    дружины, занятость агента, окно ответа) и то, что живёт настоящими сутками (почта, ежедневка,
//    потолок догона). Со шкалой не идёт: заход остаётся заходом;
//  · **решает владелец** — служба тянет в обе стороны, или записанное решение говорит одно, а новое
//    правило другое. Пока не решено, идёт настоящим временем, как шло.
//
// Класс записан там же, где число: величина объявляется через конструктор своего класса, и второго
// списка «что в каком классе» нет — он разошёлся бы с кодом. Сколько величин в каждом классе,
// печатает `npm run time:report`, раздел 4, чтением исходников; держит правило `game/pace.test.ts`.

/** Игровых секунд в игровом дне. Живёт у двери времени, чтобы его читал и мир; `constants.ts` отдаёт его дальше. */
export const DAY_LENGTH = 60;

/** Игровое время на часах племени: срок в игровых секундах. */
export const gameSec = (seconds: number): number => seconds;
/** Игровое время: ставка работы в игровую секунду (стройка, ковка, учения). */
export const gameRate = (perSecond: number): number => perSecond;
// Ставка на часах мира — `worldDayRate` и `realHourRate`, ниже: им нужен `gameDaysPerHour`.
/** Игровое время на часах мира: срок в игровых днях → настоящие миллисекунды мира. Идёт со шкалой. */
export const worldDays = (days: number): number => realMs(days * DAY_LENGTH);

/** Настоящее время на часах мира, миллисекунды. */
export const realTime = (ms: number): number => ms;
/** Настоящее время, секунды: сырое число для формулы, которая сама переведёт итог (`sessionSec`). */
export const realSec = (seconds: number): number => seconds;
/** Настоящее время на часах племени: срок в настоящих секундах → игровые секунды `s.time`. */
export const sessionSec = (seconds: number): number => gameSeconds(seconds);
/**
 * Окно защиты игрока, настоящие миллисекунды мира. Правило (решение владельца, docs/time.md, раздел 16):
 * **окно, которое даёт игроку время прийти и ответить, меряется его временем, а не временем мира.**
 * Свой конструктор — затем, чтобы правило было записано там же, где число: окно защиты, объявленное
 * игровым временем, после поворота шкалы молча растянулось бы или сжалось вместе с миром.
 */
export const shieldTime = (ms: number): number => ms;

/** Решает владелец; пока не решено — настоящее время мира, миллисекунды. `why` — в чём вопрос. */
export const ownerTime = (ms: number, _why: string): number => ms;
/** Решает владелец; величина племени, как есть. */
export const ownerSec = (seconds: number, _why: string): number => seconds;

// ---------- Игровые дни против настоящих часов ----------
//
// Один перевод на мост, мир и отчёты: «игровой день — настоящая минута» верно только при шкале 1,
// и писать это равенство числом (`3600 / DAY_LENGTH`, `ms / 1000 / DAY_LENGTH`) больше нельзя.

/** Сколько настоящих секунд длится игровой день. */
export const dayRealSeconds = (): number => realSeconds(DAY_LENGTH);
/** Сколько игровых дней укладывается в настоящий час. */
export const gameDaysPerHour = (): number => 3600 / dayRealSeconds();
/** Настоящие миллисекунды мира → игровые дни. */
export const gameDaysOfMs = (ms: number): number => gameSecondsOfMs(ms) / DAY_LENGTH;

// ---------- Ставки: число, встречающееся с прошедшим временем ----------
//
// Срок говорит «сколько ждать», ставка — «сколько за время», и класс нужен обоим по одной
// причине: ставка «в настоящий час» после поворота шкалы съедает хозяйство в тридцать раз
// быстрее, чем оно производит. Ровно это и случилось с расходом еды чужого города
// (`SIEGE_TOWN_EAT`): единица стояла в прозе, конструктора у числа не было, и пачка 2 его не
// увидела — она искала сроки (docs/time.md, разделы 17.4 и 18).
//
// Единицу ставки называет не список, а тот идентификатор, что её несёт: `townPerHour`,
// `foodPerHour`, `consumptionPerHour`. На часах племени ставка идёт за игровой день и настоящего
// времени не встречает никогда (`POP_GROWTH_PER_DAY`, `moralePerDay`) — там класс в имени, как у
// `*_DAYS`. На часах мира час настоящий (`siege.fallsAt` умножает на `HOUR`), и там ставке нужен
// конструктор. Ищет ставку без класса `scripts/lib/timeclasses.ts`, чтением исходников.

/** Игровое время на часах мира: ставка за игровой день → за настоящий час. Идёт со шкалой. */
export const worldDayRate = (perGameDay: number): number => perGameDay * gameDaysPerHour();
/** Настоящее время на часах мира: ставка за настоящий час, как есть. Со шкалой не идёт. */
export const realHourRate = (perRealHour: number): number => perRealHour;

// ---------- Какими часами идёт срок — в типе ----------
//
// Игровые секунды помечены в типе, и форматтер настоящего времени их не принимает: «срок напечатан не
// теми часами» — ошибка компиляции, а не находка глаза. Срок племени игроку показывают только
// через `ui/parts/wait.ts` (`wait…`), срок мира — через `real…` и `world/geo.formatLeft`.

/** Срок в игровых секундах. Арифметика метку снимает — после неё срок называют заново (`asGame`). */
export type GameSec = number & { readonly __clock: 'game' };
/** Срок в настоящих секундах: обычное число проходит, помеченное игровым — нет. */
export type RealSecArg = number & { readonly __clock?: 'real' };

/** «Это игровые секунды» — говорит тот, кто срок посчитал. */
export const asGame = (seconds: number): GameSec => seconds as GameSec;

// ---------- Скорость проверки: часы партии ----------
//
// Инструмент проверки, а не механика: после поворота шкалы склад наполняется часами, поход идёт часами,
// и глазами не видно почти ничего. Скорость — во сколько раз **часы партии** идут быстрее часов игрока.
// Живёт она за выключателем кодов (`src/cheats.ts`), и с опущенным выключателем её нет вовсе:
// кнопки нет, а часы партии — это `net/clock.serverNow` как есть.
//
// **Почему не поворот `scale`, хотя ×30 — это ровно «игровой день за минуту».** Поворот шкалы на ходу
// дошёл бы не до всего, и именно этим он опасен:
//
//  · числа мира считаются из шкалы **при импорте** (`worldDays(7)` в `world/data/tuning.ts` — уже число
//    миллисекунд): повёрнутая шкала ускорила бы шаг племени и новые походы, а набеги, логова, рогатки и
//    осадный голод шли бы прежним ходом — быстрая деревня при медленных угрозах, та самая болезнь, которую
//    чинили пачки 5 и 6 (docs/time.md, разделы 18.6 и 19);
//  · всё, что мир выводит из прошедшего (`gameDaysOfMs(now − t0)`: возраст логова, часы голода), пересчиталось
//    бы новой шкалой **за всё прошлое сразу** — логово, родившееся час назад, мгновенно постарело бы в `speed`
//    раз, а обратный поворот вернул бы его в молодость;
//  · настоящее время (окно защиты, почта) не поворачивается по определению класса, и отношение «окно
//    защиты против паузы между набегами» разошлось бы в тридцать раз — болезнь пачки 5 в другую сторону.
//
// Поэтому поворачивается не шкала, а часы, по которым живёт партия целиком — и племя, и мир, и оба класса
// величин разом: ускоренная партия — та же игра, что у игрока, прожившего в `speed` раз больше. Шкала при
// любой скорости тридцать, и это тест. Часы партии — настоящее время плюс **опережение**: на сколько
// настоящих миллисекунд партия ушла вперёд. Оно — функция минуты устройства на чтении (пара «сколько было и
// когда» плюс скорость), а не счётчик тиков; при скорости 1 не меняется, поэтому прошлое не переписывается
// никогда, а партия, вернувшаяся к ×1, идёт дальше обычным ходом. Опережение лежит в партии
// (`GameState.lead`) — оно же метка «партию ускоряли».

/**
 * Ступени скорости. Числа не выбраны, а выведены — тест держит вывод (`game/speed.test.ts`):
 *
 *  · **×30** — шкала тридцать делится на тридцать: партия живёт при дне в минуту, как до поворота. При
 *    ней написаны все тесты правил мира (`game/pace.minute`), и пульс мира при ней — шестьдесят секунд
 *    партии, ровно пол пульса отчётов (`autopilot.PULSE_FLOOR`), на котором сверены три отчёта;
 *  · **×120** — шаг живой игры (`store.TICK_MS`) становится ровно шагом догона отлучки (`CATCHUP_STEP`,
 *    две игровые секунды), а пульс мира — 240 секундами партии, внутри трёхсот, на которых `siege:report`
 *    совпал с шагом в шестьдесят (docs/time.md, раздел 18.10). Выше обе величины грубее всего, что мерено.
 */
export const SPEEDS = [1, 30, 120] as const;

/**
 * Сколько опережения могло набежать за `realMs` настоящего времени: не больше высшей ступени скорости проверки (AC-8). Сервер
 * прибавляет опережение к допуску сверок времени и берёт не больше этого: названное описью сверх открывало бы любое время.
 */
export const leadGrowth = (fromLead: number, toLead: number, realMs: number): number =>
  Math.min(Math.max(0, toLead - fromLead), (SPEEDS[SPEEDS.length - 1] - 1) * Math.max(0, realMs));

let rate = 1;
let from = 0;
let base = 0;

/** Во сколько раз часы партии идут быстрее часов игрока сейчас. */
export const speed = (): number => rate;

/**
 * Опережение часов партии над настоящими на минуту устройства `at` (мс), миллисекунд. Функция на чтении:
 * сколько было на минуту последней смены скорости плюс то, что с тех пор набежало. При скорости 1 — ровно
 * то, что было.
 */
export const lead = (at: number): number => base + (rate - 1) * (at - from);

/**
 * Сменить скорость на минуте устройства `at`. Набежавшее до смены становится базой — прошлое не
 * переписывается ни на миллисекунду. Зовёт одна дверь — `net/clock.hurry` (тест по исходникам).
 */
export function setSpeed(next: number, at: number): void {
  if (!SPEEDS.includes(next as (typeof SPEEDS)[number])) throw new Error(`нет такой ступени скорости: ${next}`);
  base = lead(at);
  from = at;
  rate = next;
}

/**
 * Партия вошла в игру (загрузка, новая партия): её опережение — `ms`, скорость — ×1. Партия начинается с
 * правды: ускорять её снова — нажатием, и от этой минуты.
 */
export function startLead(ms: number, at: number): void {
  base = ms;
  from = at;
  rate = 1;
}

/**
 * Сколько настоящих секунд прожила партия за шаг цикла: настоящие секунды устройства плюс то, на сколько за
 * шаг выросло опережение. Шаг племени получает это, мир — часы партии; второго умножения на скорость нет
 * нигде (тест «ускорение идёт одной дверью»).
 */
export const livedSeconds = (real: number, leadFrom: number, leadTo: number): number =>
  Math.max(0, real + (leadTo - leadFrom) / 1000);
