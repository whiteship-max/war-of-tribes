// Сетка привоза рынка (РН-1б, docs/city_v3.md, «РН-1б»): ровно каждые 3 часа по UTC, восемь в сутки, одна минута у всех
// игроков. Отдельным модулем — затем, что её читает живой шаг (`sim/caravan.rollShift`) в первой загрузке, а правила торга
// (`marketrules`, оттуда же она и отдаётся) едут докачкой с окном рынка. Без `@/`-импортов: модуль читает сервер.
import { realTime } from './pace';

/** Длина привоза, настоящих мс: ровно три часа, восемь привозов в сутки (решение владельца, РН-1б). */
export const SHIFT = realTime(3 * 3600_000);

/** Номер привоза в минуту `now` (настоящие мс): сетка UTC — привоз меняется в 00, 03, 06 … 21 у всех игроков. */
export const shiftOf = (now: number): number => Math.floor(now / SHIFT);

/** Минута начала привоза `w`. */
export const shiftStart = (w: number): number => w * SHIFT;
