// Действия игрока вокруг боя: выбор между мгновенным итогом и просмотром. Сохранённых схем
// больше нет — они хранили план, приказы и раскладку удара, а у удара их нет (docs/battle_eu4.md,
// 14.5); расстановки обороны нет тоже — у частокола строй раскладывает правило (14.27). Как и все
// действия, возвращают null при успехе или текст ошибки — стор покажет его тостом.
import type { GameState } from '../types';

/** Что игрок предпочитает после боя: сразу итог или журнал по фазам. Выбор запоминается. */
export function setBattleWatch(s: GameState, watch: boolean): string | null {
  s.battleWatch = watch;
  return null;
}
