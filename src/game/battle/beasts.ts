// Слова боя для стаи у ворот (docs/battle_eu4.md, 14.28–14.29). Ядро думает родами: стая бьётся лёгкой конницей, и
// журнал ядра (`battle/log.describeEvent`) и итог (`battle/report.summarize`) зовут её «конницей», а её сторону —
// «чужими». Имена по отряду даёт слой показа, а не ядро (слово владельца): ядро не знает, кто стоит на стороне, и знать
// не должно — сервер соберёт тот же журнал, не зная ни волков, ни людей.
//
// Звери у ворот сегодня одни — волки (`world/data/gate.GATE_FOES`), и запись боя несёт только сторону зверей
// (`BattleRecord.beasts`), а не их вид. Появится второй зверь — запись понесёт его имя, а слова станут по зверю; держит
// это тест (`beasts.test.ts`).
import type { BattleSummary, Side } from '@/battle';

/** Падежи «конницы» — падежами «стаи»: слово того же рода и числа, и глаголы при нём не меняются. */
const FLOCK: Record<string, string> = { а: 'стая', у: 'стаю', ы: 'стаи', е: 'стае', ей: 'стаей' };

/**
 * Замены по порядку: сперва фразы, где меняется строй, потом слова. Каждая фраза — ровно та, что пишет ядро о стороне
 * зверей; о нашей стороне ядро пишет «наши», и её строк замены не касаются.
 */
const WOLVES: readonly [RegExp, string | ((m: string, g: string) => string)][] = [
  // Наши копья остановили стаю: у копий — наше событие, а «конница» в нём — волки.
  [/остановили кавалерийский удар: конница потеряла/g, 'остановили стаю: волки потеряли'],
  [/Чужая конница/g, 'Стая'],
  [/Чужие сектора побежали один за другим, и армия рассыпалась/g, 'Волки побежали один за другим, и стая рассыпалась'],
  [/Чужие сломались: бегущие сектора весили (\d+)% армии/g, 'Волки сломались: бегущие сектора весили $1% стаи'],
  [/чужие: армия сломалась/g, 'волки: стая сломалась'],
  // Стрелять волкам нечем: «перестрелку» они не проигрывают, а попадают под стрелы.
  [/Чужие проиграли перестрелку/g, 'Волки попали под стрелы'],
  [/чужие: проиграли перестрелку/g, 'волки: попали под стрелы'],
  [/Чужой (.+?) сломался — бойцы побежали/g, 'Стая: $1 сломался — волки побежали'],
  [/Чужой /g, 'Стая: '],
  [/Чужие/g, 'Волки'],
  [/чужие/g, 'волки'],
  [/конниц(ей|а|у|ы|е)/g, (_, end) => FLOCK[end]],
];

/**
 * Строка ядра о бое, где на стороне `beasts` звери, — словами о стае. Бой людей (`beasts` нет) — как есть. Своей стороной
 * игрок зверем не бывает (звери только приходят к воротам, `LocalWorld.gateRecord`), поэтому слова — о чужой стороне.
 */
export function beastWords(text: string, beasts: Side | undefined, us: Side): string {
  if (beasts === undefined || beasts === us) return text;
  return WOLVES.reduce((t, [re, to]) => t.replace(re, to as string), text);
}

/** Итог боя (`summarize`) теми же словами: причина исхода и ключевые события. */
export function beastSummary(sum: BattleSummary, beasts: Side | undefined, us: Side): BattleSummary {
  if (beasts === undefined || beasts === us) return sum;
  return {
    ...sum,
    reason: beastWords(sum.reason, beasts, us),
    keys: sum.keys.map((k) => ({ ...k, text: beastWords(k.text, beasts, us) })),
  };
}
