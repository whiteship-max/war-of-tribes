// Где и когда случился бой — и что из этого видно в ролике.
//
// Мост, а не ядро, и по той же причине, что `faces.ts`: ядро боя знает четыре
// рода и девять фаз, а «бой у брода на закате» — это отображение мира в
// картинку. Отображение живёт здесь, а в раскадровку уезжает готовым (`Ground`).
//
// Правило одно и оно важнее удобства: **показ не читает мир**. Земля и свет
// выводятся из записи боя чистой функцией, а не добираются из карты в момент
// показа. Иначе раскадровка перестала бы быть самодостаточной ровно тогда,
// когда журнал приедет с сервера, — и «сервер прислал, клиент показал»
// превратилось бы в «сервер прислал, клиент дочитал у себя».
import type { Ground } from '@/battle';
import { dayFraction, seasonOf } from '../derived';

/** Что под ногами. Тот же набор, что у раскадровки: второго словаря заводить нечего. */
export type BattleLand = Ground['land'];

/**
 * Место боя, как его записал мир. Полей ровно столько, сколько меняет картинку:
 * биты `FEATURE` сюда не едут — они язык географии, а не показа, и читать их
 * пришлось бы обеим сторонам.
 *
 * Всё необязательное: запись боя, сделанная до этой пачки, места не несёт вовсе,
 * и открыться она обязана.
 */
export interface BattlePlace {
  /** Земля клетки: ровное поле, холмы или берег. */
  land: BattleLand;
  /** Через поле идёт река. */
  river?: boolean;
  /** На реке брод — по нему её и переходят. */
  ford?: boolean;
  /** Рядом хребет: за строем земля обрывается. */
  ridge?: boolean;
  /** Через поле идёт тракт. */
  road?: boolean;
  /** Рядом лес: по краю поля стоит стена деревьев. */
  woods?: boolean;
  /**
   * Игровое время племени в секундах на момент боя. Из него выводятся и час, и
   * время года: две мерки из одного числа, поэтому разойтись им негде.
   */
  time?: number;
}

/**
 * Светлая дуга ролика. Ночного боя в ролике нет и не будет: чёрный экран — это
 * не зрелище, а отсутствие зрелища, и разглядеть в нём, где чьё войско, нельзя.
 * Поэтому игровые сутки укладываются целиком в дугу от восхода до заката: чем
 * позже случился бой, тем ниже солнце и длиннее тени.
 *
 * Границы стоят ровно на 0 и 0.5 нарочно — там у рига (`applyDayNight`) солнце
 * на двенадцати градусах и в полном закатном цвете, а лампа ещё не начала
 * переезжать в луну.
 */
export const REPLAY_ARC = { from: 0, to: 0.5 } as const;

/** Полдень: свет боя, о котором ничего не известно. */
export const NOON = 0.25;

/**
 * Час боя в мере света. Чистая функция от игрового времени: тот же бой даёт тот
 * же свет и через неделю, и на сервере.
 */
export const solarOfTime = (time: number): number =>
  REPLAY_ARC.from + dayFraction(Math.max(0, time)) * (REPLAY_ARC.to - REPLAY_ARC.from);

/**
 * Место и время боя — в землю и свет ролика. Единственный путь из записи боя в
 * `Cast.ground`, и он чистый: ни часов устройства, ни `Math.random`, ни карты.
 *
 * `seed` — сид боя: им расставляются трава, деревья и камни. Место у двух боёв
 * на одной клетке одно, а поле всё-таки разное, и это правильно — второй бой
 * идёт не по следам первого.
 */
export function groundOf(place: BattlePlace | undefined, seed: number): Ground {
  if (!place) {
    // Ровное поле в полдень. Выдумывать старой записи брод и закат нельзя: она
    // про них ничего не говорила, а показать её надо.
    return { ...PLAIN, seed };
  }
  const time = place.time;
  return {
    land: place.land,
    river: place.river === true,
    // Брод без реки — не брод. Мир такого не пишет, но правило дешевле проверки.
    ford: place.river === true && place.ford === true,
    ridge: place.ridge === true,
    road: place.road === true,
    woods: place.woods === true,
    winter: time !== undefined && seasonOf(time) === 'winter',
    solar: time === undefined ? NOON : solarOfTime(time),
    seed,
  };
}

/** Ровное поле в полдень — то же, что знает ядро, но собранное здесь по полям. */
const PLAIN: Ground = {
  land: 'plain',
  river: false,
  ford: false,
  ridge: false,
  road: false,
  woods: false,
  winter: false,
  solar: NOON,
  seed: 0,
};

/**
 * Как называется место. Одна строка на бой — для стенда и для приёмки: по кадру
 * должно быть видно, что земля своя, а по подписи — что она не случайна.
 */
export function groundName(g: Ground): string {
  const parts: string[] = [];
  if (g.ford) parts.push('у брода');
  else if (g.river) parts.push('у реки');
  if (g.ridge) parts.push('на гребне');
  if (g.woods) parts.push('у опушки');
  if (g.road) parts.push('на тракте');
  if (parts.length === 0) parts.push(g.land === 'hills' ? 'в холмах' : g.land === 'shore' ? 'на берегу' : 'в чистом поле');
  return parts.join(', ');
}

/** Как называется час. Тем же порядком, что у света: рассвет → полдень → закат. */
export function hourName(g: Ground): string {
  const u = (g.solar - REPLAY_ARC.from) / (REPLAY_ARC.to - REPLAY_ARC.from);
  if (u < 0.12) return 'на рассвете';
  if (u < 0.34) return 'утром';
  if (u < 0.62) return 'в полдень';
  if (u < 0.85) return 'под вечер';
  return 'на закате';
}
