// Предметы агентов — фундамент без предметов. Три места, три роли, и ни одно не
// знает того, что знает другое:
//
// | что                | где                                   | что знает                        |
// |--------------------|---------------------------------------|----------------------------------|
// | ячейка агента      | партия, `GameState.agents[id].slots`  | только **имя** предмета или пусто |
// | таблица предметов  | здесь, `ITEMS`                        | что предмет **даёт**             |
// | владение           | `net/owned.ts`, вне партии            | какие имена у игрока есть         |
//
// Действие предмета берётся **только** из этой таблицы. Что бы ни пришло снаружи
// — метаданные коллекции, ответ кошелька, строка в сохранении, — числа в нём нет
// и взять его неоткуда: подделать предмет значило бы подделать силу. Правило то
// же, что у алмазов, и держит его тот же род теста — по всему `src`
// (`items.lock.test.ts`).
//
// Сегодня таблица пуста, и это тест: первый предмет потребует решения, а не
// проедет молча. Решать до первого предмета — не прибавляет ли он кружок, который
// на пятом уровне упрётся в предел (docs/AGENTS.md, возражение 4).

import { own } from '../guard';

/**
 * Имя предмета. Строка без полей, и поля ей не приделать: элемент владения или
 * ячейки с числом внутри — ошибка компиляции, как ссылка на группу с наградой.
 */
export type ItemId = string & { readonly __item: unique symbol };

/** Что предмет даёт. Поля действия появятся вместе с первым предметом — здесь. */
export interface ItemDef {
  id: ItemId;
  name: string;
}

export const ITEMS: Readonly<Record<string, ItemDef>> = Object.freeze({});

/** Что лежит в ячейке — ровно одно из четырёх. */
export type SlotState =
  /** Пусто. */
  | { kind: 'empty' }
  /** Имени нет в таблице: приехало из будущего, из чужой коллекции или с опечаткой. */
  | { kind: 'unknown'; id: ItemId }
  /**
   * Имя есть, но во владении его нет. Из ячейки оно не стирается: владение может
   * быть временно неизвестно (сети нет), и молча выбрасывать надетое нельзя.
   */
  | { kind: 'unowned'; def: ItemDef }
  | { kind: 'worn'; def: ItemDef };

/**
 * Единственная дверь к тому, что даёт надетое. Действует только `worn`, и
 * `def` у него — строка нашей таблицы, а не то, что приехало вместе с именем.
 */
export function itemIn(slot: ItemId | null, owned: readonly ItemId[]): SlotState {
  if (slot === null) return { kind: 'empty' };
  const def = own(ITEMS, slot);
  if (!def) return { kind: 'unknown', id: slot };
  return owned.includes(slot) ? { kind: 'worn', def } : { kind: 'unowned', def };
}

/**
 * Имя из сохранения — в ячейку. Ячейка хранит имя и больше ничего: всё, что не
 * строка, становится пустым местом, а не «чем-то похожим на предмет».
 */
export const slotName = (raw: unknown): ItemId | null =>
  typeof raw === 'string' && raw.length > 0 && raw.length <= 64 ? (raw as ItemId) : null;
