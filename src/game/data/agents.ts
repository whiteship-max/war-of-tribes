/**
 * Натиск: прибавка к стойкости (`ArmySetup.resolve`) за кружок сверх первого.
 * Кладётся в ту же дверь, что и обряд храма, — сложением, как конюшня
 * складывается с кузницей в ступени снаряжения. Потолок морали у них общий, и
 * карточка говорит это замером, а не обещает «+12».
 */
export const ONSLAUGHT_PER_CIRCLE = 3;

/** Зоркость: клеток радиуса, которым разведчик открывает землю, за кружок сверх первого. */
export const SIGHT_PER_CIRCLE = 1;

/**
 * Скрытность: доля провалов, прошедших незамеченными, за кружок сверх первого.
 * Шанс дела она не трогает — им владеет Дозор, и у него свой потолок (`SPY_CHANCE_MAX`).
 */
export const STEALTH_PER_CIRCLE = 0.15;

/**
 * Скрытность и гибель: во сколько раз реже гибнет лазутчик на пятом кружке, чем на
 * первом. Кружки делят этот размах поровну в разах, а не в процентах: каждый
 * следующий режет гибель во столько же раз, сколько предыдущий.
 *
 * Это второе дело скрытности, и оно **главное в выживании по построению**: размах
 * любого другого множителя гибели выводится из этого числа как его доля
 * (`world/peril.ts`) и потому всегда меньше. Дозор в гибель не входит вовсе — он
 * владеет шансом дела.
 */
export const STEALTH_PERIL_SPAN = 4;

// ---------- Возраст и покой ----------

/**
 * Год жизни агента, игровых секунд. **Сейчас это год деревни (`YEAR_DAYS` игровых
 * дней), и это рычаг, а не решение:** ход времени владелец подберёт отдельно. При
 * нынешнем годе служба от `AGENT_AGE0` до `RETIRE_AGE` слишком коротка по времени
 * деревни, и никто не успевает вырасти; сколько должен длиться год, чтобы успевали, считает
 * щуп пачки (docs/AGENT_LIFE.md, раздел «Что вышло»). Меняется одной строкой.
 */
export const AGENT_YEAR = YEAR_DAYS * DAY_LENGTH;

/** Сколько лет агенту в минуту прихода: так начинает партия, так приходит новичок из здания первого уровня. */
export const AGENT_AGE0 = 24;
/** В этом возрасте агент бросает дело: возвращается домой и уходит на покой. */
export const RETIRE_AGE = 60;
/** С этого возраста карточка предупреждает, что покой близко. */
export const RETIRE_WARN = RETIRE_AGE - 3;


/** Мест под вещи у каждого агента. Открыты не все: см. `slotsOpen`. */
export const SLOT_COUNT = 3;
/** С какого уровня открывается третье место. Первые два — с первого. */
export const THIRD_SLOT_LEVEL = 4;

/** Уровень по опыту. Не хранится: выводится при чтении, и разойтись ему не с чем. */
export function levelOf(xp: number): number {
  const have = Math.max(0, Number.isFinite(xp) ? xp : 0);
  let level = 1;
  for (let i = 1; i < LEVEL_XP.length; i++) if (have >= LEVEL_XP[i]) level = i + 1;
  return level;
}

/**
 * Кружков навыка — ровно уровень. Отдельного счётчика нет и заводить его нельзя:
 * два числа об одном уровне расходятся ровно тогда, когда один из них правят.
 */
export const circlesOf = (xp: number): number => levelOf(xp);

/** Порог следующего уровня. null — дальше расти некуда. */
export function nextLevelXp(xp: number): number | null {
  const level = levelOf(xp);
  return level >= MAX_AGENT_LEVEL ? null : LEVEL_XP[level];
}

/** Потолок опыта: порог последнего уровня. */
export const XP_CAP = LEVEL_XP[LEVEL_XP.length - 1];

/** Сколько мест под вещи открыто на этом опыте. */
export const slotsOpen = (xp: number): number => (levelOf(xp) >= THIRD_SLOT_LEVEL ? 3 : 2);
