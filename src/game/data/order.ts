// Невольники, порядок и мятеж: все слова, какими игра о них говорит.
//
// Лежат в одном месте нарочно, по той же причине, что слова писем в
// `world/data/letters.ts`: тон этой механики обязан быть одним на всю игру, и
// проверяется он тестом, который читает ровно этот модуль. Строка, написанная
// где-то в разметке своими словами, мимо такой проверки прошла бы.
//
// Тон один и простой: буднично. Невольник — работник без воли: у него есть
// цена, он ест, работает под присмотром и уходит при мятеже. Ни похвалы сделке,
// ни шутки, ни подробностей насилия. Людей не считают штуками и головами.
//
// Модуль чистый: только слова и числа из аргументов. Считать здесь нечего —
// числа приходят готовыми из `derived.ts` и `sim/mutiny.ts`.
import { realSeconds } from '../pace';
import type { IconName } from '@/ui/icons/alias';

/** Имя значка набора (docs/icons.md) — с проверкой `tsc`: опечатка в имени — ошибка сборки, а не пустое место. */
const ico = (name: IconName): IconName => name;

/** «N невольник / невольника / невольников». */
export function bondedWord(n: number): string {
  const t = Math.abs(n) % 100;
  const o = Math.abs(n) % 10;
  if (t >= 11 && t <= 14) return 'невольников';
  if (o === 1) return 'невольник';
  if (o >= 2 && o <= 4) return 'невольника';
  return 'невольников';
}

/** «N житель / жителя / жителей». */
export function townsWord(n: number): string {
  const t = Math.abs(n) % 100;
  const o = Math.abs(n) % 10;
  if (t >= 11 && t <= 14) return 'жителей';
  if (o === 1) return 'житель';
  if (o >= 2 && o <= 4) return 'жителя';
  return 'жителей';
}

/** Минуты и секунды для срока ропота: «2:05». Срок идёт игровыми секундами, игрок ждёт настоящими. */
export function clockText(sec: number): string {
  const total = Math.max(0, Math.ceil(realSeconds(sec)));
  const m = Math.floor(total / 60);
  const s = total % 60;
  return `${m}:${String(s).padStart(2, '0')}`;
}

