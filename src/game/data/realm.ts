// Держава: очки правителя, потолок и цена уровня технологии. Только числа и чистые
// формулы — ни состояния, ни чтения партии: приток, трата и перезапись базы живут в
// `sim/points.ts`, а человек — в `sim/dynasty.ts`. Разбор с замерами — docs/dynasty.md.
//
// **Главное свойство модуля: своих чисел у него почти нет, и это проверяется глазом
// по этому файлу.** Потолок очков — потолок догона офлайна (`MAX_OFFLINE_DAYS`) по
// верхнему навыку, а верхний навык — верх агентской лестницы; лестница военной ветви
// выведена из работы вещей кузницы (`EquipmentDef.work`), и виды бойцов ложатся на неё
// сами, по своему снаряжению (`TroopDef.gear`). Рукописного «что открывает уровень»
// нет ни строки — есть предикат, читающий то, что в таблицах уже лежит.
//
// Что здесь **нельзя** заводить: поля `requiresTech` у здания, бойца, вещи или товара
// (решение владельца, docs/dynasty.md, раздел 10.1, решение 1) и второй двери к одному
// открытию. Список, написанный рукой, разойдётся с лестницей при первом же новом виде.
