// ---------- Навык правителя ----------

/**
 * Ступеней у навыка правителя столько же, сколько у агента (`MAX_AGENT_LEVEL`), и это
 * не совпадение: лестница человека в игре одна — пять уровней, кружков столько, сколько
 * уровень. Второго визуального языка заводить не надо, кружки уже рисует карточка агента.
 * В EU4 у монарха 0…6; ноль нам не годится — ветвь, которая не движется вовсе, это тупик,
 * а «тупика нет» — правило игры.
 */
export const MAX_RULER_SKILL = MAX_AGENT_LEVEL;
export const MIN_RULER_SKILL = 1;

/** Середина лестницы: «средний правитель», которым считаны все сроки в docs/dynasty.md. */
export const MEAN_RULER_SKILL = Math.round((MIN_RULER_SKILL + MAX_RULER_SKILL) / 2);

/**
 * Приток: **одно очко за игровой день на кружок навыка**. Это определение единицы, а не
 * замер, и сказано это прямо: у EU4 монарх с административным 3 даёт три очка в месяц, а
 * место месяца у нас занимает игровой день.
 *
 * Класс величины — ставка за **игровой день** на часах племени, и класс в имени, как у
 * `POP_GROWTH_PER_DAY` и `moralePerDay`: настоящего времени она не встречает нигде, поэтому
 * конструктор из `game/pace.ts` ей не нужен (docs/time.md, раздел 13.1).
 */
export const POINTS_PER_SKILL_PER_DAY = 1;

/** Сколько очков в игровой день даёт правитель с таким навыком. */
export const pointsPerDay = (skill: number): number =>
  Math.max(0, Math.min(MAX_RULER_SKILL, Math.round(skill))) * POINTS_PER_SKILL_PER_DAY;

/**
 * Потолок очков каждого вида. **Нового числа нет:** это полная отлучка самого сильного
 * правителя, какой в игре бывает, — `MAX_OFFLINE_DAYS` игровых дней притока по верхнему
 * навыку. Обещание у него то же, что у склада и у догона: сутки отлучки не теряют ничего,
 * и игра не наказывает за сон (docs/dynasty.md, раздел 3.3).
 *
 * Потолок зажимает и того, кто не уходит, а просто не тратит: копить впрок больше одной
 * полной отлучки нельзя. Отлучку зажимает и без него — `sim/tick.awayGameSeconds`.
 */
export const POINTS_CAP = MAX_OFFLINE_DAYS * MAX_RULER_SKILL * POINTS_PER_SKILL_PER_DAY;

// ---------- Военная ветвь: лестница выводится из работы вещей ----------

/**
 * Порядок, в котором военная ветвь открывает вещи кузницы: по работе горна
 * (`EquipmentDef.work`), от дешёвой к дорогой. Ключ вторичной сортировки — имя, чтобы
 * порядок не зависел от порядка строк в таблице, если у двух вещей однажды сойдётся работа.
 *
 * Работа — единственное закоммиченное число, которое означает «насколько эта вещь
 * продвинутая», и потому она и есть лестница. Рукописного порядка рядом быть не должно.
 */
export const WAR_GEAR_ORDER: EquipmentId[] = [...EQUIPMENT]
  .sort((a, b) => a.work - b.work || (a.id < b.id ? -1 : 1))
  .map((e) => e.id);

/**
 * На каком уровне ветви открывается вещь. Первый уровень — то состояние, в котором партия
 * начинается (дубина, которую не куют), поэтому первая вещь лежит на втором.
 */
export const warLevelOfGear = (item: EquipmentId): number => WAR_GEAR_ORDER.indexOf(item) + 2;

/**
 * На каком уровне ветви открывается вид бойца: **когда открыто всё, что он носит.** Вид
 * без снаряжения (дубинщик) открыт с первого уровня, то есть с первой секунды партии.
 *
 * Правило, а не список: заведи вид с новой вещью — он встанет в лестницу сам.
 */
export function warLevelOfTroop(troop: TroopId): number {
  let level = 1;
  for (const [item, n] of Object.entries(TROOP_BY_ID[troop].gear)) {
    if ((n ?? 0) > 0) level = Math.max(level, warLevelOfGear(item as EquipmentId));
  }
  return level;
}

/**
 * Верх военной ветви — участи, которые открываются покупкой. Сегодня одна: «увести людей»
 * (`FATES.captives`) — её объявляет игрок против логова, то есть она живая. «Ограбить» — то,
 * с чем партия начинается (`FATE_DEFAULT`), и ступени у него нет, как нет её у дубины. Ступени
 * «сжечь» в ветви нет — она не предлагается никому (`FATES.burn.vsWorld` = false), а уровень,
 * открывающий ничто, это второй раз удалённое задание «Взятый замок» (решение владельца 10).
 *
 * Порядок «сперва все вещи, потом участи» — единственная рукописная строка этой ветви, и
 * довод у неё такой: снаряжение — то, чем вообще воюют, участь — то, что делают после победы.
 *
 * **Участь начатой партии не засчитывается никогда** (решение владельца, docs/dynasty.md,
 * раздел 11.2): правило «по самой дорогой вещи на складе и в дружине» — про вещи, а участь
 * вещью не является, и доказательства для неё в сохранении нет по определению. Это та же
 * граница, что у ячейки стола донесений: новая возможность, а не пройденное.
 */
export const WAR_FATES = ['captives'] as const satisfies readonly Fate[];

export type WarFate = (typeof WAR_FATES)[number];

/** Ступень ли это участи в военной ветви. Гейт спрашивает этим, а не сравнением со строкой. */
export const isWarFate = (v: string): v is WarFate => (WAR_FATES as readonly string[]).includes(v);

/** На каком уровне ветви открывается участь: за последней вещью, в порядке списка. */
export const warLevelOfFate = (fate: WarFate): number => WAR_GEAR_ORDER.length + 2 + WAR_FATES.indexOf(fate);

/** Уровень ступени «увести людей» — для отчётов, которые печатают лестницу. */
export const WAR_CAPTIVES_LEVEL = warLevelOfFate('captives');

/** Ступеней в военной ветви: бесплатная, по одной на вещь и по одной на участь. */
export const WAR_LEVELS = 1 + WAR_GEAR_ORDER.length + WAR_FATES.length;

// ---------- Административная ветвь: места наёмных мастеров ----------

/**
 * Где стоят наёмные мастера, объявлено рядом с таблицей зданий (`data/buildings.MASTERS_AT`):
 * лестница ниже выводится из мест этого здания и ничего не пишет сама.
 */
export { MASTERS_AT };

const HALL = BUILDING_BY_ID[MASTERS_AT];

/**
 * Ступеней в административной ветви: бесплатная — с ней партия начинается, и наёмных у неё
 * нет, — плюс по одной на каждый уровень Мастерской. Длина ветви — длина лестницы здания.
 */
export const ADMIN_LEVELS = 1 + Math.min(HALL.maxLevel ?? MAX_BUILDING_LEVEL, MAX_BUILDING_LEVEL);

/**
 * Сколько мест Мастерской ветвь пускает под наёмных мастеров при таком уровне: **места
 * одного уровня Мастерской на ступень** — той же формулой, которой считаются её настоящие
 * места (`data/buildings.slotsAt`). Своего числа мест у ветви нет: поменяй места Мастерской
 * за уровень — лестница поменяется сама. Сколько мастеров стоит на деле, решают ещё и
 * свободные места самой Мастерской (`derived.mastersRoom`).
 *
 * Прежде здесь был вариант А — потолок уровня построек. Он снят замером: потолок запрещает,
 * а не даёт, и перекос военного гейта в середине партии углублял (docs/admin_branch.md, раздел 1).
 */
export const mastersAt = (level: number): number =>
  slotsAt(HALL, Math.max(1, Math.min(ADMIN_LEVELS, Math.round(level))) - 1);

// ---------- Дипломатическая ветвь: тонкая, и список назван ----------

/**
 * Что открывает дипломатическая ветвь, по ступеням сверх бесплатной. Это **рукописный
 * список, и он назван таким вслух** (docs/dynasty.md, раздел 4.6): вещи в нём разнородные —
 * место агента и ячейка стола донесений, — и общего закоммиченного числа, которое означало
 * бы «насколько эта возможность продвинутая», у них нет. Выводить порядок из скорости или
 * обзора фигуры было бы выводом только по названию.
 *
 * Список короткий не от лени: дипломатия спит почти целиком — у дипломата нет ни одного
 * работающего приказа, договоры и письма ждут живых соседей. Наполнять ветвь придуманным
 * значило бы обещать механики, которых нет.
 */
export const DIPLO_RUNGS = ['spy', 'letterSlot'] as const;

export type DiploRung = (typeof DIPLO_RUNGS)[number];

/** Ступеней в дипломатической ветви: бесплатная плюс живые. */
export const DIPLO_LEVELS = DIPLO_RUNGS.length + 1;

/**
 * На каком уровне открывается ступень. Выводится из места в списке, а не пишется рядом:
 * припиши уровень руками — и он разойдётся со списком при первой же вставке в середину.
 * Первый уровень бесплатен и занят тем, с чем партия начинается, поэтому `+ 2`.
 *
 * Тот же приём, что у военной лестницы (`warLevelOfGear`), и та же причина.
 */
export const diploLevelOf = (rung: DiploRung): number => DIPLO_RUNGS.indexOf(rung) + 2;

/** Ступень ли это дипломатической ветви. Гейт спрашивает этим, а не сравнением со строкой. */
export const isDiploRung = (v: string): v is DiploRung => (DIPLO_RUNGS as readonly string[]).includes(v);

/**
 * Как ступень называется игроку. **Слова — единственное, что здесь пишется рукой**, и это
 * то же исключение, что у названий ветвей: из числа слово не выведешь. Что ступень делает,
 * словами не описано нарочно — это меряется дверьми гейта (`sim/tech.techGains`), иначе
 * подпись разойдётся с правилом ровно тогда, когда правило поправят.
 */
export const DIPLO_RUNG_NAME: Record<DiploRung, string> = {
  spy: 'Место лазутчика',
  letterSlot: 'Ячейка стола донесений',
};

// ---------- Цена уровня ----------

/** Сколько ступеней у ветви. Длина ветви — длина списка того, что она открывает. */
export const levelsOf = (branch: RealmBranch): number =>
  branch === 'war' ? WAR_LEVELS : branch === 'admin' ? ADMIN_LEVELS : DIPLO_LEVELS;

/**
 * Цена уровня, очков. Прямая, у которой последний уровень стоит ровно потолок, а первый
 * бесплатен: первый — то состояние, в котором партия начинается.
 *
 * **Геометрию (`UPGRADE_GROWTH`, как у улучшений) здесь взять нельзя, и это не вкус.**
 * Уложи в ×1.4 ту же дугу — и последний уровень выходит дороже потолка, то есть его нельзя
 * накопить никогда. Потолок задаёт цене верхнюю границу, значит кривая обязана быть
 * ограниченной, а самая простая ограниченная — прямая (docs/dynasty.md, раздел 4.5).
 */
export function levelPrice(branch: RealmBranch, level: number): number {
  const n = levelsOf(branch);
  const l = Math.round(level);
  if (l <= 1 || n <= 1) return 0;
  if (l > n) return 0;
  return Math.round((POINTS_CAP * (l - 1)) / (n - 1));
}

/** Вся ветвь: сколько очков стоит пройти её целиком. */
export const branchPrice = (branch: RealmBranch): number => {
  let sum = 0;
  for (let l = 2; l <= levelsOf(branch); l++) sum += levelPrice(branch, l);
  return sum;
};

/**
 * С чем новая партия начинает: очков ровно на первый покупаемый уровень каждой ветви. Не
 * подарок, а тот же приём, которым в игре стоит готовый посёлок, — игра начинается со
 * сделанным первым ходом. Практическая причина: без этого проводка первых шагов встала бы
 * на часы, ожидая первого копья (docs/dynasty.md, раздел 6.1).
 */
export const startingPoints = (branch: RealmBranch): number => levelPrice(branch, 2);
