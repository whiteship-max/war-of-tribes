/**
 * Код приглашения. Тридцать шестая система — чтобы ссылка была короткой:
 * идентификатор Telegram занимает десять знаков, в base36 — шесть.
 */
export const refCode = (id: number): string => `r${Math.abs(Math.trunc(id)).toString(36)}`;

/**
 * Ссылка приглашения. `null`, если игрока не опознали: вне Telegram
 * идентификатора нет, а сочинять «свой код» в localStorage нельзя — он пропадёт
 * с очисткой данных и может совпасть с чужим. Игрок думал бы, что приглашает по
 * личной ссылке, а это была бы неправда.
 */
export function inviteLink(id: number | null): string | null {
  if (id === null || !BOT_USERNAME || !MINI_APP_NAME) return null;
  return `https://t.me/${BOT_USERNAME}/${MINI_APP_NAME}?startapp=${refCode(id)}`;
}

