/**
 * Витрина алмазов. Только описание наборов — ни цены в рублях, ни платёжной
 * логики здесь нет и быть не может: в Telegram Mini App за реальные деньги
 * платят через Telegram Stars, счёт выставляет бот, а подтверждает его вебхук
 * на сервере. Сервера у нас нет, поэтому витрина показывается, а кнопки не
 * нажимаются — изображать покупку, которой не будет, нечестно.
 *
 * Когда сервер появится: набор уходит боту как счёт на `stars` звёзд, ответ
 * вебхука приходит расписком в `creditGems` (sim/gems.ts). Ни одна кнопка
 * интерфейса алмазы не начисляет и начислять не сможет.
 */
export interface GemPack {
  id: string;
  name: string;
  icon: string;
  /** Сколько алмазов в наборе. */
  gems: number;
  /** Цена в Telegram Stars. */
  stars: number;
  /** Подпись выгоды: считается от первого набора, писать руками нечего. */
  best?: boolean;
}

export const GEM_PACKS: GemPack[] = [
  { id: 'handful', name: 'Горсть', icon: '♦️', gems: 60, stars: 100 },
  { id: 'pouch', name: 'Кошель', icon: '👝', gems: 330, stars: 500 },
  { id: 'chest', name: 'Сундук', icon: '🧰', gems: 700, stars: 1000, best: true },
  { id: 'wagon', name: 'Обоз', icon: '🛒', gems: 1800, stars: 2500 },
];

/** Сколько алмазов за звезду даёт набор — по нему и видно, что выгоднее. */
export const packRate = (p: GemPack): number => p.gems / p.stars;
