export const DAILY_GAME_BY_ID = Object.fromEntries(DAILY_GAMES.map((g) => [g.id, g])) as Record<
  DailyGameId,
  DailyGameDef
>;

/** Шесть перестановок трёх игр — все, какие бывают. */
const PERMS: readonly (readonly [number, number, number])[] = [
  [0, 1, 2],
  [0, 2, 1],
  [1, 0, 2],
  [1, 2, 0],
  [2, 0, 1],
  [2, 1, 0],
];

/**
 * Игра этого календарного дня.
 *
 * Дни идут тройками: внутри тройки каждая из трёх игр выпадает ровно один раз —
 * это и есть чередование. А какая в каком месте, решает перестановка, выбранная
 * хешем номера тройки, — поэтому порядок случаен и пятый день не угадывается из
 * второго. Одно и то же число всегда даёт один и тот же ответ, значит сегодня у
 * всех одна игра и сервер повторит выбор.
 */
export function dailyGameOf(day: number): DailyGameId {
  const block = Math.floor(day / 3);
  const slot = day - block * 3; // 0, 1 или 2
  const perm = PERMS[Math.floor(seeded((block * 2654435761 + 1013904223) >>> 0)() * PERMS.length)];
  return DAILY_GAMES[perm[slot]].id;
}

/**
 * Сид сегодняшнего задания: мишень, составы викторины, лабиринт — всё из него.
 * Своя константа смешивания, чтобы сид задания не совпал ни с сидом прилавка
 * рынка, ни с сидом выбора игры выше: соседние дни не должны давать похожие
 * уровни.
 */
export const dailySeed = (day: number): number => ((day * 2654435761 + 40503) ^ 0x5f356495) >>> 0;
