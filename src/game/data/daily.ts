// Ежедневное задание: календарь и содержимое. Ни React, ни three, ни состояния
// игры — только числа и чистые функции от номера дня.
//
// Устроено оно так же, как прилавок рынка (data/market.ts): в состоянии не
// хранится ни какая сегодня игра, ни что у неё внутри. И то, и другое выводится
// из номера календарного дня, поэтому у всех игроков в этот день одно и то же
// задание, перезагрузка его не тасует, а сервер потом получит тот же ответ из
// того же числа.
import type { ResourceId } from '../types';
import { seeded } from '../sim/random';
import { DAY_MS } from '../time';

/**
 * Календарный день: сколько целых суток UTC прошло от эпохи.
 *
 * Не местная дата и не `new Date().getDate()`: у полуночи должна быть одна
 * граница на всех, иначе «одинаковое задание у всех» рассыпается на двадцать
 * четыре разных, а у игрока, перелетевшего через часовой пояс, день то пропадёт,
 * то повторится. То же число потом посчитает сервер из своего времени — сверять
 * будет нечего.
 *
 * Часы читает не эта функция, а тот, кто её зовёт: время приходит числом. Это
 * условие того, что симуляция остаётся чистой, а тесты обходятся без подмены
 * глобальных часов.
 */
export const dayIndex = (nowMs: number): number => Math.floor(nowMs / DAY_MS);

/** Сколько миллисекунд осталось до следующего задания. */
export const untilNextDay = (nowMs: number): number => (dayIndex(nowMs) + 1) * DAY_MS - nowMs;

export type DailyGameId = 'archery' | 'quiz' | 'maze';

export interface DailyGameDef {
  id: DailyGameId;
  icon: string;
  name: string;
  /** Правило одной строкой — его читает игрок до того, как потратит попытку. */
  rules: string;
  /**
   * Награда под посёлок в `START_POP` душ. Настоящая считается от нынешнего
   * размера племени — см. `dailyReward` в sim/daily.ts. Ресурсы и только они:
   * алмазы начисляет единственная дверь `creditGems`, и она ждёт сервера.
   */
  reward: Partial<Record<ResourceId, number>>;
}

