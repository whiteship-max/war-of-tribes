// ---------- Наклон при уровне храма ----------

/**
 * Доля наклона при храме такого уровня. Ровно уровень, делённый на потолок:
 * первый уровень даёт десятую часть и дара, и цены, десятый — всё целиком.
 *
 * Линейно нарочно. Уровень здесь не «сила», которую копят, а **насколько далеко
 * деревня зашла в свою веру**, и заходить туда наполовину должно быть ровно
 * наполовину дорого — иначе ступень посередине оказалась бы бесплатной.
 */
export const tiltShare = (level: number): number =>
  Math.max(0, Math.min(1, level / MAX_BUILDING_LEVEL));

/**
 * Наклон веры при этом уровне храма и этом укладе. Единственный способ узнать,
 * во что вера обходится прямо сейчас: второго места, где это считалось бы, быть
 * не должно — ни в панели, ни в тике.
 *
 * Множители (`output`, `learning`) приводятся к единице тем же коэффициентом:
 * половина наклона у множителя 0.92 — это 0.96, а не 0.46.
 */
export function tiltAt(faith: FaithId, level: number, observance: ObservanceId): FaithTilt {
  const t = FAITH_BY_ID[faith].tilt;
  const k = tiltShare(level) * OBSERVANCE_BY_ID[observance].mult;
  const lerp = (v: number): number => 1 + (v - 1) * k;
  return {
    boon: t.boon,
    burden: t.burden,
    goldPerPop: t.goldPerPop * k,
    morale: t.morale * k,
    output: lerp(t.output),
    steadfast: t.steadfast * k,
    learning: lerp(t.learning),
    growth: t.growth * k,
    fervour: t.fervour * k,
    // Давление чужой веры от уклада и уровня не зависит: оно про то, что вокруг
    // деревни, а не про то, как в ней служат.
    pressure: t.pressure,
  };
}
