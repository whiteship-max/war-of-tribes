// Четыре веры: что каждая даёт деревне и чего за это просит.
//
// Здесь только таблица. Логика читает её и ничего своего не считает — тот же
// договор, что у `data/policy.ts` с указами, рационом и налогом.
//
// ЧЕТЫРЕ ПРАВИЛА, КОТОРЫЕ НЕЛЬЗЯ НАРУШАТЬ.
//
// 1. **Никаких боевых бонусов «моя вера бьёт твою».** Различия идут вбок —
//    хозяйство, мораль, дипломатия, знание, — а не по силе удара против другой
//    веры. Держится это не обещанием, а устройством: у `BattleInput` вообще нет
//    поля веры, и взяться ему неоткуда. Единственное, что вера кладёт в бой, —
//    `fervour`: прибавка к стойкости **своей** дружины на время обряда, ровно
//    такая же против кого угодно. Проверяет `sim/faith.test.ts`.
// 2. **Ни одна вера не выставляется дурной или отсталой** — ни числом, ни
//    словом. У каждой свой дар и своя цена, и ни у одной цена не выглядит
//    расплатой за невежество.
// 3. **Наклон, а не сила.** Числа ниже — то, во что вера обходится и что даёт
//    при храме десятого уровня и ровном укладе. Уровень храма не добавляет
//    прибавки — он растит наклон целиком, вместе с ценой (`tiltAt`). Оттого
//    каждая ступень и есть выбор: она усиливает и дар, и то, что он стоит.
// 4. **Праздники называются настоящими именами.** Содержание игровое, тон
//    уважительный, и ни один обряд не выведен смешным. Оговорка про лунный
//    календарь — в комментарии к исламским праздникам и в docs/faiths.md.
import type { FaithId, ObservanceId, Season } from '../types';
import { MAX_BUILDING_LEVEL } from '../constants';
import { num } from '../num';
import type { IconName } from '@/ui/icons/alias';

/** Праздник: настоящее имя и одна строка о том, что в этот день делают. */
export interface FeastDef {
  name: string;
  /** Значок обряда (набор ЗН-1, docs/icons.md). */
  icon: IconName;
  /** Что происходит в деревне — текст обряда и события. */
  text: string;
}

/**
 * Наклон веры: чем она деревню держит и чего просит. Все числа даны **при храме
 * десятого уровня и ровном укладе**; настоящую величину считает `tiltAt`.
 */
export interface FaithTilt {
  /** Что вера даёт — одной строкой, на панель. */
  boon: string;
  /** Чего просит — там же и рядом, а не мелким шрифтом внизу. */
  burden: string;
  /**
   * Золота с человека за игровой день. Плюс — приход собирает (десятина),
   * минус — приход раздаёт (закят). Мерка та же, что у налога: `TAX_PER_POP`
   * при полном сборе.
   */
  goldPerPop: number;
  /** Сдвиг целевой морали. */
  morale: number;
  /** Множитель всей выработки посёлка: 1 — не трогает. */
  output: number;
  /** Прибавка к обороне деревни, долей от неё же. */
  steadfast: number;
  /** Во сколько раз быстрее идут ступени изучения округи в Дозоре. */
  learning: number;
  /** Прибавка к приросту населения, долей. */
  growth: number;
  /**
   * Прибавка к стартовой боевой морали **своих** секторов, пока идёт обряд.
   * Против кого угодно одна и та же: чужой веры в бою не существует.
   */
  fervour: number;
  /**
   * Во сколько раз тяжелее ложится чужая вера вокруг. Единица — как у всех.
   * Больше единицы — не «слабая вера», а открытая: у язычества нет ни списка,
   * ни грамоты, ни человека, приезжающего рассудить спор, поэтому спор с
   * соседями идёт в самой деревне.
   */
  pressure: number;
}

export interface FaithDef {
  id: FaithId;
  name: string;
  /** Знак веры (набор ЗН-1). */
  icon: IconName;
  /** Как в этой вере называется само здание. */
  temple: string;
  /** Как называется тот, кто в нём служит. */
  priest: string;
  /**
   * Он же во множественном числе. Написан руками, а не выведен правилом:
   * «имам» + «и» даёт «имами», и такие слова из числа не выводятся — ровно как
   * падежи родов войск в `game/battle/describe.ts`.
   */
  priests: string;
  /** Одна строка о том, чем эта вера живёт. Без оценок. */
  creed: string;
  /** Имя реликвии этой веры. Реликвия одна на веру и одинакова по силе у всех. */
  relic: string;
  tilt: FaithTilt;
  /** Праздник на каждый сезон. */
  feasts: Record<Season, FeastDef>;
}

