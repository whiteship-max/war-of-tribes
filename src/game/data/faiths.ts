// ---------- Уклад храма ----------

/**
 * Уклад — единственный рычаг у игрока внутри веры, и он ничего не добавляет от
 * себя: он множит наклон целиком, вместе с ценой. Строгий устав усиливает и
 * десятину, и просадку морали от неё; мирской гасит и то, и другое.
 *
 * Плата за строгость — набожность в другую сторону: строгий устав её поднимает,
 * мирской роняет. Поэтому «поставить мирской и жить спокойно» не работает —
 * упавшая набожность доводит приход до ереси.
 */
export interface ObservanceDef {
  id: ObservanceId;
  name: string;
  icon: string;
  /** Во сколько раз сильнее наклон веры. */
  mult: number;
  /** Сдвиг набожности, пока держат этот уклад. */
  piety: number;
  /** Строка последствий — она же надпись на кнопке. */
  effect: string;
}

