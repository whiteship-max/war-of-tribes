// Содержание войска: жалованье, терпение и уход.
//
// Потолка дружины больше нет — Статуя его не держит. Держит цена: каждый боец ест
// из общего котла (`SOLDIER_FOOD`) и получает жалованье из казны. Нечем кормить или
// нечем платить — войско убывает. Дверь одна, поводов два (`sim/upkeep.ts`).
//
// **Все числа — доли и игровые дни, а не минуты.** Жалованье — доля полного сбора с
// человека (`TAX_PER_POP`), уход — доля неоплаченной или некормленной части войска
// за игровой день, терпение и отсрочка — игровые дни. Доход, еда и жалованье
// считаются за игровой день, поэтому замедление дня двигает их вместе, и отношение
// «сколько армии держит казна» от него не зависит. Что при замедлении перемерить
// всё-таки придётся — docs/upkeep.md, раздел «Время».
//
// Числа выбраны прогоном, а не на глаз: `npm run pop:report`, раздел «Содержание
// войска».

/**
 * Жалованье за игровой день — с головы, в долях полного сбора с человека.
 *
 * Часть с головы нужна потому, что боец платит налог как житель (население считает
 * и бойцов): без неё жалованье дубинщика на высоком налоге было бы не больше
 * налога, который он платит сам (`derived.wageOf`, `data/policy.ts`), и армию
 * дубинщиков не держало бы ничто, кроме еды, — стена Статуи сменилась бы стеной
 * амбара.
 */
export const WAGE_HEAD = 0.5;

/**
 * Жалованье за игровой день — с бойца строя (`battle/kinds.weightOf`: дубинщик
 * один, копейщик два, латник восемь), в долях полного сбора с человека. Золото
 * держит силу, еда — головы.
 */
export const WAGE_MAN = 0.85;

/**
 * Какая доля неоплаченной или некормленной части войска уходит за игровой день,
 * когда терпение кончилось. Неоплаченная часть — нехватка, делённая на жалованье;
 * некормленная — нехватка еды, делённая на то, что ест войско. Уходит равная доля
 * каждого вида: дешёвые первыми выбили бы целые рода, и игрок терял бы не
 * численность, а возможность воевать.
 */
export const DESERT_SHARE = 0.15;

/**
 * Сколько игровых дней жалованья нет у партии, начатой до содержания войска: с
 * минуты входа, после догона офлайна (ступень сохранения 13 → 14). Без неё армия,
 * набранная при потолке Статуи, начала бы разбегаться при первом же входе — а
 * игрок о правиле ещё не знал.
 */
export const WAGE_AMNESTY_DAYS = 10;

