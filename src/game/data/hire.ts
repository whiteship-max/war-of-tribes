// Найм агентов: где, почём и как быстро. Числа здесь, поведение — `sim/hire.ts`.
//
// Место агента пустует, когда человек погиб или ушёл на покой, и нанимают нового в
// профильном здании. Уровень здания даёт новичку две вещи — приходит быстрее и
// моложе, — и не даёт третьей: опыта. Иначе здание стало бы вторым источником
// уровня агента, ровно тем, что запрещает `agents.owners.test.ts` в обратную сторону.
import type { BuildingTypeId } from '../types';
import type { FigureId } from '@/world/types';

/**
 * Где нанимают: разведчика и лазутчика — в Дозоре, дипломата — в Храме, полководца —
 * в Статуе Героя (он и герой — один человек, и нанять его в казармах значило бы
 * развести одного человека по двум зданиям).
 */
export const HIRE_AT: Readonly<Record<FigureId, BuildingTypeId>> = {
  scout: 'watch',
  spy: 'watch',
  diplomat: 'church',
  general: 'statue',
};

/**
 * Золото за найм на каждого жителя — одна формула на всех, как смена рода у героя.
 * Цена нарочно небольшая: настоящая цена гибели — ушедший с человеком опыт, и второе
 * наказание за тот же случай оставило бы бедное племя без разведчика надолго.
 */
export const HIRE_GOLD_PER_POP = 2;

/** Сколько идёт найм при здании первого уровня, игровых секунд. Уровень его ускоряет. */
export const HIRE_SECONDS = 20 * 60;

/**
 * На сколько лет моложе приходит новичок за каждый уровень здания сверх первого: на
 * десятом он моложе на четыре с половиной года, и служба длиннее на восьмую часть.
 */
export const HIRE_YOUNGER = 0.5;
