// Орудия башни: балиста и катапульта — третий ответ осаждённого города, кроме вылазки
// и удара полководца с тыла: бить по лагерю, не выходя за стены.
//
// Числа не подобраны, а выведены одной меркой — кривой вылазки всем гарнизоном
// (docs/tower.md, `npm run siege:report`, раздел «орудия башни»):
//
//  - заметно — минута, с которой вылазка безнадёжна, сдвинута хотя бы на шаг замера;
//  - не отменяет осаду — вылазка становится безнадёжной раньше голода, хвост до 4 %.
//
// Цены у орудия своей нет: оно стоит, как улучшение башни до уровня, на котором
// открывается (`derived.upgradeCost`), и ставится столько же труда. Жалованье оно не
// обходит устройством: без расчёта лучников на башне оно молчит, а расчёт — столько
// лучников, чтобы их жалованье между двумя осадами было не меньше цены орудия. Сколько
// это людей, печатает тот же раздел отчёта строкой «расчёт».
import type { EngineId } from '../types';

export interface EngineDef {
  id: EngineId;
  name: string;
  /** Название в винительном падеже: «ставят балисту». */
  acc: string;
  icon: string;
  description: string;
  /** С какого уровня башни его можно поставить. Ниже этого уровня оно молчит. */
  level: number;
  /** Сколько лучников на башне нужно, чтобы оно било в полную силу; меньше — та же доля силы. */
  crew: number;
  /**
   * Какую долю выработки рогаток **со стороны города** съедает обстрел: фронт лагеря
   * рубится долей `1 − slow`. Тыл орудие не достаёт.
   */
  slow: number;
  /**
   * Какую долю мощи лагеря выбивает обстрел: растёт ровно со временем за
   * `CAMP_WORKS_RIPE` — часы самих рогаток — и дальше не растёт.
   */
  thin: number;
}

