/** Пассивные эффекты здания — растут не множителем, а прибавкой за уровень. */
export interface BuildingStats {
  /** Сколько жителей может жить. */
  housing?: number;
  /** Прибавка вместимости склада. */
  storage?: number;
  /** Защита поселения. */
  defense?: number;
  /** Постоянный бонус к морали. */
  morale?: number;
  /**
   * Сколько ополченцев выходит стрелками, а не пехотой. Это и есть работа башни:
   * частокол даёт плоскую оборону, башня — стрелков на ней. Число не добавляет
   * людей, а переводит часть уже посчитанного ополчения в другой род боя
   * (см. world/bridge.militiaArchers).
   */
  archers?: number;
  /**
   * Мест лучников на башне — расчёт её орудия (`data/engines.ts`). Места людей не
   * добавляют: на них встают уже нанятые лучники, пока они дома. Читается целым вниз
   * (`derived.towerSeats`): одно место на первом уровне и ещё одно каждые пять.
   */
  seats?: number;
  /** Какая доля павших в бою ранена и ляжет в лазарет, в процентах. */
  heal?: number;
  /** Сколько раненых лазарет держит разом. Сверх мест раненые не выживают (docs/infirmary.md). */
  beds?: number;
  /** На сколько процентов медленнее стареют разведданные — работа дозора. */
  intel?: number;
  /**
   * Насколько дольше видно чужую армию до прихода, **игровых** секунд: прибавка к предупреждению мира.
   * Одна семья с `AI_WARNING_BASE` — ритм угрозы, игровое время (docs/time.md, раздел 16).
   */
  warn?: number;
  /** На сколько процентов быстрее учится конница — работа конюшни. */
  train?: number;
  /** Сколько коней держит конюшня: общий потолок обоих конных родов (`derived.stalls`). */
  stalls?: number;
  /** Сколько единиц каждого ресурса тайник прячет от грабежа. */
  hidden?: number;
  /** Прибавка к морали, пока идёт пир в трактире. */
  feast?: number;
  /**
   * Сколько игровых дней войско терпит неуплату жалованья и голод, прежде чем
   * начать уходить. Работа Статуи: терпение дружины (с полководцем она не связана,
   * ДР-7). Потолка дружины у Статуи больше нет — войско держит цена
   * (`data/upkeep.ts`), а Статуя решает, сколько времени у вождя, чтобы эту цену
   * заплатить.
   */
  loyalty?: number;
}

export interface BuildingDef extends BuildingStats {
  id: BuildingTypeId;
  name: string;
  /** Строка вкуса (docs/voice.md, 3): одна фраза, образ эпохи, без чисел и без пользы. */
  flavor: string;
  /** Строка дела: что постройка даёт игре. Числа — не здесь, а функциями игры рядом (правило 18). */
  description: string;
  /**
   * База цены улучшений: подъём до уровня L стоит cost × UPGRADE_GROWTH^(L−1)
   * ресурсов и столько же раз больше труда, чем `work` (см. derived.upgradeCost).
   */
  cost: Partial<Record<ResourceId, number>>;
  /** База труда строителей на улучшение. */
  work: number;
  /**
   * Дела здания — профессии, которым оно даёт рабочие места (ЗД-1). У большинства одно; у двора их бывает два: Ферма —
   * поле и загон, Охотничий двор — охота и сбор, Шахта — руда и камень. Места и выработка — у каждого дела свои, как у
   * прежнего здания того же уровня; уровень — общий (`derived.deedSlots`).
   */
  jobs?: readonly JobId[];
  /**
   * Рабочих мест за уровень **на одно дело**. По умолчанию `SLOTS_PER_LEVEL`. Своё число нужно
   * там, где толпа бессмысленна: у горна, у верстака и в церкви людей помещается
   * заметно меньше, чем на поле или в лесу.
   */
  slotsPerLevel?: number;
  /**
   * Цены дел двора с двумя делами (ЗД-1): у каждого — цена прежнего здания, из которого дело пришло. По ним считается
   * лестница цены и её округление каждого дела врозь (`labour.upgradeCost`), а `cost` и `work` — их сумма. Кладёт поле
   * строка двора (`data/yards.yardBuilding`); руками не ставится.
   */
  parts?: readonly { cost: Partial<Record<ResourceId, number>>; work: number }[];
  /** Прибавка пассивных эффектов за каждый уровень сверх первого. */
  perLevel?: BuildingStats;
  /**
   * С какого уровня эффект вообще появляется. По умолчанию с первого.
   * Ратуша так и раздаёт жильё: сначала это дом одного человека, и только
   * с шестого уровня — двор с людьми (см. buildingStat).
   */
  since?: Partial<Record<keyof BuildingStats, number>>;
  /** Потолок уровня для этого типа. По умолчанию MAX_BUILDING_LEVEL. */
  maxLevel?: number;
  /**
   * Здание стоит **за стеной**. Это правило игры, а не рисунок: поле, загон
   * и штольня стоят там, где ресурс, и чужой набег дотягивается ровно до них
   * (см. sim/expedition.sackOutskirts). План поселения ставит такие здания на
   * четвёртое кольцо, и тест сверяет обе стороны.
   *
   * Руками не ставится: за стеной стоят ровно дворы, и поле кладёт строка двора
   * (`data/yards.yardBuilding`) вместе с делами и ценой.
   */
  outside?: boolean;
}

