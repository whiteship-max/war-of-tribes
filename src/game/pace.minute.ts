// Закрепление «игровой день — настоящая минута» для тестов правил мира.
//
// Тесты правил мира (осада, рогатки, набег, перехват, письма, башня) написаны литералами того
// времени, когда игровой день был настоящей минутой: «за четыре часа набег обязан случиться»,
// «на 32-й минуте лагерь стоит», расход еды слепка в настоящий час. Проверяют они правило, а не
// шкалу, и при боевой шкале их литералы неверны тривиально. Файл такого теста первой строкой
// берёт этот модуль — до чисел мира, которые считаются при импорте, — и честно говорит этим, при
// какой шкале снят. Свойства двери времени держат свои тесты при шкале, отличной от единицы
// (`game/pace.test.ts`, `scripts/lib/timeclasses.test.ts`), боевую шкалу — тест «для игроков
// шкала — тридцать». В игре модуль не берёт никто — тест по исходникам.
//
// Долг назван: взаимодействие настоящего времени (поход, сбор дружины) с игровым (предупреждение,
// рогатки) при боевой шкале эти тесты не видят — его меряют отчёты (docs/time.md, раздел 17).
import { setTimeScale } from './pace';

setTimeScale(1);
