/**
 * Выключатель Пути меча (ПН-1, docs/gdd/path_of_sword.md, 7.5, угроза У1; «Решения ПН-1»; с 30.10.2026 — по игроку, 0.4).
 *
 * Путь делается пачками неделями (Срез 1 — тринадцать пачек), а `master` всё это время обязан оставаться годным к выкладке:
 * любая выкладка между пачками — нынешняя игра плюс невидимый игрокам код. Поэтому фаза бродяги закрыта **одним** правилом:
 *   — шаг партии не выбирает дверь бродяги (`sim/tick.liveStep`, `absence`);
 *   — чтение сохранения не пускает фазу и отряд (`save.deserialize`);
 *   — войти в путь нельзя (`sim/roam.beginRoam` отказывает);
 *   — обоз не пишется (`sim/stock.addStock` с ключом `cargo` ничего не кладёт);
 *   — сервер отклоняет приказы отряда 403 без флага и строк отряда игроку не отдаёт (`routes/castles`).
 *
 * **Правило одно на клиент и сервер — `roamOpenFor`:** путь открыт всем, когда выпущен (`ROAM_ON`), а до выпуска — только админам
 * (решение владельца 30.10.2026: владелец проходит путь бродягой с нуля, игрокам он закрыт). Админ — тот же список, что у команд
 * бота и указов (`ADMIN_IDS`, `netlify/lib/admin.isAdmin`). Сервер спрашивает правило по подписи игрока; клиент — по слову сервера в
 * записке админки (`AdminNote.admin`), которое устройство помнит (`net/admin`), чтобы партия бродяги читалась раньше первого ответа
 * сервера. Своего списка у клиента нет: подделанная память устройства откроет путь только на нём самом — приказы отряда сервер
 * такому игроку отклонит.
 *
 * Включает путь всем выпуск Среза 1 (ГДД 7.3, чат 14) — вместе с `SAVE_VERSION` и чистым стартом эпохи (6.7). Тесты пути открывают
 * его подменой модуля (`vi.mock`) или словом сервера (`setRoamOpen`), а не правкой этой строки.
 *
 * Без `@/`: модуль собирает и сервер.
 */
export const ROAM_ON = false;

/** Открыт ли путь игроку: выпущен всем — да, до выпуска — только админу. Одно правило на клиент и сервер. */
export const roamOpenFor = (admin: boolean): boolean => ROAM_ON || admin;

/** Клиент: сервер назвал этого игрока админом (`AdminNote.admin`, память устройства — `net/admin`). Сервер это поле не читает. */
let deviceAdmin = false;

/** Клиент: слово сервера об админе. Зовёт только записка админки (`net/admin`) и тесты. */
export const setRoamOpen = (admin: boolean): void => {
  deviceAdmin = admin;
};

/** Клиент: открыт ли путь этому игроку на этом устройстве — тем же правилом, что у сервера. */
export const roamOn = (): boolean => roamOpenFor(deviceAdmin);
