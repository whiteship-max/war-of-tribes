// Ежедневное задание «Меткий выстрел»: уровень выводится из сида и ничего больше
// не знает — ни про React, ни про сцену, ни про состояние игры, ни про часы.
// Это условие того, что задание сегодня одинаково у всех, что перезагрузка его не
// перетасует и что сервер потом повторит расчёт из того же числа.
//
// Мишени, по которой надо попасть пальцем, здесь нет, и заводить её не надо.
// На 375 px палец накрывает мишень целиком, а мишени нужно поле около 260x260 px,
// тогда как в свёрнутой шторке остаётся ~359 px полезной высоты. Поэтому целятся
// ВРЕМЕНЕМ: по горизонтальной дорожке ходит бегунок, зачётная зона стоит на месте,
// и весь снаряд помещается в 56 px — той же высоты и того же языка, что полоска
// прогресса в остальном интерфейсе.
import { seeded } from '../sim/random';

/** Зона одного выстрела: где стоит и насколько широка. Числа — доли дорожки 0..1. */
export interface ArcheryShot {
  /** Середина зоны. */
  center: number;
  /** Полуширина яблочка (3 очка). */
  bull: number;
  /** Полуширина кольца (1 очко). Всегда больше `bull`. */
  ring: number;
}

/** Уровень одного дня. */
export interface ArcheryLevel {
  /** Полный проход дорожки из конца в конец, секунды. Период колебания — вдвое больше. */
  sweep: number;
  shots: ArcheryShot[];
}

/** Выстрелов за попытку. */
export const ARCHERY_SHOTS = 3;
/** Очки за яблочко. */
export const SCORE_BULL = 3;
/** Очки за кольцо. */
export const SCORE_RING = 1;
/** Идеальная попытка. */
export const ARCHERY_MAX = ARCHERY_SHOTS * SCORE_BULL;
/**
 * Порог победы. Пять из девяти — это либо два яблочка, либо одно яблочко и два
 * кольца: одной удачной вспышки мало, но и три яблочка не требуются. При обычном
 * человеческом разбросе времени реакции проигрывает примерно треть — так и
 * задумано, задание дня без риска проиграть не задание.
 */
export const ARCHERY_WIN = 5;

/**
 * Скорость бегунка. Медленнее 1.4 с игра перестаёт быть игрой, быстрее 1.15 с
 * промах становится делом случая, а не руки.
 */
const SWEEP_MIN = 1.15;
const SWEEP_MAX = 1.4;

/**
 * Зона стоит не у самого края: у краёв бегунок разворачивается и задерживается,
 * и попадание там стоило бы дешевле, чем в середине хода.
 */
const CENTER_MIN = 0.3;
const CENTER_MAX = 0.7;

const BULL_MIN = 0.04;
const BULL_MAX = 0.05;
const RING_MIN = 0.098;
const RING_MAX = 0.113;

/**
 * Насколько зоны трёх выстрелов обязаны разойтись по дорожке. Сойдись они в одну
 * точку — все три выстрела делались бы одним заученным движением, и попытка
 * решалась бы первым тапом.
 */
const MIN_GAP = 0.06;

/** Потолок отбраковки: цикл без потолка — это зависание, а не строгость. */
const TRIES = 24;

/**
 * Запасной уровень: зоны разведены поровну, ширины — из середины вилок. Он
 * детерминирован и играется ровно так же, как любой другой, просто на нём никогда
 * не сойдётся то, ради чего заведена отбраковка. Дойти до него почти невозможно
 * (условие расхождения выполняется примерно в половине случаев), но «почти» в
 * генераторе, который зовут все игроки мира, — не довод.
 */
const fallbackShots = (): ArcheryShot[] => {
  const mid = (a: number, b: number): number => (a + b) / 2;
  const step = (CENTER_MAX - CENTER_MIN) / (ARCHERY_SHOTS - 1);
  const out: ArcheryShot[] = [];
  for (let i = 0; i < ARCHERY_SHOTS; i++) {
    out.push({ center: CENTER_MIN + step * i, bull: mid(BULL_MIN, BULL_MAX), ring: mid(RING_MIN, RING_MAX) });
  }
  return out;
};

/** Уровень одного дня. Один сид — всегда один и тот же уровень. */
export function archeryLevel(seed: number): ArcheryLevel {
  const rng = seeded(seed >>> 0);
  const span = (min: number, max: number): number => min + rng() * (max - min);

  // Скорость одна на все три выстрела. Разная по выстрелам ломала бы наработанный
  // за первый выстрел ритм и вдвое расширяла вилку вероятностей: тот же игрок то
  // выигрывал бы, то нет, не понимая, чем эти попытки отличались.
  const sweep = span(SWEEP_MIN, SWEEP_MAX);

  let shots = fallbackShots();
  for (let t = 0; t < TRIES; t++) {
    const draft: ArcheryShot[] = [];
    for (let i = 0; i < ARCHERY_SHOTS; i++) {
      const ring = span(RING_MIN, RING_MAX);
      const bull = span(BULL_MIN, BULL_MAX);
      // Зона обязана лежать на дорожке целиком: вылезший за край край кольца — это
      // очки, которых игрок не может взять. Проверяется здесь, а не выводится из
      // вилок: вилки правят чаще, чем перечитывают это условие.
      const center = Math.min(Math.max(span(CENTER_MIN, CENTER_MAX), ring), 1 - ring);
      draft.push({ center, bull, ring });
    }
    const spread = draft.every((a, i) => draft.every((b, j) => i === j || Math.abs(a.center - b.center) >= MIN_GAP));
    if (spread) {
      shots = draft;
      break;
    }
  }

  return { sweep, shots };
}

/**
 * Где бегунок в этот момент. Треугольная волна: от 0 до 1 за `sweep`, обратно за
 * столько же, период — `2 * sweep`.
 *
 * Функция обязана оставаться чистой: её зовут и из кадра отрисовки, и из
 * обработчика тапа. Совпадение того, что игрок видит, с тем, что ему засчитали, —
 * вся честность этой игры, и держится она на том, что оба считают одно и то же
 * одним и тем же выражением, а не двумя похожими.
 */
export function markerAt(lv: ArcheryLevel, elapsedMs: number): number {
  const phase = elapsedMs / 1000 / lv.sweep;
  const u = ((phase % 2) + 2) % 2; // отрицательное время тоже должно давать точку на дорожке
  return u <= 1 ? u : 2 - u;
}

/** Очки за выстрел в точке `x`: яблочко, кольцо или мимо. */
export function scoreAt(shot: ArcheryShot, x: number): number {
  const d = Math.abs(x - shot.center);
  if (d <= shot.bull) return SCORE_BULL;
  if (d <= shot.ring) return SCORE_RING;
  return 0;
}

/** Взята ли попытка. */
export function archeryWon(score: number): boolean {
  return score >= ARCHERY_WIN;
}
