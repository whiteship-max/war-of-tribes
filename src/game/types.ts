/**
 * Изучение округи в Дозоре: сколько ступеней пройдено и идёт ли одиннадцатая.
 *
 * Хранятся два числа и отметка времени, а не ход работы: ступень доводится
 * **чистой функцией от времени начала** — наступил срок, значит изучено, и
 * офлайн даёт ровно то же, что непрерывная игра. Труда людей здесь нет вовсе:
 * разъезды идут сами, и снимать за них кого-то с поля не надо.
 */
export interface SurveyState {
  /** Сколько ступеней изучено. Ноль — деревня видит только свой круг. */
  done: number;
  /** Игровое время начала текущей ступени. 0 — изучение не идёт. */
  startedAt: number;
  /** Игровое время, когда ступень будет пройдена. */
  until: number;
}

/** Орудие на башне (`data/engines.ts`). */
export type EngineId = 'ballista' | 'catapult';

/**
 * Орудие башни. Ставится из отметки времени, как ступень изучения округи: здесь только
 * какое и когда встанет, а готово ли — считается при чтении (`sim/tower.readyEngine`).
 * Поле новое и необязательное по смыслу: партия, записанная до башни с орудиями,
 * приезжает умолчанием, и версию сохранения это не поднимает.
 */
export interface EngineState {
  /** Какое орудие стоит или ставится; null — башня без орудия. */
  id: EngineId | null;
  /** Игровое время, когда его поставят; до этой минуты башня молчит. */
  until: number;
}

/** Чем кончилась сегодняшняя попытка. 'none' — сегодня ещё не начинали. */
export type DailyResult = 'none' | 'lost' | 'won';

/**
 * Ежедневное задание. Попытка одна в календарные сутки: начал — попытка
 * потрачена, выиграл — забрал награду, проиграл или ушёл с экрана — сегодня уже
 * не переиграешь. Ни какая сегодня игра, ни что у неё внутри в состоянии не
 * хранится: и то, и другое выводится из номера дня (data/daily.ts) — ровно так
 * же, как прилавок рынка выводится из номера игрового дня. Поэтому у всех
 * игроков в один календарный день одно и то же задание, перезагрузка его не
 * тасует, а сервер потом получит то же самое из того же числа.
 *
 * Хода самой игры здесь нет и быть не может: состояние целиком уезжает на
 * сервер раз в `PUSH_MS` (`net/sync.ts`) и на диск раз в `AUTOSAVE_MS`, а `tick`
 * переписывает его каждые `TICK_MS` (оба — `store.ts`). Позиция мишени и путь
 * рыцаря живут в компоненте, наружу выходит только исход.
 */
export interface DailyState {
  /**
   * Календарные сутки, к которым относится запись: целых суток UTC от эпохи
   * (`dayIndex` в data/daily.ts). Не игровой день: тот идёт по минуте, и
   * «раз в 24 часа» им не измеришь.
   */
  day: number;
  /** Исход попытки за этот день. Другой день — запись просрочена, попытка снова есть. */
  result: DailyResult;
}

export interface ActiveEvent {
  defId: string;
  /** Момент появления (игровое время, сек). */
  at: number;
  /**
   * До какой минуты событие ждёт ответа — **настоящими часами** (`serverNow`,
   * мс), а не игровыми: почта державы живёт в ритме игрока, а игровой день
   * длится минуту (docs/realm.md, раздел 2.5). Ставит его `sim/mail.mailStep`
   * при первом взгляде после прихода. Поля нет — срока ещё не ставили: так
   * приезжает и событие из сохранения, сделанного до почты, и срок у него
   * начинается с минуты входа. У события со своим сроком (`EventDef.deadline`,
   * мятеж) поля не бывает вовсе.
   */
  until?: number;
}

