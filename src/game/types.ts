  war: string;
  /** Войско лагеря на последнем разборе: разница с новым, кроме павших в боях, — истощение фаз и выбитые башней. */
  army: Partial<Record<TroopId, number>>;
  /** Разобранные итоги: бои (`<война>.<n>`), падение (`fall:<война>`), конец (`end:<война>`) — не больше `SIEGE_SEEN_MAX`. */
  seen: string[];
