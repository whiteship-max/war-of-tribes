// Базовые типы состояния игры. Симуляция не зависит от рендера и UI.
import type { DecreeId, RationId, TaxId } from './data/policy';
import type { BattlePlanTemplate, Formation } from './battle/formation';
import type { UnitKind } from '@/battle';
import type { ProfileState } from '@/profile/types';

export type ResourceId = 'wood' | 'stone' | 'food' | 'hides' | 'bones' | 'copper' | 'iron';
export type Resources = Record<ResourceId, number>;

/**
 * Снаряжение. Счётчики того же рода, что и ресурсы, но живут отдельно:
 * вместимость склада на них не действует, и чужой набег их не уносит — см. data/equipment.ts.
 */
export type EquipmentId = 'spear' | 'bow' | 'axe' | 'shield' | 'sword' | 'armor';
export type Equipment = Record<EquipmentId, number>;

/**
 * Товар рынка: либо ресурс, либо предмет снаряжения. Ключи снаряжения носят
 * префикс, чтобы один словарь `s.market.bought` держал и то, и другое.
 */
export type GoodId = ResourceId | `eq:${EquipmentId}`;

/**
 * Войска. Боец — не житель с профессией, а единица в счётчике: нанятый уходит
 * из рабочих совсем. Роли «воин» в списке профессий поэтому больше нет.
 */
export type TroopId =
  | 'clubman'
  | 'spearman'
  | 'archer'
  | 'axeman'
  | 'swordsman'
  | 'shieldman'
  | 'rider'
  | 'legionary';
export type Army = Record<TroopId, number>;

export type JobId =
  | 'idle'
  | 'gatherer'
  | 'hunter'
  | 'woodcutter'
  | 'stonecutter'
  | 'miner'
  | 'farmer'
  | 'herder'
  | 'crafter'
  | 'smith'
  | 'priest';

export type BuildingTypeId =
  | 'campfire'
  | 'town_hall'
  | 'houses'
  | 'storage'
  | 'gathering'
  | 'sawmill'
  | 'quarry'
  | 'hunter_hut'
  | 'mine'
  | 'workshop'
  | 'farm'
  | 'pen'
  | 'church'
  | 'statue'
  | 'infirmary'
  | 'watch'
  | 'stable'
  | 'cache'
  | 'tavern'
  | 'palisade'
  | 'tower'
  | 'smithy'
  | 'barracks'
  | 'market';

/**
 * Герой племени — единственный поимённый человек в игре. Он не житель и не боец
 * из счётчика: его даёт Статуя, он ходит с одним походом за раз и усиливает один
 * выбранный род войск. Погибнув, он не пропадает совсем — возвращается через
 * время: имя у племени остаётся, а вместе с ним и вложенные в статую уровни.
 */
export interface Hero {
  /** Имя с прозвищем. Даётся один раз за партию и не меняется. */
  name: string;
  /** Род войск, который он ведёт. Меняется в Статуе за золото. */
  kind: UnitKind;
  /**
   * До какого игрового времени он лежит после гибели. Ноль — в строю.
   * Не «убит навсегда»: героя нельзя потерять, можно только остаться без него.
   */
  downUntil: number;
  /** Поход, с которым он ушёл. null — дома, на площади. */
  marchId: string | null;
}

/**
 * Покровитель племени: одноразовый выбор в церкви. Раньше это назывался тотем —
 * имя сменилось вместе со зданием, развилка осталась той же и по-прежнему
 * необратима (см. sim/actions.choosePatron).
 */
export type PatronId = 'wolf' | 'bear' | 'eagle';

export type Season = 'spring' | 'summer' | 'autumn' | 'winter';

export interface Building {
  id: number;
  type: BuildingTypeId;
  /** Текущий уровень, от единицы: все здания стоят с первого дня. */
  level: number;
  /** Накопленная работа текущего улучшения. */
  work: number;
  /** Работа до конца улучшения. 0 — улучшение не идёт. */
  workRequired: number;
}

/**
 * Заказ в кузнице. Очередь одна и идёт последовательно, сверху вниз — тем же
 * складом, что и набор в казармах.
 *
 * Ресурсы за весь заказ списаны при постановке, поэтому здесь их нет: заказ не
 * может встать посреди дела из-за пустого склада. Что при отмене возвращается,
 * а что нет, решает `cancelForge`.
 */
export interface ForgeOrder {
  id: number;
  item: EquipmentId;
  /** Сколько предметов заказано. */
  count: number;
  /** Сколько уже сковано и легло на склад. */
  done: number;
  /** Накопленная работа над текущим предметом. */
  work: number;
}

/** Заказ в казармах. Очередь одна и идёт последовательно, сверху вниз. */
export interface RecruitOrder {
  id: number;
  troop: TroopId;
  /** Сколько бойцов заказано. */
  count: number;
  /** Сколько уже обучено и ушло в армию. */
  done: number;
  /** Накопленная работа над текущим бойцом. */
  work: number;
/**
   * Сколько человек ушло на учения. Они уже не в племени: не добывают и не строят.
   * Отмена вернёт ровно столько же голов — поимённых жителей в игре нет.
   */
  people: number;
}

/**
 * Рынок. Ассортимент не хранится: он выводится из номера дня (см. data/market.ts),
 * поэтому перезагрузка не тасует прилавок заново. Хранить нужно только то, что
 * уже разобрали сегодня — на этом счётчике держатся и дневной лимит, и рост цены.
 */
export interface MarketState {
  /** Игровой день, на который составлен нынешний прилавок. */
  day: number;
  /** Сколько единиц каждого товара уже куплено за этот день. */
  bought: Partial<Record<GoodId, number>>;
}

/**
 * Караван за покупкой. Золото списано при заказе, груза на складе ещё нет:
 * телега выезжает из ворот и возвращается только к `arriveAt`.
 */
export interface Caravan {
  id: number;
  good: GoodId;
  count: number;
  /** Уплаченное золото — ровно столько вернётся при отмене. */
  gold: number;
  /** Игровое время выхода и возвращения, сек. */
  departAt: number;
  arriveAt: number;
}

/**
 * Изучение округи в Дозоре: сколько ступеней пройдено и идёт ли одиннадцатая.
 *
 * Хранятся два числа и отметка времени, а не ход работы: ступень доводится
 * **чистой функцией от времени начала** — наступил срок, значит изучено, и
 * офлайн даёт ровно то же, что непрерывная игра. Труда людей здесь нет вовсе:
 * разъезды идут сами, и снимать за них кого-то с поля не надо.
 */
export interface SurveyState {
  /** Сколько ступеней изучено. Ноль — деревня видит только свой круг. */
  done: number;
  /** Игровое время начала текущей ступени. 0 — изучение не идёт. */
  startedAt: number;
  /** Игровое время, когда ступень будет пройдена. */
  until: number;
}

/** Чем кончилась сегодняшняя попытка. 'none' — сегодня ещё не начинали. */
export type DailyResult = 'none' | 'lost' | 'won';

/**
 * Ежедневное задание. Попытка одна в календарные сутки: начал — попытка
 * потрачена, выиграл — забрал награду, проиграл или ушёл с экрана — сегодня уже
 * не переиграешь. Ни какая сегодня игра, ни что у неё внутри в состоянии не
 * хранится: и то, и другое выводится из номера дня (data/daily.ts) — ровно так
 * же, как прилавок рынка выводится из номера игрового дня. Поэтому у всех
 * игроков в один календарный день одно и то же задание, перезагрузка его не
 * тасует, а сервер потом получит то же самое из того же числа.
 *
 * Хода самой игры здесь нет и быть не может: состояние целиком уезжает на
 * сервер раз в минуту и на диск каждые пятнадцать секунд, а `tick` переписывает
 * его дважды в секунду. Позиция мишени и путь рыцаря живут в компоненте, наружу
 * выходит только исход.
 */
export interface DailyState {
  /**
   * Календарные сутки, к которым относится запись: целых суток UTC от эпохи
   * (`dayIndex` в data/daily.ts). Не игровой день: тот идёт по минуте, и
   * «раз в 24 часа» им не измеришь.
   */
  day: number;
  /** Исход попытки за этот день. Другой день — запись просрочена, попытка снова есть. */
  result: DailyResult;
}

export interface ActiveEvent {
  defId: string;
  /** Момент появления (игровое время, сек). */
  at: number;
}

export interface LogEntry {
  at: number; // игровое время
  text: string;
  kind: 'info' | 'good' | 'bad' | 'quest';
  /**
   * Ключ склейки повторов. Подряд идущие записи с одним ключом внутри игровых
   * суток сливаются в одну со счётчиком: сто двадцать строк «Кузница: готов
   * копьё» подряд — это вывод отладки, а не летопись.
   */
  group?: string;
  /** Сколько раз повторилось. Старые записи приходят без него — читать `n ?? 1`. */
  n?: number;
}

export interface Stats {
  hunts: number;
  battlesWon: number;
  battlesLost: number;
  /** Сколько человек прибавилось и убыло за партию — приростом, голодом, боем. */
  born: number;
  died: number;
  eventsResolved: number;
  /** Отправлено разведок и набегов — по ним считаются задания про карту. */
  scouted: number;
  raids: number;
  /** Замков, из которых привезли золото. */
  castles: number;
  /**
   * Сожжённых логов. Считается по отметке из мира, а не по добыче: логово,
   * в котором нечего было взять, сожжено ровно так же.
   */
  lairs: number;
  /** Покупок на рынке. */
  purchases: number;
  /** Выиграно ежедневных заданий. Проигранные не считаются — считать нечего. */
  dailyWins: number;
}

/**
 * Осада глазами племени. Ровно то, что нужно тику и панели, и ни поля больше:
 * само окно с его арифметикой живёт в мире (`world/siege.ts`), сюда приезжает
 * уже посчитанное.
 */
export interface SiegeState {
  /** Кто осадил — для панели и летописи. */
  byName: string;
  /** Игровое время, к которому кончится еда. До него осада идёт. */
  until: number;
  /** Гарнизон, по которому посчитаны часы голода. */
  garrison: number;
}

export interface GameState {
  version: number;
  /** Игровое время в секундах (1 игровой день = DAY_LENGTH сек). */
  time: number;
  resources: Resources;
  /** Снаряжение на складе: счётчики, не ограниченные вместимостью. */
  equipment: Equipment;
  /** Армия поселения — счётчики бойцов по видам. */
  army: Army;
  /** Очередь найма в казармах: первый заказ обучается, остальные ждут. */
  recruits: RecruitOrder[];
  /** Очередь заказов кузницы: первый куётся, остальные ждут. Пусто — она стоит. */
  forge: ForgeOrder[];
  /** Изучение округи в Дозоре: ступени и текущая работа. См. SurveyState. */
  survey: SurveyState;
  /** Указ вождя: действует, пока выбран. */
  decree: DecreeId;
  /** Рацион племени. */
  ration: RationId;
  /** Уровень налога. */
  tax: TaxId;
  /**
   * Казна племени. Не ресурс: вместимость склада на золото не действует,
   * и чужой набег его не уносит — казну прячут, а не сваливают в амбар.
   */
  gold: number;
  /**
   * Алмазы — премиальная валюта. Не ресурс и не золото: склад её не ограничивает,
   * набег не уносит, купить за неё нельзя ничего, кроме времени (см. sim/gems.ts).
   * Начисляет её ровно одно место — `creditGems`, и оно ждёт сервера.
   */
  gems: number;
  /** Состояние рынка: на какой день собран прилавок и что с него уже взяли. */
  market: MarketState;
  /** Караваны в пути: их груз ещё не на складе. */
  caravans: Caravan[];
  /** Ежедневное задание: за какие календарные сутки запись и чем кончилась попытка. */
  daily: DailyState;
  /**
   * Жителей в посёлке. Поимённых жителей с возрастом, полом и характером в игре
   * нет: население — число. Бойцы и новобранцы сюда не входят, они живут в
   * счётчиках `army` и `recruits` (см. derived.population).
   */
  pop: number;
  /**
   * Сколько человек работает в каждом здании: ключ — id постройки. Личного навыка
   * у жителя нет, работники одинаковы, поэтому назначение — это число, а не список.
   */
  workers: Record<number, number>;
  /**
   * Сколько человек занято «вольным сбором» — работой по профессии без профильного
   * здания, вполсилы. Остальные (`pop` минус здания минус вольный сбор) свободны.
   */
  freeJobs: Partial<Record<JobId, number>>;
  buildings: Building[];
  completedQuests: string[];
  activeEvent: ActiveEvent | null;
  nextEventAt: number;
  morale: number; // 0..100
  prestige: number;
  patron: PatronId | null;
  /** Герой племени: имя, род войск и состояние. См. Hero. */
  hero: Hero;
  starvation: number; // накопленное время голода, сек
  freezing: number; // накопленное время зимы без дров, сек
  /** Год, за который уже показали предупреждение о зиме (0 — ещё не показывали). */
  winterWarnedYear: number;
  /** Предупреждение «Скоро зима» ждёт показа. */
  winterWarning: boolean;
  /**
   * Накопленный прирост населения, −1..1. Дошёл до единицы — в посёлке одним
   * человеком больше, упал до минус единицы — одним меньше: при низкой морали
   * племя разбегается.
   */
  growth: number;
  /** Население на начало текущего игрового дня: по нему летопись считает дневной прирост. */
  popDay: number;
  /**
   * Осада деревни: пока она идёт, приток ресурсов срезан (см. derived.siegeYield).
   * null — под стенами никого.
   *
   * Своей жизни у этого поля нет: его кладёт мир каждым пульсом через мост
   * (`world/bridge.syncSiege`), а симуляция только читает. Причина та же, что у
   * `warriorsAway`: осада — событие карты, и второй правды о ней между миром и
   * племенем быть не должно.
   *
   * Хранится оно в **игровом** времени, а не в мировом, и это не мелочь: тик и
   * офлайн-догон считают по `s.time`, поэтому осада, кончившаяся, пока игрока
   * не было, перестаёт резать выработку ровно там, где кончилась, — а не по
   * первому пульсу мира после возвращения.
   */
  siege: SiegeState | null;
  /** Бойцы, ушедшие в поход: деревню они не защищают (см. derived.defense). */
  warriorsAway: number;
  /** Свободные жители, ушедшие разведчиками: они не строят. */
  scoutsAway: number;
  /**
   * Как племя встречает набег: расстановка обороны деревни. null — обороняемся
   * тем, что вышло само (быстрая раскладка по сиду набега).
   */
  defenseFormation: Formation | null;
  /** Сохранённые схемы похода: состав, расстановка, план, приказы, резерв. */
  battlePlans: BattlePlanTemplate[];
  /** Что игрок предпочитает после боя: смотреть журнал или сразу итог. */
  battleWatch: boolean;
  /**
   * Пир в трактире: до какого игрового времени он греет племя и когда его
   * задавали в прошлый раз. Два числа, а не флаг: по первому считается прибавка
   * к морали, по второму — откат (см. derived.feastInfo).
   */
  feastUntil: number;
  feastAt: number;
  /**
   * Профиль игрока: имя, лицо, итоги партии и визитка. Лежит отдельным куском,
   * потому что из него потом соберётся карточка для чужих глаз на карте мира —
   * там не будет ни зданий, ни армии, только готовые значения (см. profile/types).
   */
  profile: ProfileState;
  /** Номер текущего шага обучения (см. data/tutorial.ts). */
  tutorialStep: number;
  /** Обучение пройдено или пропущено. */
  tutorialDone: boolean;
  log: LogEntry[];
  stats: Stats;
  nextId: number;
  lastSaved: number; // wall-clock ms
}
