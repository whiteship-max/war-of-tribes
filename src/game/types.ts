/**
 * Герой племени — единственный поимённый человек в игре. Он не житель и не боец
 * из счётчика: его даёт Статуя, он ходит с одним походом за раз и усиливает один
 * выбранный род войск. Погибнув, он не пропадает совсем — возвращается через
 * время: имя у племени остаётся, а вместе с ним и вложенные в статую уровни.
 */
/**
 * Счёт дел человека на месте агента — то, из чего выводятся черты
 * (`data/traits.traitsOf`). Пишет его та же дверь, что опыт (`sim/agents.recordDeed`),
 * и только засчитанными делами. Начинается с нуля у каждого нового человека и у
 * всех, кто стоял на месте до черт: задним числом побед от поражений не отличить.
 */
export interface Tally {
  /** Удачных дел. */
  ok: number;
  /** Неудачных дел: проигранный бой, поимка часовыми, провал лазутчика. */
  fail: number;
  /** Сколько бойцов дружины пало в его боях. */
  bled: number;
  /** Сколько логов сожжено его боями. */
  burned: number;
}

/**
 * Три ветви технологий — три вида очков и три навыка правителя (docs/dynasty.md).
 * Тип живёт здесь, а не в `data/realm.ts`, по той же причине, что `TroopId` и
 * `EquipmentId`: его читают и состояние, и данные, и цикла между ними быть не должно.
 */
export type RealmBranch = 'admin' | 'diplo' | 'war';

/** Три навыка правителя, кружками той же лестницы, что у агента: 1…`MAX_RULER_SKILL`. */
export type RulerSkills = Record<RealmBranch, number>;

/**
 * Человек дома правителя. Наследник — тот же тип: у него уже есть имя и навыки, и
 * игрок видит их заранее, как в EU4. **Возраста у наследника нет нарочно** — он
 * начинается вступлением: новый правитель приходит в `AGENT_AGE0` лет, тем же
 * правилом, каким приходит нанятый агент. Второго числа возраста заводить не надо.
 */
export interface HousePerson {
  /**
   * Номер человека в доме, с нуля. Из него выводятся и навыки (`sim/dynasty.skillsOf`), и
   * начало поиска имени: одно число вместо двух счётчиков.
   */
  n: number;
  /** Имя. null — вера деревни ещё не названа миром, имя будет первым пульсом. */
  name: string | null;
  skills: RulerSkills;
}

/** Правитель — тот же человек дома, но с началом правления: от него идёт возраст. */
export interface Ruler extends HousePerson {
  /** Игровое время вступления: от него и `age0` выводится возраст (`sim/dynasty.rulerAge`). */
  bornAt: number;
  /** Сколько лет было в минуту вступления. */
  age0: number;
}

/**
 * Держава: правитель, наследник, очки трёх видов и изученные уровни ветвей.
 *
 * **Очки не тикают.** В партии лежит пара «сколько было и когда» (`points`, `pointsAt`),
 * а нынешнее число выводится при чтении одной дверью — `sim/points.pointsOf`. Накопителя
 * нет, догон офлайна очки прибавляет сам тем, что двигает `s.time`.
 */
export interface RealmState {
  ruler: Ruler;
  /** Наследник. Дом всегда выставляет преемника: междуцарствия нет — «тупика нет». */
  heir: HousePerson;
  /** Отложенные очки каждого вида: сколько было на минуту `pointsAt`. */
  points: RulerSkills;
  /** Игровое время, на которое отложены очки. Пишут её только двери `sim/points`. */
  pointsAt: number;
  /**
   * Изученные уровни ветвей. Первый уровень — то состояние, в котором партия
   * начинается, поэтому единица, а не ноль. Смерть правителя их не трогает — это и
   * есть решение владельца «смерть отнимает только навыки».
   */
  tech: RulerSkills;
  /** Сколько человек дом уже дал: шаг по перестановке имён (`data/names.houseName`). */
  born: number;
}

/**
 * Место, чью родословную ведёт книга: четыре места агентов и дом правителя. Книга одна
 * на всех (`GameState.lineage`), и пишет её одна дверь — `sim/agents.vacate` у агентов,
 * `sim/dynasty.succeed` у дома.
 */
export type LineagePlace = FigureId | 'ruler';

/**
 * Ушедший с места: погиб или дослужил до покоя. Запись делается один раз, в ту
 * минуту, когда место освободилось (`sim/agents.vacate`), и больше не меняется.
 */
export interface LineageEntry {
  name: string;
  /** До какого уровня дошёл. У правителя уровня нет — у него навыки, см. `skills`. */
  level: number;
  /** Сколько дел засчитано. */
  deeds: number;
  /** С какого года служил. */
  from: number;
  /** До какого года служил. */
  to: number;
  end: 'fell' | 'rest';
  /** Чем прослыл к концу службы. */
  traits: TraitId[];
  /** Три навыка — только у записи правителя: у него не уровень, а три числа. */
  skills?: RulerSkills;
}

/**
 * Что агент карты накопил за партию. Опыт, счёт дел и места под вещи — и ничего
 * выводимого: уровня, кружков, черт и действия навыка здесь нет.
 */
export interface AgentProgress {
  /**
   * Опыт **этого человека**. Не убывает никогда: гибель не отнимает часть пути, а
   * забирает человека целиком, и новый приходит с нуля.
   */
  xp: number;
  /**
   * Мировое время последнего засчитанного дела, мс. null — дел ещё не было.
   * По нему дело, пришедшее раньше `DEED_GAP`, опыта не даёт.
   */
  deedAt: number | null;
  /**
   * Места под вещи: **только имя** предмета или пусто. Что предмет даёт, знает
   * таблица `data/items.ITEMS`, а есть ли он у игрока — `net/owned.ts`.
   */
  slots: (ItemId | null)[];
  /**
   * Какой по счёту человек стоит на этом месте: 0 — тот, с кем партия началась,
   * дальше по одному на найм. Нужен не для показа, а для защиты: весть о гибели
   * приезжает из мира поздно, и убить она обязана того, кто погиб, а не того, кого
   * наняли после (`HomeEffect.fell.person`).
   */
  person: number;
  /**
   * Имя с прозвищем, очищенное `contract.cityName`. null — имени ещё неоткуда
   * взять: набор выбирает вера, а её называет мир первым пульсом.
   */
  name: string | null;
  /** Игровое время прихода (`s.time`): от него считается возраст. */
  bornAt: number;
  /** Сколько лет было в минуту прихода. */
  age0: number;
  /** Место пустует: человек погиб или ушёл на покой, нового не наняли. */
  vacant: boolean;
  /**
   * Идёт найм: когда придёт новый (игровое время) и как его зовут — имя известно
   * сразу, оно выводится из сида партии и номера найма. null — найма нет.
   */
  hiring: { until: number; name: string | null; age0: number } | null;
  /** Счёт дел этого человека: из него выводятся черты. */
  tally: Tally;
}

/**
 * Вера деревни. Достаётся вместе с землёй — по клетке, на которой реестр
 * поставил замок (`world/faith.faithAt`), — а не выбирается из меню: в 1200
 * году вера у людей была та же, что у соседей и у отцов. Меняется она ровно
 * одним способом и ровно в одну сторону: крещением язычника (`sim/faith.baptize`).
 *
 * Тип живёт здесь, а не в мире, потому что хранит его сохранение племени; мир
 * читает его отсюда — так же, как `world/gen.ts` читает `@/game/sim/random`.
 */
export type FaithId = 'catholic' | 'orthodox' | 'islam' | 'pagan';

/**
 * Уклад храма: насколько строго держат обычай. Тот же рычаг, что рацион и налог
 * в ратуше, и с той же ценой, написанной на кнопке, — он не добавляет ничего
 * своего, а усиливает или гасит наклон самой веры (`data/faiths.tiltAt`).
 */
export type ObservanceId = 'strict' | 'even' | 'worldly';

/** Реликвия: по одной на веру, поэтому имя выводится из веры (`data/faiths`). */
export type RelicId = FaithId;

/**
 * Всё, что деревня знает о своей вере. Один кусок состояния, а не пять полей
 * вразброс: набожность считается из них разом и только при чтении
 * (`sim/faith.pietyBreakdown`), тика у неё нет.
 */
export interface FaithState {
  /**
   * Вера деревни. null — мир ещё не назвал клетку замка: на первом же пульсе
   * мост её проставит (`world/bridge.syncFaith`). Пустого выбора у игрока при
   * этом не возникает — до ответа мира панель храма честно говорит, что
   * грамоты из округи ещё не пришли.
   */
  id: FaithId | null;
  observance: ObservanceId;
  /**
   * Доля чужой веры вокруг деревни, 0..1. Приезжает из мира тем же пульсом:
   * племя про координаты не знает, а мир — про приход.
   */
  pressure: number;
  /** До какого игрового времени держится обряд праздника. */
  riteUntil: number;
  /** Когда обряд справляли: по нему считается «раз в сезон». */
  riteAt: number;
  /**
   * Надлом: чего стоили навязанные решения — отказ Риму, крещение, уступка
   * раскольникам. Убывает сам со временем от `strainAt`, поэтому в состоянии
   * два числа, а не медленно сползающее третье.
   */
  strain: number;
  strainAt: number;
  /** Реликвия прихода. null — нет; теряется при разорении (`sim/expedition`). */
  relic: RelicId | null;
  /** Язычник, принявший крещение. Нужно словам, а не числам: путь был свой. */
  converted: boolean;
}

