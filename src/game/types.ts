/**
 * Осада глазами племени. Ровно то, что нужно тику и набожности, и ни поля больше:
 * само окно с его арифметикой живёт в мире (`world/siege.ts`), сюда приезжает
 * уже посчитанное.
 *
 * У старых сохранений здесь лежит ещё `garrison` — гарнизон, по которому мир
 * посчитал голод. Его не читал никто: окно осады показывает гарнизон из мира.
 */
export interface SiegeState {
  /** Кто осадил — для набожности (`derived.pietyBreakdown`). */
  byName: string;
  /**
   * Игровое время, к которому кончится еда, — последнее слово мира, переведённое
   * в секунды партии. Читает его **только офлайн-догон** (`sim/tick`): пока игры
   * не было, спросить мир некому, и осада снимается по этой отметке. При игроке
   * осаду снимает мир — пульсом, убирая поле целиком (`bridge.syncSiege`).
   */
  until: number;
}

/**
 * Содержание войска. Жалованья и еды здесь нет — они считаются при чтении из армии,
 * налога и склада (`derived.upkeepInfo`). Лежит только то, что вывести нельзя:
 * сколько не доплатили, как долго войско терпит и какая доля бойца уже «на выходе».
 */
export interface PayState {
  /** Долг жалованья, золотом. Уносят его те, кто уходит; гасит — казна. */
  debt: number;
  /**
   * Сколько секунд **живой игры** войску не платят или его нечем кормить. Дошло до
   * терпения Статуи — начинается уход. Без игрока не растёт: долг копится, уход ждёт.
   */
  late: number;
  /**
   * С какой игровой секунды платят жалованье. У новой партии — ноль; у партии,
   * начатой до содержания войска, — минута входа плюс отсрочка (ступень 13 → 14).
   */
  from: number;
  /** Дробный остаток ухода по видам: равная доля каждого вида копится до целого бойца. */
  gone: Partial<Record<TroopId, number>>;
  /**
   * Тот же остаток у раненых и у новобранцев на учениях: они едят солдатский паёк и при голоде
   * уходят той же дверью (`sim/upkeep`). Необязательные — партия, записанная до лазарета,
   * приезжает без них, и остаток начинается с нуля.
   */
  hurt?: Partial<Record<TroopId, number>>;
  drafts?: Partial<Record<TroopId, number>>;
}

/**
 * Раненые одного боя (docs/infirmary.md). Встают в строй того же вида со снаряжением: боец,
 * его ковка и учения не потеряны. Пишет их одна дверь — `sim/infirmary.ts`.
 */
export interface WoundGroup {
  troops: Partial<Record<TroopId, number>>;
  /**
   * Игровая секунда, когда встанут в строй. null — лежат при полководце в поле: срок и место в
   * лазарете у них начинаются, когда дружина вернулась к своим воротам.
   */
  until: number | null;
}

export interface GameState {
  version: number;
  /** Игровое время в секундах (1 игровой день = DAY_LENGTH сек). */
  time: number;
  resources: Resources;
  /** Снаряжение на складе: счётчики, не ограниченные вместимостью. */
  equipment: Equipment;
  /** Армия поселения — счётчики бойцов по видам. */
  army: Army;
  /** Очередь найма в казармах: первый заказ обучается, остальные ждут. */
  recruits: RecruitOrder[];
  /** Очередь заказов кузницы: первый куётся, остальные ждут. Пусто — она стоит. */
  forge: ForgeOrder[];
  /** Изучение округи в Дозоре: ступени и текущая работа. См. SurveyState. */
  survey: SurveyState;
  /** Орудие на башне: какое и когда встанет. См. EngineState. */
  engine: EngineState;
  /** Указ вождя: действует, пока выбран. */
  decree: DecreeId;
  /** Рацион племени. */
  ration: RationId;
  /** Уровень налога. */
  tax: TaxId;
  /**
   * Казна племени. Не ресурс: вместимость склада на золото не действует. Взявший
   * город уносит её тем же правилом, что склад, — до тайника и сколько поднимет
   * (`world/spoils.fate`).
   */
  gold: number;
  /**
   * Алмазы — премиальная валюта. Не ресурс и не золото: склад её не ограничивает,
   * набег не уносит, купить за неё нельзя ничего, кроме времени (см. sim/gems.ts).
   * Начисляет её ровно одно место — `creditGems`, и оно ждёт сервера.
   */
  gems: number;
  /** Состояние рынка: на какой день собран прилавок и что с него уже взяли. */
  market: MarketState;
  /** Караваны в пути: их груз ещё не на складе. */
  caravans: Caravan[];
  /** Ежедневное задание: за какие календарные сутки запись и чем кончилась попытка. */
  daily: DailyState;
  /**
   * Жителей в посёлке. Поимённых жителей с возрастом, полом и характером в игре
   * нет: население — число. Бойцы и новобранцы сюда не входят, они живут в
   * счётчиках `army` и `recruits` (см. derived.population).
   */
  pop: number;
  /**
   * Сколько человек работает в каждом здании: ключ — id постройки. Личного навыка
   * у жителя нет, работники одинаковы, поэтому назначение — это число, а не список.
   */
  workers: Record<number, number>;
  /**
   * Сколько человек занято «вольным сбором» — работой по профессии без профильного
   * здания, вполсилы. Остальные (`pop` минус здания минус вольный сбор) свободны.
   */
  freeJobs: Partial<Record<JobId, number>>;
  /**
   * Невольников в посёлке. Не жители: в `pop` они не входят, налога не платят,
   * жилья не занимают, в оборону не встают и не растут приростом — их покупают
   * на рынке и приводят из павших городов. Едят наравне со всеми
   * (`derived.townFoodPerDay`), а держат их стража и спокойные горожане
   * (`derived.orderBreakdown`).
   *
   * Устроены ровно как жители: число, а не список, и назначение — тоже число.
   */
  bonded: number;
  /**
   * Сколько невольников стоит в каждом здании: ключ — id постройки, как у
   * `workers`. Места у них общие с вольными (`buildingSlots`), таблица выработки
   * та же (`JOBS`), множитель тот же (`workerMultiplier`) — отличается только
   * доля, которую невольник даёт против вольного (`BONDED_OUTPUT`). Второй системы
   * занятости здесь нет: это второе число на тех же местах.
   *
   * Кто не стоит ни в одном здании, тот на стройке — как свободные руки.
   */
  bondedWork: Record<number, number>;
  /**
   * Ропот: сколько секунд **при игроке** порядок стоит ниже порога
   * (`ORDER_UNREST`). Дошёл до `MUTINY_FUSE` — поднимается мятеж. Растёт только
   * в игре, а не в офлайн-догоне: мятеж, как и набег, не случается, пока игрока
   * нет (`sim/mutiny.unrestTick`). Порог отпустило — тает вдвое быстрее, как голод.
   *
   * Самого порядка в состоянии нет: он считается при чтении. Здесь лежит только
   * срок, который ему дан, — тот же род поля, что `starvation`.
   */
  unrest: number;
  /** Содержание войска: долг жалованья, терпение и дробный остаток ухода (`sim/upkeep`). */
  pay: PayState;
  /**
   * Раненые: в лазарете и при полководце в поле (`sim/infirmary`). В войске они не числятся —
   * не бьются, не стоят в обороне и жалованья не получают, — но едят солдатский паёк. Поле
   * необязательно для старой партии: `deserialize` кладёт пустой список, версия не растёт.
   */
  wounded: WoundGroup[];
  buildings: Building[];
  completedQuests: string[];
  /**
   * События посёлка, ждущие ответа в почте державы (`sim/mail`). Их несколько: стол на
   * `LETTER_DECISIONS` обычных событий плюс своя ячейка мятежу — тот же стол, что у писем
   * мира, и лишнее сгоняется тем же правилом (`world/letters.kickFrom`). До пятнадцатой
   * версии здесь было одно поле `activeEvent`, и новое событие ждало, пока ответят на прежнее.
   */
  inbox: ActiveEvent[];
  nextEventAt: number;
  morale: number; // 0..100
  prestige: number;
  /** Вера деревни и всё, что вокруг неё. См. FaithState. */
  faith: FaithState;
  /** Герой в настроенном бою: какой род ведёт и с каким походом ушёл. Имя — у полководца. */
  hero: Hero;
  /**
   * Четыре места агентов карты: кто на них стоит — имя, возраст, опыт и вещи, — или
   * что место пустует. Живёт в партии, а не в сохранении мира: мир уже дважды
   * собирался заново при смене своей версии и стёр бы недели опыта одной правкой
   * формата. Уровень, кружки и возраст здесь не лежат — они выводятся при чтении
   * (`data/agents.levelOf`, `sim/agents.ageOf`).
   */
  agents: Record<FigureId, AgentProgress>;
  /**
   * Родословная мест: кто стоял на месте до нынешнего, новые первыми. Помнят всех
   * погибших и ушедших на покой не ниже `LINEAGE_LEVEL`; потолок у каждого места
   * свой (`data/traits.LINEAGE_KEEP`) — у Статуи он есть, у остальных ноль.
   */
  lineage: Partial<Record<FigureId, LineageEntry[]>>;
  /**
   * Сид партии — корень её случайности: кость событий (`sim/random.roll`) и имена
   * агентов. Заводится один раз, с новой партией (`sim/random.freshSeed`); у партии,
   * записанной до него, выводится ступенью сохранения из неё самой.
   */
  seed: number;
  /** Сколько костей партии уже брошено: номер следующего числа её потока. */
  rolls: number;
  /** Сколько имён агентов уже выдано: номер следующего в перестановке (`data/names`). */
  hires: number;
  starvation: number; // накопленное время голода, сек
  freezing: number; // накопленное время зимы без дров, сек
  /** Год, за который уже показали предупреждение о зиме (0 — ещё не показывали). */
  winterWarnedYear: number;
  /** Предупреждение «Скоро зима» ждёт показа. */
  winterWarning: boolean;
  /**
   * Накопленный прирост населения, −1..1. Дошёл до единицы — в посёлке одним
   * человеком больше, упал до минус единицы — одним меньше: при низкой морали
   * племя разбегается.
   */
  growth: number;
  /** Население на начало текущего игрового дня: по нему летопись считает дневной прирост. */
  popDay: number;
  /**
   * Осада деревни: пока она идёт, приток ресурсов срезан (см. derived.siegeYield).
   * null — под стенами никого.
   *
   * Своей жизни у этого поля нет: его кладёт и снимает мир каждым пульсом через
   * мост (`world/bridge.syncSiege`), а симуляция только читает. Причина та же, что
   * у `away`: осада — событие карты, и второй правды о ней между миром и
   * племенем быть не должно. Поэтому при игроке «идёт ли осада» — это «лежит ли
   * поле»: срок не сверяется, осада кончается ровно тем пульсом, которым её снял мир.
   *
   * Одно исключение, и оно настоящее: офлайн-догон идёт раньше первого пульса, и
   * мира в нём нет. Там осада снимается по отметке `until` — сроку голода,
   * переведённому в игровое время, — иначе осада, кончившаяся вскоре после ухода,
   * резала бы выработку весь догон (до `MAX_OFFLINE_SECONDS`).
   */
  siege: SiegeState | null;
  /**
   * Бойцы не в обороне, по видам: отряды в пути и дружина полководца в сборе, в
   * пути и в поле. Дружина, собранная у своих ворот, сюда не входит — она в обороне
   * (см. derived.defense и world/muster). Кладёт мир каждым пульсом, тем же правилом,
   * каким считает гарнизон; отряд, ушедший числом без состава, здесь уже снят со
   * слабых. Дома — всё войско минус это (`derived.homeTroops`), и мощь дома — сумма
   * мощи тех, кто дома: латник в поле дубинщиком дома не становится.
   *
   * Прежде здесь лежало число (`warriorsAway`), и мощь дома выходила средней.
   * Сохранение, записанное тогда, приезжает с пустым составом — до первого пульса
   * мира всё войско считается дома; лишнее числовое поле в нём никто не читает.
   */
  away: TroopStack;
  /** Свободные жители, ушедшие разведчиками: они не строят. */
  scoutsAway: number;
  /**
   * Как племя встречает набег: расстановка обороны деревни. null — обороняемся
   * тем, что вышло само (быстрая раскладка по сиду набега).
   */
  defenseFormation: Formation | null;
  /** Сохранённые схемы похода: состав, расстановка, план, приказы, резерв. */
  battlePlans: BattlePlanTemplate[];
  /** Что игрок предпочитает после боя: смотреть журнал или сразу итог. */
  battleWatch: boolean;
  /**
   * Пир в трактире: до какого игрового времени он греет племя и когда его
   * задавали в прошлый раз. Два числа, а не флаг: по первому считается прибавка
   * к морали, по второму — откат (см. derived.feastInfo).
   */
  feastUntil: number;
  feastAt: number;
  /**
   * Профиль игрока: имя, лицо, итоги партии и визитка. Лежит отдельным куском,
   * потому что из него потом соберётся карточка для чужих глаз на карте мира —
   * там не будет ни зданий, ни армии, только готовые значения (см. profile/types).
   */
  profile: ProfileState;
  /** Номер текущего шага обучения (см. data/tutorial.ts). */
  tutorialStep: number;
  /** Обучение пройдено или пропущено. */
  tutorialDone: boolean;
  /**
   * В этой партии применяли коды (`src/cheats.ts`).
   *
   * Метка навсегда и снимается только новой партией. Нужна она не игроку — он
   * сам это и нажал, — а нам: накрученную партию через месяц примут за
   * настоящую и сделают из неё вывод о балансе. Поле со значением по умолчанию
   * версию сохранения не поднимает: старая партия приезжает непомеченной, и это
   * правда — кодов в ней не было.
   */
  cheated: boolean;
  log: LogEntry[];
  stats: Stats;
  nextId: number;
  lastSaved: number; // wall-clock ms
}
