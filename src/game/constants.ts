import type { ResourceId, Resources } from './types';

/** Длина игрового дня в секундах реального времени. */
export const DAY_LENGTH = 60;
/** Максимум офлайн-прогресса при возвращении в игру. */
export const MAX_OFFLINE_SECONDS = 4 * 3600;

// ---------- Население ----------
//
// Поимённых жителей в игре нет. Население — число, и растёт оно не рождениями
// конкретных людей, а приростом: сколько прибавится за игровой день, решают
// свободное жильё, запас еды и мораль. Игра идёт к боям в сотни бойцов, поэтому
// посёлок на потолке уровней держит порядка семисот человек, а не полусотни.

/** Доля населения, прибавляющаяся за игровой день при полном довольствии. */
export const POP_GROWTH_PER_DAY = 0.035;
/**
 * База прироста: маленькое племя растёт не только процентом от себя, иначе
 * первые дни партии оно топталось бы на месте.
 */
export const POP_GROWTH_BASE = 10;
/**
 * Мораль и прирост. Ниже `MORALE_GROWTH_ZERO` племя не растёт, а разбегается:
 * прирост уходит в минус ровно так же плавно, как рос. Выше `MORALE_GROWTH_FULL`
 * прирост идёт на полной скорости. Это и делает рацион, указ и налог видимыми:
 * мораль двигает не только выработку, но и то, сколько народу в посёлке.
 */
export const MORALE_GROWTH_ZERO = 45;
export const MORALE_GROWTH_FULL = 85;
/**
 * Сколько мест под крышей должно оставаться свободными для полной скорости роста.
 * Ближе к потолку прирост тормозится, но не обнуляется досрочно — иначе посёлок
 * навсегда останавливался бы, немного не дойдя до вместимости жилья.
 */
export const GROWTH_ROOM = 40;
/** Дней запаса еды, с которых прирост идёт на полной скорости. */
export const GROWTH_FOOD_DAYS = 3;

/** Через сколько секунд голода (или зимы без дров) племя теряет людей. */
export const STARVATION_DEATH = 2 * DAY_LENGTH;
/**
 * Какую долю населения забирает один удар голода или холода. Доля, а не
 * фиксированное число: в посёлке на семьсот душ смерть одного человека
 * не была бы даже заметна.
 */
export const FAMINE_TOLL = 0.03;

export const BASE_STORAGE_CAP = 1200;
export const BASE_HOUSING = 10;
export const EVENT_INTERVAL_MIN = 70;
export const EVENT_INTERVAL_MAX = 140;

/**
 * Потолок уровня здания. Каждый тип строится ровно один раз, поэтому уровни —
 * единственная линия развития постройки, и их должно хватать на всю партию.
 */
export const MAX_BUILDING_LEVEL = 10;
/** Прибавка к выработке каждого рабочего за уровень здания. */
export const LEVEL_OUTPUT_STEP = 0.1;
/**
 * Рабочих мест, которые даёт здание за каждый свой уровень. Личного навыка у
 * жителя больше нет — его роль целиком взял на себя уровень здания: он и добавляет
 * места, и поднимает выработку каждому рабочему. Отдельные здания правят это
 * число полем `slotsPerLevel`: в кузнице у горна семьдесят человек не встанут.
 */
export const SLOTS_PER_LEVEL = 12;
/**
 * Во сколько раз дорожает улучшение с каждым уровнем. На десяти уровнях
 * 1.4 даёт ×20 к цене последнего шага — дорого, но в пределах склада.
 */
export const UPGRADE_GROWTH = 1.4;
/**
 * Труд одного свободного жителя на стройке в секунду. Больше единицы: племя
 * позднего средневековья строит с инструментом, а не голыми руками.
 */
export const BUILDER_RATE = 1.2;
/**
 * Труд ремесленника в мастерской на улучшениях, в секунду на единицу его
 * множителя. Мастер стоит больше строителя с площади — на этом и держится
 * мастерская.
 */
export const CRAFTER_BUILD = 1.5;
/**
 * Насколько ускоряет стройку каждый уровень ратуши сверх первого. Ратуша — то
 * место, откуда ведут все стройки, и её уровень обязан значить что-то, кроме
 * морали и жилья: на потолке (10 уровень) посёлок строит в 1.72 раза быстрее.
 * Это множитель ко всей скорости стройки, а не отдельный источник труда:
 * ратуша не строит сама, она распоряжается.
 */
export const TOWN_HALL_BUILD_STEP = 0.08;
/** Оборона посёлка без единого бойца и здания: щиты и клинки по домам. */
export const BASE_DEFENSE = 20;
/** Сколько обороны добавляет один житель: отбиваться может каждый, но слабо. */
export const VILLAGER_DEFENSE = 0.25;
/**
 * Мораль устоявшегося племени при прочих равных: тёплая одежда, вождь и обычаи
 * у него уже есть, поэтому база выше половины шкалы.
 */
export const MORALE_BASE = 72;
/**
 * Во что мораль обходится выработке: при нуле работают вполсилы с небольшим,
 * при сотне — с прибавкой. Числа вынесены сюда, потому что их показывает
 * справочный экран счастья, а расходиться с симуляцией ему нельзя.
 */
export const MORALE_OUTPUT_LOW = 0.7;
export const MORALE_OUTPUT_SPAN = 0.45;
/** Разовый сдвиг морали за отбитый и за проигранный набег на посёлок. */
export const BATTLE_MORALE_WIN = 5;
export const BATTLE_MORALE_LOSS = 12;
/**
 * Теснота: во что обходится морали набитый сверх крыш посёлок. Считается долей от
 * вместимости жилья, а не головами — иначе один лишний человек в посёлке на семь
 * сотен стоил бы столько же, сколько сотня лишних в посёлке на тридцать.
 * `CROWDING_PENALTY` — просадка при вдвое переполненном посёлке, `CROWDING_MAX` — потолок.
 */
export const CROWDING_PENALTY = 45;
export const CROWDING_MAX = 30;

/** Потолок прибавки к морали от шаманов: их на потолке уровней два десятка. */
export const SHAMAN_MORALE_CAP = 12;
/** Прибавка к морали за одного шамана, пока не упёрлись в потолок. */
export const SHAMAN_MORALE = 0.4;
/**
 * Сколько уровней приходится на одну визуальную ступень здания: 1–3, 4–7, 8–10.
 * Ступеней три, и каждая заметно крупнее предыдущей — см. render/buildings.ts.
 */
export const VISUAL_TIERS: [number, number] = [4, 8];
/**
 * «Вольный сбор»: работа по профессии без профильного здания. Вполсилы, но доступна
 * всегда — новая партия не должна начинаться с нулевым доходом.
 */
export const FREE_RANGE_MULT = 0.5;

/**
 * Работа кузнеца в секунду при множителе 1. Предметы стоят сотни очков
 * (см. data/equipment.ts): у горна помещается немного народу, зато уровень
 * кузницы поднимает и число мест, и выработку каждого.
 */
export const SMITH_WORK = 1;
/**
 * Работа казарм в секунду на первом уровне. Растёт быстрее выработки зданий —
 * умножается ещё и на уровень: дружина в сотни бойцов иначе набиралась бы часами.
 */
export const RECRUIT_WORK = 1;
/**
 * Сколько ест боец против жителя. Он не добывает и не строит, но кормится
 * из того же котла — армия должна стоить не только людей, но и еды.
 */
export const SOLDIER_FOOD = 1.2;

/**
 * Алмазы новой партии. Запас тестовый и небольшой: он существует ровно затем,
 * чтобы трату можно было проверить, пока покупки нет. Начисляет алмазы одно
 * место на всю игру — `creditGems` в sim/gems.ts, и оно ждёт сервера.
 */
export const TEST_GEMS = 40;

