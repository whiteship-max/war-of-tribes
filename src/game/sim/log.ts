import type { GameState, LogEntry } from '../types';
import { DAY_LENGTH } from '../constants';

/**
 * Летопись живёт по возрасту, а не по числу строк.
 *
 * Обрезка по количеству врала: при бурной партии полсотни строк укладывались в
 * один день, при спокойной — растягивались на полгода, и «последние 80 записей»
 * означали то неделю, то век. Возраст — мера, понятная игроку: он видит месяц
 * и знает, что видит месяц.
 *
 * Дальше месяца не показываем и не храним. Сервера нет, класть полную летопись
 * некуда — когда появится бэкенд, туда она и поедет, а пока старое отбрасывается.
 *
 * Замерено `npm run log:report`: при активной игре набегает ~2.6 записи в игровой
 * день, то есть месяц — это около 80 строк и ~7 КБ, ровно столько же, сколько
 * занимал прежний предел в 80 записей. Разница в том, что теперь это обещание по
 * времени, а не по счёту.
 */
export const LOG_MAX_DAYS = 30;

/**
 * Запасной предел по количеству. Возраст один посёлок не спасёт: партия с боями,
 * событиями, караванами и наймом пишет вдесятеро чаще спокойной, и месяц такой
 * игры раздул бы сохранение. Триста строк — это десяток записей в день за все
 * тридцать дней: столько бурная партия и пишет. Обходится этот потолок в 28–43 КБ
 * летописи (6–9 чанков CloudStorage по 4000 символов) — смотря какой длины строки,
 * `log:report` печатает число для конкретной партии. В обычной игре предел не
 * работает вовсе: до него не доходит, там всё решает возраст.
 */
export const LOG_MAX = 300;

/**
 * Отбрасывает всё, что старше месяца, и подрезает хвост под запасной предел.
 * Летопись хранится новыми записями вперёд, поэтому старое лежит в хвосте и
 * отрезается одним `length`.
 *
 * Возраст считается в игровых днях от `s.time`: записи из будущего (их не бывает,
 * но состояние приходит из сохранения) не отбрасываются — у них отрицательный
 * возраст.
 */
export function trimLog(s: GameState): void {
  const cut = s.time - LOG_MAX_DAYS * DAY_LENGTH;
  // Массив отсортирован по времени убыванию: первая же старая запись — граница.
  let n = s.log.length;
  while (n > 0 && s.log[n - 1].at < cut) n--;
  if (n > LOG_MAX) n = LOG_MAX;
  if (n < s.log.length) s.log.length = n;
}

export function log(s: GameState, text: string, kind: LogEntry['kind'] = 'info'): void {
  s.log.unshift({ at: s.time, text, kind });
  // Предел по количеству дёшев и проверяется на каждой записи; возраст —
  // раз в игровой день, на смене суток в `tick`.
  if (s.log.length > LOG_MAX) s.log.length = LOG_MAX;
}
