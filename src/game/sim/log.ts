import type { GameState, LogEntry } from '../types';
import { DAY_LENGTH } from '../constants';

/**
 * Летопись живёт по возрасту, а не по числу строк.
 *
 * Обрезка по количеству врала: при бурной партии полсотни строк укладывались в
 * один день, при спокойной — растягивались на полгода, и «последние 80 записей»
 * означали то неделю, то век. Возраст — мера, понятная игроку: он видит месяц
 * и знает, что видит месяц.
 *
 * Дальше месяца не показываем и не храним. Сервера нет, класть полную летопись
 * некуда — когда появится бэкенд, туда она и поедет, а пока старое отбрасывается.
 */
export const LOG_MAX_DAYS = 30;

/**
 * Запасной предел по количеству. Возраст один посёлок не спасёт: партия с боями,
 * событиями, караванами и наймом пишет вдесятеро чаще спокойной.
 *
 * Число измерено, а не выбрано: `npm run log:report` играет партию, где кузница
 * всё время под нарядом, казармы набирают, а события поднимаются и разбираются.
 * Сколько записей такая партия пишет в игровой день, в самый плотный день и за
 * месяц, печатает сам отчёт; предел стоит с запасом над её месяцем.
 *
 * Предел обязан НЕ срабатывать в обычной игре: сработал — значит ступень «за
 * месяц» показала меньше месяца, и обещание нарушено молча. Отчёт кричит об
 * этом отдельной строкой.
 */
export const LOG_MAX = 250;

/**
 * Окно склейки повторов — игровые сутки. Внутри них одно и то же событие
 * считается тем же событием и получает счётчик вместо новой строки.
 *
 * Без склейки половину летописи занимала одна строка: кузница пишет по строке на
 * каждый выкованный предмет, и за месяц набегало 121 одинаковое «Кузница: готов
 * копьё» из 242 записей — замерено, а не предположено. Это не летопись, а вывод
 * отладки, и он вытеснял то, ради чего летопись читают: зиму, набеги, события.
 */
export const LOG_COALESCE = DAY_LENGTH;

/**
 * Отбрасывает всё, что старше месяца, и подрезает хвост под запасной предел.
 * Летопись хранится новыми записями вперёд, поэтому старое лежит в хвосте и
 * отрезается одним `length`.
 *
 * Возраст считается в игровых днях от `s.time`: записи из будущего (их не бывает,
 * но состояние приходит из сохранения) не отбрасываются — у них отрицательный
 * возраст.
 */
export function trimLog(s: GameState): void {
  const cut = s.time - LOG_MAX_DAYS * DAY_LENGTH;
  // Массив отсортирован по времени убыванию: первая же старая запись — граница.
  let n = s.log.length;
  while (n > 0 && s.log[n - 1].at < cut) n--;
  if (n > LOG_MAX) n = LOG_MAX;
  if (n < s.log.length) s.log.length = n;
}

/**
 * Пишет строку в летопись.
 *
 * `group` — ключ склейки, и задан он только там, где источник пишет по строке на
 * единицу товара: ковка и наём. Всё остальное случается по разу и склеиваться не
 * должно — две зимы подряд это две зимы, а не «зима ×2».
 */
export function log(s: GameState, text: string, kind: LogEntry['kind'] = 'info', group?: string): void {
  if (group) {
    // Ищем не только первую строку, а всё окно склейки: между двумя копьями
    // успевают лечь итог дня, событие и смена сезона, и склейка по одной лишь
    // голове рвалась на каждой из них — за месяц набегало вдвое больше строк,
    // чем нужно. Окно короткое (записи одних игровых суток), потолок на всякий
    // случай — чтобы цена записи оставалась постоянной.
    for (let i = 0; i < s.log.length && i < 32; i++) {
      const e = s.log[i];
      if (s.time - e.at > LOG_COALESCE) break;
      if (e.group !== group || e.kind !== kind) continue;
      e.n = (e.n ?? 1) + 1;
      // `at` не трогаем: летопись отсортирована по времени убыванию, и на этом
      // держится обрезка хвостом. Строка остаётся на месте, растёт только счёт.
      e.text = text;
      return;
    }
  }
  s.log.unshift({ at: s.time, text, kind, ...(group ? { group, n: 1 } : {}) });
  // Предел по количеству дёшев и проверяется на каждой записи; возраст —
  // раз в игровой день, на смене суток в `tick`.
  if (s.log.length > LOG_MAX) s.log.length = LOG_MAX;
}
