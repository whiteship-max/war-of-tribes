/**
 * Что код делает с посёлком.
 *
 * Одна дверь на всю деревню, и она же ставит метку. Правила кода — какие есть и
 * что набирать — живут отдельно и общие на два режима (`src/cheats.ts`); здесь
 * только то, что нельзя написать без состояния племени.
 *
 * ДАЁТСЯ РОВНО ТО, ЧЕГО СТОИТ ЖДАТЬ, И НИ ОДНОГО УРОВНЯ СВЕРХ. Склад, казна,
 * снаряжение и дружина — то, за чем игрок ходит часами и что не меняет саму
 * игру: посёлок остаётся первого уровня, стройка остаётся стройкой, время
 * остаётся временем. Поднять заодно уровни зданий было бы соблазнительно и
 * неверно — уровни и есть вся прогрессия посёлка (docs/handbook/village.md, «Здания»), и код,
 * который их раздаёт, проверял бы не игру, а сам себя.
 *
 * АЛМАЗОВ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. Начисление в игре одно (`sim/gems.ts`), и
 * замок по всему `src` (`gems.test.ts`) стоит в том числе над этим файлом: ни
 * вызвать начисление, ни тронуть поле отсюда нельзя. Золото — другое дело: это
 * обычная казна, её зарабатывают налогом и набегами.
 *
 * МЕТКА СТАВИТСЯ ЗДЕСЬ И НИГДЕ БОЛЬШЕ. Поле `s.cheated` и строка в летописи —
 * одним движением, чтобы «применили код» и «партия помечена» нельзя было
 * развести по разным местам и забыть второе.
 */
import type { CheatId } from '@/cheats';
import { CHEAT_MARK, HASTE_MARK } from '@/cheats';
import { RESOURCE_IDS } from '../constants';
import { EQUIPMENT_IDS } from '../data/equipment';
import { TROOP_IDS } from '../data/troops';
import { storageCap } from '../derived';
import type { GameState } from '../types';
import { log } from './log';

/**
 * Сколько золота кладёт код.
 *
 * Не «бесконечность»: казна с бесконечностью перестала бы быть числом, а на
 * рынке и в трактире по ней считают цены. Сто тысяч — заведомо больше всего, что
 * можно потратить за партию, и всё ещё обычное число.
 */
export const CHEAT_GOLD = 100_000;

/** Сколько каждого предмета снаряжения. Хватает на дружину любого состава. */
export const CHEAT_GEAR = 500;

/** Сколько бойцов каждого вида. Сотня на вид — это сотни бойцов в поле, как и задумано. */
export const CHEAT_TROOPS = 100;

/**
 * Применить код к посёлку.
 *
 * Возвращает строку для игрока — ту же, что ляжет в летопись. Кода, который
 * ничего не делает, здесь нет: до сюда доходит только узнанный (`cheatOf`).
 */
export function applyCheat(s: GameState, id: CheatId): string {
  if (id !== 'tribe') return '';
  const cap = storageCap(s);
  for (const r of RESOURCE_IDS) s.resources[r] = cap;
  s.gold = CHEAT_GOLD;
  for (const e of EQUIPMENT_IDS) s.equipment[e] = CHEAT_GEAR;
  for (const t of TROOP_IDS) s.army[t] = CHEAT_TROOPS;
  const said = `Код: склад полон (${Math.round(cap)}), казна ${CHEAT_GOLD}, снаряжения по ${CHEAT_GEAR}, дружины по ${CHEAT_TROOPS}.`;
  mark(s, said);
  return said;
}

/**
 * Пометить партию.
 *
 * Отдельной функцией, потому что метка — не следствие кода, а его цена: она
 * ставится **всегда**, даже если сам код когда-нибудь станет давать другое.
 * Строка в летописи пишется один раз за партию: применивший код десять раз не
 * должен получить десять строк, а помеченной партия остаётся навсегда.
 */
function mark(s: GameState, said: string): void {
  const first = !s.cheated;
  s.cheated = true;
  if (first) log(s, CHEAT_MARK, 'bad');
  log(s, said, 'bad', 'cheat');
}

/**
 * Партию ускорили скоростью проверки (`game/pace`): метка навсегда и одна строка летописи за партию.
 *
 * `lead` — опережение часов партии на эту минуту (`net/clock.leadAt`). Поле `s.lead` одно на два дела:
 * есть оно — партию ускоряли (метка), а число в нём — данные её часов, и живым его пишет запись
 * (`save.serialize`). Строка летописи — только при первом ускорении: партия помечена один раз и
 * навсегда, а летопись живёт месяц и сама метку не удержит — её держит поле.
 */
export function markHaste(s: GameState, lead: number): void {
  if (s.lead === undefined) log(s, HASTE_MARK, 'bad');
  s.lead = lead;
}
