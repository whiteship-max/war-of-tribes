// Хлеб осаждённого города — хлеб окна осады (docs/siege_v2.md, 21.1, Р-5).
//
// Часы голода считает окно осады мира (`world/siege.starvesAt`): хлеб в минуту, когда встал лагерь, и расход города с
// гарнизоном. Склад племени живёт своим счётом, и разойтись они могут в одну сторону — склад выше окна: офлайн-догон не
// знал об осаде, начатой без игрока, и вырастил хлеб, которого за стеной не было; слепок, по которому сервер войны открыл
// окно, лёг до осады. Голод тогда приходил при полном складе. Правда одна — окно: пока город в осаде, хлеба на складе не
// больше его остатка, и строка склада доходит до нуля в ту минуту, когда приходит голод. Вниз и только вниз: съел город
// больше окна — голодно ему самому, а падения раньше часов окна нет.
import type { GameState } from '../types';
import { outlay } from './pay';

/** Насколько склад может обогнать окно, прежде чем его урезать: пульс приносит окно раз в 2 с, а племя ест своим расходом. */
const BREAD_SLACK = 0.02;
const BREAD_SLACK_MIN = 5;

/**
 * Хлеб на складе — не больше остатка окна осады `bread`. Урезан — разовая трата (`sim/pay.outlay`): иначе книга запасов
 * сервера сочла бы убыль спрятанным хлебом (docs/security.md, ЗЩ-2). Возвращает, урезан ли.
 */
export function breadCap(s: GameState, bread: number): boolean {
  if (!(bread >= 0) || !Number.isFinite(bread)) return false;
  const left = Math.floor(bread);
  if (s.resources.food <= left + Math.max(BREAD_SLACK_MIN, left * BREAD_SLACK)) return false;
  s.resources.food = Math.max(0, left);
  outlay(s);
  return true;
}
