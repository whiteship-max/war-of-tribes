// Хлеб осаждённого города — склад племени (ОС-1, docs/siege_v2.md, раздел 23).
//
// До ОС-1 правдой о хлебе было окно осады мира: хлеб в минуту постановки и расход той минуты, и мост урезал склад до его
// остатка (Р-5, «вниз и только вниз»). Окно не видело ни сезона, ни прихода хлеба, ни догона без осады, и город сдавался по
// прогнозу, а хлеб со склада исчезал (23.1). Теперь правда — склад: шаг племени — добыча (со штрафом осады, `derived.siegeYield`)
// → прокорм → проверка, и только неоплаченный прокорм (`siegefood.starves`) начинает засуху. Засуха — срок, с которого ни один
// шаг не оплачен; мир читает его слепком и сдаёт город голодом в шаге осады — фазе, лёгшей на засуху. Хлеб, пришедший в тот же
// шаг (караван, задание), засуху не начинает: проверка — в конце шага.
import type { GameState } from '../types';
import { starves } from '@/world/siegefood';

/**
 * Итог шага под осадой: `balance` — склад после добычи и прокорма этого шага, до того как шаг отрезал его по нулю. Склад не
 * оплатил прокорм и к концу шага пуст — засуха (с этой минуты, если не шла); оплатил или хлеб пришёл — засухи нет. Без осады
 * ничего не делает. Единственный писатель `SiegeState.dry`.
 */
export function siegeHunger(s: GameState, balance: number): void {
  const w = s.siege;
  if (!w) return;
  if (starves(balance) && s.resources.food <= 0) {
    if (w.dry === undefined) w.dry = s.time;
  } else if (w.dry !== undefined) delete w.dry;
}

/** Сколько игровых секунд склад уже не оплачивает прокорм; кормит — null. */
export const dryFor = (s: GameState): number | null => (s.siege?.dry !== undefined ? Math.max(0, s.time - s.siege.dry) : null);
