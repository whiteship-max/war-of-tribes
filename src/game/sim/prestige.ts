// Престиж — одна дверь (ПН-2, docs/gdd/path_of_sword.md, 3.9 и «Решения ПН-2»).
//
// Престиж — одно число для всех: слава бродяги на дороге и престиж лорда в замке (`GameState.prestige`). Прежде его писали
// три места своей арифметикой (итог похода `sim/expedition`, награда задания `sim/tick`, ответ вести `data/eventKit`); теперь
// пишет только эта дверь, и правило у всех одно — ниже нуля престиж не падает. Держит это тест по исходникам
// (`sim/prestige.test.ts`): `.prestige =` мимо двери — красный.
//
// Ступени престижа (3.9.1) — функцией от порогов, а не таблицей: пороги в ГДД — ориентир, и до вывода (`npm run roam:report`,
// раздел «Престиж») в код они не идут (ГДД, «Как читать числа»). Пока путь за выключателем (`roamflag.roamOn`), ступени
// читает только прибор — своими порогами-заглушками; пачки, которым ступень нужна в игре (ПН-5, ПН-6, ПН-7, ПН-10), придут
// с выведенными порогами. Имена ступеней — слова ГДД, не числа: они здесь.
//
// Импорты — только относительные: ступень читает и сервер (вольные замки, ПН-10).
import type { GameState } from '../types';

/** Престиж после сдвига на `d`: ниже нуля не падает. Одна арифметика на партию и на автопилот прибора. */
export const prestigeAfter = (now: number, d: number): number => Math.max(0, now + d);

/** Сдвинуть престиж партии на `d` — единственная запись в `GameState.prestige`. Возвращает, на сколько он сдвинулся. */
export function movePrestige(s: GameState, d: number): number {
  const was = s.prestige;
  s.prestige = prestigeAfter(was, d);
  return s.prestige - was;
}

/** Имена ступеней престижа по порядку (ГДД 3.9.1). */
export const PRESTIGE_STAGES: readonly string[] = ['Безвестный', 'Замеченный', 'Известный', 'Грозный', 'Прославленный'];

/**
 * Ступень престижа `p` при порогах `steps` (по возрастанию, первый — ноль): наибольшая, чей порог взят. Порогов в коде нет —
 * их передаёт тот, кто их знает (до вывода — прибор своей заглушкой). Ступеней не больше, чем имён.
 */
export function prestigeStage(p: number, steps: readonly number[]): number {
  let k = 0;
  const n = Math.min(steps.length, PRESTIGE_STAGES.length);
  for (let i = 0; i < n; i++) if (p >= steps[i]) k = i;
  return k;
}
