import type { Building, BuildingTypeId, GameState } from './types';
import { serverNow } from '@/net/clock';
import { TEST_GEMS } from './constants';
import { BUILDINGS } from './data/buildings';
import { emptyEquipment } from './data/equipment';
import { emptyArmy } from './data/troops';
import { heroName } from './data/names';
import { emptyProfile, refreshCard } from '@/profile/stats';

/**
 * Формат сохранения. Поднимается при изменении структуры состояния (см. save.ts).
 *
 * Версия 12 — вера деревни (`s.faith`) вместо покровителя (`s.patron`). Само по
 * себе новое поле версию не поднимает — `deserialize` мержит его поверх новой
 * партии, и старое сохранение приезжает с верой по умолчанию. Поднимает её
 * **исчезновение старого**: покровитель был необратимым выбором за партию и
 * давал охоте ×1.15, фермам ×1.1 или +2 обороны, и молча забрать это нельзя.
 * Ступень 11 → 12 покровителя отпускает и говорит об этом в летописи. Вера при
 * этом не подставляется: её ставит первый ответ мира по клетке замка
 * (`sim/faith.syncFaith`), а до него панель храма честно говорит, что грамоты
 * из округи ещё не пришли.
 *
 * Версия 11 — кузница работает по заказам: `s.forging` и `s.forgeWork` уступили
 * место очереди `s.forge`. Наряд из десятки приводить не к чему — за него не
 * платили вперёд, и накопленная работа была работой над предметом, которого
 * никто не заказывал; она просто отбрасывается, а склад при этом не беднеет.
 *
 * Версия 10 — изучение округи в Дозоре (`s.survey`). Три числа, из которых
 * первое — сколько ступеней пройдено, а два других считаются от времени начала.
 * Задним числом их взять неоткуда, и приводить нечего: девятка приходит с нулём
 * изученных ступеней, то есть ровно с тем, с чего начинает новая партия. Молча
 * это не делается — миграция пишет строку в летопись.
 *
 * Версия 9 — профиль игрока: имя, лицо, итоги партии и визитка (`s.profile`).
 * Это первый раз с седьмой версии, когда сохранение младшего формата не
 * отбрасывается, а приводится: терять из-за аватара отыгранную партию не за что.
 * Цепочка миграций начинается с восьмёрки — см. `MIN_SAVE_VERSION` в save.ts;
 * всё, что старше, по-прежнему отбрасывается, и по той же причине, что и раньше.
 *
 * Версия 8 — перестройка посёлка и ратуша разом. Укрытия больше нет, тотем стал
 * церковью, хижина — жилищами, `s.totem` — `s.patron`, а Дом вождя — Ратушей.
 * У четырёх зданий сменился идентификатор, одно исчезло, шесть появилось: старое
 * сохранение пришло бы и с постройками, которых в игре больше нет (вместе с
 * рабочими за ними и их местами на плане), и без тех, что появились. Приводить
 * это не к чему: сохранение младшей версии отбрасывается, партия начинается
 * заново, и игроку об этом говорят прямо (LegacyModal).
 */
export const SAVE_VERSION = 12;

const built = (s: GameState, type: BuildingTypeId): Building => ({
  id: s.nextId++,
  type,
  level: 1,
  work: 0,
  workRequired: 0,
});

/** Сколько человек в племени на старте. Крыш хватает ещё примерно на столько же. */
const START_POP = 30;

/**
 * Новая партия: посёлок стоит целиком, включая стену, всё первого уровня.
 * Стройки с нуля в игре нет — единственная прогрессия посёлка это уровни, а
 * центр игры — карта, армия и бой. Стартовые запасы рассчитаны так, чтобы первые
 * копьё и боец делались без ожидания, но на дружину пришлось работать.
 */
export function createInitialState(): GameState {
  const s: GameState = {
    version: SAVE_VERSION,
    time: 0,
    resources: { wood: 900, stone: 600, food: 900, hides: 180, bones: 150, copper: 180, iron: 120 },
    equipment: emptyEquipment(),
    army: emptyArmy(),
    recruits: [],
    // Кузница стоит без заказа: первое дело игрока — заказать копьё.
    forge: [],
    // Округа не изучена: деревня видит ровно свой круг обзора, дальше темнота.
    survey: { done: 0, startedAt: 0, until: 0 },
    decree: 'none',
    ration: 'normal',
    tax: 'none',
    gold: 320,
    // Тестовый запас алмазов: он существует, чтобы можно было проверить трату,
    // пока покупки нет. Начисляет алмазы одно место на всю игру — creditGems.
    gems: TEST_GEMS,
    market: { day: 0, bought: {}, sold: {} },
    caravans: [],
    // Ноль — 1 января 1970: он не совпадёт ни с каким сегодняшним номером,
    // и новая партия честно читается как «сегодня ещё не играли».
    daily: { day: 0, result: 'none' },
    pop: START_POP,
    workers: {},
    freeJobs: {},
    // Невольников в новой партии нет: их покупают на рынке и приводят из павших
    // городов. Поля со значением по умолчанию версию сохранения не поднимают.
    bonded: 0,
    bondedWork: {},
    unrest: 0,
    buildings: [],
    completedQuests: [],
    activeEvent: null,
    nextEventAt: 50,
    morale: 60,
    prestige: 5,
    // Веры ещё нет: её называет мир по клетке, на которой реестр поставил замок
    // (`sim/faith.syncFaith`). Подставлять её здесь нельзя — деревня под
    // Вильнюсом на минуту стала бы католической и сменила бы веру молча.
    faith: {
      id: null,
      observance: 'even',
      pressure: 0,
      riteUntil: 0,
      riteAt: 0,
      strain: 0,
      strainAt: 0,
      relic: null,
      converted: false,
    },
    // Герой стоит у своей статуи с первого дня, как и всё остальное. Имя даётся
    // один раз за партию; род войск игрок меняет в Статуе за золото.
    hero: { name: heroName(Math.random), kind: 'infantry', downUntil: 0, marchId: null },
    starvation: 0,
    freezing: 0,
    winterWarnedYear: 0,
    winterWarning: false,
    growth: 0,
    popDay: START_POP,
    // Под стенами никого: осада приезжает из мира, а не заводится тут.
    siege: null,
    warriorsAway: 0,
    scoutsAway: 0,
    defenseFormation: null,
    battlePlans: [],
    battleWatch: false,
    feastUntil: 0,
    feastAt: 0,
    profile: emptyProfile(),
    tutorialStep: 0,
    tutorialDone: false,
    // Кодов в новой партии не было, и метка честно пуста (`src/cheats.ts`).
    cheated: false,
    log: [],
    stats: { hunts: 0, battlesWon: 0, battlesLost: 0, born: 0, died: 0, eventsResolved: 0, scouted: 0, raids: 0, castles: 0, lairs: 0, purchases: 0, dailyWins: 0 },
    nextId: 1,
    lastSaved: serverNow(),
  };
  for (const def of BUILDINGS) s.buildings.push(built(s, def.id));
  const at = (type: BuildingTypeId): number => s.buildings.find((b) => b.type === type)!.id;

  // Хозяйство укомплектовано: еда, лес, камень, руда. Назначение — число людей
  // в здании, а не список имён: люди одинаковы, разницу делает уровень постройки.
  const crew: [BuildingTypeId, number][] = [
    ['hunter_hut', 5],
    ['farm', 4],
    ['gathering', 4],
    ['sawmill', 5],
    ['quarry', 3],
    ['mine', 2],
  ];
  for (const [type, n] of crew) s.workers[at(type)] = n;
  // Остаток — свободные руки у костра: из них выйдут кузнецы, ремесленники и
  // первые бойцы. Сколько их, столько и видно на площади.

  s.log.push({ at: 0, text: 'Посёлок стоит за стеной, у ворот рынок, в кузнице холодный горн. Соседи не дремлют.', kind: 'info' });
  s.log.push({ at: 0, text: 'Поставь кузнеца к горну, скуй копьё и найми первого бойца — дальше карта.', kind: 'info' });
  // Визитка собирается сразу: мощь стоящего посёлка не ноль, и в профиле она
  // должна быть видна до первого тика.
  refreshCard(s);
  return s;
}
