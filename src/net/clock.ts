/**
 * Единственная дверь к «сейчас».
 *
 * Часы телефона игра больше не спрашивает напрямую нигде: `Date.now()` в
 * `src/game`, `src/world`, `src/ui` и `src/profile` запрещён тестом
 * (`clock.test.ts`), и дверь эта — здесь. Причина простая: по «сейчас»
 * считается догон офлайна и календарный день ежедневки, а часы устройства
 * сбиваются сами и переводятся руками.
 *
 * Что дверь делает и чего не делает:
 *
 * - **делает:** запоминает поправку к серверным часам и отдаёт время с ней.
 *   Сервер присылает своё «сейчас» с каждым ответом, поправка живёт до конца
 *   сессии;
 * - **не делает:** ничего не ловит и никого не судит. Игрок с переведёнными
 *   часами и без сети получит своё устройство и ничего больше — потому что
 *   больше взять неоткуда. Это место синхронизации, а не сторож; сторожа надо
 *   делать целиком и отдельно, а не намёком здесь.
 *
 * Поправка одна на игру: складывать вторую поверх — значит завести две правды
 * о времени, которые разъедутся ровно в тот день, когда одна из них обновится,
 * а другая нет.
 *
 * Опережение часов партии (ниже, «Часы партии») второй поправкой к тем же часам
 * не является: это другие часы — те, что прожила партия под скоростью проверки, —
 * и читают их не вместо `serverNow`, а там, где живёт партия. Кто какие часы
 * читает, записано поимённо и держится тестом.
 */

import { CHEATS_ON } from '@/cheats';
import { lead, setSpeed, startLead } from '@/game/pace';

let offset = 0;
let synced = false;

/** Сколько сейчас, по лучшему, что у нас есть. */
export const serverNow = (): number => Date.now() + offset;

/**
 * Часы устройства без серверной поправки: мерка **прошедшего** внутри сессии. Поправка приезжает с ответом
 * сервера и сдвигает «сейчас» скачком, а скачок не должен стать ни догоном, ни простоем.
 */
export const deviceNow = (): number => Date.now();

// ---------- Часы партии ----------
//
// У «сейчас» два читателя. Игрок живёт настоящим временем: календарный день ежедневки, предыстория (своя
// игра, связи с деревней нет), слой синхронизации и реестр. **Партия** — племя и мир — живёт часами партии:
// настоящее время плюс опережение, набежавшее под скоростью проверки (`game/pace`, «Скорость проверки»).
// Кто чем живёт, держит тест по исходникам (`clock.test.ts`).
//
// С опущенным выключателем кодов часы партии — `serverNow` как есть: от скорости в сборке остаётся этот
// псевдоним, а первая загрузка не выросла (docs/time.md, раздел 21.5).

/** Часы партии с опережением — то, что читает партия при поднятом выключателе. */
export const leadNow = (): number => {
  const at = Date.now();
  return at + offset + lead(at);
};

/** «Сейчас» партии: по этим часам живут племя и мир. */
export const partyNow: () => number = CHEATS_ON ? leadNow : serverNow;

/** Опережение партии прямо сейчас, мс. */
export const leadAt = (): number => lead(Date.now());

/** Сменить скорость проверки. Единственный, кто зовёт `pace.setSpeed`, — тест по исходникам. */
export const hurry = (next: number): void => setSpeed(next, Date.now());

/** Партия вошла в игру со своим опережением: скорость — ×1, опережение — то, что лежит в партии. */
export const enterLead = (ms: number): void => startLead(ms, Date.now());

/** Сверялись ли мы с сервером хоть раз за эту сессию. */
export const clockSynced = (): boolean => synced;

/** На сколько часы устройства расходятся с серверными, в миллисекундах. */
export const clockDrift = (): number => offset;

/**
 * Принять серверное «сейчас». Зовёт только слой синхронизации — из ответа
 * любого запроса: отдельного похода за временем игре не нужно.
 */
export function setServerTime(now: number): void {
  if (!Number.isFinite(now) || now <= 0) return;
  offset = now - Date.now();
  synced = true;
}

/** Для тестов: вернуть дверь в исходное. */
export function resetClock(): void {
  offset = 0;
  synced = false;
}
