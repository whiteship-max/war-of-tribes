// Испытательный стенд: логово у порога, чья сила зеркалит войско игрока.
//
// **Это не механика игры, а прибор, и по умолчанию он выключен** — `MIRROR_ON`,
// тем же приёмом, что `CHEATS_ON` и `NOTIFY_ON`. Выключенный стенд означает не
// «считает и не применяет», а «его нет в сборке»: единственное место вызова
// стоит за `if (MIRROR_ON)` (`LocalWorld.powerNow`), сборщик выбрасывает ветку
// под постоянной ложью, а с нею и весь этот модуль — ни байта кода. Поэтому
// выбор логова и кэш живут здесь, а не частными методами мира: частный метод
// класса из сборки не выбрасывается, даже если его никто не зовёт (меряно —
// 0.2 КБ gzip в чанке игры). Держит это `mirror.test.ts` с двух сторон:
// выключатель опущен и вход заперт.
//
// **Зачем он.** Бой заявлен сердцем игры, а в живой партии не решает ничего:
// логова слабее дружины в 5–120 раз, и полководец не проиграл ни одного боя ни в
// одном прогоне (docs/SUBTRACT.md, раздел 1, пункт 1). Тонкость ядра — кольцо
// контрров, мораль секторов, планы, приказы, расстановка — проверить сегодня
// нечем: любой план выигрывает. Стенд подставляет противника, на котором план
// что-то значит, и ничего больше в мире не трогает.
//
// **Опора — мощь всего войска игрока, и второй правды о ней здесь нет.**
// Берётся то же произведение, которым мир уже считает силу нашего лагеря
// (`LocalWorld.campArmy`: `men × warriorPower`), из тех же полей слепка. Своего
// счёта «насколько силён игрок» стенд не заводит: он был бы третьим ответом на
// вопрос, на который уже отвечают `defense` и это произведение.
//
// Почему войско, а не `defense`: оборона включает частокол, башню и жителей с
// дубинами — они на карту не выходят, и зеркало обороны полководцу непроходимо
// по построению. Войско — то, чем игрок дерётся; и оно не проседает, когда
// дружина ушла в поле, — иначе вышедший в поход сам ослаблял бы себе противника.
//
// Тика у стенда нет, и хранить ему нечего: коэффициент выводится из сида мира и
// имени логова, сила — из слепка при чтении. Ступеней сохранения он не заводит.
import { troopTotal } from '@/game/battle/kinds';
import { marchSeed } from './combat';
import { seeded } from '@/game/sim/random';
import { distance } from './geo';
import { isLair, type GenSettlement } from './gen';
import { AI_RANGE } from './data/tuning';
import type { Coord, PlayerProfile, SettlementId } from './types';

/**
 * Выключатель стенда. **Для игроков — `false`, и менять это в коммите нельзя**
 * (`mirror.test.ts`): поднимают его у себя, на время замера, как `CHEATS_ON`.
 */
export const MIRROR_ON = false;

/**
 * Разброс коэффициента вокруг единицы: сила зеркала — `опора × (1 ± MIRROR_SPREAD)`,
 * ровно, без кости в бою.
 *
 * Четверть — число меряное, а не «поменьше». Мерили двумя прогонами ядра:
 *
 *  1. **Чего стоит расстановка.** Настроенная армия и быстрая атака держат поле
 *     в половине боёв при разном перевесе врага (`npm run battle:report`, раздел
 *     «Перебор расстановок», строка «точка поля»); разница этих двух точек и есть
 *     цена расстановки силой.
 *  2. **Где ломается бой полководца.** Дружина против зеркала: при ×0.75 она
 *     берёт 98–100 % боёв, при ×1.25 — 22–24 %, а между ними разные планы на
 *     одних и тех же силах расходятся на 65–100 пунктов.
 *
 * Отсюда и четверть: половина разброса (±25 %) вдвое шире цены расстановки
 * (±13 %), поэтому примерно половина встреч решается планом, а половина — силой.
 * Уже (±10 %) — каждая встреча становится монеткой, и «иногда сильнее» пропадает;
 * шире (±40 %) — план перестаёт что-либо значить на краях, и стенд снова меряет
 * одну силу.
 */
export const MIRROR_SPREAD = 0.25;

/**
 * Что стенду нужно знать о мире. Отдельным описанием, а не самим `LocalWorld`:
 * у того всё это частное, и вытаскивать его наружу ради прибора нельзя.
 */
export interface MirrorWorld {
  lairs: readonly GenSettlement[];
  home: Coord;
  seed: number;
  profile: PlayerProfile | null;
}

/**
 * Насколько силён игрок в поле — тем же произведением, каким мир считает силу
 * нашего лагеря. Слепка без войска не бывает только у новой партии, поэтому
 * ноль здесь законный ответ: зеркалить нечего.
 */
export const hostPower = (p: PlayerProfile): number =>
  troopTotal(p.army ?? {}) * Math.max(0, p.warriorPower ?? 0);

/**
 * Номер логова для сида. Имена логов — `b<номер>` у сгенерированных и
 * `l<номер>` у заведённых по ходу партии (`gen.generateWorld`,
 * `LocalWorld.spawnLair`); первая буква разводит две череды, чтобы `b1` и `l1`
 * не тянули один коэффициент. Своего хеша строк стенд не заводит — их в мире и
 * так три.
 */
const ordinalOf = (id: SettlementId): number => Math.imul(id.charCodeAt(0), 1013) + (Number(id.slice(1)) || 0);

/**
 * Коэффициент зеркала: ровный разброс вокруг единицы, свой у каждого логова и
 * постоянный на всю его жизнь. Постоянный нарочно — разведав соседа однажды,
 * игрок знает, с кем имеет дело, и решает, идти ли; кость, брошенная в минуту
 * боя, превратила бы стенд в лотерею и мерила бы не расстановку, а удачу.
 */
export const mirrorCoef = (worldSeed: number, id: SettlementId): number =>
  1 + (seeded(marchSeed(worldSeed, ordinalOf(id)))() * 2 - 1) * MIRROR_SPREAD;

/**
 * Какое логово сейчас зеркало. Оно одно, и это **ближайшее живое логово в
 * досягаемости** (`AI_RANGE` — дальше боты за игроком не ходят): сожгли его —
 * зеркалом становится следующее, ближних не осталось — стенд молчит, и мир
 * считает всё по-старому.
 *
 * Пепелища список переживает: логова из `gen.settlements` не исчезают, меняется
 * только их стадия, — поэтому «живо ли» спрашивают у самого мира, а не у списка.
 */
export function mirrorAt(w: MirrorWorld, alive: (s: GenSettlement, now: number) => boolean, now: number): SettlementId | null {
  let best: GenSettlement | null = null;
  let bestAt = Infinity;
  for (const s of w.lairs) {
    if (!isLair(s)) continue;
    const d = distance(s, w.home);
    if (d > AI_RANGE || d >= bestAt) continue;
    if (!alive(s, now)) continue;
    best = s;
    bestAt = d;
  }
  return best ? best.id : null;
}

/**
 * Сила зеркала, если спрашивают про него. `null` — обычное поселение, и дальше
 * всё идёт своим чередом. Времени здесь нет: логово растёт вместе с игроком, а
 * не само.
 */
export function mirrorPower(
  w: MirrorWorld,
  alive: (s: GenSettlement, now: number) => boolean,
  s: GenSettlement,
  now: number,
): number | null {
  if (!w.profile || !isLair(s) || s.id !== mirrorAt(w, alive, now)) return null;
  return Math.max(1, hostPower(w.profile) * mirrorCoef(w.seed, s.id));
}
