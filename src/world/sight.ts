// Кто наблюдает — одно правило на весь мир и на всю карту.
//
// Слоёв тумана два, и до сих пор второй из них работал вполсилы: живые данные
// держал всякий, у кого была фигура или отряд в поле, а значит — почти вся
// открытая земля. Теперь они разведены до конца:
//
// - **местность** открывают все и навсегда: фигуры по пройденному пути, свои
//   отряды по дороге, изучение округи Дозором — сразу целым радиусом;
// - **живые данные** — численность, стадия, чьё это, откуда выходят войска и
//   где сейчас чужой отряд — видны только в живом обзоре. А живой обзор дают
//   ровно двое: круг у своей деревни и **стоящий лазутчик**.
//
// Отсюда и цена решения. Разведчик открывает карту, но не следит; полководец
// ходит с войском, но не следит; изученная округа показывает, что там лежит, а
// не что там происходит. Смотреть за чужой землёй можно в одном месте разом —
// том, где стоит единственный лазутчик, — и пока он смотрит, он не работает.
//
// Модуль чистый: ни состояния, ни часов. Считают по нему двое — мир
// (`LocalWorld.sightDiscs`) и карта (`world/store.sightDiscs`), — и второй
// правды о том, кто наблюдает, между ними быть не должно.
import type { Coord, FigureId, FigurePhase } from './types';
import { FIGURE_BY_ID } from './data/figures';
import { HOME_SIGHT } from './data/tuning';
import { type Placed, placeOf } from './shelter';
import { SICILY_SIGHT, sicilySlot } from './spawn';

/**
 * Кольцо живого обзора у своего города, клеток. Обычное — `HOME_SIGHT`. У города на одном из двенадцати мест острова
 * (тест с игроками, `TRIBE_SPAWN=sicily`, docs/test_world.md) — `SICILY_SIGHT`: соседи там стоят в шести клетках, и
 * из любого из двенадцати городов видно остальные одиннадцать.
 *
 * Мерка — место, а не настройка сервера: на место острова ставит только этот режим, место не меняется, а мир
 * пересобирает логова из сида при каждой загрузке — правило от флага сервера двигало бы их при его смене. Спрашивают
 * одну эту функцию мир (`LocalWorld`), карта (`world/store`) и генерация (`gen`).
 */
export const homeSight = (home: Coord): number => (sicilySlot(home) > 0 ? SICILY_SIGHT : HOME_SIGHT);

/**
 * Единственная фигура, дающая живой обзор. Не «список наблюдателей»: лазутчик у
 * игрока один, и в этом вся острота — смотреть можно за одним местом.
 */
export const WATCHER: FigureId = 'spy';

/** Фигура наблюдает, стоя на месте? В пути она идёт, а не смотрит. */
export const standing = (phase: FigurePhase): boolean => phase === 'field' || phase === 'home';

/**
 * Радиус живого обзора фигуры, клеток. Ноль — она землю открывает, но за
 * происходящим не следит.
 *
 * Наблюдение включается **приказом** (`watching`), а не само собой: пока
 * лазутчик смотрит, он не выведывает войско и не поднимает бунт. Это и есть
 * решение — смотреть или действовать.
 *
 * Укрывшийся в городе не смотрит никуда: его нет на карте (`world/shelter`), и
 * живого обзора из-за стены он не даёт — даже если отметка наблюдения осталась.
 */
export function liveSight(id: FigureId, f: Placed & { watching?: boolean }): number {
  if (id !== WATCHER || !f.watching) return 0;
  if (placeOf(f) !== 'map' || !standing(f.phase)) return 0;
  return FIGURE_BY_ID[id].sight;
}
