// Правила мира при боевой шкале (docs/time.md, раздел 18).
//
// Десять файлов `src/world/*.test.ts` первой строкой берут `@/game/pace.minute` и закрепляют
// «игровой день — настоящая минута»: их литералы («за четыре часа набег обязан случиться»,
// «на 32-й минуте лагерь стоит») писаны тогда, и проверяют они правило, а не шкалу. Долг,
// названный пачкой 4, был в том, что **взаимодействия настоящего времени с игровым** такие
// тесты не видят вовсе: при дне в минуту обе величины идут одинаково, и любое их отношение
// зелёное даром. Ровно на этом стыке и проскочил `SIEGE_TOWN_EAT` — ставка «в настоящий час»
// рядом с вылазкой в игровых днях.
//
// Этот файл — то же дерево при **боевой** шкале: он нарочно НЕ берёт `pace.minute`, и модули
// мира считаются при тридцати. Держать в нём надо ровно то, чего при единице не видно:
// отношения величин разных часов. Литералам времени тут не место — они уедут при следующем
// повороте шкалы; здесь сравнивают одно время с другим.
import { describe, expect, it } from 'vitest';
import { timeScale, realMs, DAY_LENGTH, gameDaysOfMs } from '@/game/pace';
import { distance, terrainFactor, travelTime } from './geo';
import { UNIT_BY_ID } from './data/units';
import { FIGURE_BY_ID } from './data/figures';
import { LocalWorld } from './local/LocalWorld';
import type { PlayerProfile } from './types';
import {
  AI_ATTACK_MAX,
  AI_ATTACK_MIN,
  AI_RANGE,
  MARCH_MIN_SECONDS,
  AI_WARNING_BASE,
  BURN_IMMUNE,
  CAMP_WORKS_RIPE,
  HANDOVER_MAX,
  SIEGE_COOLDOWN,
  SIEGE_IMMUNE,
  SIEGE_RELIEF_AT,
  SIEGE_SORTIE_AT,
  SIEGE_TOWN_EAT,
  SIEGE_TOWN_EAT_MAN,
  SIEGE_TOWN_LARDER,
} from './data/tuning';
import { townEatPerHour, townLarder } from './siege';

/** Игровых дней в сроке мира. */
const days = (ms: number): number => gameDaysOfMs(ms);

describe('боевая шкала: этот файл считает мир при ней, а не при дне в минуту', () => {
  // Точка внутри области. Без неё весь файл — копия тестов при единице, зелёная даром:
  // именно так «взаимодействие двух часов» и осталось непроверенным в пачке 4.
  it('шкала здесь боевая, и она не единица', () => {
    // Числом тридцать здесь не проверяется нарочно: боевую шкалу держит свой тест у двери
    // (`game/pace.test.ts`), и второй её копии быть не должно. Здесь важно одно — что файл не
    // взял `pace.minute` и считает мир не при единице, иначе всё ниже зелено даром.
    expect(timeScale(), 'файл не берёт pace.minute').toBeGreaterThan(1);
    expect(realMs(DAY_LENGTH), 'игровой день длиннее минуты').toBeGreaterThan(60_000);
    expect(realMs(DAY_LENGTH), 'и равен шкале, взятой у двери').toBe(timeScale() * DAY_LENGTH * 1000);
  });
});

describe('осадный голод против того, что за осаду успевает', () => {
  /**
   * Ради чего и заведён класс ставки. Расход еды чужого города сравнивается с вылазкой,
   * выручкой и рогатками — всё это игровые дни, — значит и сам он идёт игровым временем. Пока
   * он стоял «в настоящий час», при боевой шкале город падал за 20–25 настоящих минут, то есть
   * меньше чем за игровой день: раньше собственной вылазки (4 дня), выручки (7) и рогаток (28).
   *
   * Тест сравнивает не с числом, а с этими тремя сроками: перепишут любой из них — он поедет
   * следом. При дне в минуту он был бы зелёным даром: тогда «настоящий час» и «шестьдесят
   * игровых дней» — одно и то же.
   */
  it('город стоит дольше, чем вылазка и выручка, — и в игровых днях столько же, сколько при дне в минуту', () => {
    const POP = 100;
    const bare = (townLarder(POP) / townEatPerHour(POP)) * 3_600_000;
    const held = (townLarder(POP) / (townEatPerHour(POP) + POP * SIEGE_TOWN_EAT_MAN)) * 3_600_000;

    // Сорок игровых дней на полном амбаре, двадцать четыре — с гарнизоном вровень с жителями.
    expect(days(bare), 'без гарнизона').toBeCloseTo(40, 6);
    expect(days(held), 'с гарнизоном').toBeCloseTo(24, 6);

    // И главное: успевает всё, ради чего осада задумана как осада.
    expect(held, 'вылазка осаждённого внутри окна').toBeGreaterThan(SIEGE_SORTIE_AT);
    expect(held, 'выручка соседей внутри окна').toBeGreaterThan(SIEGE_RELIEF_AT);
    // Рогатки дозревают дольше окна — так и задумано: лагерь не успевает закрыться совсем.
    expect(held, 'рогатки дозреть не успевают').toBeLessThan(CAMP_WORKS_RIPE);
  });

  it('ставка объявлена за игровой день, а не за настоящий час', () => {
    // Настоящий час при боевой шкале — два игровых дня, и ставка обязана быть вдвое от дневной.
    expect(SIEGE_TOWN_EAT, 'душевой расход в настоящий час').toBeCloseTo((SIEGE_TOWN_LARDER / 40) * 2, 12);
    expect(SIEGE_TOWN_EAT_MAN, 'расход бойца в настоящий час').toBeCloseTo((SIEGE_TOWN_LARDER / 60) * 2, 12);
  });
});

describe('окна защиты игрока против часов мира', () => {
  /**
   * Окно защиты — настоящее время (решение владельца), всё вокруг него — игровое. Отношение
   * между ними и есть то, что при дне в минуту не проверишь: там оно ровно другое.
   */
  it('окно после падения длиннее паузы между набегами — иначе павший город встречает следующий без защиты', () => {
    expect(SIEGE_IMMUNE, 'окно длиннее самой длинной паузы между набегами').toBeGreaterThan(AI_ATTACK_MAX);
    expect(AI_ATTACK_MIN, 'точка внутри области: паузы объявлены и не нулевые').toBeGreaterThan(0);
    // Ровно этого и не было при сорока пяти настоящих минутах: окно стало короче одной паузы,
    // и падений без защиты стало вдвое-втрое больше (docs/time.md, раздел 17.4). Числом игровых
    // дней окно тут не проверяется: оно настоящее время, и в игровых днях его величина зависит от
    // шкалы — а литералам времени в этом файле не место.
    expect(days(SIEGE_IMMUNE), 'окно длиннее паузы и в игровых днях тоже').toBeGreaterThan(days(AI_ATTACK_MAX));
  });

  it('остывание осады соразмерно окну защиты', () => {
    // Два ограничителя частоты крутятся врозь (`SIEGE_CHANCE` и остывание), но остывание не
    // должно тонуть в окне: иначе оно ничего не ограничивает. Отношение разноклассовое —
    // остывание игровое, окно настоящее, — и потому живёт здесь, а не в `siege.test.ts`.
    expect(SIEGE_COOLDOWN).toBeGreaterThan(SIEGE_IMMUNE / 2);
  });

  it('защита после сожжения длиннее защиты после падения: иначе длинное окно накрыто коротким', () => {
    // Смысл лестницы поражения: сожжение тяжелее грабежа, значит и защита после него дольше.
    // Оба окна ставятся от одной минуты падения, поэтому равные числа означали бы, что
    // длинного окна нет вовсе: у своего города второго падения внутри суток не бывало, и
    // понижение «сжечь → ограбить» не спрашивалось ни разу (docs/time.md, раздел 19).
    // Насколько дольше — вывод из отстройки (`npm run sack:report`, «Окна защиты»); здесь
    // держится только порядок: он от шкалы не зависит и числом времени не пишется.
    expect(BURN_IMMUNE, 'окно после сожжения длиннее окна после любого падения').toBeGreaterThan(SIEGE_IMMUNE);
    // И оба они — время игрока: при боевой шкале в игровых днях они значат не то, что в
    // настоящих часах, а порядок между ними обязан держаться в обеих мерах.
    expect(days(BURN_IMMUNE), 'и в игровых днях порядок тот же').toBeGreaterThan(days(SIEGE_IMMUNE));
  });
});

describe('предупреждение о набеге против потолка сбора', () => {
  /**
   * Наследник правила «предупреждение длиннее заморозки» (поставка 2 боя, docs/battle_eu4.md, 14.26–14.27):
   * заморозки нет, последний ответ дома — сбор дружины, и набег обязан появляться тогда, когда полный сбор к его
   * приходу ещё успевает. Оба — игровое время, и отношение между ними от шкалы не зависит; проверяется при боевой
   * шкале затем, что в настоящих часах это уже не минуты, а часы, и ошибка класса у любого из двух вылезла бы сразу.
   * Черта «Мясник» (сбор ×1.5) правило нарушает: у такого полководца полный сбор не успевает никогда — в пересмотре
   * баланса (14.24); письмо о набеге при этом приходит всегда (`world/notice.test.ts`).
   */
  it('предупреждение длиннее потолка сбора, и оба в игровых днях', () => {
    expect(AI_WARNING_BASE, 'полный сбор успевает к приходу').toBeGreaterThan(HANDOVER_MAX);
    expect(days(AI_WARNING_BASE), 'ритм угрозы — семь игровых дней').toBeCloseTo(7, 6);
    expect(days(HANDOVER_MAX), 'потолок сбора — шесть игровых дней').toBeCloseTo(6, 6);
  });
});

describe('дорога против ритма угрозы', () => {
  const START = 1_700_000_000_000;
  const profile: PlayerProfile = {
    name: 'Тест',
    pop: 120,
    defense: 30,
    units: { warrior: 10, scout: 4 },
    army: { spearman: 12 },
    stock: { food: 120, wood: 80 },
    stash: 0,
  };

  /**
   * Решение владельца (docs/time.md, раздел 19): **поход идёт игровым временем**. Мерится он
   * здесь не формулой, а самим миром: сколько мир кладёт между выходом и приходом. Это и есть
   * то место, где путь превращался в часы мира мимо двери (`seconds * 1000`), — при дне в
   * минуту разницы не видно вовсе, и проверка была бы зелёной даром.
   */
  it('мир кладёт на дорогу ровно то, что даёт дверь, — а не тридцатую долю', async () => {
    let now = START;
    const world = new LocalWorld({ seed: 7, now: () => now, storage: null });
    const home = (await world.info()).home;
    const to = { x: home.x + 9, y: home.y + 4 };
    expect(await world.moveFigure('scout', to)).toBeNull();
    const f = (await world.sync(profile)).figures.find((x) => x.id === 'scout')!;
    const road = travelTime(distance(home, to), terrainFactor(7, home, to), FIGURE_BY_ID.scout.speed);
    expect(road, 'точка внутри области: путь длиннее пола').toBeGreaterThan(MARCH_MIN_SECONDS);
    expect(f.arriveAt - f.departAt, 'дорога в часах мира — через дверь').toBe(Math.round(realMs(road)));
    // И она вправду длиннее самой себя в настоящих секундах: при дне в минуту это одно число.
    expect(f.arriveAt - f.departAt, 'мимо двери вышло бы в тридцать раз меньше').toBeGreaterThan(road * 1000);
  });

  /**
   * Ради этого отношения решение и принято: ритм угрозы объявлен в игровых днях, а дорога шла
   * настоящими минутами — и после поворота шкалы игрок стал в тридцать раз быстрее собственной
   * деревни. Теперь оба срока одни часы, и круг похода к самой дальней цели полководца
   * укладывается в паузу между набегами.
   */
  it('круг похода к дальней цели короче паузы между набегами', () => {
    const road = travelTime(AI_RANGE, 1, UNIT_BY_ID.warrior.speed);
    expect(realMs(road) * 2, 'круг короче самой долгой паузы').toBeLessThan(AI_ATTACK_MAX);
    expect(days(realMs(road) * 2), 'и он не пренебрежимо мал: дорога чего-то стоит').toBeGreaterThan(1);
  });

  /** Пол похода — пол у времени пути, и мерить его надо игровым днём, а не настоящей минутой. */
  it('самый короткий поход — доля игрового дня, а не доля настоящей минуты', () => {
    const near = travelTime(0.01, 1, UNIT_BY_ID.warrior.speed);
    expect(near, 'точка внутри области: путь упёрся в пол').toBe(MARCH_MIN_SECONDS);
    expect(near, 'пол короче игрового дня').toBeLessThan(DAY_LENGTH);
    expect(realMs(near), 'но настоящей минуты он длиннее — игрок ждёт его своими часами').toBeGreaterThan(60_000);
  });
});
