// Где агент: на карте или в своём городе — одно правило на весь мир и на всю карту.
//
// Агент, стоящий у своих ворот, может войти в город и укрыться: с общей карты он
// пропадает и выходит обратно по слову игрока. Это **не второе место рядом с
// первым**, а то же самое место, только внутри: клетка у него прежняя (`to`),
// фаза прежняя (`home`), и выйдя, он встаёт ровно там, откуда вошёл. Отдельной
// точки «в городе» у агента нет и заводить её нельзя — у нас уже было войско,
// числившееся в двух местах сразу.
//
// Поэтому и хранится не «укрыт/не укрыт», а **отметка стоянки**, на которой агент
// вошёл: `departAt` в минуту входа. Любой уход — приказ идти, погоня, удар по
// лагерю, гибель — переписывает `departAt`, и отметка перестаёт совпадать сама.
// Забыть снять укрытие в новом пути нельзя: снимать нечего, оно просто больше не
// про эту стоянку. Агент вне строя — третье состояние: его нет ни на карте, ни в
// городе, он возвращается, и об этом говорит его срок. Четвёртое — **место
// пустует**: человек погиб или ушёл на покой, и вернуться некому, пока не наймут
// нового. Хранится оно отметкой `gone` поверх фазы `down`, поэтому всякая проверка
// «вне строя» закрывает и пустое место — забыть его где-то нельзя.
//
// Модуль чистый: ни состояния, ни часов. Считают по нему двое — мир
// (`LocalWorld`: обзор, туман, «кто здесь стоит», приказы) и карта (через
// `FigureView.place`, которое мир выводит этой же функцией), — и второй правды о
// том, где агент, между ними быть не должно.
import type { FigurePhase } from './types';

/** Где агент: на карте, в своём городе, вне строя — или места некому занять. Ровно одно из четырёх. */
export type FigurePlace = 'map' | 'city' | 'down' | 'vacant';

/** То, из чего место выводится. Больше ничего о фигуре правилу знать не нужно. */
export interface Placed {
  phase: FigurePhase;
  departAt: number;
  /** Отметка стоянки, на которой агент вошёл в город (`departAt` в минуту входа). */
  sheltered?: number;
  /** Человек погиб или ушёл, место пустует. Есть только у фазы `down`. */
  gone?: unknown;
}

export function placeOf(f: Placed): FigurePlace {
  if (f.phase === 'down') return f.gone ? 'vacant' : 'down';
  return f.phase === 'home' && f.sheltered !== undefined && f.sheltered === f.departAt ? 'city' : 'map';
}

/**
 * Войти в город можно только стоя у своих ворот: из поля и с дороги туда не
 * попадают, а выбывший и так не на карте.
 */
export const canShelter = (f: Placed): boolean => f.phase === 'home';

/**
 * Переодеть агента можно дома — **у своих ворот или в городе**, укрываться для
 * этого не нужно. Условие то же, что у входа в город, и это не совпадение: оба
 * спрашивают «стоит ли он у себя». Выбывший не переодевается — его нет ни на
 * карте, ни в городе.
 *
 * Почему не «только укрывшись». Укрытие у своих ворот ничего не стоит — ни
 * времени, ни решения, — и требовать его значит добавить два нажатия без выбора,
 * а у лазутчика ещё и снять наблюдение. Правило, которое стоит только нажатий, —
 * церемония.
 */
export const canRegear = (f: Placed): boolean => f.phase === 'home';
