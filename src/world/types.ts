/** Что изменилось с прошлого обращения. */
export interface WorldPulse {
  now: number;
  marches: MarchView[];
  /** Фигуры целиком: их положение выводится из времени, а не из тика. */
  figures: FigureView[];
  /** Новые отчёты — их ещё не видели. */
  reports: Report[];
  /** Последствия для деревни: применяет игровая сторона. */
  effects: HomeEffect[];
  /** Осада деревни игрока. null — под стенами никого. */
  siege: SiegeView | null;
  /**
   * Вера земли под замком и доля чужой веры вокруг. Едет каждым пульсом,
   * потому что мир — единственный, кто знает, на какой клетке стоит деревня:
   * племя про координаты не знает и знать не должно.
   *
   * Приход этого числа **ставит** веру новой партии (`sim/faith.syncFaith`) и
   * дальше её не трогает: крещение — дело деревни, а не земли.
   */
  faith: { id: FaithId; pressure: number };
  unread: number;
  /**
   * Какие вызовы к воротам из слепка мир уже посчитал — в этот пульс или раньше. Племя снимает их с партии: последствие
   * может потеряться (партия не успела записаться после пульса), а второго боя за один вызов быть не должно.
   */
  gateDone?: string[];
}
