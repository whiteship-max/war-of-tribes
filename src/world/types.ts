  power: Estimate;
  pop: Estimate;
  /**
   * Сколько добра можно с него взять. **Открытая часть склада**: то, что
   * помещается в тайник, сюда не входит и не входит никогда — ни разведкой, ни
   * боем чужой подпол не сосчитать. Своя деревня знает своё точно.
   *
   * Стареет вместе с прочей разведкой: это такие же данные, как численность
   * гарнизона, и добывать их надо тем же способом.
   */
  loot: Estimate;
  intel: IntelReading | null;
  /** Какие фигуры стоят у этой цели вплотную — им и доступны здешние действия. */
  figuresHere: FigureId[];
