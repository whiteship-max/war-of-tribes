/**
 * Фигура на карте. Положение считается из времени выхода и времени прибытия —
 * ровно как у похода. Поэтому фигура, шедшая, пока игрока не было, оказывается
 * там же, где оказалась бы при непрерывной игре: догон ничего не «доигрывает».
 */
export interface FigureView {
  id: FigureId;
  name: string;
  icon: string;
  phase: FigurePhase;
  /**
   * На карте она, укрылась в своём городе, выбыла или место пустует — ровно одно из них
   * (`world/shelter.placeOf`). Карта рисует, берёт в руку и держит камеру только
   * у той, что `map`; укрывшаяся стоит у своих ворот и выйдет туда же.
   */
  place: FigurePlace;
  /** Где она сейчас: в пути — точка между `from` и `to`. */
  at: Coord;
  from: Coord;
  to: Coord;
  departAt: number;
  arriveAt: number;
  /** Радиус обзора в клетках. */
  sight: number;
  /** Поселение, у которого фигура стоит вплотную. null — чистое поле. */
  atId: SettlementId | null;
  atName: string | null;
  /** Стоит у своего поселения: полководец здесь меняет состав. */
  atHome: boolean;
  /** Когда фигура вне строя вернётся, мс. 0 — она в строю. У пустого места не значит ничего. */
  downUntil: number;
  /**
   * Вне строя потому, что задержана, а не разбита: пойманного отпустят, а не выходят.
   * Лазутчика держат на месте (`busyUntil`), разведчика уводят с карты — у обоих здесь
   * истина, пока держат.
   */
  held: boolean;
  /** Почему место пустует: погиб или ушёл на покой. null — на месте человек. */
  gone: 'died' | 'retired' | null;
  /** Человек дожил до покоя: приказов не берёт, идёт домой и уйдёт у ворот. */
  retiring: boolean;
  /**
   * До какого момента фигура занята прошлым приказом, мс. 0 — свободна.
   * Приказы конкурируют за её время: агент каждого вида один, и в этом смысл.
   */
  busyUntil: number;
  /**
   * Стоит наблюдателем. Только у лазутчика: живой обзор за пределами круга
   * деревни даёт он один, и пока он смотрит — он не работает.
   */
  watching: boolean;
  /**
   * Радиус живого обзора, который фигура даёт **прямо сейчас**, клеток. Ноль —
   * она открывает местность, но за происходящим не следит. Не то же, что
   * `sight`: тот про землю и есть у всех.
   */
  watchSight: number;
  /** Войско при полководце. Пусто у остальных. */
  troops: TroopStack;
  /** Мощь этого войска — сумма мощи бойцов (`kinds.troopPower`). */
  power: number;
  /**
   * Поселение, которое эта фигура держит в осаде. null — лагеря нет. Пока он
   * стоит, других дел у полководца не бывает, а приказ уйти снимает осаду, —
   * и панель обязана сказать это до приказа, а не после.
   */
  besieging: SettlementId | null;
  /**
   * Когда закончится передача дружины, мс. 0 — все на месте. Пока идёт
   * передача, эти люди уже не в гарнизоне, но ещё не в строю: они на дороге.
   */
  readyAt: number;
}

