/**
 * Что мир требует применить к деревне игрока: погибших, добычу, награбленное у него.
 * Мир считает исход, племя применяет последствия — так расчёт переедет на сервер целиком.
 */
export interface HomeEffect {
  id: string;
  lost: UnitStack;
  /** Кого именно недосчитались: бой знает состав, и списывать надо тех же. */
  lostTroops?: TroopStack;
  /** Плюс — привезли, минус — унесли. */
  resources: Loot;
  /**
   * Сколько людей прибавилось в племени. Только плюс: отнять людей мир умеет
   * одним боем, а бой считает потери сам (`lost`/`lostTroops`). Сюда они
   * приходят единственным путём — выкупом пленных, то есть тех, кого племя уже
   * посчитало убитыми (та же условность, что у лазарета).
   */
  pop?: number;
  prestige: number;
  morale: number;
  /** Настоящий бой — для летописи побед и поражений. null — боя не было. */
  battle: 'won' | 'lost' | null;
  /**
   * Насколько плохо кончился бой у стены, 0..1. Мир не знает, что с этим числом
   * сделает племя, и знать не должен: у него это просто мера того, насколько
   * чужие похозяйничали вокруг деревни.
   */
  sacked?: number;
  /**
   * Сколько оружия взято в логове, штук. Та же условность, что у `sacked`: мир
   * отдаёт число, а какие это будут предметы, решает племя — про кузницу и её
   * список мир не знает и знать не должен.
   */
  arms?: number;
  /**
   * Логово сожжено этим походом. Одно поле на один счётчик в профиле: считать
   * сожжённые логова по добыче (как считаются замки по золоту) нельзя — пустое
   * логово тоже сожжено.
   */
  lair?: boolean;
  /**
   * Невольники после падения города: плюс — мы привели их из павшего чужого,
   * минус — их увели из нашего. Кого и сколько, решает одно правило на обе
   * стороны (`world/spoils.lead`); что с этим числом делать, знает племя.
   */
  bonded?: number;
  text: string;
  good: boolean;
}

/**
 * Слепок деревни игрока для мира: мир не лезет в состояние племени сам.
 * На сервере эти данные будут его собственными, а метод sync станет heartbeat-ом.
 */
export interface PlayerProfile {
  name: string;
  pop: number;
  /** Оборона прямо сейчас — без тех, кто не дома: в походе и при полководце. */
  defense: number;
  /** Сила одного воина с нынешними технологиями. */
  warriorPower: number;
  /**
   * **Всё** войско племени по видам бойцов — и гарнизон, и дружина полководца.
   * Кто из него дома, мир считает сам, в ту минуту, когда решает
   * (`world/muster`): слепок едет раз в пульс, а дружина уходит к полководцу и
   * гибнет между пульсами. Раньше здесь ехал готовый гарнизон, и мир, поверив
   * ему, отдавал полководцу тех же бойцов второй раз.
   */
  army?: TroopStack;
  /** Что даёт оборону помимо бойцов — частокол, башня, сами жители. В поле это ополчение. */
  militia?: number;
  /** Сколько из этого ополчения стоит стрелками: столько людей ставит на стену башня. */
  militiaArchers?: number;
  /** Как деревня встречает набег. null — обороняется тем, что вышло само. */
  defenseSetup?: ArmySetup | null;
  /**
   * Разведчики, которых можно отправить: свободные руки деревни. Воинов слепок
   * не везёт — сколько их дома, мир считает из `army`.
   */
  units: UnitStack;
  /**
   * Склад целиком, вместе со спрятанным в тайнике. Золота здесь нет: казну
   * набегом не берут.
   *
   * Одно число на два дела, и второго быть не должно. Им игрок **платит** —
   * дань, выкуп, дар: тайник прячет добро от чужаков, а не от вождя, и ровно
   * это число стоит в полоске ресурсов наверху экрана и в строке «нужно / из».
   * Из него же считается **добыча** победителя — вместе с `stash`, по одному
   * правилу на обе стороны (`world/spoils.plunder`).
   *
   * Раньше рядом лежало второе поле, `resources` — склад уже за вычетом
   * тайника. Оно было тем же самым числом, посчитанным заранее, и с появлением
   * общего правила дележа стало лишним: вычитает тайник теперь тот, кто делит,
   * и делает это одинаково у игрока и у бота.
   */
  stock: Loot;
  /**
   * Сколько каждого припаса прячет Тайник. Не «доля» и не «защита»: это
   * вместимость схрона, и делёж вычитает её из склада (`spoils.plunder`).
   * У бота это число выводится из его же склада — правило одно, считает каждая
   * сторона своим, ровно как гарнизон выводится из мощи.
   */
  stash: number;
  /**
   * Сколько в деревне невольников. Мир пользуется этим числом ровно для одного:
   * павший от голода город лишается их тем же правилом, каким мы уводим их из
   * павшего чужого (`world/spoils.lead`). У бота это число выводится из его же
   * населения (`AI_BONDED_SHARE`) — правило одно, считает каждая сторона своим,
   * ровно как тайник.
   */
  bonded?: number;
  /**
   * Вера деревни. null — мир ещё не назвал клетку замка (см. `PlayerProfile` в
   * первом пульсе новой партии). Мир пользуется ею ровно для одного:
   * стартового отношения соседа иной веры (`world/faith.faithAttitude`).
   */
  faith?: FaithId | null;
  /**
   * Прибавка к стойкости дружины: идёт ли обряд перед боем. Мир не спрашивает,
   * откуда она, и в бой кладёт как есть (`FieldSide.resolve`). Ни веры, ни
   * храма у боевого расчёта нет ни одним полем — потому «моя вера бьёт твою»
   * и не может случиться.
   */
  fervour?: number;
  /**
   * Сколько еды лежит на складе. То же, что `stock.food`, но отдельным числом:
   * осада считает не добычу, а на сколько дней хватит хлеба, и спрятанное в
   * тайнике племя ест наравне с остальным.
   */
  food?: number;
  /**
   * Что съедает сам город за час осады — без дружины, — и что добавляет к
   * этому один боец гарнизона. Оба числа приезжают из обычного расхода племени
   * (`foodConsumptionPerDay`), приведённого к часу: осадного пайка в игре нет,
   * и второй правды о том, сколько ест деревня, быть не должно.
   */
  foodPerHour?: number;
  soldierFoodPerHour?: number;
  /** Насколько дольше видно чужую армию до прихода, секунд. Работа Дозора. */
  warning?: number;
  /**
   * Радиус земли, открытой изучением округи, клеток. Тоже работа Дозора, и мир
   * получает от неё одно число, не спрашивая, откуда оно. Открывает он этим
   * **только местность**: живого обзора изученный радиус не даёт — иначе
   * изучение стало бы вторым способом наблюдать за половиной карты, и правило
   * «живой обзор только у деревни и у лазутчика» держалось бы на честном слове.
   */
  survey?: number;
  /**
   * Игровое время племени в секундах. Мир его не считает и не толкует — он
   * ставит его отметкой на записи боя, чтобы ролик знал час и время года.
   * Без него бой пришлось бы освещать настоящими часами устройства, и повтор
   * через неделю показал бы другое небо.
   */
  time?: number;
  /** Во сколько раз медленнее стареет разведка игрока. Тоже Дозор. */
  intelKeen?: number;
  /** Ступень снаряжения, которую конюшня добавляет коннице игрока. */
  mountGear?: number;
  /**
   * Сколько бойцов полководец может увести в поле. Работа Статуи Героя; мир
   * получает число и не спрашивает, откуда оно, — про здания он не знает.
   */
  command?: number;
}

