// Разорение: последствие выигранного набега, которое видно на карте.
//
// Чистый модуль того же рода, что `siege.ts`, `spy.ts` и `lairs.ts`: тика у
// разорения нет, поля «производство просело» нет, состояния «сколько ещё» нет.
// В сохранении лежит одно окно времени, и всё остальное выводится при чтении.
// Поэтому офлайн даёт ровно то же, что непрерывная игра, а сервер потом получит
// тот же ответ из тех же двух чисел.
//
// Петля целиком: набег выигран → на поселении висит окно → пока оно висит,
// собственные часы поселения стоят (не растёт мощь, не растёт население, не
// копится добро на складе, не отстраивается разбитый гарнизон) и сверх того
// просела сама мощь → окно истекло, и поселение живёт дальше с того места, где
// его застали. Второй набег в это окно приносит крохи не потому, что мы так
// решили, а потому, что взять неоткуда: склад пополняется по тем же часам.
//
// Поселение при этом не исчезает и владельца не меняет: оно чужое, а позже
// будет человеческое. Убрать с карты можно только логово (`lairs.ts`).
import { SACK_DURATION, SACK_POWER_LOSS } from './data/tuning';

/**
 * Окно, на время которого поселение стоит. Та же пара чисел, что у бунта
 * (`spy.revoltWindow`), и это не совпадение: и там, и там поселение перестаёт
 * жить своей жизнью — разница в причине, в сроке и в том, насколько просел
 * гарнизон. Сводить их в одну сущность нельзя: бунт и разорение случаются
 * независимо и кончаются в разные минуты.
 */
export interface Halt {
  since: number;
  until: number;
}

/**
 * Разорение — та же пара чисел плюс одно, которого не вывести ниоткуда: кто
 * разорил. Оно нужно ровно одному экрану — своей деревне («кто нас разорил»), —
 * и не участвует ни в одной формуле: чужому двору оно даже не показывается.
 */
export interface SackRec extends Halt {
  by?: string;
}

/**
 * Новое окно. Повторный набег по разорённому не складывает сроки и не удваивает
 * просадку — он ставит окно заново от нынешней минуты: разоряют то, что успели
 * отстроить, а не то, что уже сожжено.
 */
export const sackWindow = (at: number, by?: string): SackRec => ({
  since: at,
  until: at + SACK_DURATION,
  by,
});

/** Разорение держится прямо сейчас? Считается при чтении, а не отмечается тиком. */
export const sackActive = (w: Halt | undefined, now: number): boolean => Boolean(w && now < w.until);

/** Сколько разорению осталось, мс. 0 — его нет или оно уже кончилось. */
export const sackLeft = (w: Halt | undefined, now: number): number =>
  w ? Math.max(0, w.until - now) : 0;

/** Во сколько раз слабее гарнизон, пока держится разорение. */
export const sackPower = (active: boolean): number => (active ? 1 - SACK_POWER_LOSS : 1);

/**
 * Что видно глазами. Чужой двор игрок читает по виду, а не по часам: сколько
 * ещё чинить чужую стену, ему никто не докладывает (то же правило, по которому
 * у чужой осады в карточке нет часов голода). Своё разорение показывается
 * сроком, и это другой путь — см. `WorldPulse.sack`.
 */
export function sackLook(w: Halt | undefined, now: number): string {
  const left = sackLeft(w, now);
  if (left <= 0) return '';
  const share = SACK_DURATION > 0 ? left / SACK_DURATION : 0;
  if (share > 2 / 3) return 'дым ещё не осел';
  if (share > 1 / 3) return 'разбирают завалы';
  return 'почти отстроились';
}

/**
 * Сколько времени поселение простояло к моменту `now` — по **объединению** окон,
 * а не по их сумме.
 *
 * Это и есть то единственное, что у бунта и разорения обязано быть общим.
 * Собственные часы поселения (`LocalWorld.liveAt`) — одна величина, и тормозов
 * у неё теперь два. Сложи их — и поселение, разорённое во время бунта, поедет
 * во времени назад: часы пойдут вспять, а вместе с ними задним числом починится
 * разбитый гарнизон и наполнится склад. Пересечение считается ровно здесь и
 * ровно один раз, чтобы третьему тормозу не пришлось выводить это заново.
 */
export function haltElapsed(windows: (Halt | undefined)[], now: number): number {
  const spans: [number, number][] = [];
  for (const w of windows) {
    if (!w) continue;
    const end = Math.min(now, w.until);
    if (end > w.since) spans.push([w.since, end]);
  }
  if (spans.length === 0) return 0;
  spans.sort((a, b) => a[0] - b[0]);
  let total = 0;
  let [from, to] = spans[0];
  for (let i = 1; i < spans.length; i++) {
    const [a, b] = spans[i];
    if (a > to) {
      total += to - from;
      from = a;
      to = b;
    } else if (b > to) {
      to = b;
    }
  }
  return total + (to - from);
}
