// У разведчика, лазутчика, дипломата и полководца запас в сто. Тратится он на дорогу — по дням пути — и на дела;
// ожидание у цели и стоянка в поле даром. Дома — у своих ворот или за стеной — запас копится за два игровых дня, ровно
// и постепенно. Дела стоят энергию — у каждого агента свои, по его ремеслу, — и цена у каждого дела одна, здесь: её
// показывает меню, по ней гаснет кнопка и её же списывает приказ. Считает энергию одна дверь — `world/energy.ts`; мир и
