// `world/siegefood.ts`; племя, мир на клиенте и сервер войны спрашивают её. Без `@/`: файл собирает сервер.

/**
 * Точки кривой штрафа к добыче по соотношению сил «лагерь к гарнизону» (`blockade.blockadeRatio` — та же мерка, что у кольца):
 * слабее на те же полторы — ⅔, равны — 1, сильнее на 50 % — 1,5. Точки симметричны в логарифме: мощь — мера произведения, и
 * «втрое слабее» с одной стороны — «втрое сильнее» с другой (docs/siege_v2.md, 23.2, решение 2).
 */
export const CUT_RATIO_WEAK = 2 / 3;
export const CUT_RATIO_EVEN = 1;
export const CUT_RATIO_STRONG = 3 / 2;

/**
 * Штраф к добыче хлеба в трёх точках — доля, которую лагерь отнимает у полей за стеной.
 *
 * - `CUT_MAX` — лагерь сильнее на половину и больше: поля, загон и угодья — за стеной, и на них не выйти. Хлеб — ноль, как был
 *   под любым лагерем до ОС-1 (`SIEGE_FOOD_YIELD`). Осада голодом реальна: город ест запас.
 * - `CUT_MIN` — лагерь слабее на треть: «голодом не возьмёт». Выведено: наибольший штраф, при котором каждый посёлок мерки
 *   (`autopilot.townAt`, уровни 1–10) за год под осадой кормится сам — годовая добыча хлеба после штрафа не меньше годового
 *   расхода в осаде (`npm run siege -- --derive`, строка «слабый»).
 * - `CUT_MID` — силы равны: голод сдаёт город заметно позже, чем до ОС-1. Выведено: штраф, при котором посёлок мерки средней
 *   опоры (5-го уровня) держится голодом втрое дольше, чем до ОС-1 (`npm run siege -- --derive`, строка «равные»).
 */
export const CUT_MAX = 1;
export const CUT_MIN = 0.678;
export const CUT_MID = 0.856;

/**
 * Во сколько раз дольше держится голодом посёлок мерки средней опоры при равных силах, чем до ОС-1 (цель `CUT_MID`;
 * предложение ОС-1 — втрое: заметно, но лагерь, вставший вровень, всё ещё может взять город голодом).
 */
export const EVEN_HUNGER_LATER = 3;
/** Уровень посёлка мерки средней опоры — середина лестницы 1–10, им меряется `EVEN_HUNGER_LATER`. */
export const EVEN_LEVEL = 5;

/**
 * Допуск, с которым опись склада двигает окно осады сервера войны (ОС-1, `war.regarrison`): хлеб описи разошёлся с окном
 * больше 2 % или 5 хлеба — окно встаёт на опись. Меньше — расход между описями и округление описи: каждая запись партии
 * открывала бы окно заново. Те же числа, что держал мост Р-5 (`BREAD_SLACK`), — шаг пульса и описи один порядок.
 */
export const BREAD_SLACK = 0.02;
export const BREAD_SLACK_MIN = 5;
