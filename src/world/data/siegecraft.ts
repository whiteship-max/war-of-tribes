// Дела полководца в своём осадном лагере — числа дизайна в одном месте (задание владельца 06.10.2026, ночь 2):
// «Укрепить лагерь» и «Обстрел города». Цена в энергии — строкой таблицы энергии (`data/energy.ENERGY_PRICE`, `fortify` и
// `bombard`): цена у дела одна, и живёт она там же, где цены остальных дел. Здесь — что каждое дело даёт и сколько раз.
//
// Образец — EU4, буквально, без подгонки под отчёты:
//  - **укрепление лагеря — штраф кости нападающему**, та же грань, что у земли (`world/place`, таблица EU4: пересечённая
//    земля −1, горы −2). Рогатки — это холм, который лагерь насыпал себе сам;
//  - **обстрел — пролом и дух**: у EU4 артиллерия под стенами ломает стену (пролом) и торопит осаду, а не дерётся сама.
//    Пролом здесь — доля стены, на которой ополчение и стрелки башни уже не стоят; дух — часы самой осады
//    (`siege.siegeWear`): залп продвигает их вперёд, а дна (`SIEGE_WEAR_FLOOR`) не ломает.
//
// **Убывающая польза** (слово владельца): каждое следующее дело даёт половину предыдущего, и строк в таблице ровно столько,
// сколько раз дело можно сделать за осаду. Новая строка — новое дело сверх предела, со своим обоснованием.
//
// Считает всё одна дверь — `world/siegecraft.ts`; мир на клиенте и сервер войны спрашивают её.
import { worldDays } from '../../game/pace';

/**
 * Укрепления лагеря: сколько граней кости снимает у нападающих на лагерь — вылазки, выручки, удара с тыла и совместного
 * удара — каждое следующее. Первое — холм (−1, как пересечённая земля у EU4); второе — половина: рогатки за рогатками, а
 * не гора. Оба вместе — −1.5, меньше гор (−2): лагерь остаётся тем, что можно взять.
 */
export const FORTIFY_FACES: readonly number[] = [1, 0.5];

/** Залп обстрела: что он делает со стеной и с духом гарнизона. */
export interface Volley {
  /** Доля стены, на которой больше не стоят — ополчение и стрелки башни при штурме, 0..1. */
  wall: number;
  /** На сколько вперёд залп продвигает часы осады для духа гарнизона (`siege.siegeWear`), мс мира. */
  wear: number;
}

/**
 * Залпы обстрела, каждый следующий — половина предыдущего. Первый ломает пятую часть стены и стоит духу гарнизона восьми
 * дней осады — пятой части её пути до дна (40 игровых дней, `SIEGE_WEAR_SPAN`). Три залпа — 35 % стены и 14 дней: частокол
 * пушками лагеря не сносят целиком, а осада торопится, но не кончается.
 */
export const BOMBARD_VOLLEYS: readonly Volley[] = [
  { wall: 0.2, wear: worldDays(8) },
  { wall: 0.1, wear: worldDays(4) },
  { wall: 0.05, wear: worldDays(2) },
];
