// нетронутым после победы оно не должно: победа обязана быть видна на карте, а
// не только в отчёте. Арифметика — в `world/sack.ts`, окно одно, тика нет.

/**
 * Сколько держится разорение. Срок **реальный**, и это не оговорка: игровой день
 * у нас — минута, «сутки игрового времени» это двадцать четыре минуты, которых
 * игрок между двумя заходами не увидит вовсе. Меряется тем же, чем меряется
 * перерыв между заходами, — часами устройства (та же причина, что у `LAIR_RUIN`).
 *
 * Четыре часа — это лестница из трёх сроков, а не круглое число:
 * `REVOLT_DURATION` — люди отказались работать, бунт унимают за вечер;
 * разорение (4 ч) — сожжённые амбары и выбитый гарнизон, отстраиваются полдня;
 * `LAIR_RUIN` — места больше нет, след остывает.
 *
 * Четырёх часов хватает, чтобы разорение пережило вечернюю отлучку и половину
 * рабочего дня: игрок, ударивший перед уходом, вернётся к разорённому соседу.
 * И не хватает, чтобы пережить ночь: к утру округа отстроилась, и карта не
 * копит мёртвые дворы месяцами.
 */
export const SACK_DURATION = ownerTime(4 * HOUR, 'срок из лестницы трёх настоящих сроков мира, а держит он часы двора — хозяйство');

