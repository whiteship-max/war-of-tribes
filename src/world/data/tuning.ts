// ---------- Письма ----------
//
// Письмо — ожидающее решение: сосед предлагает пакт, требует дань, зовёт в
// поход, торгует пленными. Плюс один особый вид — предупреждение о набеге, у
// которого решение принимается не в письме, а на карте.
//
// Все числа здесь связаны между собой одним равенством, и врозь их менять
// нельзя: **`LETTER_TTL / LETTER_PAUSE_MIN ≈ LETTER_SLOTS − 1`**. Столько
// решений и успевает накопиться, пока живёт первое, — отсюда и пять ячеек, а не
// семь и не три. Разойдутся числа — либо стол никогда не заполняется (и правило
// переполнения становится мёртвым кодом), либо переполняется всегда, и тогда
// срок в сутки становится украшением: письмо вытесняется задолго до него.

/**
 * Сколько писем лежит на столе. Больше не хранится: очереди за столом нет.
 *
 * **Связано равенством: `LETTER_TTL / LETTER_PAUSE_MIN ≈ LETTER_SLOTS − 1`.**
 * Меняешь ячейки — меняй и паузу, иначе стол либо не заполняется никогда, либо
 * переполняется всегда.
 *
 * Минус единица — ячейка, которую держит под собой предупреждение о набеге.
 * Она стоит пустой, пока никто не идёт, и это не потеря места, а условие того,
 * чтобы предупреждение никого не сгоняло. Иначе набег, а он выходит каждые
 * четверть часа, вышибал бы со стола по решению за раз — и стол превратился бы
 * в ленту, где ничего не доживает до ответа.
 */
export const LETTER_SLOTS = 5;

/**
 * Сколько письмо ждёт ответа. Сутки — щедро нарочно: игрок спит, работает и
 * заходит раз в день в разное время, и письмо обязано пережить эту разницу.
 *
 * **Связано равенством: `LETTER_TTL / LETTER_PAUSE_MIN ≈ LETTER_SLOTS − 1`.**
 * Поднимешь срок, не тронув паузу, — стол начнёт вытеснять письма задолго до
 * того, как они истекут, и обещанные сутки станут словами.
 */
export const LETTER_TTL = 24 * 60 * MIN;

/**
 * Через сколько приходит следующее письмо.
 *
 * **Здесь и захочется «сделать письма почаще» — не надо: число связано
 * равенством `LETTER_TTL / LETTER_PAUSE_MIN ≈ LETTER_SLOTS − 1`.** Шесть часов
 * снизу — это ровно `24 ч / 4`: за сутки жизни письма приходит столько, сколько
 * влезает на стол, и ни одним больше. Опустишь паузу вдвое — писем станет вдвое
 * больше, но лишние не лягут на стол, а **вытеснят те, что уже на нём**, и
 * обещанные сутки на ответ превратятся в шесть часов. Хочешь чаще — поднимай
 * заодно ячейки (`LETTER_SLOTS`) или опускай срок (`LETTER_TTL`), но тогда
 * пересмотри и обещание, которое срок даёт игроку.
 *
 * Из равенства же следует, что за один заход (три-пять минут) письмо приходит
 * редко. Так и задумано: письма — это то, что накопилось, пока игрока не было,
 * а во время игры столбик наполняет второй, свой канал — предупреждения о
 * набегах.
 */
export const LETTER_PAUSE_MIN = 6 * 60 * MIN;
export const LETTER_PAUSE_MAX = 10 * 60 * MIN;

