// Виды писем: заголовки, значки, тексты и подписи выбора в одном месте.
//
// Форма та же, что у приказов дипломата и лазутчика: всё, что игрок читает,
// собирается здесь, а разметка только раскладывает готовые строки. Причина та
// же, по которой карточка вида бойцов выводится из конфига: текст, написанный
// руками в JSX, расходится с числом при первой же правке баланса, и игрок
// учится неправде.
import type { Letter, LetterKindId, Loot } from '../types';

/**
 * Правило длинных имён — одно на все письма, и вот оно.
 *
 * **Имя поселения стоит только там, где строка переносится.** Тело письма,
 * строка молчания и подпись «от кого» — это абзацы: они растут вниз, и им
 * всё равно, что имя пришло из данных и длину его никто не обещал. Подпись
 * выбора — не абзац: она стоит на кнопке рядом с её названием, и лишний
 * десяток букв там не переносится, а обрезается на полуслове. Игрок при этом
 * не понимает, что подписывает, — а это хуже короткой фразы.
 *
 * Отсюда запрет: **в `yesHint` и `noHint` имени нет никогда** — ни отправителя,
 * ни третьего двора. Сосед в них называется «оттуда», «зовущие», «там». Кто
 * это — сказано выше, в подписи «от кого», где имя стоит ровно один раз на
 * письмо и где рядом с ним стоит лупа.
 *
 * Держит это тест: он подставляет самое длинное имя, какое вообще может
 * сгенерироваться, и требует, чтобы в подписях выбора его не было.
 */

export interface LetterKindDef {
  id: LetterKindId;
  title: string;
  icon: string;
  /**
   * Тело письма. Числа берутся из самого письма, а не из таблицы. `home` — имя своего
   * города (`LocalWorld.homeName`): тело переносится, и имя любой длины в нём уместно.
   */
  body: (l: Letter, goods: string, home: string) => string;
  /** Подпись согласия. Пусто — у письма нет выбора (предупреждение). */
  yes: string | null;
  no: string | null;
  /** Что даст согласие и что даст отказ — теми же словами, что и летопись. */
  yesHint: (l: Letter, goods: string) => string;
  noHint: (l: Letter) => string;
  /** Что будет, если промолчать. */
  silence: (l: Letter) => string;
}

