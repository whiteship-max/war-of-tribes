// Кто приходит к воротам по событиям племени и как о нём говорит отчёт (docs/battle_eu4.md, 14.28).
//
// Своих чисел здесь нет: сколько их и какой силы, решает племя (доля обороны, `data/events`), какого рода — мир при бое
// (`LocalWorld.gateFight`: волки — лёгкая конница без снаряжения, разбойники — отряд тем же генератором, что набег
// логова). Здесь только слова и то, чем звери отличаются от людей.
import type { GateFoe } from '../types';

export interface GateFoeDef {
  /** Как зовут пришедших в отчёте. */
  name: string;
  /**
   * Звери, а не люди: видов племени у них нет — ролику рисовать их нечем (`BattleRecord.beasts`), — и склада они не
   * уносят: поражение от них стоит павших и морали (слово владельца по 14.28, пункт 3).
   */
  beasts: boolean;
  /** Заголовок отчёта, когда их отбили. */
  repelled: string;
  /** Заголовок отчёта, когда они взяли верх. */
  broke: string;
  /** Донесение голосом гонца (docs/voice.md, 1), когда их отбили. */
  held: string;
  /** Донесение голосом гонца, когда они взяли верх. */
  lost: string;
}

