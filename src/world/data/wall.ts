import { BREACH_MAX } from './siegeroll';

/**
 * Стена в гранях кости нападающего (docs/siege_v2.md, 4.1 и 17.1; поправка владельца по итогам 2в). Два числа:
 *
 * - **`WALL_FACES`** — оборона стены: защитники держат линию стены в каждом проёме — в проломе (завал), в воротах, на мосту
 *   башни. Выведено из цели владельца «через три пролома штурм берёт половину боёв при перевесе ×1.3 против поля»;
 * - **`LADDER_FACES`** — сверх неё тем, кто лезет по лестницам. Выведено из цели «с ходу, по лестницам на себе, — половину
 *   боёв при перевесе ×2 против поля».
 *
 * Вывод — `npm run siege:report`, раздел «сила стены»: бисекция по граням на тех же замороженных осадах, что «способы
 * штурма»; «поле» — тот же бой без стены. Пока стена была горами EU4 (−2 только лестницам), она стоила обороне 7–10 % силы.
 * Выведено на W 128 (2д): 9.6 и 10.1. На W 90 (полная приёмка осады, docs/siege_v2.md, 19.4): оборона — 9.7 (в допуске, не
 * переписана), лестницы — 7.4: узкий фронт сам держит штурм с ходу, и при 10.1 с ходу брали половину боёв лишь при ×2.43 поля.
 * На W 96 (`siege:report` на `f7a70e0`): оборона — 9.9 (при 9.6 три пролома ×1.28 поля), лестницы — 7.3. На W 94 (полная
 * приёмка на `6fddeaa`): оборона — 9.2 при 9.9 записанных, лестницы — 7.4 (в допуске). Оборона качается 9.2 ↔ 9.9 (и 9.7 на
 * W 90) — полусумма 9.55, записано 9.6 (правило 16; docs/siege_v2.md, 19.5). Грань здесь — слабый рычаг: 0.7 грани — 2–3 %
 * ровного штурма, в пределах мерки на восьми осадах. После ОС-1 осады стенда — сильным лагерем (×1.5 гарнизона, ровный
 * штурм поля ×1.01 лагеря; docs/siege_v2.md, 23.14): на W 102 оборона — 10.4, лестницы — 7.9, вместе с `CAMP_WASTE` 0.021;
 * второй прогон сошёлся — с ходу ×2.00 поля, три пролома ×1.31.
 */
export const WALL_FACES = 8.2;
export const LADDER_FACES = 6.1;

/**
 * Цели владельца, из которых выведены грани (docs/siege_v2.md, 17.1): ровный штурм — перевес над лагерем, при котором
 * штурм берёт половину боёв, — в долях того же боя без стены. Через три пролома — ×1.3, с ходу по лестницам — ×2.
 */
export const WALL_TARGET_BREACHED = 1.3;
export const WALL_TARGET_SCALING = 2;

/** Грани стены, которыми считают фронт: числа игры или пробные — у раздела отчёта, который их выводит. */
export interface WallFaces {
  wall: number;
  ladder: number;
}
export const WALL: WallFaces = { wall: WALL_FACES, ladder: LADDER_FACES };

/**
 * Доля фронта, которую открывает один проём, — треть: фронт ядра — три полосы (`battle.FRONT`), и проём — полоса.
 *
 * - **пролом** — треть стены (`BREACH_MAX` проломов — вся стена), как и было со 2б (`siegecraft.breachOf`);
 * - **ворота** стоят в средней полосе (ролик ставит надвратную напротив середины строя, `render/tw/plan`): выбитые тараном,
 *   они отдают полосу ворот;
 * - **осадная башня** — пролёт стены в полосу: к ней приставляют одну башню, и с её моста через парапет идут, как через
 *   пролом;
 * - **лестницы с ходу** — их несли на себе, и хватает на одну полосу из трёх (docs/siege_v2.md, 1.3: «лестниц принесли
 *   на треть стены»).
 *
 * Своего числа ни у кого нет: доля — полоса ядра, как у пролома.
 */
export const LANE_SHARE = 1 / 3;
export const BREACH_SHARE = LANE_SHARE;
export const GATE_SHARE = LANE_SHARE;
export const TOWER_SHARE = LANE_SHARE;
export const SCALING_SHARE = LANE_SHARE;

/** Проломов до трёх: три пролома — вся стена без защитников и без штрафа. */
export const WALL_BREACHES = BREACH_MAX;

