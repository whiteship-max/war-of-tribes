// Четыре фигуры на карте — по одной каждой. Не отряды и не юниты: фигура одна,
// её нельзя размножить. Человек в ней смертен — гибнет на деле и уходит на покой, — а
// место остаётся: нового нанимают в здании (docs/AGENT_LIFE.md).
//
// Разница между ними — в трёх числах и в том, что они умеют у чужого поселения.
// Разведчик открывает карту, дипломат даёт отношения, полководец водит армию,
// лазутчик работает у чужих ворот и один держит живой обзор вдали от дома.
// Складывать эти умения в одну фигуру нельзя: тогда исчезнет выбор, кого послать.
//
// Список закрыт, но не заперт: новая фигура дописывается сюда целиком — со
// скоростью, обзором и умением, — и обязана получить свой силуэт на карте
// (`ui/map/agent.ts`), иначе её не отличить от соседа. Это тест, а не пожелание.
import type { DealId, FigureId } from '../types';

export interface FigureDef {
  id: FigureId;
  name: string;
  /** Имя в винительном падеже: «отправить разведчика». */
  one: string;
  icon: string;
  description: string;
  /** Клеток в минуту по равнине — той же меркой, что и юниты (`data/units.ts`). */
  speed: number;
  /** Радиус обзора в клетках: и открывает местность, и держит живые данные. */
  sight: number;
  /** Что фигура делает, стоя у чужого поселения. */
  ability: string;
}

