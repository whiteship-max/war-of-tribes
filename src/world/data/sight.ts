// Вывод — `npm run roam:report`, раздел «Доля обнаружений по видам лагеря»: из целей обнаружения ГДД 3.5.4 («скрытый лагерь в лесу
// круг замка видит не дальше 6 клеток» и остальные — по строке на число) неподвижной точкой, пока выведенное не сойдётся с
// записанным. Руками числа не правят: тест прибора («записано = выведено») сверяет таблицу с выводом из целей, и правка цели без
// нового вывода роняет его. Сменить цель — одной строкой ГДД и одной строкой целей прибора (`SIGHT_GOALS`), потом перенести сюда,
// что напечатал раздел.
//
// Множитель сезона (зимой снег выдаёт следы) лежит не здесь, а в таблице сезонов — `SEASON_MODIFIERS.camouflage` (правило проекта:
// сезон меняет баланс только через неё); выводится тем же разделом.
//
// Без импортов значений: модуль собирают и сервер, и прибор.
import type { Terrain } from '../types';
import type { Gait } from './gait';
import type { CampKind } from '../roammove';

export interface SightTable {
  /** Местность клетки, где стоит или идёт отряд. Вода — для полноты: в воде отряд не стоит. */
  ground: Readonly<Record<Terrain, number>>;
  /** Вид лагеря; в руинах — вместо местности, пока отряд помещается (`RUIN_CAP`). Стоит без лагеря — как открытый. */
  camp: Readonly<Record<CampKind, number>>;
  /** Колонна в пути. */
  march: number;
  /** Режим марша в пути: налегке — тише, с обозом — громче. Стоящему — единица. */
  gait: Readonly<Record<Gait, number>>;
  /** Размер: `(люди / per) ^ pow`, не ниже `floor`. */
  size: Readonly<{ per: number; pow: number; floor: number }>;
  /** Ночь. */
  night: number;
  /** Радиус обзора стоящего отряда бродяги и дружины в поле, клеток. */
  band: number;
}

