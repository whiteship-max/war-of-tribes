// Обстрел машинами по фазам — числа дизайна в одном месте (Р-5, docs/siege_v2.md, 21.1). Считает всё одна дверь —
// `world/shelling.ts`, её зовёт кость фаз (`siegeroll.rollPhase`) у мира на клиенте и у сервера войны. Без `@/`: файл
// собирает сервер. Веса машин — `data/machines.ARTILLERY_WEIGHT`.
import { MACHINE_CAMP_WOOD, CAMP_WORKS_RIPE } from './tuning';
import { MACHINE_WOOD } from './machines';

/**
 * Цель артиллерии лагеря на фазу (выбирает осаждающий в окне лагеря): стены — грани к кости фазы (пролом и сдача), город —
 * постройки, машины — требушет на стене. Нет приказа — стены: так было до Р-5, камнемёт бил по кости.
 */
export type Aim = 'wall' | 'town' | 'engines';
export const AIMS: readonly Aim[] = ['wall', 'town', 'engines'];

/** Цель требушета на стене (выбирает осаждённый): лагерь — люди, машины — самая дорогая машина у стены. Нет — лагерь. */
export type GunAim = 'camp' | 'machines';
export const GUN_AIMS: readonly GunAim[] = ['camp', 'machines'];

/**
 * Попадание выстрела — верхняя половина той же кости фаз (d14, `SIEGE_DIE`): 8–14, каждый второй. Выведено: у выстрела нет
 * поправок (их несёт бросок фазы), и половина — граница, у которой одна машина за осаду до голода (пять фаз) попадает
 * два-три раза: заметно, но не решает осаду одна.
 */
export const SHOT_HIT = 8;

/**
 * Каждое второе попадание в одну постройку за осаду — −1 уровень, не ниже первого (как пожар у Жилищ, `data/events`);
 * каждое попадание — фаза без работы (её работники не дают ничего, пока не брошена следующая фаза).
 */
export const HITS_PER_LEVEL = 2;
export const BUILDING_FLOOR = 1;

/** Требушет на стене (Р-5): та же машина, что у лагеря, — вес и выстрелы требушета (`ARTILLERY_WEIGHT.trebuchet`). */
export const GUN_ID = 'trebuchet' as const;

/**
 * Сколько строится требушет на стене — столько же, сколько у лагеря, отдающего ему весь лес (½ стороны при выработке
 * лагеря бота, `MACHINE_CAMP_WOOD` за `CAMP_WORKS_RIPE`): плотники города рубят не быстрее плотников лагеря. Мс.
 */
export const GUN_SPAN = (MACHINE_WOOD[GUN_ID] / MACHINE_CAMP_WOOD) * CAMP_WORKS_RIPE;

/** Требушетов на стене сразу — один, как машин одного рода у лагеря (`MACHINE_HOLD`): строят под осаду, а не впрок. */
export const GUN_HOLD = 1;
