// Осада: одно окно на поселении, всё остальное — производные при чтении.
//
// Модуль чистый, как `spy.ts` и `letters.ts`: ни состояния мира, ни часов, ни
// `Math.random`. И правило второго порядка то же — **считаем при чтении, не
// тикаем**. Осада хранится одним окном, а срезанный приток, оставшееся время и
// сам момент падения выводятся из него в момент вопроса. Отсюда главное
// свойство: тот же сейв и то же прошедшее время дают то же состояние, и офлайн
// даёт ровно то, что дала бы непрерывная игра.
//
// Фоновой работы за осадой нет и заводить её нельзя. Стоит завести тик — и
// придётся отвечать на вопрос, что делать с часами, пока игрок спал.
import type { Fate, SettlementId } from './types';
import type { WoodPlan } from './works';
import { SIEGE_EAT_FLOOR, SIEGE_IMMUNE, SIEGE_TOWN_EAT, SIEGE_TOWN_LARDER } from './data/tuning';

/** Час в миллисекундах: расход еды считается в час, окно живёт в мс. */
const HOUR = 3_600_000;

/**
 * Окно осады. Всё, что здесь лежит, заморожено в момент, когда окно открылось:
 * ни одно поле не двигается само.
 *
 * Почему заморожено, а не пересчитывается: пересчёт на каждое изменение
 * гарнизона и есть тик, а тик здесь запрещён. Гарнизон меняется по событиям
 * (подкрепление дошло, вылазка вышла) — вот в этих событиях окно и открывается
 * заново, от остатка еды на тот момент. Один пересчёт на одно событие, и
 * больше ни одного.
 */
export interface SiegeWindow {
  /** Кто осадил: двор, из которого вышел отряд, или `HOME_ID` — если это мы. */
  byId: SettlementId;
  /**
   * Лагерь осаждающего на карте: номер марша у чужой осады, `PLAYER_CAMP` — у
   * нашей. Он же и признак стороны (`ourCamp`): второго поля «чей лагерь» в
   * окне нет, оно разошлось бы с этим при первой же правке.
   */
  campId: string;
  /** Когда окно открылось, мс. */
  startedAt: number;
  /** Сколько еды лежало на складе в этот момент. */
  foodAtStart: number;
  /** Сколько бойцов было в гарнизоне в этот момент. */
  garrisonAtStart: number;
  /**
   * Что съедает сам город за час — без дружины. Приезжает из племени как доля
   * его обычного дневного расхода (`foodConsumptionPerDay` минус бойцы),
   * приведённая к часу: осадного пайка мы не заводим, второй правды о том,
   * сколько ест деревня, быть не должно.
   */
  townPerHour: number;
  /** Что добавляет к часовому расходу один боец гарнизона (`SOLDIER_FOOD`). */
  perManPerHour: number;
  /**
   * Когда лагерь встал под стенами. Не то же, что `startedAt`: часы голода
   * пересчитываются от остатка еды и новой отметки времени, а осада при этом
   * идёт всё та же — и события, назначенные от её начала (вылазка осаждённого,
   * выручка соседей), не должны от пересчёта уезжать.
   *
   * Поля может не быть у окна из старого сохранения — тогда началом считается
   * `startedAt`, и это ровно то, чем оно и было до появления событий.
   */
  sinceAt?: number;
  /** Осаждённый уже решал, выходить ли на вылазку. Событие одно на осаду. */
  sortied?: boolean;
  /** Соседи уже решали, идти ли на выручку. Событие одно на осаду. */
  relieved?: boolean;
  /**
   * До какой минуты занят проход через рогатки **фронта** — стороны лагеря,
   * обращённой к городу. Пишет его только бой у лагеря — в самом событии, как
   * пересчёт часов голода; свободная доля прохода выводится из него при чтении, и
   * тика за ним нет. Через фронт лезут вылазка и выручка соседей, а при совместном
   * ударе — гарнизон.
   *
   * Живёт в окне, а не рядом: снята осада — окно удалено, и проход новой осады
   * начинается свободным. Поля нет у окна из старого сохранения и у окна, по
   * лагерю которого ещё не били, — тогда проход свободен. У окна из сохранения до
   * сторон отметка одна и читается фронтом: тыл такого окна свободен. Часов голода
   * оно не касается никак.
   */
  gateAt?: number;
  /**
   * До какой минуты занят проход через рогатки **тыла** — стороны, обращённой в
   * поле. Через тыл бьёт полководец. Своя отметка, а не общая с фронтом: кто лезет
   * с одной стороны, другую не занимает. Всё остальное — как у `gateAt`.
   */
  rearGateAt?: number;
  /**
   * Какую участь осаждающий объявил приказом «Осадить». Лежит в окне, а не в
   * приказе: город падает в минуту голода, часто без осаждающего в игре, и падение
   * читает участь отсюда. Осаждённый видит её с первой минуты. Нет поля — «ограбить»:
   * так садится лагерь бота и так читается окно из сохранения до лестницы.
   */
  fate?: Fate;
  /**
   * Древесина лагеря: доли сторон и то, что вложено к последней смене долей
   * (`world/works.WoodPlan`). Делит их только лагерь игрока, в окне осады; нет поля —
   * лагерь рубит по правилу бота (`CAMP_WOOD`).
   */
  wood?: WoodPlan;
}

/** Когда осада началась. Пересчёт часов голода эту отметку не двигает. */
export const siegeSince = (w: SiegeWindow): number => w.sinceAt ?? w.startedAt;

/**
 * Расход еды за час осады. Это и есть `f(гарнизон)`, обещанная моделью: город
 * ест сам по себе, а каждый боец добавляет сверху.
 *
 * Отсюда следствие, ради которого всё и заведено: большой гарнизон выигрывает
 * бой, но проедает город быстрее. Приведёшь дружину домой — стены будут держать
 * дольше, а еда кончится раньше.
 */
export const consumptionPerHour = (w: SiegeWindow): number =>
  Math.max(SIEGE_EAT_FLOOR, w.townPerHour + Math.max(0, w.garrisonAtStart) * w.perManPerHour);

/**
 * Когда кончится еда. Чистая функция от окна и только от него: ни часов, ни
 * состояния мира. Одинаковый вход — одинаковый выход, и сервер потом получит
 * то же число из тех же полей.
 */
export const starvesAt = (w: SiegeWindow): number =>
  w.startedAt + (Math.max(0, w.foodAtStart) / consumptionPerHour(w)) * HOUR;

/** Осада идёт прямо сейчас? Считается при чтении, а не отмечается тиком. */
export const siegeActive = (w: SiegeWindow | undefined, now: number): boolean =>
  Boolean(w && now < starvesAt(w));

/**
 * Новое окно. Единственный способ его завести — и он же единственный способ
 * пересчитать: пересчёт это то же открытие, только с новой отметкой времени и
 * от остатка еды на неё.
 */
export function openSiege(at: {
  byId: SettlementId;
  campId: string;
  now: number;
  food: number;
  garrison: number;
  townPerHour: number;
  perManPerHour: number;
  /** Когда осада началась. Пусто — она начинается прямо сейчас. */
  since?: number;
  /** Что переносится из прежнего окна при пересчёте: события одноразовые. */
  sortied?: boolean;
  relieved?: boolean;
  /** Занятость проходов той же осады: переносится при пересчёте, а не при новой. */
  gateAt?: number;
  rearGateAt?: number;
  /** Объявленная участь и доли древесины: у той же осады переносятся при пересчёте. */
  fate?: Fate;
  wood?: WoodPlan;
}): SiegeWindow {
  return {
    byId: at.byId,
    campId: at.campId,
    startedAt: at.now,
    sinceAt: at.since ?? at.now,
    sortied: at.sortied,
    relieved: at.relieved,
    ...(at.gateAt !== undefined ? { gateAt: at.gateAt } : {}),
    ...(at.rearGateAt !== undefined ? { rearGateAt: at.rearGateAt } : {}),
    ...(at.fate !== undefined ? { fate: at.fate } : {}),
    ...(at.wood !== undefined ? { wood: at.wood } : {}),
    foodAtStart: Math.max(0, at.food),
    garrisonAtStart: Math.max(0, Math.round(at.garrison)),
    townPerHour: Math.max(0, at.townPerHour),
    perManPerHour: Math.max(0, at.perManPerHour),
  };
}

/** До какого момента павший город нельзя осадить снова. */
export const immuneUntil = (fellAt: number): number => fellAt + SIEGE_IMMUNE;

/**
 * Окно неприкосновенности ещё держится? Оно закрывает от **осады**, а не от
 * набега: набег после падения — обычное давление, и отбиваться от него игроку
 * есть чем. Запрещена именно цепочка осад, потому что вторая осада пустого
 * амбара кончилась бы тем же, чем первая, не дав между ними ни одного решения.
 */
export const siegeImmune = (until: number | undefined, now: number): boolean =>
  now < (until ?? 0);

/**
 * Отказ на выход из осаждённого города — одной строкой и в одном месте.
 *
 * Точек, откуда войска могут выйти, несколько — гонец с отрядом, любая фигура,
 * дружина при полководце, приказ на перехват, — а причина у отказа одна. Разведи
 * слова по этим точкам, и они разъедутся при первой же правке; хуже того,
 * пропущенная точка станет приказом, который молча ничего не делает, а это хуже
 * отказа.
 */
export const SIEGE_BLOCK = 'Выйти нельзя — город в осаде. Доступна вылазка.';

/**
 * Лагерь игрока. У чужой осады под стенами стоит отряд, и `campId` — номер его
 * марша; у нашей под стенами стоит полководец, и марша за ним нет. Имя лагеря
 * поэтому одно и постоянное: фигура в мире одна, второго полководца не бывает.
 *
 * Это же и признак стороны: `campId === PLAYER_CAMP` читается как «лагерь наш»,
 * и второго поля «чей лагерь» в окне нет — оно разошлось бы с этим при первой
 * же правке.
 */
export const PLAYER_CAMP = 'general';

/** Наш ли это лагерь. Единственный способ спросить: поле «чей» не заводить. */
export const ourCamp = (w: SiegeWindow): boolean => w.campId === PLAYER_CAMP;

/**
 * Амбар и рты чужого города. Своих чисел о еде у мира нет: он знает про
 * поселение население и мощь, а не хлеб и пайки, — поэтому и то и другое
 * выводится из населения и гарнизона той же формой, что у деревни игрока
 * (`townPerHour` плюс `perManPerHour` на бойца). Второй арифметики осады из
 * этого не появляется: считает всё та же `starvesAt`, меняются только два
 * числа на входе.
 *
 * Пропорция взята на душу нарочно: тогда чужой город держится примерно
 * одинаковое время независимо от размера, а разницу делает гарнизон — ровно тот
 * же размен, что и у игрока. Большой гарнизон не даёт взять город приступом и
 * проедает его быстрее.
 */
export const townLarder = (pop: number): number => Math.max(1, pop) * SIEGE_TOWN_LARDER;
export const townEatPerHour = (pop: number): number => Math.max(1, pop) * SIEGE_TOWN_EAT;

/**
 * Отказ полководцу, занятому осадой. Причина одна, и текст к ней один: пока
 * лагерь стоит, эта армия занята. Увести её можно — но это и есть снятие
 * осады, и сказано об этом должно быть до приказа, а не после.
 */
export const CAMP_BUSY = 'Полководец держит осаду: пока лагерь стоит, других дел у него нет.';

/**
 * Отказ полководцу, который в городе. Не проверка приказа, а следствие учёта
 * (`world/muster`): дома дружина — часть гарнизона, в поле её нет, и бить из поля
 * некому. Её путь за ворота — вылазка.
 */
export const STRIKE_FROM_TOWN = 'Полководец в городе: его дружина — часть гарнизона, и за ворота она выходит вылазкой.';

/** Что случится, если увести полководца из лагеря. Одна строка на все точки. */
export const CAMP_LEAVE = 'Уведёшь полководца — осада снята, и город снова ест.';

/**
 * Что случится, если из лагеря пойти на приступ. Штурм — это бой с гарнизоном, а
 * не продолжение осады: лагерь снимается до боя, и сказано это до приказа.
 */
export const STORM_LIFTS = 'Штурм снимает осаду: возьмёшь город — будет объявленная участь, отобьют — лагеря больше нет.';
