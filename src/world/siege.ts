// Осада: одно окно на поселении, всё остальное — производные при чтении.
//
// Модуль чистый, как `spy.ts` и `letters.ts`: ни состояния мира, ни часов, ни
// `Math.random`. И правило второго порядка то же — **считаем при чтении, не
// тикаем**. Осада хранится одним окном, а срезанный приток, оставшееся время и
// сам момент падения выводятся из него в момент вопроса. Отсюда главное
// свойство: тот же сейв и то же прошедшее время дают то же состояние, и офлайн
// даёт ровно то, что дала бы непрерывная игра.
//
// Фоновой работы за осадой нет и заводить её нельзя. Стоит завести тик — и
// придётся отвечать на вопрос, что делать с часами, пока игрок спал.
import type { Fate, SettlementId } from './types';
import type { WoodPlan } from './works';
import type { Fire } from './bombard';
import type { Craft } from './siegecraft';
import type { DefendOrders, PhaseRow, SiegeDeed, SiegeOrders } from './siegeroll';
import type { MachineOrder } from './machines';
import type { SiegeOffer } from './parley';
import { SIEGE_EAT_FLOOR, SIEGE_IMMUNE, SIEGE_TOWN_EAT, SIEGE_TOWN_LARDER, SIEGE_WEAR_FLOOR } from './data/tuning';
import { HOUR_MS as HOUR } from '../game/time';
import { SIEGE_RATION } from '../game/constants';
import { yieldShare } from './siegefood';
import { CUT_MAX } from './data/siegefood';

/**
 * Окно осады. Всё, что здесь лежит, заморожено в момент, когда окно открылось:
 * ни одно поле не двигается само.
 *
 * Почему заморожено, а не пересчитывается: пересчёт на каждое изменение
 * гарнизона и есть тик, а тик здесь запрещён. Гарнизон меняется по событиям
 * (подкрепление дошло, вылазка вышла) — вот в этих событиях окно и открывается
 * заново, от остатка еды на тот момент. Один пересчёт на одно событие, и
 * больше ни одного.
 */
export interface SiegeWindow {
  /** Кто осадил: двор, из которого вышел отряд, или `HOME_ID` — если это мы. */
  byId: SettlementId;
  /**
   * Лагерь осаждающего на карте: номер марша у чужой осады, `PLAYER_CAMP` — у
   * нашей. Он же и признак стороны (`ourCamp`): второго поля «чей лагерь» в
   * окне нет, оно разошлось бы с этим при первой же правке.
   */
  campId: string;
  /** Когда окно открылось, мс. */
  startedAt: number;
  /** Сколько еды лежало на складе в этот момент. */
  foodAtStart: number;
  /** Сколько бойцов было в гарнизоне в этот момент. */
  garrisonAtStart: number;
  /**
   * Что съедает сам город за час — без дружины. Приезжает из племени как доля
   * его обычного дневного расхода (`foodConsumptionPerDay` минус бойцы),
   * приведённая к часу: осадного пайка мы не заводим, второй правды о том,
   * сколько ест деревня, быть не должно.
   */
  townPerHour: number;
  /** Что добавляет к часовому расходу один боец гарнизона (`SOLDIER_FOOD`; у города игрока — осадным пайком, ОС-1). */
  perManPerHour: number;
  /**
   * Валовая добыча хлеба города за час без штрафа осады (ОС-1, docs/siege_v2.md, 23) и штраф к ней по соотношению сил в
   * минуту, когда окно открылось (`siegefood.siegeCut`). Заморожены, как расход: соотношение меняется событием (фаза, бой,
   * смена гарнизона), и окно открывается заново. Нет полей — города без добычи (логово, двор мира) и окна до ОС-1: хлеб только
   * убывает.
   */
  yieldPerHour?: number;
  cut?: number;
  /**
   * Хлеб в минуту, когда встал лагерь, — мера доли хлеба для поправки «голод» кости фаз (`siegeroll.breadLeft`). Пересчёт
   * часов голода его не двигает. Нет поля — окно до ОС-1: мерой служит хлеб этого окна.
   */
  breadAtSince?: number;
  /**
   * Когда лагерь встал под стенами. Не то же, что `startedAt`: часы голода
   * пересчитываются от остатка еды и новой отметки времени, а осада при этом
   * идёт всё та же — и события, назначенные от её начала (вылазка осаждённого,
   * выручка соседей), не должны от пересчёта уезжать.
   *
   * Поля может не быть у окна из старого сохранения — тогда началом считается
   * `startedAt`, и это ровно то, чем оно и было до появления событий.
   */
  sinceAt?: number;
  /** Осаждённый уже решал, выходить ли на вылазку. Событие одно на осаду. */
  sortied?: boolean;
  /** Соседи уже решали, идти ли на выручку. Событие одно на осаду. */
  relieved?: boolean;
  /**
   * До какой минуты занят проход через рогатки **фронта** — стороны лагеря,
   * обращённой к городу. Пишет его только бой у лагеря — в самом событии, как
   * пересчёт часов голода; свободная доля прохода выводится из него при чтении, и
   * тика за ним нет. Через фронт лезут вылазка и выручка соседей, а при совместном
   * ударе — гарнизон.
   *
   * Живёт в окне, а не рядом: снята осада — окно удалено, и проход новой осады
   * начинается свободным. Поля нет у окна из старого сохранения и у окна, по
   * лагерю которого ещё не били, — тогда проход свободен. У окна из сохранения до
   * сторон отметка одна и читается фронтом: тыл такого окна свободен. Часов голода
   * оно не касается никак.
   */
  gateAt?: number;
  /**
   * До какой минуты занят проход через рогатки **тыла** — стороны, обращённой в
   * поле. Через тыл бьёт полководец. Своя отметка, а не общая с фронтом: кто лезет
   * с одной стороны, другую не занимает. Всё остальное — как у `gateAt`.
   */
  rearGateAt?: number;
  /**
   * Какую участь осаждающий объявил приказом «Осадить». Лежит в окне, а не в
   * приказе: город падает в минуту голода, часто без осаждающего в игре, и падение
   * читает участь отсюда. Осаждённый видит её с первой минуты. Нет поля — «ограбить»:
   * так садится лагерь бота и так читается окно из сохранения до лестницы.
   */
  fate?: Fate;
  /**
   * Древесина лагеря: доли сторон и то, что вложено к последней смене долей
   * (`world/works.WoodPlan`). Делит их только лагерь игрока, в окне осады; нет поля —
   * лагерь рубит по правилу бота (`CAMP_WOOD`).
   */
  wood?: WoodPlan;
  /**
   * Сколько бойцов строя ставили рогатки — люди лагеря в минуту, когда он встал. Рогатки
   * держат те, кто их строил (`world/works.campPass`): убыль лагеря после этого проход не
   * сужает. Пишется при открытии новой осады и переносится при пересчёте часов голода.
   * Нет поля у окна из сохранения до этого правила — тогда строившими считаются те, кто
   * стоит в лагере на минуту вопроса: другого числа у такого окна нет.
   */
  builders?: number;
  /**
   * Обстрел лагеря с башни осаждённого города (`world/bombard`): сила и что выбито к
   * минуте, когда она сменилась. Нет поля — башня не била. Переносится при пересчёте
   * часов голода той же осады.
   */
  fire?: Fire;
  /**
   * Дела полководца в своём лагере (`world/siegecraft`): сколько раз лагерь укрепили и сколько залпов дал обстрел. Нет поля —
   * ничего не делали. Переносится при пересчёте часов голода той же осады; у новой осады его нет.
   */
  craft?: Craft;
  /**
   * Уровень частокола осаждённого города в минуту, когда встал лагерь (`siegeroll.wallFaces`: −1 к кости фазы за каждые
   * два уровня). Нет поля — стены нет: логово, двор мира, окно из сохранения до фаз.
   */
  wall?: number;
  /**
   * Дни пути лагеря от своего дома — города игрока или логова отряда, игровые (`siegeroll.wasteOf`: истощение растёт с
   * дальностью). Заморожено при постановке; нет поля — ноль.
   */
  homeDays?: number;
  /**
   * Режим марша лагеря при постановке (ДР-2, `world/gait`): с обозом — лагерь без подвоза из дома (`siegeroll.wasteOf`).
   * Налегке лагерь не встаёт. Нет поля — обычный, как до ДР-2.
   */
  gait?: 'train';
  /**
   * Журнал дел с минутой — входы фазы, которые должны быть известны задним числом (docs/siege_v2.md, 2.1): залп ложится
   * сюда, и кость его фазы читает его отсюда. Нет поля — окно из сохранения до фаз: его прежние залпы переводятся в
   * проломы (`siegeroll.breachesOf`).
   */
  log?: SiegeDeed[];
  /** Брошенные фазы — журнал фаз (`siegeroll.PhaseRow`). Нет поля — ни одной. */
  phases?: PhaseRow[];
  /** Наказы осаждающего на отлучку (`siegeroll.SiegeOrders`). Нет поля — наказов нет. */
  orders?: SiegeOrders;
  /**
   * Осадные машины лагеря — очередь заказов (`world/machines`): что, когда заказано и когда истрачено на штурм. Древесину
   * им даёт план древесины (`wood.machines`). Нет поля — машин не заказывали.
   */
  machines?: MachineOrder[];
  /**
   * Осадный паёк осаждённого (docs/siege_v2.md, раздел 5): с минуты `startedAt` этого окна город ест ×¾ (`SIEGE_RATION`).
   * Урезать и вернуть паёк — пересчёт часов голода от остатка хлеба, как смена гарнизона. Нет поля — паёк обычный.
   */
  ration?: boolean;
  /** Наказы осаждённого на отлучку (`siegeroll.DefendOrders`): чинить пролом, урезать паёк. Нет поля — наказов нет. */
  defend?: DefendOrders;
  /**
   * Отметки «осада» того, кто ведёт лагерь (`siegeroll.leadFaces`: +1 к кости фазы за каждую, до трёх; docs/siege_v2.md,
   * 2.3, этап 2е) — заморожены при постановке. Нет поля — ноль: у логова и двора мира полководца нет.
   */
  lead?: number;
  /**
   * Переговоры у стен (`world/parley`, docs/siege_v2.md, раздел 7): предложения сторон — сдача на условиях и дань — и ответ
   * на них. Нет поля — никто ничего не предлагал. Переносится при пересчёте часов голода той же осады.
   */
  offers?: SiegeOffer[];
  /**
   * Требушет на стене осаждённого (Р-5, docs/siege_v2.md, 21.1; `world/shelling`) — очередь заказов, как машины лагеря:
   * когда заказан, когда разбит. Нет поля — не ставили. Переносится при пересчёте часов голода.
   */
  guns?: MachineOrder[];
  /**
   * Постройки осаждённого города, по которым бьёт артиллерия лагеря с целью «город» (Р-5, `world/shelling`) — заморожены при
   * постановке лагеря. Нет поля — построек нет: логово, двор мира, окно до Р-5.
   */
  targets?: string[];
}

/** Когда осада началась. Пересчёт часов голода эту отметку не двигает. */
export const siegeSince = (w: SiegeWindow): number => w.sinceAt ?? w.startedAt;

/**
 * Расход еды за час осады. Это и есть `f(гарнизон)`, обещанная моделью: город
 * ест сам по себе, а каждый боец добавляет сверху.
 *
 * Отсюда следствие, ради которого всё и заведено: большой гарнизон выигрывает
 * бой, но проедает город быстрее. Приведёшь дружину домой — стены будут держать
 * дольше, а еда кончится раньше.
 */
export const consumptionPerHour = (w: SiegeWindow): number =>
  Math.max(SIEGE_EAT_FLOOR, (w.townPerHour + Math.max(0, w.garrisonAtStart) * w.perManPerHour) * rationShare(w));

/** Добыча хлеба за час под штрафом этого окна (ОС-1): у города без добычи — ноль. */
export const yieldPerHourOf = (w: Pick<SiegeWindow, 'yieldPerHour' | 'cut'>): number =>
  Math.max(0, w.yieldPerHour ?? 0) * yieldShare(w.cut ?? CUT_MAX, true);

/** На сколько хлеба за час убывает склад окна: расход минус добыча под штрафом. Меньше нуля — склад растёт. */
export const netPerHour = (w: SiegeWindow): number => consumptionPerHour(w) - yieldPerHourOf(w);

/** Доля обычного расхода, которую ест город: осадный паёк — ×¾ (`SIEGE_RATION`), без него — единица. Без единиц времени. */
export const rationShare = (w: Pick<SiegeWindow, 'ration'>): number => (w.ration ? SIEGE_RATION : 1);

/**
 * Когда кончится еда. Чистая функция от окна и только от него: ни часов, ни
 * состояния мира. Одинаковый вход — одинаковый выход, и сервер потом получит
 * то же число из тех же полей.
 */
export function starvesAt(w: SiegeWindow): number {
  const net = netPerHour(w);
  return net > 0 ? w.startedAt + (Math.max(0, w.foodAtStart) / net) * HOUR : Infinity;
}

/**
 * Хлеб окна в минуту `at` со знаком: склад + добыча − прокорм от минуты открытия (ОС-1). Ниже нуля — склад окна не оплатил
 * прокорм (`siegefood.starves`): так шаг осады судит город, чей склад — само окно (сервер войны). Округления нет.
 */
export const breadAt = (w: SiegeWindow, at: number): number =>
  w.foodAtStart - (netPerHour(w) * Math.max(0, at - w.startedAt)) / HOUR;

/**
 * Во сколько раз мораль гарнизона в бою ниже от того, что осада идёт с минуты `since`: единица в минуту, когда лагерь
 * встал, дальше прямой до дна (`SIEGE_WEAR_FLOOR`) за `span` — срок голода окна (`wearSpan`; docs/siege_v2.md, 2.6: к
 * голоду гарнизон на дне). Одна дверь на осаду логова (`LocalWorld.garrisonRest`) и на осаду игроком
 * (`netlify/lib/war.ts`). Тика нет — считается при чтении.
 */
export const siegeWear = (since: number, at: number, span: number): number =>
  1 - (1 - SIEGE_WEAR_FLOOR) * Math.min(1, Math.max(0, at - since) / Math.max(1, span));

/**
 * Сколько хлеба осталось у осаждённого к минуте `at` — от окна, той же арифметикой, что часы голода. **Хлеб осаждённого
 * города — хлеб окна** (docs/siege_v2.md, 21.1): падение, дань и цена дани в минуту осады берут хлеба не больше этого, а
 * племя под осадой не держит на складе больше (`bridge.syncSiege`). Голод — ноль: съеденного в обоз не положить.
 */
export const foodLeft = (w: SiegeWindow, at: number): number => Math.max(0, breadAt(w, at));

/** Склад осаждённого с хлебом не больше остатка окна `bread` (`foodLeft`): прочее добро — как есть. */
export function breadStock<T extends Partial<Record<string, number>>>(stock: T, bread: number): T {
  if (!(bread < Infinity)) return stock;
  const left = Math.max(0, Math.floor(bread));
  const food = stock.food ?? 0;
  if (food <= left) return stock;
  const out = { ...stock };
  if (left > 0) (out as Record<string, number>).food = left;
  else delete (out as Record<string, number>).food;
  return out;
}

/**
 * Когда кончится хлеб, если с минуты `at` паёк станет `on` (docs/siege_v2.md, раздел 5): остаток хлеба к этой минуте, расход
 * окна с пайком или без. Та же арифметика, что пересчёт часов голода при приказе, — окно говорит игроку пользу до нажатия.
 */
export function starvesIfRation(w: SiegeWindow, at: number, on: boolean): number {
  const net = netPerHour({ ...w, ration: on });
  return net > 0 ? at + (foodLeft(w, at) / net) * HOUR : Infinity;
}

/** Путь износа гарнизона до дна — от начала осады до голода этого окна, мс (docs/siege_v2.md, 2.6). */
export const wearSpan = (w: SiegeWindow): number => Math.max(1, starvesAt(w) - siegeSince(w));

/** Осада идёт прямо сейчас? Считается при чтении, а не отмечается тиком. */
export const siegeActive = (w: SiegeWindow | undefined, now: number): boolean =>
  Boolean(w && now < starvesAt(w));

/**
 * Новое окно. Единственный способ его завести — и он же единственный способ
 * пересчитать: пересчёт это то же открытие, только с новой отметкой времени и
 * от остатка еды на неё.
 */
export function openSiege(at: {
  byId: SettlementId;
  campId: string;
  now: number;
  food: number;
  garrison: number;
  townPerHour: number;
  perManPerHour: number;
  /** Когда осада началась. Пусто — она начинается прямо сейчас. */
  since?: number;
  /** Что переносится из прежнего окна при пересчёте: события одноразовые. */
  sortied?: boolean;
  relieved?: boolean;
  /** Занятость проходов той же осады: переносится при пересчёте, а не при новой. */
  gateAt?: number;
  rearGateAt?: number;
  /** Объявленная участь и доли древесины: у той же осады переносятся при пересчёте. */
  fate?: Fate;
  wood?: WoodPlan;
  /** Кто ставил рогатки: у новой осады — лагерь в минуту постановки, у той же — переносится. */
  builders?: number;
  /** Обстрел той же осады: переносится при пересчёте. */
  fire?: Fire;
  /** Дела полководца в лагере той же осады: переносятся при пересчёте. */
  craft?: Craft;
  /** Ход осады фазами (`world/siegeroll`): стена, путь от дома, журнал дел и фаз, наказы — переносятся при пересчёте. */
  wall?: number;
  homeDays?: number;
  gait?: 'light' | 'normal' | 'train';
  log?: SiegeDeed[];
  phases?: PhaseRow[];
  orders?: SiegeOrders;
  /** Паёк и наказы осаждённого той же осады: переносятся при пересчёте. */
  ration?: boolean;
  defend?: DefendOrders;
  /** Очередь осадных машин той же осады (`world/machines`): переносится при пересчёте, как журнал дел. */
  machines?: MachineOrder[];
  /** Отметки «осада» полководца лагеря: у новой осады — при постановке, у той же — переносятся. */
  lead?: number;
  /** Переговоры той же осады (`world/parley`): переносятся при пересчёте. */
  offers?: SiegeOffer[];
  /** Требушет на стене и постройки под обстрелом той же осады (Р-5): переносятся при пересчёте. */
  guns?: MachineOrder[];
  targets?: string[];
  /** Добыча хлеба без штрафа и штраф этой минуты (ОС-1); хлеб при постановке — у новой осады свой, у той же переносится. */
  yieldPerHour?: number;
  cut?: number;
  breadAtSince?: number;
}): SiegeWindow {
  return {
    byId: at.byId,
    campId: at.campId,
    startedAt: at.now,
    sinceAt: at.since ?? at.now,
    sortied: at.sortied,
    relieved: at.relieved,
    ...(at.gateAt !== undefined ? { gateAt: at.gateAt } : {}),
    ...(at.rearGateAt !== undefined ? { rearGateAt: at.rearGateAt } : {}),
    ...(at.fate !== undefined ? { fate: at.fate } : {}),
    ...(at.wood !== undefined ? { wood: at.wood } : {}),
    ...(at.builders !== undefined ? { builders: Math.max(0, Math.round(at.builders)) } : {}),
    ...(at.fire !== undefined ? { fire: at.fire } : {}),
    ...(at.craft !== undefined && (at.craft.fort || at.craft.shots) ? { craft: { ...at.craft } } : {}),
    ...(at.wall ? { wall: Math.max(0, Math.floor(at.wall)) } : {}),
    ...(at.homeDays ? { homeDays: Math.max(0, at.homeDays) } : {}),
    ...(at.gait === 'train' ? { gait: 'train' as const } : {}),
    ...(at.log !== undefined ? { log: at.log.map((d) => ({ ...d })) } : {}),
    ...(at.phases?.length ? { phases: at.phases.map((r) => ({ ...r, mods: { ...r.mods }, ...(r.orders ? { orders: [...r.orders] } : {}) })) } : {}),
    ...(at.orders ? { orders: { ...at.orders } } : {}),
    ...(at.ration ? { ration: true } : {}),
    ...(at.defend ? { defend: { ...at.defend } } : {}),
    ...(at.machines?.length ? { machines: at.machines.map((m) => ({ ...m })) } : {}),
    ...(at.lead ? { lead: Math.max(0, Math.floor(at.lead)) } : {}),
    ...(at.offers?.length ? { offers: at.offers.map((o) => ({ ...o })) } : {}),
    ...(at.guns?.length ? { guns: at.guns.map((g) => ({ ...g })) } : {}),
    ...(at.targets?.length ? { targets: [...at.targets] } : {}),
    ...(at.yieldPerHour ? { yieldPerHour: Math.max(0, at.yieldPerHour) } : {}),
    ...(at.cut !== undefined ? { cut: Math.min(1, Math.max(0, at.cut)) } : {}),
    breadAtSince: Math.max(0, at.breadAtSince ?? at.food),
    foodAtStart: Math.max(0, at.food),
    garrisonAtStart: Math.max(0, Math.round(at.garrison)),
    townPerHour: Math.max(0, at.townPerHour),
    perManPerHour: Math.max(0, at.perManPerHour),
  };
}

