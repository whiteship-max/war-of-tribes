// Вера клетки: чем живёт земля под замком.
//
// ЭТО НАША РАЗМЕТКА, А НЕ ИСТОЧНИК. Данных о границах вероисповеданий 1200 года
// с ясной лицензией не существует — ни в Natural Earth, откуда взята земля
// (`atlas/`), ни где-либо ещё, откуда их можно было бы взять и назвать. Всё,
// что ниже, нарисовано нами по школьному представлению об эпохе: прямоугольники
// по долготе и широте (`FAITH_REGIONS`) плюс одна наклонная линия по Тахо.
// Выдавать это за карту исторических конфессий нельзя ни в игре, ни в
// документах, и границы здесь заведомо грубее любой настоящей: Толедо
// оказывается южнее нашей линии Тахо, хотя христиане взяли его за сто лет до
// 1200-го, а волжские булгары попадают в православную Русь. Мерка была одна —
// **узнаваемость**: игрок, поставивший замок под Вильнюсом, должен получить
// язычество, а под Кордовой — ислам.
//
// Три правила, из которых следует всё остальное.
//
// 1. **Вера — чистая функция координат.** Ни сида, ни состояния, ни порядка
//    чтения: карта одна на всех, и вера клетки обязана быть одинаковой у
//    каждого игрока и при любом порядке вопросов. Держит это `faith.test.ts`.
// 2. **Порядок областей — часть разметки.** Совпадений между прямоугольниками
//    много (Сицилия внутри Средиземноморья, Грузия внутри рамки Анатолии), и
//    разбирается это одним способом: список идёт сверху вниз, побеждает первое
//    совпадение. Переставить две строки местами — значит изменить карту.
// 3. **Иудаизма в стартовых верах нет, и это решение, а не забывчивость.**
//    В 1200 году у него нет территории: он живёт общинами в городах, а городов
//    в игре нет вовсе — на карте только земля, логова и замки живых игроков.
//    Вера у нас достаётся вместе с землёй, и приписать целую клетку общине
//    значило бы соврать сильнее, чем промолчать. Появятся города — вернёмся к
//    этому разговору с другой стороны: не как к четвёртой краске на карте, а
//    как к жителям города.
import type { FaithId } from '@/game/types';
import { lonLatOf } from './atlas/project';
import { isWaterAt } from './land';
import { WORLD_ORIGIN } from './data/tuning';

/**
 * Линия Тахо: широта, южнее которой Иберия в 1200 году мусульманская.
 * Прямая по двум концам настоящей реки — устье под Лиссабоном и верховья у
 * Сарагосы. Ровно та грубость, о которой сказано в заголовке.
 */
const tagus = (lon: number): number => 38.55 + (lon + 9.2) * 0.3;

interface Region {
  /** Имя области — для отчёта, теста и документа, а не для игрока. */
  id: string;
  faith: FaithId;
  /** Попадает ли точка. Долгота и широта в градусах. */
  hit: (lon: number, lat: number) => boolean;
}

const box =
  (lon0: number, lon1: number, lat0: number, lat1: number) =>
  (lon: number, lat: number): boolean =>
    lon >= lon0 && lon <= lon1 && lat >= lat0 && lat <= lat1;

/**
 * Области по порядку разбора. Первое совпадение выигрывает, не совпало ничего —
 * латинский запад: он занимает большую часть карты, и перечислять его
 * прямоугольниками значило бы описывать всю Европу по кускам.
 */
export const FAITH_REGIONS: readonly Region[] = [
  // Острова разбираются раньше материка: они лежат внутри чужих рамок.
  { id: 'sicily', faith: 'catholic', hit: box(11.8, 16.4, 36.4, 38.6) },
  { id: 'crete', faith: 'orthodox', hit: box(23.2, 26.6, 34.6, 35.9) },
  { id: 'cyprus', faith: 'catholic', hit: box(32.2, 34.8, 34.4, 35.8) },
  // Грузия стоит впереди Анатолии: её рамка лежит внутри анатолийской.
  { id: 'georgia', faith: 'orthodox', hit: box(39.0, 49.0, 40.8, 45.0) },
  // Левант впереди Египта: у обоих ислам, но по имени области видно, откуда она.
  { id: 'levant', faith: 'islam', hit: box(33.0, 45.0, 28.0, 37.5) },
  { id: 'egypt', faith: 'islam', hit: box(24.0, 37.0, 20.0, 32.0) },
  { id: 'rum', faith: 'islam', hit: box(29.8, 46.0, 34.0, 41.5) },
  { id: 'maghreb', faith: 'islam', hit: box(-18.0, 12.0, 18.0, 37.6) },
  // Ливия отделена от Магриба нарочно: общая рамка на всю Африку захватила бы
  // Пелопоннес, который лежит на тех же широтах.
  { id: 'libya', faith: 'islam', hit: box(12.0, 28.0, 18.0, 33.5) },
  { id: 'andalus', faith: 'islam', hit: (lon, lat) => lon >= -10 && lon <= 3 && lat >= 34 && lat < tagus(lon) },
  { id: 'ionia', faith: 'orthodox', hit: box(24.5, 30.2, 35.0, 41.8) },
  { id: 'rus', faith: 'orthodox', hit: box(27.0, 50.0, 45.0, 70.0) },
  // Балканы начинаются восточнее каблука Италии: Отранто — латинский.
  { id: 'balkans', faith: 'orthodox', hit: box(18.6, 30.0, 34.5, 47.2) },
  { id: 'baltic', faith: 'pagan', hit: box(19.3, 27.0, 52.8, 60.5) },
  { id: 'finns', faith: 'pagan', hit: box(20.3, 32.0, 59.3, 70.5) },
  { id: 'sami', faith: 'pagan', hit: box(11.0, 24.0, 65.5, 72.0) },
];

/** Область, в которую попала точка. null — ни одна, то есть латинский запад. */
export function regionAt(lon: number, lat: number): string | null {
  for (const r of FAITH_REGIONS) if (r.hit(lon, lat)) return r.id;
  return null;
}

/**
 * Вера клетки мира. Координаты — мировые (`WORLD_ORIGIN` уже включён), как у
 * `terrainAt` и всего остального в мире.
 *
 * Сида здесь нет и быть не может: земля одна на всех, и вера — её свойство.
 */
export function faithAt(x: number, y: number): FaithId {
  const { lon, lat } = lonLatOf(x - WORLD_ORIGIN.x, y - WORLD_ORIGIN.y);
  for (const r of FAITH_REGIONS) if (r.hit(lon, lat)) return r.faith;
  return 'catholic';
}

/**
 * Шаг решётки при обходе округи. Считать все клетки круга радиусом `FAITH_AROUND`
 * незачем: разметка грубая, и одна клетка из квадрата `STEP × STEP` даёт то же
 * число с точностью до процента, а стоит в `STEP²` раз дешевле.
 */
const STEP = 3;

/**
 * Доля чужой веры вокруг клетки, 0..1. Вода не считается ни своей, ни чужой:
 * море не давит на приход, и деревня на мысу не должна оказываться в кольце
 * иноверцев только потому, что вокруг неё нет земли.
 *
 * Круг целиком на своей земле даёт 0, круг целиком на чужой — 1. Земли вокруг
 * нет вовсе — тоже 0: давить некому.
 */
export function faithPressure(x: number, y: number, radius: number, mine: FaithId): number {
  let land = 0;
  let other = 0;
  const r2 = radius * radius;
  for (let dy = -radius; dy <= radius; dy += STEP) {
    for (let dx = -radius; dx <= radius; dx += STEP) {
      if (dx * dx + dy * dy > r2) continue;
      const cx = x + dx;
      const cy = y + dy;
      if (isWaterAt(cx, cy)) continue;
      land++;
      if (faithAt(cx, cy) !== mine) other++;
    }
  }
  return land > 0 ? other / land : 0;
}

/**
 * Насколько чужая вера портит первое впечатление соседа: сдвиг стартового
 * отношения, отрицательный или ноль.
 *
 * Правило простое и симметричное. Одна вера — ноль. Две веры Писания
 * (`FAITH_RIFT`) знают друг о друге и спорят об одном, поэтому расходятся
 * вполовину от того, насколько любая из них расходится с язычеством
 * (`FAITH_GULF`), — а с ним спорить не о чем ни одной. **Дурных вер тут нет**:
 * число зависит от пары, а не от того, кто в ней первый, и `attitude(a, b)`
 * равно `attitude(b, a)`. Это тест.
 *
 * Боя это не касается никак и касаться не может: сдвиг ложится в стартовое
 * отношение двора, а отношение в бой не входит ни одним числом.
 */
export const FAITH_RIFT = -8;
export const FAITH_GULF = -16;

export function faithAttitude(a: FaithId, b: FaithId): number {
  if (a === b) return 0;
  const abrahamic = (f: FaithId): boolean => f !== 'pagan';
  if (abrahamic(a) && abrahamic(b)) return FAITH_RIFT;
  return FAITH_GULF;
}
