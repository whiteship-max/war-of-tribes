/**
 * Фигура в сохранении. Положение не хранится: оно выводится из `from`, `to` и
 * пары времён — поэтому фигура, шедшая, пока игрока не было, оказывается там же,
 * где оказалась бы при непрерывной игре, и догону нечего доигрывать.
 */
export interface StoredFigure {
  phase: FigurePhase;
  from: Coord;
  to: Coord;
  departAt: number;
  arriveAt: number;
  /** До какого момента фигура вне строя. 0 — она в строю. У пустого места не значит ничего. */
  downUntil: number;
  /**
   * Какой по счёту человек стоит на месте — номер из партии (`PlayerProfile.agents`).
   * Нет поля — ноль, тот, с кем партия началась. Новый номер в слепке — новый человек у
   * своих ворот. Версию сохранения мира поле не поднимает.
   */
  person?: number;
  /**
   * Человек на месте погиб или ушёл на покой, и место пустует до найма. Лежит поверх
   * фазы `down`, поэтому всякое «вне строя» закрывает и его (`world/shelter.placeOf`).
   * `person` — кто ушёл: пока слепок называет того же, место остаётся пустым.
   */
  gone?: { person: number; at: number; why: 'died' | 'retired' };
  /**
   * Риск разведчика, **замороженный в минуту отправки**: у какого поселения, в какую
   * минуту прихода, схватят ли и погибнет ли. Приход применяет ровно эти числа — даже
   * если игрок закрыл игру и разведчик пришёл без него. Бросок сеет минута прихода, а
   * она решена в минуту отправки (`arriveAt`), поэтому кость тоже известна заранее и не
   * зависит от того, когда мир разберёт приход. Нет поля — фигуру отправили до смертных
   * агентов: прежний бросок часовых, гибели нет.
   */
  peril?: { target: SettlementId; at: number; caught: number; peril: number; why: string[] };
  /**
   * До какого момента фигура занята прошлым приказом. 0 — свободна. Приказы
   * конкурируют за её время: агент каждого вида один, и в этом смысл.
   */
  busyUntil?: number;
  /**
   * Занятость — это задержание, а не своё дело. Отдельное поле, а не догадка по
   * длине `busyUntil`: сколько ждать и почему ждать — разные вещи, и говорить
   * игроку «держат под стражей» там, где лазутчик просто отлёживается, значит
   * врать ему.
   */
  held?: boolean;
  /**
   * Лазутчик стоит наблюдателем: пока он смотрит, он даёт живой обзор вокруг
   * себя и **не работает** — ни выведать войско, ни поднять бунт. У остальных
   * фигур поля нет и появляться не должно: наблюдатель в игре один, и в этом
   * вся острота выбора (см. world/sight.ts).
   *
   * Версию сохранения мира это поле не поднимает: словарь фигур мержится с
   * новой партией, и старое сохранение приезжает с ненаблюдающим лазутчиком —
   * ровно тем, с чего начинается новая партия.
   */
  watching?: boolean;
  /**
   * Агент вошёл в свой город и укрылся: `departAt` той стоянки, на которой он
   * вошёл. Место выводит одно правило (`world/shelter.placeOf`), и совпадать с
   * `departAt` отметка перестаёт сама, стоит агенту куда-нибудь пойти, — поэтому
   * «в городе и на дороге разом» не бывает даже у забытого поля.
   *
   * Версию сохранения мира это поле не поднимает: необязательное, и старое
   * сохранение приезжает с агентами на карте — ровно там, где их оставили.
   */
  sheltered?: number;
  /** Войско при полководце. У остальных пусто и появляться не должно. */
  troops?: TroopStack;
  /**
   * Идущая передача дружины: каким войско станет и когда. Пока она идёт, в
   * `troops` числятся **и те, кого уводят, и те, кого возвращают**, — эти люди
   * уже не в гарнизоне и ещё не в строю. Считается при чтении, как всё
   * остальное: срок наступил — состав меняется сам.
   */
  handover?: { troops: TroopStack; until: number };
  /**
   * Погоня за чужим отрядом. Хранится только его номер: где будет встреча и
   * когда, уже записано в `to` и `arriveAt` самой фигуры — погоня не «идёт»,
   * она вычислена. Сменит цель курс — встреча пересчитается тем же уравнением
   * в момент этого события, а не тиком.
   */
  chase?: { marchId: string };
  /**
   * Удар по лагерю из поля: куда полководец идёт и зовут ли гарнизон. Где и когда
   * он придёт, уже записано в `to` и `arriveAt`; бой считается в минуту прихода,
   * пока он ещё в пути, — дома его дружина стала бы гарнизоном. Поле необязательное:
   * версию сохранения мира оно не поднимает, у старой фигуры его просто нет.
   */
  strike?: { id: SettlementId; garrison: boolean };
  /**
   * Война между игроками, которую ведёт полководец (docs/pvp.md): номер войны на сервере. Пока поле лежит,
   * где он и что при нём, говорит сервер (`LocalWorld.stepWars`), а не свой путь: идёт к чужому замку, стоит
   * лагерем, возвращается. Необязательное — версию сохранения мира не поднимает.
   */
  war?: string;
  /**
   * Мораль дружины между боями (docs/battle_eu4.md, 14.31): доля полной морали, с которой она вышла из последнего боя,
   * минута и сколько вышло (`world/rest`). Читает её одна дверь — `restAt`. Нет поля — дружина свежая; поле
   * необязательное, версию сохранения мира оно не поднимает. У остальных фигур поля нет.
   */
  rest?: RestPair;
}

/**
 * Что игрок в последний раз видел в поселении. Это и есть второй слой тумана:
 * живые данные, снятые в момент, когда клетка была в обзоре. Дальше они не
 * обновляются, а стареют — и показываются с отметкой давности.
 */
export interface Sighting {
  at: number;
  stage: Stage;
  relation: Relation;
  owner: string | null;
  tribeId: TribeId | null;
  pop: number;
  castle: boolean;
  /**
   * Имя поселения в момент снимка. Есть только у замков живых игроков — у них имя города
   * называет владелец и может его сменить, а показывать новое имя поверх давнего снимка
   * значило бы врать о том, когда смотрели. Поля нет у снимка из старого сохранения —
   * тогда показывается имя вождя, как было.
   */
  name?: string;
  /**
   * Мощь на момент снимка. Есть только у замков живых игроков, и это не
   * оговорка: у чужого двора мощь даёт разведка (`Intel`), а разведать замок
   * игрока в этой пачке нечем — походов между игроками нет. Значит либо игрок
   * видел его своими глазами, либо не знает о нём ничего.
   *
   * Поля может не быть у снимка обычного поселения — там оно и не нужно.
   */
  power?: number;
  /**
   * Двор был разорён в момент снимка. Поля может не быть у снимка из старого
   * сохранения — тогда читается как «цел», и это правда: до появления разорений
   * их и не было.
   */
  sacked?: boolean;
}

