/**
 * Версия 8 — **дом ставит не сид, а общий реестр**. Где стоит замок игрока,
 * решает теперь сервер (`netlify/functions/castles.mts`), и клетка приезжает
 * оттуда. Приводить тут нечего по той же причине, по какой было нечего у
 * семёрки: у старого сохранения дом найден поиском по сиду, а на общей карте
 * он стоит в другом месте — и весь разведанный туман вокруг него оказался бы
 * туманом чужой округи.
 *
 * Сделать это молча было нельзя, а сделать без потери — не из чего: принять
 * клетку старого сохранения значило бы дать клиенту выбирать себе место, то
 * есть выбирать себе соседей. Поэтому нижняя граница поднята до восьмёрки:
 * всё, что старше, читается как «мира нет», и мир собирается заново на той
 * клетке, которую назвал реестр. Сохранение племени этим не тронуто — деревня
 * переживает смену мира целиком, как пережила смену земли.
 *
 * Версия 7 — **другая земля**. Мир перестал быть личной картой из зерна и стал
 * одним на всех: настоящая Европа, Магриб и Анатолия из атласа. Приводить тут
 * нечего и приводить нельзя: у старого сохранения координаты от другой карты, и
 * замок, стоявший на 541|822, оказался бы посреди Бискайского залива. Поэтому
 * нижняя граница поднята до семёрки — всё, что старше, читается как «мира нет»,
 * и мир собирается заново.
 *
 * Сетка при этом выросла с 200 на 200 до 800 на 800, а поселений ботов не стало
 * вовсе. Ни того, ни другого миграцией не выразить: это не новое поле, а другой
 * мир под теми же числами.
 *
 * Сохранение племени (`SAVE_VERSION`) при этом не трогается: координат карты в
 * нём нет ни одного поля, деревня переживает смену мира целиком.
 *
 * Версия 6 — письма: ожидающие решения игрока, их срок и пленные, взятые
 * прорвавшимся набегом. Приводить тут нечего — писем задним числом взять
 * неоткуда, а пленные считаются только в момент боя, — поэтому ступень заводит
 * пустой стол и назначает первое письмо от «сейчас». Молча это не делается:
 * первое же письмо приходит обычным порядком, а не толпой за прошедшее время.
 *
 * Версия 5 — отношения с поселениями: число, состояние (нейтралитет, пакт,
 * война) и характер владельца. Племенная враждебность с самозатуханием при этом
 * исчезла как отдельная величина: она стала производной от отношений, и двух
 * правд об одном не осталось (см. docs/MAP_ACTIONS.md).
 *
 * Четвёрка была про географию: реки, переправы, хребты с перевалами и тракты
 * между станами. Станы племён тогда переехали в `geography.tribeCenters`, то
 * есть при том же сиде поселения встали иначе, — и всё, что старше, по-прежнему
 * приводить не к чему.
 *
 * **Сохранение мира теперь приводится, а не выбрасывается.** Порядок тот же,
 * что у сохранения племени: цепочка ступеней начинается с `MIN_WORLD_SAVE_VERSION`,
 * всё, что старше, читается как «мира нет», и мир генерируется заново.
 *
 * Девятка — логова растут от жителей города (docs/lair_growth.md). Формат сохранения
 * не изменился ни одним полем: логово по-прежнему две отметки времени. Изменился смысл
 * этих отметок — логово старой партии в первую же минуту становится сильным по жителям
 * её города, — и молча такое не делают. Ступень кладёт в очередь последствий одну строку
 * летописи, и больше ничего.
 */
export const WORLD_SAVE_VERSION = 9;
/** Младше этой версии сохранение мира не приводится: там другой дом и другая земля. */
export const MIN_WORLD_SAVE_VERSION = 8;
export const WORLD_KEY = 'tribe.world.v1';

