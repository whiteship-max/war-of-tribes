/**
 * Последняя дверь в облако Telegram — и она открывается только наружу.
 *
 * **Облако CloudStorage перестало быть местом хранения.** Мест стало два, и
 * роли у них разные: устройство — рабочая копия (игра запускается с неё и
 * играется без сети), наш сервер — правда (переживает телефон, чистку данных,
 * переустановку). Третье место не давало тройной надёжности: у каждого своя
 * отметка времени, свои условия записи и свои отказы, и всё, что оно добавляло
 * на самом деле, — третий шанс разойтись. Задачу «не потерять прогресс при
 * чистке браузера» наш сервер решает лучше: без предела в 4096 символов на
 * значение, с личностью из проверенной подписи, и он наш.
 *
 * Но у кого-то партия может лежать **только** там: играли до этой правки, потом
 * потеряли локальную копию (переустановка клиента, чистка данных, вытеснение
 * хранилища вебвью на iOS), а сервера тогда ещё не было. Удалить код и сделать
 * такую партию недостижимой молча нельзя ни при каких условиях. Поэтому чтение
 * остаётся — как **разовый подъём**, а не как хранилище:
 *
 * - спрашивается облако ровно тогда, когда своей копии на устройстве нет вовсе;
 * - поднятое сразу ложится на диск, и второй раз облако уже не спрашивают;
 * - игрок узнаёт об этом строкой в летописи — подъём не бывает молчаливым;
 * - записи нет и быть не может: `setItem` убран из типа (`webapp.ts`), так что
 *   обратная дорога — ошибка компиляции, а не забытая строчка.
 *
 * Формат чтения — тот, которым писали: значение резалось на куски по 4000
 * символов (предел одного значения — 4096), рядом лежало число кусков. Это
 * историческая справка о чужих данных, а не наш формат: писать так больше
 * некому и незачем.
 *
 * Когда это можно удалить: когда подъём перестанет что-либо возвращать. Проверить
 * это со стороны кода нечем — данные лежат у игроков, — поэтому сносить надо не
 * по календарю, а по решению владельца.
 */

/** Размер куска, которым писали. Читаем чужие данные — число берём как есть. */
const CHUNK_KEYS_MAX = 512;

const store = () => {
  const app = window.Telegram?.WebApp;
  if (!app?.CloudStorage || !app.isVersionAtLeast?.('6.9')) return undefined;
  return app.CloudStorage;
};

/**
 * Поднять из облака то, что там лежит с прежних времён. `null` — если облака
 * нет, если оно пусто или если куски не собираются в целое.
 *
 * Половину строки возвращать нельзя: битый json дальше пойдёт в `deserialize`,
 * тот его не прочтёт, и игрок получит «партия начата заново» вместо честного
 * «в облаке ничего не было».
 */
export async function rescueFromCloud(key: string): Promise<string | null> {
  const cs = store();
  if (!cs) return null;
  const getOne = (k: string) =>
    new Promise<string | null>((resolve) => {
      try {
        cs.getItem(k, (err, v) => resolve(err || !v ? null : v));
      } catch {
        resolve(null);
      }
    });
  const n = Number(await getOne(`${key}:n`));
  if (!Number.isInteger(n) || n <= 0 || n > CHUNK_KEYS_MAX) return null;
  const parts = await Promise.all(Array.from({ length: n }, (_, i) => getOne(`${key}:${i}`)));
  if (parts.some((p) => p === null)) return null;
  return parts.join('');
}
