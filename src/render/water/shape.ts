/** Октав по уровню воды: низкий — две крупные, средний — четыре, высокий — все шесть. */
export const RIPPLE_OCTAVES: readonly [number, number, number] = [2, 4, 6];

/** Искривление ряби крупным шумом: масштаб (1/м) и сдвиг (м) — рябь обтекает пятна, а не лежит строками. */
export const RIPPLE_WARP: readonly [number, number] = [0.05, 4.0];

/**
 * Октава гаснет, когда её зерно мельче нескольких пикселей экрана: доля «пиксель × масштаб», с которой начинает гаснуть,
 * и с которой её нет. Иначе вдали частая рябь мерцает.
 */
export const RIPPLE_FADE: readonly [number, number] = [0.18, 0.45];

/** Круги дождя: сторона клетки, м. В клетке — одна капля за цикл, место и миг — новые каждый цикл. */
export const RAIN_CELL = 0.9;

/**
 * Наибольший радиус круга и полуширина кольца — в долях клетки. Их сумма не больше половины клетки: тогда круг
 * целиком лежит в квадрате 2 × 2 клетки вокруг пикселя, который шейдер перебирает, и краем клетки не режется
 * (тест «круг не режется краем клетки», `water.test.ts`). Прежняя вода резала круги краем клетки — отсюда квадраты.
 */
export const RAIN_RING: readonly [number, number] = [0.4, 0.085];

/** Циклов капли в секунду: при мороси и в ливень (капель больше — чаще и бьют). */
export const RAIN_RATE: readonly [number, number] = [0.7, 1.25];

/**
 * Кольцо тоньше этого числа пикселей не рисуется: доля «полуширина кольца / пиксель», с которой круг начинает
 * проступать, и с которой он в полную силу. Издали дождь — матовая рябь (`rough`), а не мерцание.
 */
export const RAIN_PX: readonly [number, number] = [0.6, 1.6];

/** Пена у берега и на бродах: глубина (м), с которой её нет, и та, на которой она сплошная. */
