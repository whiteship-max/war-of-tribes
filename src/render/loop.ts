/**
 * Дверь кадра: единственное место в игре, где зовут `requestAnimationFrame`.
 *
 * Всё, что рисует кадр за кадром, — диорама, предыстория, карта мира, ролик о
 * бое, проводка первых шагов, мини-игры, стенды, — идёт цепочкой `FrameLoop`;
 * всё, что ждёт один кадр, — `nextFrame`. Прямого вызова мимо двери нет ни
 * одного, и это тест (`loop.test.ts`, «дверь кадра одна»), как у `Math.random`.
 *
 * Дверь одна по трём причинам, и все три — не про красоту.
 *
 * 1. **Бюджет железа держит код, а не память.** Потолок частоты (`FPS_CAP`) и
 *    остановка в свёрнутой аппке записаны здесь один раз и достаются каждой
 *    цепочке сами. Цепочка, заведённая мимо двери, гнала бы видеокарту столько
 *    раз в секунду, сколько герц у монитора, — а без вертикальной синхронизации
 *    сотни раз. Машина владельца дважды выключалась ровно от этого (CLAUDE.md,
 *    раздел «Бюджет железа»).
 *
 * 2. **Причин остановки больше одной, а флаг был один.** Карта мира, ролик о
 *    бое, скрытая страница, потерянный контекст — и каждая умеет случиться поверх
 *    другой. С одним `paused` возврат из фона снимал бы остановку, поставленную
 *    картой, и диорама начинала бы рисоваться под полотном карты. С набором
 *    причин снятие одной ничего не решает: цепочка идёт тогда и только тогда,
 *    когда не осталось ни одной.
 *
 * 3. **Это надо проверять тестом, а сцену в тест не поднять.** Тесты идут в
 *    node, где нет ни WebGL, ни `requestAnimationFrame`. Здесь часы внешние —
 *    их передают в конструктор, — поэтому «в скрытой вкладке кадров нет, а при
 *    возврате они снова идут» и «на 144 Гц ровно шестьдесят» проверяются на
 *    настоящем коде, а не на его описании.
 *
 * Правило, ради которого заведена остановка: **ничего не ждать кадра, пока
 * страница скрыта.** В свёрнутом вебвью `requestAnimationFrame` не вызывается
 * вовсе — не редко, а никогда (это же записано в `boot/paint.ts`). Заявка,
 * поданная перед сворачиванием, может и не дожить до возвращения: тогда
 * цепочка обрывается молча, и на экране остаётся последний кадр или чернота.
 * Поэтому при возврате видимости цепочка заводится заново, а не «продолжается».
 */

// ---------- Бюджет железа ----------

/**
 * Потолок частоты кадров. **Бюджет железа, а не игровое число** (решение
 * владельца, 27.09.2026): от частоты кадров в игре не зависит ничего, кроме
 * плавности, — игровое время считается при чтении из часов, а не из кадров.
 *
 * Шестьдесят — частота экрана почти любого телефона: там потолок не меняет
 * ничего. Режет он монитор 120/144/165 Гц и браузер без вертикальной
 * синхронизации, где кадров было бы столько, сколько герц, или сотни.
 */
export const FPS_CAP = 60;

/**
 * Потолок плотности пикселей. Тоже бюджет железа: на экранах 3x третий пиксель
 * глазом не виден, а заливка растёт квадратом плотности — вдвое против 2x.
 * Снизу плотность экрана держится единицей: меньше — это мыло, а не экономия.
 */
export const DPR_CAP = 2;

/** Плотность экрана как есть — для отчётов стендов, а не для буфера. */
export const deviceRatio = (): number => (typeof window !== 'undefined' && window.devicePixelRatio) || 1;

/**
 * Плотность, с которой рисует буфер: экрана в [1, `DPR_CAP`], или заданная
 * стендом — но и она не выше потолка.
 */
export function pixelRatio(want?: number | null): number {
  const asked = want != null && Number.isFinite(want) && want > 0 ? want : Math.max(1, deviceRatio());
  return Math.min(DPR_CAP, asked);
}

/**
 * Насколько раньше своего срока кадр ещё пропускается, в долях шага.
 *
 * Отметки `requestAnimationFrame` на экране 60 Гц дрожат на доли миллисекунды,
 * и без допуска кадр, пришедший на десятую долю раньше срока, пропускался бы —
 * вместо шестидесяти выходило бы тридцать. На частоту допуск не влияет вовсе:
 * срок следующего кадра отсчитывается от срока прошлого, а не от минуты, когда
 * кадр случился, и каждый срок берёт ровно один кадр.
 */
const EARLY = 0.25;

/** Решение о кадре: рисовать ли и когда срок следующего. */
export interface Paced {
  draw: boolean;
  next: number;
}

/**
 * Рисовать ли кадр, пришедший в `now` (мс, отметка кадра браузера). Чистая функция
 * от времени и потолка — ей и держится вся частота.
 *
 * @param next   срок этого кадра из прошлого решения; у новой цепочки — `-Infinity`;
 * @param hidden страница скрыта или аппку свернули: кадра нет вовсе.
 *
 * **Срок копится, а не отсчитывается от кадра.** Следующий срок — прошлый плюс
 * шаг, поэтому на 144 Гц выходит ровно шестьдесят (кадры через два и три
 * интервала экрана по очереди), а не сорок восемь (каждый третий) и не
 * семьдесят два (каждый второй). Экран медленнее потолка отдаёт каждый свой кадр:
 * на 30 Гц — тридцать.
 *
 * **Отставание не догоняется очередью кадров.** Отстали больше чем на шаг —
 * первый кадр новой цепочки, тяжёлый кадр, возврат из фона — отсчёт начинается
 * заново от этой минуты: иначе цепочка рисовала бы на каждом кадре экрана, пока
 * не нагонит, то есть ровно то, от чего потолок заведён.
 */
export function pace(next: number, now: number, hidden: boolean, cap: number = FPS_CAP): Paced {
  if (hidden) return { draw: false, next: -Infinity };
  const step = 1000 / cap;
  if (now < next - step * EARLY) return { draw: false, next };
  const due = next + step;
  return { draw: true, next: due > now ? due : now + step };
}

// ---------- Видимость ----------

/** Страница скрыта: свёрнутая вкладка, скрытый вебвью. */
export const pageHidden = (): boolean => typeof document !== 'undefined' && document.visibilityState === 'hidden';

/**
 * Клиент Телеграма свернул аппку (Bot API 8.0, `deactivated`). На Telegram Desktop
 * свёрнутая аппка может оставаться для браузера видимой — кадры шли бы в пустоту.
 */
let appAsleep = false;

/** Кадров не должно быть ни у кого. */
export const awayNow = (): boolean => pageHidden() || appAsleep;

/** Живые цепочки: каждой говорят, что страница скрылась или вернулась. */
const watchers = new Set<() => void>();
let listening = false;

const tell = (): void => {
  for (const w of watchers) w();
};

/**
 * Слушатель видимости один на всю игру, а не у каждой цепочки: заводится с
 * первой цепочкой и живёт до конца страницы.
 */
function listen(): void {
  if (listening || typeof document === 'undefined') return;
  listening = true;
  document.addEventListener('visibilitychange', () => {
    // Страница вернулась — значит, и аппка развёрнута, даже если клиент не
    // прислал `activated`: иначе потерянное событие оставило бы игру чёрной.
    if (!pageHidden()) appAsleep = false;
    tell();
  });
  // Палец на экране — тоже доказательство, что аппку развернули: кадры
  // останавливает только уверенность, что их никто не видит.
  document.addEventListener(
    'pointerdown',
    () => {
      if (appAsleep) setAppAsleep(false);
    },
    { capture: true, passive: true },
  );
}

/** Клиент Телеграма свернул (`true`) или развернул (`false`) аппку. */
export function setAppAsleep(on: boolean): void {
  if (appAsleep === on) return;
  appAsleep = on;
  tell();
}

// ---------- Цепочка кадров ----------

type Raf = (cb: (now: number) => void) => number;
type Caf = (id: number) => void;

export interface LoopClock {
  raf: Raf;
  caf: Caf;
  /** Кадров не должно быть: страница скрыта или аппка свёрнута. */
  away: () => boolean;
}

const browserClock = (): LoopClock => ({
  raf: (cb) => requestAnimationFrame(cb),
  caf: (id) => cancelAnimationFrame(id),
  away: awayNow,
});

/**
 * Цепочка кадров с набором причин остановки и потолком частоты.
 *
 * `B` — имена причин владельца (у сцены это `Block` из `scenelog`). Модулю
 * довольно того, что список пуст или не пуст. Причину `hidden` ставит и снимает
 * сама дверь — у всех цепочек разом.
 *
 * Сама по себе цепочка стоит: её заводит `restart` или снятие последней причины.
 * Владелец, которому рано, держит свою причину (у ролика это `idle`).
 */
export class FrameLoop<B extends string> {
  private id = 0;
  private blocks = new Set<B | 'hidden'>();
  /** Заявка подана и ещё не сработала. */
  private pending = false;
  /** Срок следующего кадра — его ведёт `pace`. */
  private next = -Infinity;
  /** Выгружена: не оживает ни от чего. */
  private dead = false;
  /**
   * Цепочку хоть раз заводили. Дверь будит только такие: цепочка, которую
   * владелец ещё не завёл (или не успел — его конструктор упал на полпути),
   * от возврата видимости не заводится, иначе кадры пошли бы в недособранную сцену.
   */
  private armed = false;

  /**
   * @param tick    один кадр;
   * @param onStart зовётся перед первым кадром новой цепочки — сцене здесь надо
   *                съесть накопленную дельту часов, иначе кадр после возвращения
   *                прыгнет на всё время сна;
   * @param clock   часы; в тестах подменяются, в игре — браузерные.
   */
  constructor(
    private tick: () => void,
    private onStart: () => void = () => undefined,
    private clock: LoopClock = browserClock(),
  ) {
    watchers.add(this.onAway);
    listen();
  }

  /** Завести цепочку одним вызовом — для тех, кому причины не нужны. */
  static run(tick: () => void): FrameLoop<never> {
    const loop = new FrameLoop<never>(tick);
    loop.restart();
    return loop;
  }

  /** Причины, по которым цепочка сейчас стоит. Пусто — значит идёт. */
  stopped(): (B | 'hidden')[] {
    return [...this.blocks];
  }

  get running(): boolean {
    return this.pending;
  }

  /**
   * Поставить или снять причину. Идемпотентно нарочно: «развернули аппку»
   * приходит и от `visibilitychange`, и от `pageshow`, и от Телеграма — все три
   * зовут одно и то же, и второй раз снимать нечего.
   */
  block(kind: B | 'hidden', on: boolean): void {
    if (this.dead) return;
    const had = this.blocks.has(kind);
    if (on === had) return;
    if (on) this.blocks.add(kind);
    else this.blocks.delete(kind);
    if (this.blocks.size > 0) this.halt();
    else this.start();
  }

  /**
   * Завести цепочку заново, даже если она считается живой.
   *
   * Это и есть лечение третьей болезни: заявка, поданная до сворачивания, могла
   * не пережить фон, а `pending` про это не знает — он помнит, что заявку
   * подавали. Поэтому при возврате видимости цепочка не «продолжается», а
   * заводится с нуля: старая заявка снимается, новая подаётся.
   *
   * Видимость здесь спрашивается заново, а не берётся из памяти о событии:
   * вернувшаяся страница могла не прислать `visibilitychange` вовсе.
   */
  restart(): void {
    if (this.dead) return;
    // Заведена, даже если страница сейчас скрыта: вернётся — дверь её разбудит.
    this.armed = true;
    if (this.clock.away()) this.blocks.add('hidden');
    else this.blocks.delete('hidden');
    this.halt();
    if (this.blocks.size === 0) this.start();
  }

  /** Совсем и навсегда: владелец выгружен. */
  stop(): void {
    this.dead = true;
    this.blocks.clear();
    this.halt();
    watchers.delete(this.onAway);
  }

  private onAway = (): void => {
    if (this.armed) this.block('hidden', this.clock.away());
  };

  private halt(): void {
    if (this.id) this.clock.caf(this.id);
    this.id = 0;
    this.pending = false;
  }

  private start(): void {
    if (this.pending || this.dead) return;
    this.armed = true;
    this.next = -Infinity;
    this.onStart();
    this.schedule();
  }

  private schedule(): void {
    this.pending = true;
    this.id = this.clock.raf(this.step);
  }

  private step = (now: number): void => {
    this.id = 0;
    this.pending = false;
    // Причину могли поставить между заявкой и кадром — тогда кадра не будет.
    if (this.blocks.size > 0) return;
    const away = this.clock.away();
    const paced = pace(this.next, now, away);
    this.next = paced.next;
    // Скрылись, а события не было: цепочка встаёт до возвращения.
    if (away) {
      this.block('hidden', true);
      return;
    }
    this.schedule();
    if (paced.draw) this.tick();
  };
}

// ---------- Один кадр ----------

/** Есть ли у среды кадры вообще. В node их нет. */
export const hasFrames = (): boolean => typeof requestAnimationFrame === 'function';

/**
 * Дождаться одного кадра. Разовая заявка — ровно то же, что прямой
 * `requestAnimationFrame`: без потолка частоты и без проверки видимости. Потолок
 * здесь не нужен — цепочки нет, — а видимость решает сам браузер: в скрытой
 * странице кадр не придёт, и ждущий об этом знает (`boot/paint.ts` держит срок).
 *
 * Возвращает отмену.
 */
export function nextFrame(cb: () => void): () => void {
  const id = requestAnimationFrame(() => cb());
  return () => cancelAnimationFrame(id);
}
