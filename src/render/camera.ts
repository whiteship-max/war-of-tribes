/**
 * Кадр и пределы камеры деревни — чистые числа, без three.js, чтобы их можно
 * было проверить тестом, а не глазами в сцене.
 *
 * Обзор деревни отпущен: одним пальцем её водят, щипком приближают — как карту
 * мира. Значит нужны и те же ограничители, что у карты: привязка к посёлку,
 * чтобы не уехать в пустой лес, и потолок с полом приближения.
 */
import { OUTSKIRTS_RADIUS, FRAME_RADIUS } from './plan';

export interface Framing {
  /** Угол обзора по вертикали, градусы. */
  fov: number;
  /** Полярный угол камеры: 0 — зенит. */
  polar: number;
  /** Расстояние от цели до камеры. */
  dist: number;
  /** Высота точки, на которую смотрит камера. */
  targetY: number;
  /** Дальность тумана: от неё считается потолок отдаления. */
  fogNear: number;
  fogFar: number;
}

/**
 * Кадрирование от аспекта. В портрете (aspect < 0.7) камера подходит ближе и
 * поднимается выше, иначе диорама теряется в центре экрана.
 */
export function framing(aspect: number): Framing {
  // 0.75 — граница портрета; любой телефон (0.46–0.62) попадает в narrow = 1.
  const narrow = clamp((0.75 - aspect) / 0.15, 0, 1);
  // В портрете смотрим заметно сверху: кольцо стены должно читаться кольцом,
  // а не полоской у горизонта под половиной экрана неба. Но не отвесно:
  // при 0.62 верхнюю треть экрана занимала голая трава, при 0.7 — опушка.
  const polar = lerp(0.95, 0.7, narrow);
  // В портрете угол шире: иначе кадр не удержать без отъезда за предел дистанции.
  const fov = lerp(42, 48, narrow);
  // Кадр держит план целиком, а не постройки: FRAME_RADIUS задан планом раз и
  // навсегда, поэтому кадр не дёргается при каждой новой крыше — посёлок растёт
  // внутри одной и той же рамки, как на карте укреплённого города. Считается он
  // не от стены, а от края застройки: ресурсные дворы стоят снаружи, и половина
  // хозяйства иначе оказалась бы за краем экрана.
  const fitRadius = FRAME_RADIUS * lerp(1.12, 0.96, narrow);
  const halfH = Math.atan(Math.tan((fov * Math.PI) / 360) * aspect);
  const dist = clamp(fitRadius / Math.tan(halfH), 14, 92);
  // Цель чуть выше земли: деревня уходит из-под верхнего HUD.
  const targetY = lerp(0.4, 1.4, narrow);
  return { fov, polar, dist, targetY, fogNear: dist * 1.1, fogFar: dist * 1.75 };
}

/**
 * Пол и потолок приближения.
 *
 * Пол: ближе этого видно нутро моделей и деревня перестаёт читаться посёлком.
 * Он заметно ниже прежнего (0.45 от кадра): на кадровой дистанции здание занимает
 * два десятка пикселей, и приблизиться к нему до размера пальца игрок обязан.
 *
 * Потолок: дальше деревня превращается в точку, а главное — уезжает в туман.
 * Поэтому он не просто доля кадра, а ещё и обещание, что дальний край застройки
 * останется по эту сторону тумана.
 */
export function zoomRange(f: Framing): { min: number; max: number } {
  return {
    min: Math.max(12, f.dist * 0.28),
    max: Math.min(f.dist * 1.35, Math.max(f.dist, f.fogFar - FRAME_RADIUS - 4)),
  };
}

/**
 * Привязка к деревне: докуда можно увести центр экрана. Ровно до самого дальнего
 * двора — тогда любую постройку можно вывести на середину экрана, а за окрестности
 * не уехать: дальше только лес до края мира, и смотреть там не на что.
 */
export const PAN_LEASH = OUTSKIRTS_RADIUS;

/** Возвращает цель камеры внутрь привязки. */
export function clampPan(x: number, z: number, leash = PAN_LEASH): { x: number; z: number } {
  const r = Math.hypot(x, z);
  if (r <= leash || r === 0) return { x, z };
  const k = leash / r;
  return { x: x * k, z: z * k };
}

function clamp(v: number, lo: number, hi: number): number {
  return v < lo ? lo : v > hi ? hi : v;
}

function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

/**
 * Скорость поворота двумя пальцами: во сколько оборотов превращается проход
 * середины между пальцами через всю высоту холста. Число взято у прежнего
 * `OrbitControls.rotateSpeed` (0.55), чтобы поворот не изменил ощущения: он
 * работал и жалоб на него не было.
 */
export const ROTATE_SPEED = 0.55;

/**
 * Поворот от сдвига середины между двумя пальцами: сколько прибавить к азимуту
 * и к полярному углу. Мерка — высота холста в обе стороны, как у OrbitControls:
 * иначе на узком экране горизонтальный поворот выходил бы вдвое быстрее
 * вертикального.
 */
export function orbitDelta(dx: number, dy: number, height: number): { theta: number; phi: number } {
  const k = (2 * Math.PI * ROTATE_SPEED) / Math.max(1, height);
  return { theta: -dx * k, phi: -dy * k };
}

/**
 * Предел одного шага панорамы в мировых единицах.
 *
 * Панорама ведёт землю **один к одному**: точка, за которую взялись, остаётся
 * под пальцем. Считается это лучом до плоскости земли, и у самого горизонта луч
 * ложится почти параллельно ей — один пиксель там даёт километры. Такой шаг —
 * не движение пальца, а вырождение расчёта, и его надо отбрасывать целиком, а
 * не «ограничивать»: подрезанный шаг всё равно уехал бы не туда, куда вёл палец.
 * Половина привязки — заведомо больше любого честного шага и заведомо меньше
 * вырожденного.
 */
export const PAN_STEP_MAX = PAN_LEASH / 2;
