// Вид изнутри сцены города (docs/city_v3.md, Г-4): покои правителя на верхнем ярусе донжона, от первого лица.
//
// Комната — своя сцена со своей камерой, а город за окнами — тот же живой город той же сцены: жители, огни, погода и
// час одни на оба вида, второго города нет. Кадр рисует сцена города (`CityScene.draw`) двумя проходами одной цепочки:
// сначала комната — её глубина лежит в первой доле буфера (`INSIDE_DEPTH`), — потом город своей камерой с тем же местом
// и взглядом. Город проходит тест глубины только там, где комнаты нет, — в проёмах окон; заливку за стенами видеокарта
// отбрасывает ранним тестом. Небо в проёмах — цвет фона города (сцена чистит им буфер перед комнатой).
//
// Модуль без three-значений: только типы и строка шейдера, — его берут и сцена города, и кусок покоев.
import type * as THREE from 'three';
import type { Quality } from '../quality';

/**
 * Доля буфера глубины под комнату: её глубина сжата в [0, INSIDE_DEPTH]. Камера города — с ближней плоскостью в метре,
 * и её глубина меньше этой доли только ближе 1.004 м — там только стены самого донжона, и они смотрят наружу (отброшены
 * изнутри как задние грани).
 */
export const INSIDE_DEPTH = 0.004;

/** Строка вершинного шейдера комнаты: сжать глубину в первую долю буфера — после `gl_Position`. */
export const INSIDE_DEPTH_GLSL = `gl_Position.z = -gl_Position.w + ${INSIDE_DEPTH.toFixed(4)} * (gl_Position.z + gl_Position.w);`;

/** Что город видит этим кадром — свет в окна, погода у окна (числа сцены города, линейный свет). */
export interface InsideSky {
  /** 0 — ночь, 1 — день; ночь окон (`lighting.windowNight`) и глубина ночи. */
  daylight: number;
  night: number;
  nightK: number;
  /** Небо в проёмах (фон города) и дымка у горизонта. */
  sky: THREE.Color;
  haze: THREE.Color;
  /** На светило из города, единичный; прямой свет — цвет × сила после туч (0 — ночь или сплошные тучи). */
  sunDir: THREE.Vector3;
  sun: THREE.Color;
  /** Рассеянный свет неба — цвет × сила полусферы города. */
  hemi: THREE.Color;
  /** Погода кадра (`climate`): дождь, снег, туман, тучи, ветер (куда дует, оси мира) и вспышка молнии. */
  rain: number;
  snow: number;
  mist: number;
  cloud: number;
  wind: number;
  windX: number;
  windZ: number;
  flash: number;
}

/** Вид изнутри: его ставит сцена города (`CityScene.enterInside`) и рисует в каждом своём кадре. */
export interface Inside {
  /** Комната: своя сцена без огней three (свет — в шейдере комнаты) и своя камера с ближней плоскостью в сантиметрах. */
  readonly scene: THREE.Scene;
  readonly camera: THREE.PerspectiveCamera;
  /** Кадр: шаг, часы сцены, что видно за окном. Камеру комнаты двигает здесь; город берёт её место и взгляд. */
  frame(dt: number, t: number, sky: InsideSky): void;
  /** Уровень качества — сторож плавности сцены опустил его (`CityScene.lowerTo`); второго сторожа у покоев нет. */
  setLevel(q: Quality): void;
}
