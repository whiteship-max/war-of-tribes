// Голова гонца (ЛЦ-3, docs/characters.md): облик маски набора персонажа (`kit/head.ts`) — та же сетка, петли и лист лица,
// что у супруги, а таблицы мужские: челюсть шире и квадратнее (подъём к уху поздний, с углом), подбородок длиннее и
// вперёд, надбровье сильнее и ниже, нос длиннее и крупнее, щёки впалые под скулой (худой и быстрый), глаз меньше и глубже,
// рот шире и тоньше. Чертёжные меры — те же, что у супруги: листы лица у обоих одной плотности.
import { Head, bell, smooth, type HeadSpec } from '../kit/head';
import type { HeraldFace } from './looks';

const TOP_H = 0.235;
const ROWS = [0, 0.02, 0.042, 0.062, 0.08, 0.097, 0.112, 0.126, 0.14, 0.156, 0.178, 0.205, TOP_H] as const;
const COLS_M = [0, 0.017, 0.032, 0.048, 0.064, 0.085, 0.112, 0.152] as const;

/** Полуширина головы по высоте над подбородком: подбородок и челюсть шире, чем у супруги. */
function widths(jaw: number): [number, number][] {
  const base: [number, number][] = [
    [0, 0.038],
    [0.02, 0.052],
    [0.042, 0.059],
    [0.062, 0.062],
    [0.08, 0.066],
    [0.097, 0.077],
    [0.112, 0.09],
    [0.126, 0.095],
    [0.14, 0.097],
    [0.156, 0.098],
    [0.178, 0.097],
    [0.205, 0.094],
    [0.235, 0.088],
  ];
  // Челюсть шире — низ маски, к скулам — как было.
  return base.map(([h, a]) => [h, a * (1 + (jaw - 1) * Math.max(0, 1 - h / 0.11))]);
}

/** Глубина: подбородок вперёд, лоб чуть покатее. */
const DEPTH: [number, number][] = [
  [0, 0.075],
  [0.014, 0.089],
  [0.03, 0.092],
  [0.044, 0.09],
  [0.06, 0.094],
  [0.077, 0.096],
  [0.095, 0.097],
  [0.11, 0.095],
  [0.126, 0.094],
  [0.14, 0.093],
  [0.156, 0.095],
  [0.178, 0.097],
  [0.205, 0.094],
  [0.235, 0.085],
];

export function heraldHead(f: Pick<HeraldFace, 'nose' | 'jaw' | 'brow'>): HeadSpec {
  return {
    chinY: 1.284,
    hz: -0.012,
    topH: TOP_H,
    rows: ROWS,
    colsM: COLS_M,
    aT: widths(f.jaw),
    fT: DEPTH,
    // Челюсть квадратная: под подбородком линия почти ровная, к уху — поздно и круто вверх (угол челюсти).
    rise: (th) => {
      const a = Math.abs(th);
      return 0.004 * smooth(0.4, 1.0, a) + 0.043 * smooth(1.12, 1.55, a);
    },
    relief: (th, h) => {
      const a = Math.abs(th);
      const nose = f.nose * bell(th, 0, 0.075) * (0.0106 * bell(h, 0.1, 0.011) + 0.0056 * smooth(0.105, 0.116, h) * (1 - smooth(0.13, 0.148, h)) + 0.0034 * bell(h, 0.142, 0.01));
      const wing = 0.002 * bell(a, 0.21, 0.08) * bell(h, 0.099, 0.01);
      // Надбровье — сильнее и ниже, чем у супруги: глаза в тени, взгляд из-под бровей; над переносицей — бугор.
      const brow = f.brow * (0.0074 * bell(a, 0.42, 0.3) * bell(h, 0.164, 0.011) + 0.0026 * bell(th, 0, 0.13) * bell(h, 0.158, 0.01));
      const apple = 0.0016 * bell(a, 0.62, 0.22) * bell(h, 0.1, 0.02);
      // Подбородок — вперёд бугром.
      const chin = 0.0036 * bell(th, 0, 0.32) * bell(h, 0.024, 0.014);
      // Скула — наружу, под ней — впадина (худое лицо с дороги).
      const bone = 0.0076 * bell(a, 0.95, 0.24) * bell(h, 0.116, 0.018) - 0.006 * bell(a, 0.9, 0.3) * bell(h, 0.072, 0.018);
      return { front: nose + wing + brow + apple + chin, out: bone };
    },
    // Подбородок длиннее, чем у супруги: ниже рта лицо почти не короче рядов.
    chinUp: (h) => (h >= 0.06 ? h : 0.06 - (0.06 - h) * 0.9),
    // Овал — прямее: шире у челюсти, к вискам уже мало.
    faceOval: (h) => (h <= 0.118 ? 0.094 * Math.sqrt(Math.max(0, 1 - ((h - 0.118) / 0.17) ** 2)) : 0.094 - (h - 0.118) * 0.1),
    eye: { x: 0.0405, h: 0.14, half: 0.0186, up: 0.0053, down: 0.0037, tilt: 0.0016, inner: -0.0004 },
    mouth: { half: 0.0262, line: 0.0625, top: 0.0698, bow: 0.0006, bottom: 0.0538 },
    ball: { rx: 0.026, r: 0.0125, lid: 0.0016, rim: 0.0032 },
    // Уголки губ — чуть вверх: лицо открытое, но не улыбка.
    cornerUp: 0.0016,
    rimUp: 0.001,
    lipFront: { upper: 0.0012, lower: 0.0018 },
    // Шея плотная: верхнее кольцо шеи фигуры в чертёжных мерах головы (`figure.neckTop`).
    neck: { r: 0.062, zc: -0.018, drop: 0.008 },
    jaw: [0.043, 0.063],
  };
}

/** Голова гонца облика (по поправкам к маске). */
export const headOf = (f: Pick<HeraldFace, 'nose' | 'jaw' | 'brow'>): Head => new Head(heraldHead(f));
