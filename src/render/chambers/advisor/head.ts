// Голова советника (ЛЦ-5, docs/characters.md): облик маски набора персонажа (`kit/head.ts`) — та же сетка, петли и лист лица,
// что у супруги и гонца, а таблицы — пожилого мужчины: лоб выше (линия волос отступила), виски впалые, скула видна костью,
// под ней — провал, щёки чуть оплыли к углам рта (носогубная складка — бугром), под глазом — мешок, верхнее веко тяжелее,
// внешний угол глаза опущен; нос длиннее и с горбинкой, кончик ниже; губы тоньше, уголки рта чуть вниз. Челюсть и
// подбородок прячет борода — у маски они спокойные. Чертёжные меры — те же, что у супруги и гонца: листы лица одной
// плотности.
import { Head, bell, smooth, type HeadSpec } from '../kit/head';
import type { AdvisorFace } from './looks';

/** Линия волос над подбородком — выше, чем у гонца (0,235): лоб высокий. */
const TOP_H = 0.248;
const ROWS = [0, 0.02, 0.042, 0.062, 0.08, 0.097, 0.112, 0.126, 0.14, 0.156, 0.18, 0.212, TOP_H] as const;
const COLS_M = [0, 0.017, 0.032, 0.048, 0.064, 0.085, 0.112, 0.152] as const;

/** Полуширина головы по высоте над подбородком: челюсть — между супругой и гонцом, виски — уже. */
function widths(jaw: number): [number, number][] {
  const base: [number, number][] = [
    [0, 0.029],
    [0.02, 0.043],
    [0.042, 0.052],
    [0.062, 0.057],
    [0.08, 0.064],
    [0.097, 0.076],
    [0.112, 0.089],
    [0.126, 0.094],
    [0.14, 0.096],
    [0.156, 0.096],
    [0.18, 0.094],
    [0.212, 0.091],
    [0.248, 0.084],
  ];
  return base.map(([h, a]) => [h, a * (1 + (jaw - 1) * Math.max(0, 1 - h / 0.11))]);
}

/** Глубина: подбородок не выдаётся (его держит борода), лоб выпуклее и выше. */
const DEPTH: [number, number][] = [
  [0, 0.072],
  [0.014, 0.086],
  [0.03, 0.09],
  [0.044, 0.089],
  [0.06, 0.093],
  [0.077, 0.096],
  [0.095, 0.097],
  [0.11, 0.095],
  [0.126, 0.094],
  [0.14, 0.093],
  [0.156, 0.095],
  [0.18, 0.097],
  [0.212, 0.096],
  [0.248, 0.087],
];

export function advisorHead(f: Pick<AdvisorFace, 'nose' | 'jaw' | 'brow'>): HeadSpec {
  return {
    chinY: 1.284,
    hz: -0.012,
    topH: TOP_H,
    rows: ROWS,
    colsM: COLS_M,
    aT: widths(f.jaw),
    fT: DEPTH,
    rise: (th) => {
      const a = Math.abs(th);
      return 0.006 * smooth(0.4, 1.0, a) + 0.04 * smooth(1.08, 1.55, a);
    },
    relief: (th, h) => {
      const a = Math.abs(th);
      // Нос длинный, с горбинкой на кости и опущенным кончиком.
      const nose = f.nose * bell(th, 0, 0.08) * (0.0112 * bell(h, 0.097, 0.012) + 0.0058 * smooth(0.102, 0.114, h) * (1 - smooth(0.13, 0.15, h)) + 0.0042 * bell(h, 0.136, 0.007));
      const wing = 0.0022 * bell(a, 0.22, 0.08) * bell(h, 0.097, 0.01);
      const brow = f.brow * (0.0058 * bell(a, 0.42, 0.3) * bell(h, 0.166, 0.012) + 0.0028 * bell(th, 0, 0.13) * bell(h, 0.16, 0.01));
      // Мешок под глазом — мягким валиком под нижним веком.
      const bag = 0.0012 * bell(a, 0.43, 0.13) * bell(h, 0.123, 0.006);
      // Щека оплыла к углу рта: бугор над носогубной складкой.
      const jowl = 0.0026 * bell(a, 0.5, 0.17) * bell(h, 0.08, 0.016);
      const chin = 0.0026 * bell(th, 0, 0.3) * bell(h, 0.024, 0.014);
      // Лоб выпуклый над надбровьем.
      const dome = 0.002 * bell(a, 0.3, 0.35) * bell(h, 0.21, 0.025);
      // Скула — костью наружу, под ней провал; виски впалые.
      const bone = 0.0072 * bell(a, 0.95, 0.24) * bell(h, 0.118, 0.018) - 0.0056 * bell(a, 0.9, 0.3) * bell(h, 0.07, 0.02) - 0.003 * bell(a, 1.25, 0.22) * bell(h, 0.19, 0.03);
      return { front: nose + wing + brow + bag + jowl + chin + dome, out: bone };
    },
    chinUp: (h) => (h >= 0.09 ? h : 0.09 - (0.09 - h) * 0.9),
    faceOval: (h) => (h <= 0.118 ? 0.094 * Math.sqrt(Math.max(0, 1 - ((h - 0.118) / 0.17) ** 2)) : 0.094 - (h - 0.118) * 0.1),
    // Глаз меньше, верхнее веко ниже, внешний угол опущен — взгляд из-под тяжёлого века.
    eye: { x: 0.04, h: 0.14, half: 0.0186, up: 0.0056, down: 0.0036, tilt: 0.0004, inner: 0.0004 },
    mouth: { half: 0.025, line: 0.0625, top: 0.0686, bow: 0.0004, bottom: 0.0556 },
    ball: { rx: 0.026, r: 0.0125, lid: 0.0016, rim: 0.0032 },
    // Уголки губ — чуть вниз: лицо строгое, задумчивое.
    cornerUp: -0.0008,
    rimUp: -0.0004,
    lipFront: { upper: 0.001, lower: 0.0014 },
    neck: { r: 0.05, zc: -0.02, drop: 0.008 },
    jaw: [0.043, 0.063],
  };
}

/** Голова советника облика (по поправкам к маске). */
export const headOf = (f: Pick<AdvisorFace, 'nose' | 'jaw' | 'brow'>): Head => new Head(advisorHead(f));
