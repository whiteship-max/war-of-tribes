// Голова служанки (ЛЦ-6, docs/characters.md): облик маски набора персонажа (`kit/head.ts`) — та же сетка, петли и лист лица,
// что у супруги, гонца и советника, а таблицы — молодой простой женщины, и нарочно не супруги: лицо круглее и короче (щёки
// полные — яблочками вперёд и вбок, челюсть шире и мягче, подбородок маленький и круглый), скула не видна костью, нос
// короткий, курносый, с круглым кончиком, глаза чуть шире расставлены и круглее, губы пухлые и короче. Линия волос — ниже
// края чепца: от неё до чепца видны волосы на пробор (их рисует лист лица). Чертёжные меры — те же, что у остальных: листы
// лица одной плотности.
import { Head, bell, smooth, type HeadSpec } from '../kit/head';
import type { MaidFace } from './looks';

/** Верх маски над подбородком — ниже, чем у супруги (0,235): лицо короче, лоб под чепцом. */
const TOP_H = 0.228;
const ROWS = [0, 0.02, 0.042, 0.062, 0.08, 0.097, 0.112, 0.126, 0.14, 0.156, 0.176, 0.2, TOP_H] as const;
const COLS_M = [0, 0.017, 0.032, 0.048, 0.064, 0.085, 0.112, 0.152] as const;

/** Полуширина: у подбородка — круглее и шире супруги, щёки — полнее, виски — как у неё. */
function widths(round: number): [number, number][] {
  const base: [number, number][] = [
    [0, 0.03],
    [0.02, 0.046],
    [0.042, 0.059],
    [0.062, 0.07],
    [0.08, 0.08],
    [0.097, 0.089],
    [0.112, 0.094],
    [0.126, 0.098],
    [0.14, 0.099],
    [0.156, 0.098],
    [0.176, 0.096],
    [0.2, 0.092],
    [TOP_H, 0.086],
  ];
  return base.map(([h, a]) => [h, a * (1 + (round - 1) * Math.max(0, 1 - h / 0.13))]);
}

/** Глубина: подбородок не выдаётся, щёки и лоб — круглые. */
const DEPTH: [number, number][] = [
  [0, 0.064],
  [0.014, 0.08],
  [0.03, 0.086],
  [0.044, 0.087],
  [0.06, 0.092],
  [0.077, 0.095],
  [0.095, 0.096],
  [0.11, 0.095],
  [0.126, 0.094],
  [0.14, 0.094],
  [0.156, 0.095],
  [0.176, 0.096],
  [0.2, 0.094],
  [TOP_H, 0.088],
];

export function maidHead(f: Pick<MaidFace, 'round' | 'nose' | 'cheek'>): HeadSpec {
  return {
    chinY: 1.284,
    hz: -0.012,
    topH: TOP_H,
    rows: ROWS,
    colsM: COLS_M,
    aT: widths(f.round),
    fT: DEPTH,
    // Челюсть поднимается к уху мягко и поздно: подбородок круглый, а не клином.
    rise: (th) => 0.042 * Math.min(1, Math.abs(th) / 1.62) ** 1.6,
    relief: (th, h) => {
      const a = Math.abs(th);
      // Нос короткий, спинка низкая, кончик круглый и чуть вверх (курносый).
      const nose = f.nose * bell(th, 0, 0.075) * (0.0094 * bell(h, 0.104, 0.009) + 0.0026 * smooth(0.108, 0.118, h) * (1 - smooth(0.128, 0.142, h)) + 0.0016 * bell(h, 0.14, 0.01));
      const wing = 0.0019 * bell(a, 0.21, 0.08) * bell(h, 0.1, 0.01);
      const brow = 0.0042 * bell(a, 0.44, 0.27) * bell(h, 0.166, 0.012);
      // Щёки — яблочками: вперёд и вбок, ниже глаза; под ними — без провала.
      const apple = f.cheek * 0.0052 * bell(a, 0.62, 0.24) * bell(h, 0.094, 0.022);
      const chin = 0.0024 * bell(th, 0, 0.26) * bell(h, 0.022, 0.012);
      const out = f.cheek * 0.0044 * bell(a, 0.9, 0.3) * bell(h, 0.088, 0.03);
      return { front: nose + wing + brow + apple + chin, out };
    },
    // Ниже рта — коротко: подбородок маленький.
    chinUp: (h) => (h >= 0.06 ? h : 0.06 - (0.06 - h) * 0.7),
    // Овал — круглее: шире у щёк, к подбородку плавно.
    faceOval: (h) => (h <= 0.112 ? 0.096 * Math.sqrt(Math.max(0, 1 - ((h - 0.112) / 0.135) ** 2)) : 0.096 - (h - 0.112) * 0.13),
    // Глаз круглее и чуть шире расставлен, веко выше, внешний угол почти ровно.
    eye: { x: 0.0418, h: 0.14, half: 0.0168, up: 0.0052, down: 0.0038, tilt: 0.0012, inner: -0.0004 },
    mouth: { half: 0.0222, line: 0.0636, top: 0.0736, bow: 0.0014, bottom: 0.0506 },
    ball: { rx: 0.026, r: 0.0125, lid: 0.0016, rim: 0.0032 },
    // Уголки губ — вверх: лицо доброе, живое.
    cornerUp: 0.0026,
    rimUp: 0.0014,
    lipFront: { upper: 0.0021, lower: 0.0028 },
    neck: { r: 0.049, zc: -0.016, drop: 0.007 },
    jaw: [0.043, 0.063],
  };
}

/** Голова служанки облика (по поправкам к маске). */
export const headOf = (f: Pick<MaidFace, 'round' | 'nose' | 'cheek'>): Head => new Head(maidHead(f));
