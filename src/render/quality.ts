/**
 * Уровень качества графики сцены — одна дверь.
 *
 * Здесь — что уровень значит для всей сцены: плотность пикселей и мягкость тени (их ставит
 * оболочка сцены, `render/Scene.ts`), выбор уровня по устройству и сторож плавности. Что
 * уровень значит для города — слои текстур, карта теней, лес, жизнь, — числа самого города
 * (`city/spec.ts`, docs/city.md, раздел 6). Прежде здесь жили и числа окружения посёлка
 * (трава, цветы, мелочь, карта земли, ветер); посёлок убран вместе с видами `now` и `next`
 * (docs/city.md, «Город — единственный вид»). Второго места с числами уровня у сцены нет и
 * заводить его нельзя: две правды о том, что стоит «средний», разошлись бы молча — и заметил бы
 * это телефон, который перестал держать кадр.
 *
 * ЗДЕСЬ НЕТ НИ THREE, НИ БРАУЗЕРА, И ЭТО НАРОЧНО (как у ступеней предыстории,
 * `prologue/look.ts`): уровень выбирается чистой функцией от того, что умеет
 * устройство, и держит это тест, а не снимок. Что устройство умеет, спрашивает у
 * браузера сцена (`deviceCaps` ниже — единственное чтение), а решает `autoQuality`.
 *
 * ЧИСЛА — БЮДЖЕТ ЖЕЛЕЗА, А НЕ ВКУС. Цель — ровные шестьдесят кадров на телефоне
 * среднего класса (Adreno 618 / Mali-G57 / Apple A12) на среднем уровне; низкий —
 * для слабых и старых, высокий — для настольных и сильных телефонов. Бюджет города по
 * уровням и откуда он выведен — `city/budget.ts` (`CITY_BUDGET`) и docs/city.md, разделы 10 и 11.8.
 */

import type { SteadyRule } from './steady';

/** Три уровня, от дорогого к дешёвому. */
export type Quality = 'high' | 'medium' | 'low';

export const QUALITIES: readonly Quality[] = ['high', 'medium', 'low'];

/** Уровень из строки — адреса или записи; чужое слово — не уровень. */
export const qualityOf = (s: string | null | undefined): Quality | null =>
  s === 'high' || s === 'medium' || s === 'low' ? s : null;

export interface QualitySpec {
  /**
   * Плотность пикселей буфера — не выше потолка двери кадра (`loop.DPR_CAP`) и не
   * выше плотности экрана. Заливка растёт квадратом плотности: 1.5 против 2 — это
   * 56 % пикселей, и на телефоне это главная ручка цены кадра.
   */
  dpr: number;
  /**
   * Мягкий край тени (PCF, девять выборок карты на пиксель) или жёсткий (одна выборка).
   * На кадре посёлка тексель карты мельче пикселя экрана, и жёсткий край почти не виден —
   * а девять выборок на каждом пикселе земли слабому телефону дороги.
   */
  shadowSoft: boolean;
  /**
   * Плотность буфера 2D-карты (`ui/map/WorldMap.tsx`) — своя, а не `dpr` сцены: на карте подписи и значки, им
   * мыло 1.25 заметнее, чем земле города, а пиксель карты дешевле пикселя сцены (готовые тайлы, без света).
   * На низком — 1.5: 56 % пикселей плотности 2 на каждом кадре полотна (docs/perf.md).
   */
  mapDpr: number;
  /**
   * Теневой проход города — раз в столько кадров. Двигаются в тени только фигурки, а солнце идёт за часом игры:
   * через кадр отставание тени не видно (так было всегда), на низком — раз в четыре кадра, отставание 50 мс — шаг
   * прохожего на семь сантиметров. Вершины теневого прохода — вторая половина вершин кадра; на низком их вдвое меньше
   * в среднем за кадр (docs/perf.md).
   */
  shadowEvery: number;
}

/**
 * Числа уровней (docs/graphics_world.md, раздел 4 и 9.2): высокий — плотность 2, средний — 1.5,
 * низкий — 1.25, жёсткая тень лампы (одна выборка вместо девяти) и теневой проход раз в четыре кадра, а не через
 * кадр; карта — 2, на низком 1.5.
 * Остальное уровень значит у города (`city/spec.ts`).
 */
export const QUALITY: Record<Quality, QualitySpec> = {
  high: { dpr: 2, shadowSoft: true, mapDpr: 2, shadowEvery: 2 },
  medium: { dpr: 1.5, shadowSoft: true, mapDpr: 2, shadowEvery: 2 },
  low: { dpr: 1.25, shadowSoft: false, mapDpr: 1.5, shadowEvery: 4 },
};

/** Что устройство умеет — то, по чему выбирается уровень. */
export interface DeviceCaps {
  /**
   * Главный указатель — палец (`(pointer: coarse)`): граница «телефон или настольный»
   * та же, что у предыстории. Строка устройства врёт, указатель — нет.
   */
  coarse: boolean;
  /** `navigator.deviceMemory`, ГБ; `null` — браузер не говорит (Safari, Firefox). */
  memory: number | null;
  /** `navigator.hardwareConcurrency`; `null` — не говорит. */
  cores: number | null;
  /** Имя видеокарты из `WEBGL_debug_renderer_info`; `null` — скрыто. */
  gpu: string | null;
  /**
   * Класс устройства, который Телеграм на Android сам дописывает в строку браузера мини-аппы
   * (`Telegram-Android/… (…; SDK 29; LOW)` — Bot API, «Additional data in User-Agent»): `LOW`,
   * `AVERAGE` или `HIGH` по числу и частоте ядер и классу памяти. Это не строка устройства, а
   * готовый замер Телеграма — тот же, по которому он сам гасит свои эффекты. `null` — не Телеграм
   * на Android (iPhone, браузер, Телеграм на компьютере). Читает его `tgClassOf`.
   */
  tg?: TgClass | null;
}

/** Класс устройства Телеграма на Android. */
export type TgClass = 'LOW' | 'AVERAGE' | 'HIGH';

/** Класс устройства из строки браузера мини-аппы; чужая строка — `null`. */
export function tgClassOf(ua: string | null | undefined): TgClass | null {
  const m = /Telegram-Android\/[^\s(]*\s*\([^)]*;\s*(LOW|AVERAGE|HIGH)\s*\)/.exec(ua ?? '');
  return m ? (m[1] as TgClass) : null;
}

/**
 * Слабая видеокарта телефона: старые Mali (-4xx, -T, G31/G51/G52 — последняя до сих пор
 * стоит в дешёвых телефонах), Adreno ниже цели среднего уровня (618): 3xx, 4xx, 5xx до 512
 * и 605–613 — последние стоят в дешёвых телефонах 2019–2023 годов (Snapdragon 460, 665, 680)
 * и по силе ближе к Mali-G52, чем к 618 (решение ночи 4, docs/perf.md); PowerVR. Такая не
 * держит шестьдесят кадров при плотности 1.5 — низкий уровень ей положен сразу, а не после
 * двух секунд рывков.
 */
const WEAK_GPU = /mali-(4|t|g31|g51|g52)|adreno \(tm\) ((3|4|50|51)\d|60\d|61[0-3]\b)|powervr|sgx/i;

/**
 * Видеокарты нет — кадр рисует процессор (SwiftShader, llvmpipe, «базовый видеодрайвер»
 * Windows). Трава при такой отрисовке — секунды на кадр: низкий уровень, где бы ни был.
 */
const SOFT_GPU = /swiftshader|llvmpipe|softpipe|basic render/i;

/**
 * Встроенная видеокарта ноутбука прежних лет — Intel HD и UHD (не Iris): она тянет кадр
 * посёлка на среднем, а плотность 2 с двадцатью шестью тысячами пучков — нет.
 */
const WEAK_DESKTOP = /intel.*\b(hd|uhd) graphics/i;

/**
 * Уровень по устройству.
 *
 * ТЕЛЕФОН — НЕ ВЫШЕ СРЕДНЕГО (решение ночи 1, docs/graphics_world.md, 9.2). Высокий — это
 * плотность 2, тень 2048 и двадцать шесть тысяч пучков: вдвое дороже нынешнего кадра на
 * настольной видеокарте (раздел 4). Телефон, даже сильный, платит за него батареей и
 * нагревом, а глаз на экране в шесть дюймов разницы со средним почти не видит. Высокий на
 * телефоне — только рукой игрока (пункт «Графика» в настройках).
 *
 * Телефон — средний, если о нём не известно худшего: Телеграм сам назвал его слабым (класс
 * `LOW` в строке браузера, `tgClassOf`), слабая или программная видеокарта,
 * памяти не больше двух гигабайт (Chromium округляет вниз до степени двойки: телефон на
 * три гигабайта говорит «2»), или памяти не больше четырёх при не больше четырёх ядрах —
 * низкий. Ядра спрашиваются только вместе с памятью: память называет только Chromium, а
 * WebKit (все iPhone) ядра занижает нарочно — по ним каждый iPhone выходил бы слабым.
 *
 * Настольный браузер — высокий: мышь, большой экран, видеокарта без батареи; встроенная
 * Intel HD/UHD — средний, программная отрисовка — низкий. Строку устройства не читаем: по
 * ней не отличить телефон двадцатого года от двадцать четвёртого, а указатель, память и
 * видеокарта — отличают.
 */
export function autoQuality(c: DeviceCaps): Quality {
  if (c.gpu && SOFT_GPU.test(c.gpu)) return 'low';
  if (!c.coarse) return c.gpu && WEAK_DESKTOP.test(c.gpu) ? 'medium' : 'high';
  if (c.tg === 'LOW') return 'low';
  if (c.gpu && WEAK_GPU.test(c.gpu)) return 'low';
  if (c.memory !== null && (c.memory <= 2 || (c.memory <= 4 && c.cores !== null && c.cores <= 4))) return 'low';
  return 'medium';
}

/** Уровень ниже; ниже низкого — нет. */
export const lowerQuality = (q: Quality): Quality | null => QUALITIES[QUALITIES.indexOf(q) + 1] ?? null;

/**
 * Сторож плавности посёлка (`render/steady`): цель — шестьдесят, и пороги выведены из неё.
 *
 *   С высокого на средний — средний кадр окна дольше 1000/48 мс (ниже 48 кадров в среднем)
 *     или каждый пятый кадр дольше 45 мс (рывки в три интервала экрана и больше). Порог
 *     одного кадра здесь врёт: дверь кадра (`loop.pace`) держит ровно шестьдесят в среднем на
 *     любом экране от 60 Гц, но на 72 и 75 Гц кладёт кадры через один и два интервала —
 *     каждый четвёртый промежуток 26.7 мс при ровном ходе. Средний кадр от частоты экрана не
 *     зависит: ровно — 16.7, экран в 50 Гц — 20.
 *   Со среднего на низкий — правило предыстории, цель тридцать (36 мс): телефон, запертый
 *     в экономии на тридцати, ровен, и терять траву на неделю ему не за что.
 *   Доля, окно, прогрев и пауза — те же, что у предыстории (`prologue/look.ts`).
 */
export const VILLAGE_STEADY = (q: Quality): SteadyRule =>
  q === 'high'
    ? { slowMs: 45, share: 0.2, windowMs: 2000, warm: 45, gapMs: 250, meanMs: 1000 / 48 }
    : { slowMs: 36, share: 0.2, windowMs: 2000, warm: 45, gapMs: 250 };

/**
 * Плотность пикселей уровня на этом экране: не выше уровня и не выше экрана, но и не
 * ниже единицы — меньше единицы это мыло, а не экономия (правило двери кадра).
 */
export function qualityDpr(q: Quality, device: number): number {
  return Math.max(1, Math.min(QUALITY[q].dpr, device));
}
